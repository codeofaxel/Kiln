"""``route_print_job`` on an install without kiln-pro asks Kiln's servers, with what it read here.

The router and the plate survey are kiln-pro's.  A plain install used to
answer ``ROUTING_UNAVAILABLE`` at every tier (sold-reachable gate,
2026-10-06: the Business card sold fleet routing and no buyer with a plain
install could run it).  Now the door reads what only this machine can read
-- its printers as the registry sees them, each plate as it stands, the
job's own file -- and asks the served route (``plan_fleet_route``) for the
plan.  These tests pin the door's side of that wire with the server stood
in (public tests cannot import kiln-pro):

* every eligible printer is sent as a candidate, with one plate reading
  each, in the reading's shape, and never an address or an access code;
* the job's sliced file travels once, beside the readings, not once per
  machine;
* the server's plan, and its own rulings (``NO_ROOM`` with each machine's
  sentence, the tier gate), are relayed as they are;
* a call that got no answer is worded in the shared voice, says why, and
  routes nothing;
* ``plate_reading`` reads a clear plate, says when it cannot read one, and
  tells a contract for another machine apart from one for this machine
  without putting the identity on the wire;
* ``hosted_form`` carries each plate occupant's own file the way it carries
  the job's.
"""

