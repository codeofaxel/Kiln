"""Auto-wrap sliced gcode as a Bambu-compatible 3MF.

Bambu firmware ignores the ``gcode_file`` MQTT command for raw .gcode
files — it only starts prints via ``project_file`` on .3mf.  Before
this wire-up, calling ``slice_model(printer_id='bambu_a1', ...)``
returned raw gcode and the agent had to know the Bambu-specific calling
convention + manually invoke ``wrap_gcode_as_3mf`` before starting a
print.  The user caught this ("kiln shoulda known to send a 3mf
request").

These tests cover the new ``_auto_wrap_bambu_3mf`` helper that:
* detects a Bambu printer_id
* invokes the existing Bambu 3MF repackager
* returns both the raw gcode and the wrapped 3MF paths in the response
* fails gracefully (non-fatal warning) when the repackager errors
"""
from __future__ import annotations

from pathlib import Path

import pytest

from kiln.plugins.slicer_tools import _auto_wrap_bambu_3mf


def _write_dummy_gcode(tmp_path: Path) -> Path:
    """Write a minimal PrusaSlicer-style gcode so the repackager has
    something to read.  We don't care if the 3MF is valid for actual
    printing — only that the wrap logic fires for Bambu printer_ids.
    """
    p = tmp_path / "dummy.gcode"
    p.write_text(
        "; Generated by PrusaSlicer (test fixture)\n"
        "; layer_height = 0.2\n"
        "; filament_type = PLA\n"
        "G28\nG1 X0 Y0 Z0.2 F3000\nG1 X10 Y10 E0.5 F1200\n"
        "; estimated printing time (normal mode) = 30m 0s\n"
    )
    return p


class TestBambuIdDetection:
    def test_bambu_a1_triggers_wrap(self, tmp_path: Path, monkeypatch) -> None:
        gcode = _write_dummy_gcode(tmp_path)
        # Stub the repackager so we don't need valid Bambu 3MF format
        import kiln.printers.bambu_3mf as _b3mf
        captured = {}
        def fake_repackage(src, dst, source_3mf_path=None, **kwargs):
            captured["src"] = src
            captured["dst"] = dst
            Path(dst).write_bytes(b"PK\x03\x04fake3mf")
        monkeypatch.setattr(_b3mf, "repackage_gcode_as_bambu_3mf", fake_repackage)

        threemf, warning = _auto_wrap_bambu_3mf(
            str(gcode), effective_printer_id="bambu_a1", stl_path=None,
        )
        assert threemf is not None
        assert Path(threemf).exists()
        assert warning is None
        assert captured["src"] == str(gcode)

    def test_bambu_x1c_also_triggers_wrap(self, tmp_path: Path, monkeypatch) -> None:
        gcode = _write_dummy_gcode(tmp_path)
        import kiln.printers.bambu_3mf as _b3mf
        def ok(src, dst, **kwargs):
            Path(dst).write_bytes(b"PK\x03\x04")
        monkeypatch.setattr(_b3mf, "repackage_gcode_as_bambu_3mf", ok)

        threemf, _ = _auto_wrap_bambu_3mf(
            str(gcode), effective_printer_id="bambu_x1c", stl_path=None,
        )
        assert threemf is not None


