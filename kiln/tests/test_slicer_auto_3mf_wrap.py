class TestWrapFailureIsNonFatal:
    def test_repackager_exception_returns_warning_not_crash(
        self, tmp_path: Path, monkeypatch
    ) -> None:
        gcode = _write_dummy_gcode(tmp_path)
        import kiln.printers.bambu_3mf as _b3mf
        def boom(*args, **kwargs):
            raise RuntimeError("simulated repackage failure")
        monkeypatch.setattr(_b3mf, "build_bambu_3mf", boom)

        threemf, warning = _auto_wrap_bambu_3mf(
            str(gcode), effective_printer_id="bambu_a1", stl_path=None,
        )
        assert threemf is None
        assert warning is not None
        assert "auto-wrap failed" in warning.lower()


