"""A design version keeps the slicer's own print-time estimate of its slice.

Through the registered tools: a save handed the version's sliced file keeps
what that file says, the version reads it back in words, a diff says how it
moved, and a version that has no slice of its own says nothing.  The rebuild
cases slice for real and skip where this machine has no slicer.
"""

from __future__ import annotations

import json
import sys
import zipfile
from pathlib import Path
from typing import Any

import pytest

from kiln.slicer_estimate import (
    RECORD_KEY,
    estimate_change,
    estimate_sentence,
    keep_estimate,
    read_estimate,
)

_PRUSA_TAIL = (
    "; filament used [mm] = 1234.5\n"
    "; estimated printing time (normal mode) = {t}\n"
    "; estimated printing time (silent mode) = 9h 0m 0s\n"
)


def _gcode(path: Path, time_words: str | None, slicer: str = "PrusaSlicer 2.8.1") -> str:
    head = f"; generated by {slicer} on a computer\nG28\nG1 X10 Y10\n"
    tail = _PRUSA_TAIL.format(t=time_words) if time_words else "; no figures here\n"
    path.write_text(head + "G1 X20 Y20 E1\n" * 50 + tail, encoding="utf-8")
    return str(path)


def _sliced_3mf(path: Path, time_words: str) -> str:
    body = f"; generated by BambuStudio 02.02.00.85\n; model printing time: 2h; total estimated time: {time_words}\nG28\n"
    with zipfile.ZipFile(path, "w") as zf:
        zf.writestr("Metadata/plate_1.gcode", body)
    return str(path)


class _Mcp:
    def __init__(self) -> None:
        self.tools: dict[str, Any] = {}

    def tool(self, **_kwargs):
        def deco(fn):
            self.tools[fn.__name__] = fn
            return fn

        return deco


@pytest.fixture
def tools(monkeypatch, tmp_path) -> dict[str, Any]:
    """The version tools, against a library in *tmp_path*, on an install
    without kiln-pro (so what is asserted is public's own answer)."""
    from kiln.plugins.version_tools import _VersionToolsPlugin

    monkeypatch.setitem(sys.modules, "kiln_pro", None)
    monkeypatch.setattr("kiln.plugins.version_tools._DESIGNS_ROOT", str(tmp_path / "designs"))
    mcp = _Mcp()
    _VersionToolsPlugin().register(mcp)
    return mcp.tools


def _kept(tmp_path: Path, design_id: str, version: int) -> dict[str, Any]:
    path = tmp_path / "designs" / design_id / f".kiln_recipe.v{version}.json"
    return json.loads(path.read_text(encoding="utf-8"))


class TestTheReader:
    def test_a_gcode_states_its_seconds_and_its_slicer(self, tmp_path):
        estimate = read_estimate(_gcode(tmp_path / "a.gcode", "3h 1m 0s"))
        assert estimate == {"seconds": 3 * 3600 + 60, "slicer": "PrusaSlicer 2.8.1"}

    def test_a_sliced_3mf_states_its_plates_total(self, tmp_path):
        estimate = read_estimate(_sliced_3mf(tmp_path / "a.3mf", "2h 50m"))
        assert estimate is not None and estimate["seconds"] == 2 * 3600 + 50 * 60

    @pytest.mark.parametrize("name,body", [("a.stl", b"solid x\nendsolid x\n"), ("b.gcode", None)])
    def test_a_mesh_or_a_file_stating_no_time_states_nothing(self, tmp_path, name, body):
        path = tmp_path / name
        if body is None:
            _gcode(path, None)
        else:
            path.write_bytes(body)
        assert read_estimate(str(path)) is None
        assert read_estimate(str(tmp_path / "missing.gcode")) is None
        assert read_estimate(None) is None

    def test_keeping_replaces_a_stated_value_and_drops_one_no_file_backs(self, tmp_path):
        handed = {"tools_used": ["x"], RECORD_KEY: {"seconds": 5}}
        kept = keep_estimate(handed, _gcode(tmp_path / "a.gcode", "1h 0m 0s"))
        assert kept[RECORD_KEY]["seconds"] == 3600 and kept["tools_used"] == ["x"]
        assert keep_estimate(handed, None) == {"tools_used": ["x"]}
        assert keep_estimate({RECORD_KEY: {"seconds": 5}}, None) is None
        assert handed[RECORD_KEY] == {"seconds": 5}, "the caller's dict is not changed"


class TestTheWords:
    def test_one_version(self):
        assert estimate_sentence({RECORD_KEY: {"seconds": 10860}}) == "About 3h 1m, the slicer's estimate."
        assert estimate_sentence({}) is None
        assert estimate_sentence({RECORD_KEY: {"seconds": True}}) is None

    def test_a_change_names_both_figures_and_the_difference(self):
        a, b = {RECORD_KEY: {"seconds": 10200}}, {RECORD_KEY: {"seconds": 10860}}
        assert estimate_change(a, b) == (
            "The slicer's estimate went from about 2h 50m to about 3h 1m, 11m longer."
        )
        assert estimate_change(b, a).endswith("11m shorter.")
        assert estimate_change(a, {RECORD_KEY: {"seconds": 10230}}) == "The slicer's estimate stayed at about 2h 50m."

    def test_unknown_on_either_side_says_nothing(self):
        assert estimate_change({}, {RECORD_KEY: {"seconds": 10860}}) is None
        assert estimate_change({RECORD_KEY: {"seconds": 10860}}, None) is None

    def test_different_slicers_are_said(self):
        a = {RECORD_KEY: {"seconds": 3600, "slicer": "PrusaSlicer 2.8.1"}}
        b = {RECORD_KEY: {"seconds": 4200, "slicer": "OrcaSlicer 2.3.0"}}
        assert "different slicers" in estimate_change(a, b)


class TestThroughTheVersionTools:
    def test_a_save_with_its_slice_keeps_and_says_the_estimate(self, tools, tmp_path):
        r = tools["save_design_version"](
            design_id="bracket", scad_source="cube(10);", gcode_path=_gcode(tmp_path / "v1.gcode", "3h 1m 0s"),
        )
        assert r["ok"] is True, r
        assert r["version"]["print_time"] == "About 3h 1m, the slicer's estimate."
        assert _kept(tmp_path, "bracket", 1)["provenance"][RECORD_KEY]["seconds"] == 10860

    def test_a_save_with_no_slice_keeps_and_says_nothing(self, tools, tmp_path):
        r = tools["save_design_version"](
            design_id="bracket", scad_source="cube(10);",
            provenance={RECORD_KEY: {"seconds": 60}, "tools_used": ["openscad"]},
        )
        assert r["ok"] is True, r
        assert "print_time" not in r["version"]
        assert RECORD_KEY not in (_kept(tmp_path, "bracket", 1).get("provenance") or {})

    def test_get_list_and_diff_say_it_and_a_new_version_never_inherits_it(self, tools, tmp_path):
        tools["save_design_version"](
            design_id="bracket", scad_source="cube(10);", gcode_path=_gcode(tmp_path / "v1.gcode", "2h 50m 0s"),
        )
        tools["save_design_version"](
            design_id="bracket", scad_source="cube(12);", gcode_path=_gcode(tmp_path / "v2.gcode", "3h 1m 0s"),
        )
        tools["save_design_version"](design_id="bracket", scad_source="cube(14);")

        got = tools["get_design_version"](version_id="bracket:2")
        assert got["version"]["print_time"] == "About 3h 1m, the slicer's estimate."
        third = tools["get_design_version"](version_id="bracket:3")
        assert "print_time" not in third["version"], "the parent's slice is not the child's"
        assert RECORD_KEY not in (third["version"]["provenance"] or {})

        listed = {v["version"]: v for v in tools["list_design_versions"](design_id="bracket")["versions"]}
        assert listed[1]["print_time"] == "About 2h 50m, the slicer's estimate."
        assert "print_time" not in listed[3]

        diff = tools["diff_design_versions"](version_id_a="bracket:1", version_id_b="bracket:2")
        assert diff["print_time_change"] == (
            "The slicer's estimate went from about 2h 50m to about 3h 1m, 11m longer."
        )
        unknown = tools["diff_design_versions"](version_id_a="bracket:2", version_id_b="bracket:3")
        assert "print_time_change" not in unknown

    def test_a_rollback_states_no_slice_of_its_own(self, tools, tmp_path):
        tools["save_design_version"](
            design_id="bracket", scad_source="cube(10);", gcode_path=_gcode(tmp_path / "v1.gcode", "1h 0m 0s"),
        )
        tools["save_design_version"](design_id="bracket", scad_source="cube(12);")
        r = tools["rollback_design_version"](design_id="bracket", to_version_id="1")
        assert r["ok"] is True, r
        restored = tools["get_design_version"](version_id=f"bracket:{r['version']['version']}")
        assert "print_time" not in restored["version"]


def _slicer_available() -> bool:
    try:
        from kiln.slicer import find_slicer

        find_slicer()
        return True
    except Exception:
        return False


@pytest.mark.skipif(not _slicer_available(), reason="no PrusaSlicer/OrcaSlicer installed")
class TestRebuildKeepsItsSlicesEstimate:
    @pytest.fixture
    def rebuild(self):
        from kiln.plugins.design_rebuild_tools import plugin

        captured: dict[str, Any] = {}

        class _M:
            def tool(self, *a, **kw):
                def deco(fn):
                    captured[fn.__name__] = fn
                    return fn

                return deco

        plugin.register(_M())

        def call(**kw):
            out = captured["rebuild_design"](**kw)
            return next(x for x in out if isinstance(x, dict)) if isinstance(out, list) else out

        return call

    @pytest.mark.parametrize("n_parts", [1, 2])
    def test_a_mesh_rebuild(self, rebuild, tmp_path, n_parts):
        sys.path.insert(0, str(Path(__file__).parent))
        from test_design_rebuild_tools import _load, _make_mesh_recipe

        d = _make_mesh_recipe(tmp_path, n_parts)
        r = rebuild(recipe_path=str(d))
        assert r["status"] == "success", r
        seconds = _load(d).provenance[RECORD_KEY]["seconds"]
        assert seconds > 0
        assert r["print_time"] == estimate_sentence({RECORD_KEY: {"seconds": seconds}})

    def test_a_parametric_rebuild(self, rebuild, tmp_path):
        import shutil

        if shutil.which("openscad") is None:
            pytest.skip("no OpenSCAD installed")
        sys.path.insert(0, str(Path(__file__).parent))
        from test_design_rebuild_tools import _load, _make_parametric_recipe

        d = _make_parametric_recipe(tmp_path, parameters={"size": 20})
        r = rebuild(recipe_path=str(d))
        assert r["status"] == "success", r
        assert _load(d).provenance[RECORD_KEY]["seconds"] > 0
        assert r["print_time"].endswith("the slicer's estimate.")
