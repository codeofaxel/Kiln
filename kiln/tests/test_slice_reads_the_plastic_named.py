@pytest.fixture
def t_part(tmp_path: Path) -> str:
    """A T on its stem: an arm that needs supports."""
    from trimesh.creation import box

    stem = box(extents=(10, 10, 40))
    stem.apply_translation((0, 0, 20))
    arm = box(extents=(60, 10, 8))
    arm.apply_translation((0, 0, 44))
    path = tmp_path / "t.stl"
    trimesh.util.concatenate([stem, arm]).export(path)
    return str(path)


def _slice(part: str, material: str) -> dict[str, Any]:
    from kiln import server

    out = asyncio.run(server.mcp.call_tool("slice_model", {"input_path": part, "material": material}))
    if isinstance(out, tuple):
        out = out[0]
    blocks = out if isinstance(out, list) else out.content
    return json.loads(blocks[0].text)


def test_a_name_kiln_cannot_place_is_said_to_be_one(asks, t_part, stand_in_slicer):
    reply = _slice(t_part, UNPLACED)
    assert reply.get("success") is True, reply
    assert set(asks) == {UNPLACED.lower()}, asks
    assert json.dumps(reply).count(json.dumps(material_limits.UNRECOGNISED)[1:-1]) == 1


@pytest.mark.parametrize("named", ["TPU 85A", "PLA-ESD"])
def test_a_plastic_with_a_family_row_is_read_as_itself_alone(asks, t_part, stand_in_slicer, named):
    reply = _slice(t_part, named)
    assert reply.get("success") is True, reply
    assert set(asks) == {named.lower()}, asks
