"""A slice's support decision reads the plastic named, as every other check does.

The slice decides supports from the plastic's design limits.  It reads the
word the person named for the slice (else the spool the printer reports
loaded), never the material table's row for it: a name Kiln's design limits
cannot place is said to be one, as on every other check, and a grade the
table files under its family's row (TPU 85A, PLA-ESD) is read as itself
alone.  Through the real tool dispatcher on an install without kiln-pro,
with Kiln's servers and the slicer binary stood in.
"""

from __future__ import annotations

import asyncio
import json
import sys
from pathlib import Path
from types import SimpleNamespace
from typing import Any

import pytest

trimesh = pytest.importorskip("trimesh")

from kiln import material_limits  # noqa: E402

#: A name Kiln's design limits cannot place.
UNPLACED = "ABS+"


def _forget() -> None:
    from kiln import _pro_material_limits_bridge as bridge

    material_limits._answers.clear()
    material_limits._said.clear()
    bridge._service_down_until, bridge._service_down_miss = 0.0, None


def _figure(value: float | None, unit: str = "mm", basis: str = "general") -> dict[str, Any]:
    return {"value": value, "unit": unit, "basis": basis}


@pytest.fixture(autouse=True)
def _plain_install(monkeypatch):
    monkeypatch.setitem(sys.modules, "kiln_pro", None)
    _forget()
    yield
    _forget()


@pytest.fixture
def asks(monkeypatch) -> list[str]:
    """The plastic of every design-limits ask a door makes, answered: the
    unplaced name as unknown, any other as known."""
    import kiln.server as srv

    seen: list[str] = []

    def fake(tool_name, _timeout=None, _asked_by_user=True, _feature=None, **kwargs):
        if tool_name != "material_limits":
            return {"success": False, "code": "UNKNOWN_TOOL", "error": "not stood in"}
        if "quantities" in kwargs:
            return {
                "success": True, "known": False, "material_id": None, "limits": {
                    "sliced_wall_min_mm": _figure(0.19), "sliced_pin_min_mm": _figure(0.8),
                },
            }
        name = str(kwargs.get("material")).lower()
        seen.append(name)
        known = name != UNPLACED.lower()
        return {
            "success": True, "status": "ok", "known": known, "material_id": name if known else None,
            "limits": {
                "overhang_unsupported_deg": _figure(45.0, "deg"),
                "bridge_max_mm": _figure(10.0),
                "wall_recommended_mm": _figure(1.2),
                "pin_min_mm": _figure(3.0),
                "esd_wall_min_mm": _figure(None, basis="not_applicable"),
            },
            "note": "",
        }

    monkeypatch.setattr(srv, "_pro_api_call", fake)
    return seen


