def _wrap(tmp_path: Path, body: str, **kw) -> zipfile.ZipFile:
    out = tmp_path / "out.3mf"
    build_bambu_3mf(body, str(out), **kw)
    return zipfile.ZipFile(out)


class TestMulticolorWrap:
    def test_slice_info_declares_every_filament(self, tmp_path):
        zf = _wrap(tmp_path, _MULTICOLOR_GCODE)
        info = zf.read("Metadata/slice_info.config").decode()
        entries = re.findall(r'<filament id="(\d+)"[^>]*color="([^"]+)"', info)
        assert entries == [
            ("1", "#F2F2F2"), ("2", "#D32F2F"), ("3", "#1A1A1A"),
        ]

    def test_filament_sequence_covers_every_slot(self, tmp_path):
        zf = _wrap(tmp_path, _MULTICOLOR_GCODE)
        seq = zf.read("Metadata/filament_sequence.json").decode()
        assert '"filament_sequence": [0, 1, 2]' in seq

    def test_tool_changes_get_ams_blocks(self, tmp_path):
        """Without M620/M621 around each T, the printer changes tool and
        keeps extruding the filament already loaded."""
        zf = _wrap(tmp_path, _MULTICOLOR_GCODE)
        body = zf.read("Metadata/plate_1.gcode").decode(errors="replace")
        assert body.count("M620") >= 3
        assert body.count("M621") >= 3

    def test_declared_types_survive(self, tmp_path):
        zf = _wrap(tmp_path, _MULTICOLOR_GCODE)
        info = zf.read("Metadata/slice_info.config").decode()
        assert 'type="PETG"' in info

    def test_explicit_settings_win_over_the_gcode(self, tmp_path):
        """A caller that already knows its filaments is not overridden."""
        zf = _wrap(
            tmp_path,
            _MULTICOLOR_GCODE,
            settings=BambuPrintSettings(
                num_filaments=2, filament_colors=["#123456", "#654321"],
            ),
        )
        info = zf.read("Metadata/slice_info.config").decode()
        colors = re.findall(r'<filament id="\d+"[^>]*color="([^"]+)"', info)
        assert colors == ["#123456", "#654321"]


class TestSingleFilamentUnchanged:
    """The regression guard: an ordinary one-color wrap is untouched."""

    def test_single_filament_declares_one(self, tmp_path):
        zf = _wrap(tmp_path, _layers(3, tools=[0]))
        info = zf.read("Metadata/slice_info.config").decode()
        assert len(re.findall(r"<filament id=", info)) == 1
        seq = zf.read("Metadata/filament_sequence.json").decode()
        assert '"filament_sequence": [0]' in seq

    def test_toolless_gcode_declares_one(self, tmp_path):
        zf = _wrap(tmp_path, _layers(3))
        info = zf.read("Metadata/slice_info.config").decode()
        assert len(re.findall(r"<filament id=", info)) == 1

    def test_single_filament_gets_no_extra_ams_blocks(self, tmp_path):
        """Bambu's own start/end gcode carries a couple of M620s (initial
        load, return-to-AMS), so the honest measure is the DIFFERENCE: a
        one-tool body must add none beyond what a toolless body has, and
        a three-tool body must add several."""

        def m620s(body: str) -> int:
            zf = _wrap(tmp_path, body)
            return zf.read("Metadata/plate_1.gcode").decode(
                errors="replace"
            ).count("M620")

        baseline = m620s(_layers(3))
        assert m620s(_layers(3, tools=[0])) == baseline
        assert m620s(_MULTICOLOR_GCODE) > baseline
