def _text(path: str) -> str:
    return pathlib.Path(path).read_text(encoding="utf-8", errors="replace")


def _commands(text: str) -> list[str]:
    """Every line a printer acts on: comments and blank lines dropped."""
    out = []
    for line in text.splitlines():
        code = line.split(";", 1)[0].strip()
        if code:
            out.append(code)
    return out


def _slice_here(home, name: str = "part.gcode", *, text: str = GCODE) -> tuple[str, str]:
    """A slice through the tail both slice runners share."""
    from kiln import print_lineage
    from kiln.slicer import _record_slice

    model = _cube_stl(home / "part.stl")
    out = home / "sliced" / name
    out.parent.mkdir(exist_ok=True)
    out.write_text(text, encoding="utf-8")
    _record_slice("prusa_mk4.ini", model, str(out))
    print_lineage.flush()
    return model, str(out)


def _fake_adapter():
    from kiln.printers.base import PrinterAdapter, PrintResult

    class _Fake(PrinterAdapter):
        name = "fake-printer"

        def declared_printer_model(self) -> str:
            return "Prusa MK4"

        def _start_print_impl(self, file_name: str, **kwargs: Any) -> PrintResult:
            return PrintResult(success=True, message="started")

        def connect(self): ...
        def disconnect(self): ...
        def get_status(self): ...
        def get_printer_info(self): ...
        def list_files(self): ...
        def upload_file(self, file_path): ...
        def cancel_print(self): ...
        def pause_print(self): ...
        def resume_print(self): ...

    _Fake.__abstractmethods__ = frozenset()
    return _Fake()


def _open_row(printer: str = "fake-printer") -> dict[str, Any]:
    from kiln.persistence import get_db

    rows = get_db().list_unresolved_outcomes(printer_name=printer)
    assert len(rows) == 1
    return rows[0]


class TestTheStamp:
    def test_it_changes_no_command_line(self, home):
        """Mutation pin: a stamp written without its leading ``;`` fails here."""
        from kiln import print_lineage

        _model, out = _slice_here(home)
        after = _text(out)
        assert _commands(after) == _commands(GCODE)
        assert after.startswith(GCODE), "the slicer's own bytes are kept, in order"
        added = after[len(GCODE):].splitlines()
        assert len(added) == 1 and added[0].startswith("; kiln_lineage = ")
        assert print_lineage.read_stamps(out) == [added[0].split("= ")[1]]

    def test_a_file_with_no_final_newline_keeps_its_last_command(self, home):
        _model, out = _slice_here(home, text="G28\nG1 X5 Y5 E1")
        assert _commands(_text(out)) == ["G28", "G1 X5 Y5 E1"]

    def test_it_survives_the_printer_package(self, home):
        from unittest.mock import patch

        from kiln import print_lineage
        from kiln.monitor_twin import note_wrapped
        from kiln.printers.bambu_3mf import build_bambu_3mf

        _model, out = _slice_here(home)
        stamp = print_lineage.read_stamps(out)
        wrap = str(home / "sliced" / "part.gcode.3mf")
        with patch("kiln.printers.bambu_3mf._load_a1_start_gcode", return_value="; start\nG28\n"), \
             patch("kiln.printers.bambu_3mf._select_end_gcode", return_value=("; end\nM84\n", "bambu_a1")):
            build_bambu_3mf(_text(out), wrap)
        note_wrapped(out, wrap)
        assert print_lineage.read_stamps(wrap) == stamp
        # By the stamp, from a copy under another name.
        renamed = str(home / "renamed.gcode.3mf")
        shutil.copy(wrap, renamed)
        by_stamp = print_lineage.resolve("renamed.gcode.3mf", local_paths=[renamed])
        assert (by_stamp["matched_by"], by_stamp["lineage_id"]) == ("stamp", stamp[0])
        # By the package's name alone, the way a start by name asks.
        by_name = print_lineage.resolve("part.gcode.3mf")
        assert (by_name["matched_by"], by_name["lineage_id"]) == ("name", stamp[0])


class TestSliceThenPrintThenFinish:
    def test_the_row_knows_its_slice_and_the_ending_its_part(self, home, monkeypatch):
        """Mutation pins: without ``record_slice`` at the slice tail, or
        without ``resolve`` in the start's identity, this fails."""
        from kiln import community_outbox, print_lineage
        from kiln.auto_record_hook import reconcile_pending_outcomes
        from kiln.print_dna import fingerprint_model

        model, out = _slice_here(home)
        os.remove(model)  # the record holds the part, not a path to it
        os.remove(out)
        assert _fake_adapter().start_print("part.gcode").success
        row = _open_row()
        assert row["part_source"] == print_lineage.PART_SLICED_HERE
        assert row["lineage_id"] == print_lineage.resolve("part.gcode")["lineage_id"]

        sent: list[dict[str, Any]] = []
        monkeypatch.setattr(community_outbox, "contribute", lambda key, record, **kw: sent.append(record) or {"queued": True})
        monkeypatch.setattr(print_lineage, "SHARE_SLICE_SIGNATURES", True)
        resolved = reconcile_pending_outcomes(
            printer_name="fake-printer", gcode_state="finish", current_job_label="part.gcode",
        )
        assert [r["outcome"] for r in resolved] == ["success"]
        expected = fingerprint_model(_cube_stl(home / "again.stl"))
        assert len(sent) == 1
        assert sent[0]["geometric_signature"] == expected.geometric_signature
        assert sent[0]["geometric_signature_v2"] == expected.geometric_signature_v2
        # What leaves is the fields it always was: no name, no hash of a file.
        assert set(sent[0]) == {
            "geometric_signature", "geometric_signature_v2", "printer_model", "material", "outcome",
            "print_time_seconds",
        }

    def test_nothing_new_is_shared_while_the_wording_switch_is_off(self, home, monkeypatch):
        from kiln import community_outbox, print_lineage
        from kiln.auto_record_hook import reconcile_pending_outcomes

        assert print_lineage.SHARE_SLICE_SIGNATURES is False
        _slice_here(home)
        _fake_adapter().start_print("part.gcode")
        sent: list[Any] = []
        monkeypatch.setattr(community_outbox, "contribute", lambda key, record, **kw: sent.append(record) or {})
        reconcile_pending_outcomes(printer_name="fake-printer", gcode_state="finish", current_job_label="part.gcode")
        assert sent == []
        assert print_lineage.signatures_for("part.gcode")[0], "the part is known here all the same"

    def test_a_later_slice_to_the_same_name_does_not_take_the_ending(self, home):
        from kiln import print_lineage
        from kiln.slicer import _record_slice

        _model, out = _slice_here(home)
        first = print_lineage.signatures_for("part.gcode")
        _fake_adapter().start_print("part.gcode")
        other = _cube_stl(home / "other.stl", size=25.0)
        _record_slice("prusa_mk4.ini", other, out)
        print_lineage.flush()
        assert print_lineage.signatures_for("part.gcode") == first

    def test_an_unknown_ending_shares_nothing(self, home, monkeypatch):
        from kiln import community_outbox, print_lineage
        from kiln.auto_record_hook import reconcile_pending_outcomes

        _slice_here(home)
        _fake_adapter().start_print("part.gcode")
        sent: list[Any] = []
        monkeypatch.setattr(community_outbox, "contribute", lambda key, record, **kw: sent.append(record) or {})
        monkeypatch.setattr(print_lineage, "SHARE_SLICE_SIGNATURES", True)
        resolved = reconcile_pending_outcomes(printer_name="fake-printer", gcode_state="idle")
        assert [r["outcome"] for r in resolved] == ["unknown"] and sent == []


class TestAFileKilnDidNotSlice:
    def test_it_opens_a_row_marked_no_model_with_what_the_file_states(self, home):
        from kiln import print_lineage

        foreign = home / "from_elsewhere.gcode"
        foreign.write_text(GCODE, encoding="utf-8")
        assert _fake_adapter().start_print("from_elsewhere.gcode", local_file_path=str(foreign)).success
        row = _open_row()
        assert row["part_source"] == print_lineage.PART_NO_MODEL and row["lineage_id"]
        answer = print_lineage.resolve("from_elsewhere.gcode")
        assert answer["part"] == print_lineage.PART_NO_MODEL and answer["signature"] == ""
        stated = answer["stated"]
        assert stated["material"] == "PETG"
        assert stated["layer_height_mm"] == 0.2
        assert stated["nozzle_temp_c"] == 215 and stated["bed_temp_c"] == 60
        assert stated["size_mm"] == {"x": 20.0, "y": 15.0, "z": 0.4}
        assert foreign.read_text(encoding="utf-8") == GCODE, "a file Kiln did not slice is never written to"
        assert print_lineage.signatures_for("from_elsewhere.gcode") == ("", "")

    def test_a_second_print_of_it_keeps_one_record(self, home):
        from kiln import print_lineage

        foreign = home / "f.gcode"
