"""A sliced file remembers the part it is a print of, and every start asks.

What these pin, through the chokepoints every door shares (the slice
runners' tail, the wrap note, ``PrinterAdapter.start_print``) with a fake
printer:

- a slice stamps its output without changing one command line of it, and
  the stamp survives the printer package the G-code is wrapped into;
- a print of that file, started by its printer-side name alone, opens a row
  that knows which slice it is, and its ending resolves to the model's
  shape signature (handed to sharing only when the wording switch is on);
- a G-code Kiln did not slice still opens a row, marked as having no model,
  with what the file itself states;
- a dirty file states nothing rather than a guess or a non-finite number;
- every door that starts a print reaches the one resolver.

A/B: this file does not import on the tree before ``kiln.print_lineage``;
the mutation pins are named beside the tests they belong to.
"""

