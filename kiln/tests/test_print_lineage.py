class TestADirtyFile:
    @pytest.mark.parametrize("data", DIRTY, ids=["empty", "binary", "nan_inf", "half_words", "huge_word", "cut_off"])
    def test_it_states_nothing_rather_than_a_guess(self, home, data):
        from kiln import print_lineage

        path = home / "dirty.gcode"
        path.write_bytes(data)
        facts = print_lineage.stated_facts(str(path))
        json.dumps(facts, allow_nan=False)  # no nan or inf anywhere
        for key in ("layer_height_mm", "nozzle_temp_c", "bed_temp_c"):
            assert facts[key] is None or (math.isfinite(facts[key]) and facts[key] > 0)
        for word in ("material", "printer_model", "slicer"):
            assert facts[word] is None or len(facts[word]) <= 80
        for value in (facts["size_mm"] or {}).values():
            assert math.isfinite(value) and value > 0
        # And the print it belongs to is judged by the start gate as any
        # other file is; one that starts still gets its row.
        result = _fake_adapter().start_print("dirty.gcode", local_file_path=str(path))
        assert result.success or result.refused_before_send
        if result.success:
            assert _open_row()["part_source"] == print_lineage.PART_NO_MODEL

    def test_the_two_files_that_say_nothing_say_nothing(self, home):
        from kiln import print_lineage

        for data in DIRTY[:2]:
            path = home / "blank.gcode"
            path.write_bytes(data)
            facts = print_lineage.stated_facts(str(path))
            assert all(value is None for value in facts.values()), facts

    def test_a_corrupt_store_is_an_empty_store(self, home):
        from kiln import print_lineage

        print_lineage.store_path().parent.mkdir(parents=True, exist_ok=True)
        print_lineage.store_path().write_text("{not json", encoding="utf-8")
        assert print_lineage.resolve("x.gcode")["part"] == print_lineage.PART_UNKNOWN
        _slice_here(home)
        assert print_lineage.resolve("part.gcode")["part"] == print_lineage.PART_SLICED_HERE


class TestEveryDoor:
    def test_every_start_door_calls_the_template_that_asks(self):
        """The doors are read from the source (``kiln.print_doors``); each
        starts a print by calling ``start_print`` on an adapter, and no
        adapter overrides that template, so each reaches the one resolver."""
        import ast

        import kiln
        from kiln.print_doors import enumerate_print_doors

        starts = [d for d in enumerate_print_doors() if d.kind == "start"]
        assert len(starts) >= 10, "the walk found the doors"
        printers = pathlib.Path(kiln.__file__).parent / "printers"
        overriding = []
        for path in printers.glob("*.py"):
            tree = ast.parse(path.read_text(encoding="utf-8"))
            for cls in (n for n in ast.walk(tree) if isinstance(n, ast.ClassDef)):
                if cls.name == "PrinterAdapter":
                    continue
                overriding += [
                    f"{path.name}:{cls.name}" for fn in cls.body
                    if isinstance(fn, ast.FunctionDef) and fn.name == "start_print"
                ]
        assert overriding == [], f"an adapter overrides the start template: {overriding}"

    def test_the_template_asks_the_one_resolver(self, home, monkeypatch):
        from kiln import print_lineage

        asked: list[str] = []
        real = print_lineage.resolve
        monkeypatch.setattr(
            print_lineage, "resolve", lambda name, **kw: asked.append(name) or real(name, **kw)
        )
        _fake_adapter().start_print("any.gcode")
        assert asked == ["any.gcode"]

    def test_the_contribution_resolver_asks_it_too(self, home, monkeypatch):
        from kiln import community_autofire, print_lineage

        _slice_here(home)
        assert community_autofire.geometric_signatures_for("part.gcode") == ("", "")
        monkeypatch.setattr(print_lineage, "SHARE_SLICE_SIGNATURES", True)
        assert community_autofire.geometric_signatures_for("part.gcode") == print_lineage.signatures_for("part.gcode")
        assert community_autofire.geometric_signatures_for("part.gcode")[0]

    def test_the_shared_server_keeps_no_record(self, home, monkeypatch):
        from kiln import print_lineage

        monkeypatch.setattr(print_lineage, "_hosted", lambda: True)
        model = _cube_stl(home / "h.stl")
        out = home / "h.gcode"
        out.write_text(GCODE, encoding="utf-8")
        assert print_lineage.record_slice(model, str(out)) is None
        assert out.read_text(encoding="utf-8") == GCODE
        assert not print_lineage.store_path().exists()
        assert print_lineage.resolve("h.gcode", local_paths=[str(out)])["part"] == print_lineage.PART_UNKNOWN


def _find(names: tuple[str, ...], mac: str) -> str | None:
    for name in names:
        found = shutil.which(name)
        if found:
            return found
    return mac if os.path.isfile(mac) and os.access(mac, os.X_OK) else None


_PRUSA = _find(("prusa-slicer", "PrusaSlicer", "prusaslicer"), "/Applications/PrusaSlicer.app/Contents/MacOS/PrusaSlicer")


@pytest.mark.skipif(_PRUSA is None, reason="PrusaSlicer not installed")
class TestARealSlice:
    def test_the_stamp_rides_a_real_slice_and_moves_nothing(self, home, monkeypatch):
        from kiln import print_lineage
        from kiln.slicer import slice_file

        # ASCII: the slicer reads a binary STL of round numbers as text.
        binary = _cube_stl(home / "cube_bin.stl", size=12.0)
        import struct as _struct

        raw = pathlib.Path(binary).read_bytes()[84:]
        lines = ["solid cube"]
        for i in range(0, len(raw), 50):
            f = _struct.unpack("<12f", raw[i:i + 48])
            lines.append(" facet normal 0 0 0\n  outer loop")
            lines += [f"   vertex {f[j]:g} {f[j + 1]:g} {f[j + 2]:g}" for j in (3, 6, 9)]
            lines.append("  endloop\n endfacet")
        lines.append("endsolid cube")
        (home / "cube.stl").write_text("\n".join(lines) + "\n", encoding="ascii")
        model = str(home / "cube.stl")
        plain_dir, stamped_dir = home / "plain", home / "stamped"
        with monkeypatch.context() as off:
            off.setattr(print_lineage, "record_slice", lambda *a, **k: None)
            plain = slice_file(model, output_dir=str(plain_dir), slicer_path=_PRUSA)
        stamped = slice_file(model, output_dir=str(stamped_dir), slicer_path=_PRUSA)
        print_lineage.flush()
        assert plain.success and stamped.success
        before = _text(plain.output_path)
        after = _text(stamped.output_path)
        assert print_lineage.read_stamps(plain.output_path) == []
        assert len(print_lineage.read_stamps(stamped.output_path)) == 1
        assert _commands(after) == _commands(before)
        answer = print_lineage.resolve(os.path.basename(stamped.output_path), local_paths=[stamped.output_path])
        assert answer["matched_by"] == "stamp" and answer["signature"]
        assert answer["stated"]["layer_height_mm"]
