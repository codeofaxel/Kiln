"""How long prints really take on a printer, learned from its own prints.

Every print Kiln starts carries the slicer's time for its file from the
START (the one event Kiln always sees), and how long it really printed from
an ending Kiln can vouch for.  A printer's pace is the middle of the last
twenty real-over-slicer readings, and every door that states a print time
says it through :mod:`kiln.learned_print_time`.

Pinned here, through the real adapter template, the real lifecycle and the
real database:

* the start writes the slicer's time onto the row it opens;
* a watched ending writes the real length; a late reading a stopwatch kept
  counting writes nothing (the rule the hours counter already keeps);
* only finished prints teach: cancelled, failed, unknown and wild readings
  are left out, and fewer than three prints are said as the slicer's time;
* the doors: an estimate of a file, the live status, the repaired progress
  tool, and the copies plan's times sent to Kiln's servers.
"""

