def test_the_start_writes_the_slicers_time_on_the_row_it_opens(kiln_env):
    adapter = _Adapter()
    assert adapter.start_print(_gcode(kiln_env, seconds=5400)).success

    row = _row()
    assert row["outcome"] == "pending"
    assert row["estimated_seconds"] == 5400


def test_a_watched_ending_writes_how_long_it_really_printed(kiln_env):
    adapter = _Adapter()
    adapter.start_print(_gcode(kiln_env, seconds=3600))

    _watch_to_the_end(adapter, elapsed=4200)

    row = _row()
    assert row["outcome"] == "success"
    assert row["determined_by"] == "observed"
    assert (row["estimated_seconds"], row["print_seconds"]) == (3600, 4200)


def test_a_late_reading_from_a_stopwatch_teaches_nothing(kiln_env):
    """The hours counter's own rule: a stopwatch noticed late kept counting
    after the print ended, so its number is no print's length."""
    adapter = _Adapter()
    adapter._DURATION_SEMANTICS = "stopwatch"
    adapter.start_print(_gcode(kiln_env, seconds=3600))

    _watch_to_the_end(adapter, elapsed=9000, gap_seconds=3 * 3600)

    row = _row()
    assert row["estimated_seconds"] == 3600
    assert row["print_seconds"] is None


def test_a_file_kiln_cannot_read_leaves_no_estimate(kiln_env):
    adapter = _Adapter()
    adapter.start_print("only_on_the_printer.gcode")

    assert _row()["estimated_seconds"] is None


