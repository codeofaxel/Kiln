def test_the_pace_is_the_middle_of_finished_prints_only(kiln_env):
    _seed("voron", [
        (3600, 3960, "success"),   # 1.10
        (7200, 7920, "success"),   # 1.10
        (3600, 4320, "success"),   # 1.20
        (3600, 18000, "success"),  # 5.0: a print left paused overnight
        (3600, 1200, "cancelled"),
        (3600, 2000, "failed"),
        (3600, None, "unknown"),
        (120, 600, "success"),     # too short to say anything about pace
    ])

    pace = lpt.pace_for("voron")

    assert pace is not None
    assert pace.prints == 3
    assert pace.factor == pytest.approx(1.10)


def test_fewer_than_three_prints_are_said_as_the_slicers_time(kiln_env):
    _seed("voron", [(3600, 4320, "success"), (3600, 4320, "success")])

