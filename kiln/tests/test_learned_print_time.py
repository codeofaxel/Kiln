def test_the_pace_is_the_middle_of_finished_prints_only(kiln_env):
    _seed("voron", [
        (3600, 3960, "success"),   # 1.10
        (7200, 7920, "success"),   # 1.10
        (3600, 4320, "success"),   # 1.20
        (3600, 18000, "success"),  # 5.0: a print left paused overnight
        (3600, 1200, "cancelled"),
        (3600, 2000, "failed"),
        (3600, None, "unknown"),
        (120, 600, "success"),     # too short to say anything about pace
    ])

    pace = lpt.pace_for("voron")

    assert pace is not None
    assert pace.prints == 3
    assert pace.factor == pytest.approx(1.10)


def test_fewer_than_three_prints_are_said_as_the_slicers_time(kiln_env):
    _seed("voron", [(3600, 4320, "success"), (3600, 4320, "success")])

    said = lpt.learned_time(3600, "voron")

    assert said["learned"] is False
    assert said["seconds"] == 3600
    assert said["prints"] == 2
    assert "slicer's estimate" in said["said"] and "(2 so far)" in said["said"]


def test_three_prints_correct_the_slicer_and_say_from_how_many(kiln_env):
    _seed("voron", [(3600, 3960, "success")] * 3)

    said = lpt.learned_time(3600, "voron")

    assert said["learned"] is True
    assert said["seconds"] == 3960
    assert said["said"] == "About 1h 6m, from your last 3 prints on voron (the slicer says 1h 0m)."


def test_another_printers_prints_say_nothing_about_this_one(kiln_env):
    _seed("bambu", [(3600, 7000, "success")] * 5)

    assert lpt.pace_for("voron") is None


def test_on_kilns_servers_nothing_is_learned(kiln_env, monkeypatch):
    _seed("voron", [(3600, 3960, "success")] * 3)
    monkeypatch.setattr(lpt, "_hosted", lambda: True)

    assert lpt.pace_for("voron") is None
    assert lpt.learned_time_left("voron", 100) is None


