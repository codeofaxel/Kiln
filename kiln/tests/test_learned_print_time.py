def test_a_reprint_resliced_elsewhere_keeps_each_prints_own_slicer(kiln_env):
    """Same file name, sliced again in another slicer: each start's row says
    what made ITS file, and the older row is never rewritten."""
    adapter = _Adapter()
    path = _bambu_gcode(kiln_env, name="plate.gcode")
    adapter.start_print(path)
    _watch_to_the_end(adapter, elapsed=3700)

    with open(path, "w") as fh:
        fh.write("; generated by OrcaSlicer 2.3.2 on 2026-10-26 at 12:00:00\n; total estimated time: 1h 0m 0s\nG28\n")
    adapter.start_print(path)

    from kiln.persistence import get_db

    rows = get_db()._conn.execute(
        "SELECT outcome, slicer_name, slicer_version FROM print_outcomes ORDER BY id"
    ).fetchall()
    assert [r["outcome"] for r in rows] == ["success", "pending"]
    assert [(r["slicer_name"], r["slicer_version"]) for r in rows] == [
        ("BambuStudio", "02.06.00.51"),
        ("OrcaSlicer", "2.3.2"),
    ]
