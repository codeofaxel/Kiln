def test_an_estimate_of_a_file_says_the_only_printers_real_time(kiln_env, estimate_tools, monkeypatch):
    import kiln.server as _srv

    monkeypatch.setattr(_srv, "_check_auth", lambda *_a, **_k: None)
    monkeypatch.setattr("kiln.assumed_nozzle._registered_machines", lambda: ["voron"])
    _seed("voron", [(3600, 3960, "success")] * 4)

    out = estimate_tools["estimate_print_time"](file_path=_gcode(kiln_env, seconds=7200))

    assert out["success"] is True
    assert out["estimated_time_seconds"] == 7200
    assert out["learned_time"]["seconds"] == 7920
    assert out["learned_time"]["said"].startswith("About 2h 12m, from your last 4 prints on voron, the only printer")


def _running(kiln_env, *, slicer: int, elapsed: int) -> _Adapter:
    adapter = _Adapter()
    adapter.start_print(_gcode(kiln_env, name="running.gcode", seconds=slicer))
    adapter.elapsed_seconds = elapsed
    adapter.left_seconds = slicer - elapsed
    return adapter


def test_the_status_door_says_when_the_print_should_really_end(kiln_env):
    _seed("voron", [(3600, 4320, "success")] * 3)  # runs 20% long
    adapter = _running(kiln_env, slicer=3600, elapsed=1800)

    from unittest.mock import patch

    from kiln.server import printer_status

    with patch("kiln.server._get_adapter", return_value=adapter):
        out = printer_status()

    job = out["job"]
    assert job["print_time_left_seconds"] == 1800  # the printer's own countdown, as it said it
    assert job["learned_time_left"]["seconds_left"] == 4320 - 1800
    assert job["learned_time_left"]["said"] == "About 42m left, from your last 3 prints on voron."


