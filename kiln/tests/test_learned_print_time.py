def _gcode(tmp_path, name: str = "bracket.gcode", seconds: int = 3600) -> str:
    h, rest = divmod(seconds, 3600)
    m, s = divmod(rest, 60)
    path = tmp_path / name
    path.write_text(
        "; generated by PrusaSlicer 2.8.1\n"
        "G1 X0 Y0\n"
        f"; estimated printing time (normal mode) = {h}h {m}m {s}s\n"
    )
    return str(path)


class _Adapter(PrinterAdapter):
    """A scriptable printer: the real template and lifecycle run around it."""

    _DURATION_SEMANTICS = "frozen"

    def __init__(self, name: str = "voron") -> None:
        self._name = name
        self.job_label: str | None = None
        self.status = PrinterStatus.IDLE
        self.job_result: JobResult | None = None
        self.elapsed_seconds: int | None = None
        self.left_seconds: int | None = None

    def _load_filament_impl(self, plan):
        raise NotImplementedError

    def _unload_filament_impl(self, plan):
        raise NotImplementedError

    def _purge_filament_impl(self, plan):
        raise NotImplementedError

    @property
    def name(self) -> str:
        return self._name

    @property
    def capabilities(self) -> PrinterCapabilities:
        return PrinterCapabilities()

    def get_state(self) -> PrinterState:
        return PrinterState(connected=True, state=self.status, last_job_result=self.job_result)

    def get_job(self) -> JobProgress:
        return JobProgress(
            file_name=self.job_label,
            completion=40.0 if self.status == PrinterStatus.PRINTING else None,
            print_time_seconds=self.elapsed_seconds,
            print_time_left_seconds=self.left_seconds,
        )

    def _start_print_impl(self, file_name: str, **kwargs: Any) -> PrintResult:
        self.job_label = os.path.basename(file_name)
        self.status = PrinterStatus.PRINTING
        return PrintResult(success=True, message="started")

    def list_files(self) -> list:
        return []

    def upload_file(self, file_path: str) -> UploadResult:
        return UploadResult(success=True, message="ok")

    def delete_file(self, file_name: str) -> bool:
        return True

    def cancel_print(self) -> PrintResult:
        return PrintResult(success=True, message="ok")

    def pause_print(self) -> PrintResult:
        return PrintResult(success=True, message="ok")

    def _resume_print_impl(self) -> PrintResult:
        return PrintResult(success=True, message="ok")

    def emergency_stop(self) -> PrintResult:
        return PrintResult(success=True, message="ok")

    def send_gcode(self, command: str) -> str:
        return "ok"

    def set_tool_temp(self, celsius: float, tool: int = 0) -> bool:
        return True

    def set_bed_temp(self, celsius: float) -> bool:
        return True


def _rows(printer: str = "voron") -> list[dict]:
    from kiln.persistence import get_db

    return get_db().list_print_outcomes(printer_name=printer)


def _row(printer: str = "voron") -> dict:
    from kiln.persistence import get_db

    rows = get_db()._conn.execute(
        "SELECT * FROM print_outcomes WHERE printer_name = ? ORDER BY id DESC LIMIT 1", (printer,)
    ).fetchall()
    return dict(rows[0])


def _watch_to_the_end(adapter: _Adapter, elapsed: int, *, gap_seconds: float = 5.0) -> None:
    adapter.get_state()  # was printing
    pm._last_looks[pm.observation_key(adapter)] = time.monotonic() - gap_seconds
    adapter.elapsed_seconds = elapsed
    adapter.status = PrinterStatus.IDLE
    adapter.job_result = JobResult.COMPLETED
    adapter.get_state()  # notices the ending


def _seed(printer: str, pairs: list[tuple[float, float, str]]) -> None:
    """Rows as the lifecycle leaves them: (slicer seconds, real seconds, ending)."""
    from kiln.persistence import get_db

    db = get_db()
    for i, (estimate, actual, ending) in enumerate(pairs):
        job = f"{printer}-job-{i}"
        db.save_print_outcome({
            "job_id": job, "printer_name": printer, "outcome": ending,
            "determined_by": "observed", "created_at": time.time() - 100000 + i, "ended_at": time.time() - 90000 + i,
        })
        db.set_outcome_estimate(job, estimate)
        if actual:
            db.record_print_seconds(job, actual)


