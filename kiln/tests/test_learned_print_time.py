def test_the_copies_plan_sends_each_printers_pace(kiln_env, monkeypatch):
    from kiln import plate_state
    from kiln.plugins import recovery_tools

    _seed("voron", [(3600, 4320, "success")] * 3)
    monkeypatch.setattr(plate_state, "declared_model_of", lambda adapter: "voron_2")
    monkeypatch.setattr(recovery_tools, "_model_times", lambda *_a, **_k: {"voron_2": (1000.0, 100.0)})
    adapters = {"voron": _Adapter("voron"), "other": _Adapter("other")}

    times, _per_model, _model_of = recovery_tools._printer_times("part.stl", ["voron", "other"], adapters, "PLA")

    assert times["voron"]["pace"] == {"factor": 1.2, "prints": 3}
    assert "pace" not in times["other"]
    # The slicer's own times still go up as the slicer said them.
    assert times["voron"]["per_copy_seconds"] == 1000.0


def test_the_copies_plan_says_where_its_times_came_from():
    from kiln.plugins.recovery_tools import _timed_by_words

    assert _timed_by_words({}) == "by the slicer's own estimate for each printer model"
    said = _timed_by_words({"timed_by": {
        "a": {"from": "own_prints", "prints": 5},
        "b": {"from": "same_model_prints", "prints": 4},
        "c": {"from": "slicer", "prints": 0},
    }})
    assert said == (
        "by the slicer's estimate for each printer model, corrected by how long prints really take: "
        "for a by its own past prints; for b by past prints on other printers of the same model"
    )
