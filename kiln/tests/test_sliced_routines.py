"""A printer's own routines read from a sliced print file, and what leaves.

The files are built here in the shapes the three slicers write: a Bambu
Studio package (``Metadata/project_settings.config`` beside the plate's
G-code), an OrcaSlicer plain G-code (``; CONFIG_BLOCK_START`` near the top),
a PrusaSlicer plain G-code (``; prusaslicer_config = begin`` at the end) and
a PrusaSlicer binary G-code (a deflated settings block before the G-code).
"""

from __future__ import annotations

import json
import struct
import threading
import zipfile
import zlib
from pathlib import Path

import pytest

from kiln import sliced_routines as sr

#: A line of toolpath, a file name, a preset name and a filament setting that
#: must never leave this computer.
TOOLPATH_MARK = "G1 X123.456 Y78.901 E0.04321"
FILE_NAME = "grandmas_birthday_gift.gcode.3mf"
PRESET_NAME = "Alex's P1S tuned"
FILAMENT_MARK = "; my secret filament start"

END = ";===== date: 20250101 =====\nM400\nG1 Z{max_layer_z + 0.5} F900\nG1 X65 Y245 F12000\nM104 S0"
PAUSE = "M400 U1"
CHANGE = "M620 S[next_extruder]A\nG1 Z{max_layer_z + 3.0} F1200"
START = ";===== machine: P1S =====\nG28\nM104 S220"


def _bambu_settings(**over):
    settings = {
        "printer_model": "Bambu Lab P1S",
        "printer_settings_id": PRESET_NAME,
        "version": "02.08.02.61",
        "machine_start_gcode": START,
        "machine_end_gcode": END,
        "machine_pause_gcode": PAUSE,
        "change_filament_gcode": CHANGE,
        "layer_change_gcode": "; layer {layer_num+1}\nM73 L{layer_num+1}",
        "time_lapse_gcode": "",
        "filament_start_gcode": [FILAMENT_MARK],
        "different_settings_to_system": ["enable_prime_tower", "", ""],
        "nozzle_diameter": ["0.4"],
    }
    settings.update(over)
    return settings


def _package(tmp_path: Path, settings: dict, *, header: str = "; BambuStudio 02.08.02.61", name: str = FILE_NAME) -> Path:
    path = tmp_path / name
    with zipfile.ZipFile(path, "w") as zf:
        zf.writestr("Metadata/project_settings.config", json.dumps(settings))
        zf.writestr("Metadata/plate_1.gcode", f"; HEADER_BLOCK_START\n{header}\n; HEADER_BLOCK_END\n{TOOLPATH_MARK}\n")
    return path


def _escaped(text: str) -> str:
    return text.replace("\\", "\\\\").replace("\n", "\\n")


def _orca_gcode(tmp_path: Path) -> Path:
    lines = [
        "; HEADER_BLOCK_START", "; generated by OrcaSlicer 2.3.2 on 2026-01-01 at 10:00:00", "; HEADER_BLOCK_END", "",
        "; CONFIG_BLOCK_START",
        f"; change_filament_gcode = {_escaped(CHANGE)}",
        "; different_settings_to_system = ;;",
        f"; filament_start_gcode = {_escaped(FILAMENT_MARK)}",
        f"; machine_end_gcode = {_escaped(END)}",
        f"; machine_pause_gcode = {PAUSE}",
        "; printer_model = Creality K1C",
        f"; printer_settings_id = {PRESET_NAME}",
        "; CONFIG_BLOCK_END", "", TOOLPATH_MARK,
    ]
    path = tmp_path / "orca.gcode"
    path.write_text("\n".join(lines) + "\n")
    return path


PRUSA_END = "G1 Z{max_layer_z+1} F720\nG1 X241 Y170 F3600\nM84 X Y E"


def _prusa_settings_lines() -> list[str]:
    return [
        f"end_gcode = {_escaped(PRUSA_END)}",
        "pause_print_gcode = M601",
        "color_change_gcode = M600",
        "printer_model = MK4S",
        f"printer_settings_id = {PRESET_NAME}",
        f"start_filament_gcode = {_escaped(FILAMENT_MARK)}",
    ]


def _prusa_gcode(tmp_path: Path, *, preset: str = PRESET_NAME) -> Path:
    body = ["; generated by PrusaSlicer 2.9.4 on 2026-01-01 at 10:00:00 UTC", "", TOOLPATH_MARK, "",
            "; prusaslicer_config = begin"]
    body += ["; " + line.replace(" = ", " = ", 1).replace(PRESET_NAME, preset) for line in _prusa_settings_lines()]
    body += ["; prusaslicer_config = end"]
    path = tmp_path / "prusa.gcode"
    path.write_text("\n".join(body) + "\n")
    return path


def _bg_block(kind: int, payload: bytes, *, deflate: bool) -> bytes:
    stored = zlib.compress(payload) if deflate else payload
    header = struct.pack("<HHI", kind, 1 if deflate else 0, len(payload))
    if deflate:
        header += struct.pack("<I", len(stored))
    return header + struct.pack("<H", 0) + stored


def _prusa_binary(tmp_path: Path) -> Path:
    tmp_path.mkdir(parents=True, exist_ok=True)
    data = b"GCDE" + struct.pack("<IH", 1, 0)
    data += _bg_block(0, b"Producer=PrusaSlicer 2.9.4\n", deflate=False)
    settings = "\n".join(line.replace(" = ", "=", 1) for line in _prusa_settings_lines()).encode()
    data += _bg_block(2, settings, deflate=True)
    data += _bg_block(1, (TOOLPATH_MARK + "\n").encode(), deflate=False)
    path = tmp_path / "prusa.bgcode"
    path.write_bytes(data)
    return path


