class TestThePrintIsNeverTouched:
    def test_the_start_note_returns_at_once_and_reads_on_its_own_thread(self, tmp_path, monkeypatch):
        path = _package(tmp_path, _bambu_settings())
        started = threading.Event()
        release = threading.Event()
        seen: list[str] = []

        def _slow(adapter, paths):
            started.set()
            release.wait(5)
            seen.extend(paths)

        monkeypatch.setattr(sr, "_note", _slow)
        monkeypatch.setattr("kiln.print_lineage.local_copies", lambda name, kwargs=None: [str(path)])
        sr.note_print_started(_Printer("bambu_p1s"), path.name, {})
        assert started.wait(5)
        assert seen == []          # the caller came back while the read was still going
        release.set()

    def test_a_reader_that_breaks_never_reaches_the_print(self, monkeypatch):
        monkeypatch.setattr("kiln.print_lineage.local_copies", lambda *a, **k: (_ for _ in ()).throw(OSError("disk")))
        sr.note_print_started(_Printer("bambu_p1s"), "x.gcode", {})

    def test_on_kilns_shared_servers_nothing_is_read_or_kept(self, tmp_path, monkeypatch):
        monkeypatch.setattr(sr, "_hosted", lambda: True)
        calls: list[str] = []
        monkeypatch.setattr("kiln.print_lineage.local_copies", lambda *a, **k: calls.append("read") or [])
        sr.note_print_started(_Printer("bambu_p1s"), "x.gcode", {})
        assert calls == []
        assert sr.keep(_Printer("bambu_p1s"), sr.read_routines(_package(tmp_path, _bambu_settings()))) is False


