class _Printer:
    def __init__(self, model: str) -> None:
        self.model = model


@pytest.fixture
def printer_here(tmp_path, monkeypatch):
    """A printer of a declared model with a unit hash, an install that
    shares, a send switched on, and every request captured instead of sent."""
    monkeypatch.setenv("KILN_HOME", str(tmp_path / "home"))
    monkeypatch.setattr(sr, "_declared_model", lambda adapter: sr._model_id(adapter.model))
    import kiln.bench as bench

    monkeypatch.setattr(bench, "unit_of", lambda adapter: "ab" * 16)
    monkeypatch.setattr(sr, "_shares", lambda: True)
    monkeypatch.setattr(sr, "SENDING_FROM", "2000-01-01")
    monkeypatch.setattr("kiln.installation.get_installation_id", lambda *a, **k: "00000000-0000-4000-8000-000000000001")
    sent: list[bytes] = []

    class _Answer:
        status = 204

        def __enter__(self):
            return self

        def __exit__(self, *exc):
            return False

    def _urlopen(req, timeout=None):
        sent.append(req.data)
        assert req.full_url.endswith(f"/rest/v1/rpc/{sr.RPC}")
        return _Answer()

    monkeypatch.setattr("urllib.request.urlopen", _urlopen)
    return sent


class TestWhatLeaves:
    def test_only_the_routines_the_model_and_the_slicer_leave(self, tmp_path, printer_here):
        path = _package(tmp_path, _bambu_settings())
        assert sr.keep(_Printer("bambu_p1s"), sr.read_routines(path))
        assert sr.send_pending("https://example.invalid", "key") == 5
        bodies = [json.loads(b) for b in printer_here]
        expected_texts = {START, END, PAUSE, CHANGE, "; layer {layer_num+1}\nM73 L{layer_num+1}"}
        assert {b["p_text"] for b in bodies} == expected_texts
        for body in bodies:
            assert set(body) == {"p_printer_id", "p_block", "p_sha256", "p_text", "p_slicer",
                                 "p_slicer_version", "p_unit", "p_installation_id"}
            assert body["p_printer_id"] == "bambu_p1s"
            assert (body["p_slicer"], body["p_slicer_version"]) == ("bambu_studio", "02.08.02.61")
        raw = b"".join(printer_here).decode()
        for never in (TOOLPATH_MARK, FILE_NAME, PRESET_NAME, FILAMENT_MARK, "grandmas", "enable_prime_tower"):
            assert never not in raw

    def test_each_routine_is_sent_once(self, tmp_path, printer_here):
        sr.keep(_Printer("bambu_p1s"), sr.read_routines(_package(tmp_path, _bambu_settings())))
        sr.send_pending("https://example.invalid", "key")
        assert sr.send_pending("https://example.invalid", "key") == 0

    def test_a_routine_changed_by_its_owner_is_never_sent(self, tmp_path, printer_here):
        settings = _bambu_settings(different_settings_to_system=["", "", "machine_end_gcode"])
        sr.keep(_Printer("bambu_p1s"), sr.read_routines(_package(tmp_path, settings)))
        sr.send_pending("https://example.invalid", "key")
        assert END not in {json.loads(b)["p_text"] for b in printer_here}
        rider = sr.routines_for_request(_Printer("bambu_p1s"))
        assert END in {r["text"] for r in rider["routines"]}

    def test_a_routine_the_guard_would_change_never_leaves(self, tmp_path, printer_here):
        leaky = "G1 Z10\n; uploaded from http://192.168.1.40/upload\nG1 X0 Y0"
        sr.keep(_Printer("bambu_p1s"), sr.read_routines(_package(tmp_path, _bambu_settings(machine_end_gcode=leaky))))
        sr.send_pending("https://example.invalid", "key")
        assert "192.168" not in b"".join(printer_here).decode()
        rider = sr.routines_for_request(_Printer("bambu_p1s"))
        assert leaky not in {r["text"] for r in rider["routines"]}

    def test_a_file_made_for_another_model_is_neither_kept_nor_sent(self, tmp_path, printer_here):
        read = sr.read_routines(_package(tmp_path, _bambu_settings()))
        assert sr.keep(_Printer("bambu_x1c"), read) is False
        assert sr.send_pending("https://example.invalid", "key") == 0
        assert sr.routines_for_request(_Printer("bambu_x1c")) is None

    def test_nothing_leaves_while_the_send_is_switched_off(self, tmp_path, printer_here, monkeypatch):
        sr.keep(_Printer("bambu_p1s"), sr.read_routines(_package(tmp_path, _bambu_settings())))
        monkeypatch.setattr(sr, "SENDING_FROM", None)
        assert sr.send_pending("https://example.invalid", "key") == 0
        assert sr.routines_for_request(_Printer("bambu_p1s")) is None
        monkeypatch.setattr(sr, "SENDING_FROM", "2999-01-01")
        assert sr.send_pending("https://example.invalid", "key") == 0
        assert printer_here == []

    def test_nothing_leaves_when_this_install_does_not_share(self, tmp_path, printer_here, monkeypatch):
        sr.keep(_Printer("bambu_p1s"), sr.read_routines(_package(tmp_path, _bambu_settings())))
        monkeypatch.setattr(sr, "_shares", lambda: False)
        assert sr.send_pending("https://example.invalid", "key") == 0
        assert printer_here == []

    def test_signed_in_the_routines_go_to_kilns_api_as_the_person_with_no_install_id(
        self, tmp_path, printer_here, monkeypatch,
    ):
        settings = _bambu_settings(different_settings_to_system=["", "", "machine_end_gcode"])
        sr.keep(_Printer("bambu_p1s"), sr.read_routines(_package(tmp_path, settings)))
        monkeypatch.setattr(sr, "_signed_in", lambda: True)
        asked: list[tuple] = []
        monkeypatch.setattr("kiln.history_courier._request",
                            lambda tool, method, path, body, **kw: asked.append((method, path, body)) or
                            {"success": True, "kept": len(body["routines"])})
        assert sr.send_pending("https://example.invalid", "key") == 4
        assert printer_here == []                       # the database door was never used
        [(method, path, body)] = asked
        assert (method, path) == ("POST", sr.PUSH_PATH)
        assert set(body) == {"format", "model", "slicer", "version", "unit", "routines"}
        assert (body["model"], body["slicer"], body["version"]) == ("bambu_p1s", "bambu_studio", "02.08.02.61")
        assert END not in {r["text"] for r in body["routines"]}   # the owner's own edit stays out
        raw = json.dumps(body)
        for never in ("00000000-0000-4000-8000-000000000001", TOOLPATH_MARK, FILE_NAME, PRESET_NAME, FILAMENT_MARK):
            assert never not in raw
        assert sr.send_pending("https://example.invalid", "key") == 0

    def test_signed_in_nothing_is_marked_sent_when_kiln_did_not_take_it(self, tmp_path, printer_here, monkeypatch):
        sr.keep(_Printer("bambu_p1s"), sr.read_routines(_package(tmp_path, _bambu_settings())))
        monkeypatch.setattr(sr, "_signed_in", lambda: True)
        monkeypatch.setattr("kiln.history_courier._request", lambda *a, **k: {"success": False, "code": "X"})
        assert sr.send_pending("https://example.invalid", "key") == 0
        monkeypatch.setattr("kiln.history_courier._request", lambda *a, **k: {"success": True, "kept": 5})
        assert sr.send_pending("https://example.invalid", "key") == 5

    def test_the_request_carries_routines_with_no_hash_id_or_version(self, tmp_path, printer_here):
        sr.keep(_Printer("bambu_p1s"), sr.read_routines(_package(tmp_path, _bambu_settings())))
        rider = sr.routines_for_request(_Printer("bambu_p1s"))
        assert set(rider) == {"format", "model", "slicer", "routines"}
        assert rider["model"] == "bambu_p1s"
        assert all(set(r) == {"block", "text", "sha256"} for r in rider["routines"])
        assert "02.08" not in json.dumps(rider)


