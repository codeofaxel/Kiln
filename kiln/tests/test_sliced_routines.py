class TestReading:
    def test_a_bambu_package_gives_its_routines_and_nothing_else(self, tmp_path):
        read = sr.read_routines(_package(tmp_path, _bambu_settings()))
        assert read is not None
        assert read["model"] == "bambu_p1s"
        assert (read["slicer"], read["version"]) == ("bambu_studio", "02.08.02.61")
        assert set(read["routines"]) == {"start", "end", "pause", "filament_change", "layer_change"}
        assert read["routines"]["end"]["text"] == END
        flat = json.dumps(read)
        for never in (FILAMENT_MARK, PRESET_NAME, TOOLPATH_MARK, FILE_NAME):
            assert never not in flat

    def test_an_orca_plain_file_is_read_from_its_settings_block(self, tmp_path):
        read = sr.read_routines(_orca_gcode(tmp_path))
        assert read is not None
        assert (read["model"], read["slicer"], read["version"]) == ("k1c", "orca_slicer", "2.3.2")
        assert read["routines"]["end"]["text"] == END
        assert read["routines"]["filament_change"]["text"] == CHANGE
        assert FILAMENT_MARK not in json.dumps(read)

    def test_a_prusaslicer_plain_file_is_read_from_its_footer(self, tmp_path):
        read = sr.read_routines(_prusa_gcode(tmp_path))
        assert read is not None
        assert (read["model"], read["slicer"]) == ("prusa_mk4", "prusa_slicer")
        assert read["routines"]["end"]["text"] == PRUSA_END
        assert set(read["routines"]) == {"end", "pause", "color_change"}

    def test_a_prusaslicer_binary_file_is_read_up_to_its_gcode(self, tmp_path):
        read = sr.read_routines(_prusa_binary(tmp_path))
        assert read is not None
        assert (read["model"], read["slicer"], read["version"]) == ("prusa_mk4", "prusa_slicer", "2.9.4")
        assert read["routines"]["end"]["text"] == PRUSA_END

    def test_a_command_line_slice_with_no_named_preset_is_not_read(self, tmp_path):
        assert sr.read_routines(_prusa_gcode(tmp_path, preset="")) is None

    def test_a_file_kiln_sliced_is_never_read(self, tmp_path):
        path = _orca_gcode(tmp_path)
        with path.open("a") as fh:
            fh.write("; kiln_lineage = 0123456789abcdef\n")
        assert sr.read_routines(path) is None

    def test_a_package_kiln_wrapped_carries_no_routines(self, tmp_path):
        assert sr.read_routines(_package(tmp_path, {})) is None

    def test_a_package_from_an_unlisted_slicer_is_not_read(self, tmp_path):
        assert sr.read_routines(_package(tmp_path, _bambu_settings(), header="; SomeOtherSlicer 1.0")) is None

    def test_a_routine_changed_from_its_preset_is_marked_not_shared(self, tmp_path):
        settings = _bambu_settings(different_settings_to_system=["", "", "machine_end_gcode;machine_pause_gcode"])
        read = sr.read_routines(_package(tmp_path, settings))
        assert read["routines"]["end"]["share"] is False
        assert read["routines"]["pause"]["share"] is False
        assert read["routines"]["start"]["share"] is True


