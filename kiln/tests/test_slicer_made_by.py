def test_the_reader_takes_lines_one_at_a_time_and_stops_at_the_signature():
    """A reader of a whole sliced file (Kiln Pro's change costing) needs it to
    stream: splitting tens of megabytes into lines once cost 1.4 GB.  The
    first cut split its whole input first and took text only."""

    def lines():
        yield "; generated by PrusaSlicer 2.9.4 on 2026-10-26 at 18:00:00 UTC"
        yield "G28"
        raise AssertionError("read past the signature")

    assert slicer_made_by(lines()) == SlicerMadeBy("PrusaSlicer", "2.9.4")


def test_a_bambu_studio_file_read_line_by_line_is_bambu_studios():
    assert slicer_made_by(iter(BAMBU.splitlines())) == SlicerMadeBy("BambuStudio", "02.05.00.66")


def test_no_line_makes_the_reader_slow():
    """Every line of a file passes through these patterns; one written with a
    lazy capture before trailing space once took time in the square of a
    line's whitespace (60 KB: about 14 s)."""
    import time

    lines = [
        "; generated by PrusaSlicer" + " " * 60_000 + "x",
        "; generated by " + "a" * 60_000,
        "; " + "Slicer" * 10_000 + " 1" + " " * 60_000 + "x",
        "; BambuStudio " + "1." * 30_000 + "-" + "a." * 20_000 + " x",
    ]
    started = time.monotonic()
    for line in lines:
        slicer_made_by(line)
    assert time.monotonic() - started < 1.0


