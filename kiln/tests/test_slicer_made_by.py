def _packaged(tmp_path, body: str, *, resume_mode: bool) -> list[str]:
    from kiln.file_metadata import sliced_gcode_lines
    from kiln.printers.bambu_3mf import build_bambu_3mf

    out = tmp_path / ("resume.gcode.3mf" if resume_mode else "part.gcode.3mf")
    build_bambu_3mf(body, str(out), printer_model="x1c", resume_mode=resume_mode)
    return sliced_gcode_lines(str(out))


_LAYERS = "".join(f";LAYER_CHANGE\n;Z:{0.2 * (i + 1):.1f}\nG1 X{i} Y1 E1\n" for i in range(20))


def test_a_file_kiln_packaged_from_an_unsigned_body_names_no_slicer(tmp_path):
    """A resume file carries the rest of the layers and no slicer's line, under
    the header Kiln writes for the printer.  It was recorded as Bambu Studio
    02.05.00.66, a version Kiln itself typed."""
    assert slicer_made_by("\n".join(_packaged(tmp_path, _LAYERS, resume_mode=True))) is None
    assert slicer_made_by("\n".join(_packaged(tmp_path, _LAYERS, resume_mode=False))) is None


def test_a_packaged_file_still_names_the_slicer_that_signed_its_body(tmp_path):
    body = "; generated by OrcaSlicer 2.3.2 on 2026-10-26 at 12:00:00\n" + _LAYERS
    assert slicer_made_by("\n".join(_packaged(tmp_path, body, resume_mode=False))) == SlicerMadeBy("OrcaSlicer", "2.3.2")


def test_ultimakers_two_line_generator_header_is_read():
    text = ";START_OF_HEADER\n;FLAVOR:Griffin\n;GENERATOR.NAME:Cura_SteamEngine\n;GENERATOR.VERSION:5.5.0\n;END_OF_HEADER\n"
    assert slicer_made_by(text) == SlicerMadeBy("Cura_SteamEngine", "5.5.0")


def test_a_plain_word_after_generated_by_is_no_slicer():
    assert slicer_made_by("; generated by the slicer\n") is None


def test_a_crafted_name_is_never_kept_whole():
    made_by = slicer_made_by("; generated by A" + "a" * 1_000_000 + " 1." + "2" * 1_000 + "\n")
    assert made_by is not None
    assert len(made_by.name) <= 48 and len(made_by.version or "") <= 24


def test_a_sliced_3mf_names_the_slicer_of_its_plate_not_the_app_that_saved_it(tmp_path):
    """The file metadata read a sliced 3MF's slicer from the model's
    Application field, which names whoever saved the archive: Kiln, for every
    file Kiln packages."""
    from kiln.file_metadata import _extract_3mf_metadata
    from kiln.printers.bambu_3mf import build_bambu_3mf

    out = tmp_path / "part.gcode.3mf"
    build_bambu_3mf("; generated by PrusaSlicer 2.9.4\n" + _LAYERS, str(out), printer_model="x1c")
    assert _extract_3mf_metadata(str(out)).slicer_hint == "PrusaSlicer 2.9.4"


