"""Which slicer wrote a print file, read from the file's own top lines.

One reader (:func:`kiln.gcode.slicer_made_by`) for every door: the G-code
metadata, the file metadata, and the record a start writes.  Bambu Studio
names itself on ``; BambuStudio 02.05.00.66`` with no "generated by", which
both older readers missed; PrusaSlicer's line carries a build tag and a date
after the version, which is not the version.
"""

from __future__ import annotations

import pytest

from kiln.file_metadata import _extract_gcode_metadata_from_lines
from kiln.gcode import SlicerMadeBy, slicer_made_by
from kiln.gcode_metadata import extract_metadata_from_content

BAMBU = "; HEADER_BLOCK_START\n; BambuStudio 02.05.00.66\n; total layer number: 10\n; HEADER_BLOCK_END\nM140 S65\n"
PRUSA = "; generated by PrusaSlicer 2.9.4+MacOS-arm64 on 2026-10-26 at 18:00:00 UTC\nM140 S60\n"


@pytest.mark.parametrize(
    ("text", "name", "version"),
    [
        (BAMBU, "BambuStudio", "02.05.00.66"),
        (PRUSA, "PrusaSlicer", "2.9.4"),
        ("; generated by OrcaSlicer 2.3.2 on 2026-09-23 at 12:38:47\n", "OrcaSlicer", "2.3.2"),
        ("; generated by PrusaSlicer 2.9.0-rc1+win64\n", "PrusaSlicer", "2.9.0-rc1"),
        (";Generated with Cura_SteamEngine 5.5.0\n", "Cura_SteamEngine", "5.5.0"),
        ("; Simplify3D(R) Version 5.0\n", "Simplify3D", "5.0"),
        ("; generated by Slic3r\n", "Slic3r", None),
    ],
)
def test_each_slicer_is_read_by_name_and_version(text, name, version):
    assert slicer_made_by(text) == SlicerMadeBy(name=name, version=version)


def test_a_file_that_does_not_say_is_unknown():
    assert slicer_made_by("G28\nM104 S210\n; HEADER_BLOCK_START\n") is None
    assert slicer_made_by("") is None


def test_a_header_line_deep_in_the_plate_is_not_the_slicer():
    text = "G28\n" * 50 + "; SomeSlicer 1.0\n"
    assert slicer_made_by(text) is None


def test_the_label_reads_as_a_person_says_it():
    assert slicer_made_by(BAMBU).label == "BambuStudio 02.05.00.66"
    assert SlicerMadeBy(name="Slic3r", version=None).label == "Slic3r"


def test_both_older_readers_now_name_bambu_studio():
    assert extract_metadata_from_content(BAMBU).slicer == "BambuStudio 02.05.00.66"
    assert _extract_gcode_metadata_from_lines(BAMBU.splitlines()).slicer_hint == "BambuStudio 02.05.00.66"


def test_both_older_readers_give_the_version_without_the_date():
    assert extract_metadata_from_content(PRUSA).slicer == "PrusaSlicer 2.9.4"
    assert _extract_gcode_metadata_from_lines(PRUSA.splitlines()).slicer_hint == "PrusaSlicer 2.9.4"


# --- defects a lap found (2026-10-26; each fails at 6d376d48) ---
#
# The first cut read the Bambu-style header line as the slicer whenever it
# came first.  That line is also what a Bambu printer looks for, so OrcaSlicer
# and Kiln's own packaging both write it into files they made; the fixtures
# were hand-written and only Bambu Studio's own files had been pictured.


def _orca_for_bambu() -> str:
    """The shape of an OrcaSlicer plate for a Bambu printer: Bambu's header
    near the top, OrcaSlicer's own signature some 640 lines down."""
    lines = ["M73 P0 R245", "; HEADER_BLOCK_START", "; BambuStudio 02.05.00.66",
             "; total layer number: 225", "; HEADER_BLOCK_END"]
    lines += ["G1 X1 Y1"] * (640 - len(lines))
    lines += ["; generated by OrcaSlicer 2.3.2 on 2026-09-18 at 13:57:02"]
    return "\n".join(lines) + "\n"


def test_an_orcaslicer_file_for_a_bambu_printer_is_orcaslicers():
    """Found by reading files OrcaSlicer had made for a Bambu printer: each
    said Bambu Studio at the top."""
    assert slicer_made_by(_orca_for_bambu()) == SlicerMadeBy("OrcaSlicer", "2.3.2")
    assert extract_metadata_from_content(_orca_for_bambu()).slicer == "OrcaSlicer 2.3.2"


def test_a_file_kiln_packaged_for_a_bambu_printer_names_the_slicer_that_made_it(tmp_path):
    """Kiln's own Bambu packaging writes the same header over a PrusaSlicer
    body; measured through the real packager, the PrusaSlicer line sits at 640
    of 1194 and the first cut read every such file as Bambu Studio."""
    import zipfile

    from kiln.file_metadata import sliced_gcode_lines
    from kiln.printers.bambu_3mf import build_bambu_3mf

    body = "; generated by PrusaSlicer 2.9.4+MacOS-arm64 on 2026-10-26 at 18:00:00 UTC\nM83\nG28\n" + "".join(
        f";LAYER_CHANGE\n;Z:{0.2 * (i + 1):.1f}\nG1 X{i} Y1 E1\n" for i in range(20)
    )
    out = tmp_path / "part.gcode.3mf"
    build_bambu_3mf(body, str(out), printer_model="x1c")
    with zipfile.ZipFile(out) as z:
        assert any("; BambuStudio 02.05.00.66" in z.read(n).decode() for n in z.namelist() if n.endswith(".gcode"))

    lines = sliced_gcode_lines(str(out))
    assert slicer_made_by("\n".join(lines)) == SlicerMadeBy("PrusaSlicer", "2.9.4")


def test_kilns_own_signature_is_not_a_slicer():
    """Kiln signs the files it merges above the slicer's own line."""
    merged = "; Generated by Kiln — 3D printing infrastructure for AI agents\n; https://kiln3d.com\n;\n" + PRUSA
    assert slicer_made_by(merged) == SlicerMadeBy("PrusaSlicer", "2.9.4")
    alone = "; Generated by Kiln — 3D printing infrastructure for AI agents\nG28\n"
    assert slicer_made_by(alone) is None
    assert _extract_gcode_metadata_from_lines(alone.splitlines()).slicer_hint is None


def test_simplify3d_signs_with_g_code_generated_by():
    assert slicer_made_by("; G-Code generated by Simplify3D(R) Version 4.1.2\n") == SlicerMadeBy("Simplify3D", "4.1.2")
