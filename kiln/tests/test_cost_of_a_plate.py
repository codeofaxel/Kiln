"""A cost question about a sliced 3MF of several plates is answered for the
plate named, or for every plate together, and says which.

Pinned through the cost tool, the terminal's ``kiln cost`` and the
cost-intelligence ask:

* plate 2 named prices plate 2 alone, and ``covers`` says "plate 2";
* no plate named prices every plate together, and ``covers`` says
  "all 2 plates"; a plate that cannot be read is named and no total given;
* the ask sends the plate priced and nothing more, under the same fields as
  before, and is not made for all plates together (the estimate says so).
"""

from __future__ import annotations

import base64
import gzip
import zipfile
from pathlib import Path
from unittest.mock import patch

import pytest

from kiln import _pro_cost_bridge as bridge
from tests.test_cost_intelligence_bridge import _estimate_tools


def _plate(minutes: int, grams: float, mm: float) -> str:
    return (
        "; HEADER_BLOCK_START\n; generated by BambuStudio 02.03.00.70\n"
        f"; model printing time: {minutes}m 0s; total estimated time: {minutes}m 0s\n"
        f"; total filament length [mm] : {mm}\n; total filament weight [g] : {grams}\n"
        "; HEADER_BLOCK_END\n; filament_type = PLA\nG28\nG1 X10 Y10 E1\n"
    )


def _two(tmp_path: Path) -> str:
    path = tmp_path / "project.gcode.3mf"
    with zipfile.ZipFile(path, "w") as zf:
        zf.writestr("Metadata/plate_1.gcode", _plate(60, 10.0, 3000.0))
        zf.writestr("Metadata/plate_2.gcode", _plate(180, 40.0, 12000.0))
    return str(path)


@pytest.fixture(autouse=True)
def _fresh_bridge(monkeypatch):
    monkeypatch.setattr(bridge, "_service_down_until", 0.0)
    monkeypatch.setattr(bridge, "_service_down_miss", None)
    monkeypatch.setattr(bridge, "_last_miss", None)
    monkeypatch.setattr(bridge, "available", lambda: False)


def test_a_named_plate_is_priced_alone(tmp_path):
    from kiln.cost_estimator import CostEstimator

    estimate = CostEstimator().estimate_from_file(_two(tmp_path), plate_number=2)
    assert estimate.filament_weight_grams == pytest.approx(40.0)
    assert estimate.covers == "plate 2"


def test_no_plate_named_prices_every_plate_and_says_so(tmp_path):
    from kiln.cost_estimator import CostEstimator

    estimate = CostEstimator().estimate_from_file(_two(tmp_path))
    assert estimate.filament_weight_grams == pytest.approx(50.0)
    assert estimate.estimated_time_seconds == 4 * 3600
    assert estimate.covers == "all 2 plates"


def test_a_plate_that_cannot_be_read_is_named_and_no_total_given(tmp_path, monkeypatch):
    from kiln.cost_estimator import CostEstimator

    estimator = CostEstimator()
    real = estimator._estimate_one_plate

    def one(path, number, **kw):
        if number == 2:
            raise ValueError("unreadable")
        return real(path, number, **kw)

    monkeypatch.setattr(estimator, "_estimate_one_plate", one)
    with pytest.raises(ValueError, match="could not read plate 2 .* no total for all 2 plates"):
        estimator.estimate_from_file(_two(tmp_path))


def test_a_plate_the_file_does_not_hold_is_said(tmp_path):
    from kiln.cost_estimator import CostEstimator

    with pytest.raises(ValueError, match="no sliced plate 3"):
        CostEstimator().estimate_from_file(_two(tmp_path), plate_number=3)


def test_the_cost_tool_prices_the_plate_it_is_given(tmp_path):
    with patch("kiln.server._pro_api_call", return_value={"success": True}):
        tool = _estimate_tools()["estimate_cost"]
        one = tool(_two(tmp_path), plate_number=2, printer_id="a1")["estimate"]
        every = tool(_two(tmp_path), printer_id="a1")["estimate"]
    assert (one["filament_weight_grams"], one["covers"]) == (pytest.approx(40.0), "plate 2")
    assert (every["filament_weight_grams"], every["covers"]) == (pytest.approx(50.0), "all 2 plates")


def test_kiln_cost_prices_the_plate_it_is_given(tmp_path):
    from click.testing import CliRunner

    from kiln.cli.main import cli

    with patch("kiln.server._pro_api_call", return_value={"success": True}):
        out = CliRunner().invoke(cli, ["cost", _two(tmp_path), "--plate", "2"]).output
        every = CliRunner().invoke(cli, ["cost", _two(tmp_path)]).output
    assert "Priced:     plate 2" in out and "40.0 g" in out
    assert "Priced:     all 2 plates" in every and "50.0 g" in every


def test_the_ask_sends_the_plate_priced_and_nothing_more(tmp_path):
    seen: list[dict] = []
    with patch("kiln.server._pro_api_call", side_effect=lambda t, **kw: seen.append(kw) or {"success": True}):
        estimate = {"filaments": [], "total_cost_usd": 1.0, "estimated_time_seconds": 10800, "warnings": []}
        bridge.attach_cost_intelligence(estimate, _two(tmp_path), printer_id="a1", plate_number=2)
    assert len(seen) == 1
    assert gzip.decompress(base64.b64decode(seen[0]["gcode_gz_b64"])).decode() == _plate(180, 40.0, 12000.0)
    assert seen[0]["file_name"] == "project.plate2.gcode"
    assert set(seen[0]) == {
        "_timeout", "_asked_by_user", "gcode_gz_b64", "file_name", "filaments",
        "total_cost_usd", "estimated_time_seconds", "printer_id",
    }


def test_the_ask_is_not_made_for_all_plates_together(tmp_path):
    estimate = {"filaments": [], "total_cost_usd": 1.0, "estimated_time_seconds": 14400, "warnings": []}
    with patch("kiln.server._pro_api_call") as door:
        bridge.attach_cost_intelligence(estimate, _two(tmp_path), printer_id="a1")
    door.assert_not_called()
    assert estimate["cost_intelligence"] is None
    assert any("all 2 plates" in w for w in estimate["warnings"])
