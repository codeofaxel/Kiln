"""A part that fits is never handed on with its skirt or brim off the bed.

Measured 2026-09-30 on a prusa_mk4 (bed 250 x 210 x 220): a 200 x 245 x 215
part, turned to 245 x 200 to fit and centred with 2.5 mm each side, sliced
with PrusaSlicer's one-loop skirt at X -3.7 .. 253.7.  The part fits; the
check before a print refused the file anyway -- rightly, extrusion off the
plate is never sent (incident #0) -- and told the person to "rescale or
split" a part that fits.  A brim chosen for a warp-prone material lands
there too, 5-8 mm wide.

Pinned here, through the slice step every door shares, with a slicer that
draws what the profile it is handed asks for, the way PrusaSlicer does
(skirt and brim under one ``;TYPE:Skirt/Brim`` label): a skirt past the edge
is dropped and the part sliced once more; a brim Kiln asked for is never
narrowed or dropped -- the slice is refused with its width and the room
there is; anything still past the edge is refused with its own name; and the
check before a print keeps refusing such a file while naming what prints
past the edge instead of "rescale or split".  No CAD kernel, no slicer.
"""

from __future__ import annotations

import zipfile
from pathlib import Path
from unittest.mock import MagicMock, patch

import pytest

from kiln.printers import bed_fit
from kiln.slicer import SliceResult
from kiln.slicer_orca import ini_to_settings

trimesh = pytest.importorskip("trimesh")

_MK4 = "prusa_mk4"
#: The turned part's own toolpaths on the 250 x 210 bed, as PrusaSlicer printed them.
_PART = (2.7, 5.2, 247.3, 204.8)
#: PrusaSlicer's default skirt distance, plus the line it is drawn with.
_SKIRT_OUT = 6.38
_LINE = 0.45


def _loop(rect: tuple[float, float, float, float]) -> str:
    """One closed loop, with a point mid-way along each side as a slicer's
    has: a brim loop is told from a skirt by how near its points come to the
    part, and a loop of corners alone stands a diagonal off."""
    x0, y0, x1, y1 = (round(v, 3) for v in rect)
    xm, ym = round((x0 + x1) / 2, 3), round((y0 + y1) / 2, 3)
    corners = [(xm, y0), (x1, y0), (x1, ym), (x1, y1), (xm, y1), (x0, y1), (x0, ym), (x0, y0)]
    return f"G1 X{x0} Y{y0} F6000\n" + "".join(f"G1 X{x} Y{y} E0.1\n" for x, y in corners)


def _out(rect: tuple[float, float, float, float], by: float) -> tuple[float, float, float, float]:
    return (rect[0] - by, rect[1] - by, rect[2] + by, rect[3] + by)


def _gcode(
    path: Path,
    *,
    part: tuple[float, float, float, float] = _PART,
    skirts: int = 1,
    brim: float = 0.0,
    tower: tuple[float, float, float, float] | None = None,
    labelled: bool = True,
) -> str:
    """A first layer the way PrusaSlicer writes one: its brim loops hugging
    the part, its skirt the skirt distance past the brim, both under the one
    ``Skirt/Brim`` label."""
    label = (lambda name: f";TYPE:{name}\n") if labelled else (lambda _name: "")
    body = "; generated by PrusaSlicer 2.9.4\nG90\nM83\n" + label("Custom") + "G28\nG1 Z0.2 F600\n;LAYER_CHANGE\n;Z:0.2\n"
    if skirts or brim:
        body += label("Skirt/Brim") + ";WIDTH:0.42\n"
        loops = int(brim // _LINE)
        for k in range(1, loops + 1):
            body += _loop(_out(part, k * _LINE))
        if skirts:
            body += _loop(_out(part, loops * _LINE + _SKIRT_OUT))
    body += label("External perimeter") + _loop(part)
    if tower is not None:
        body += label("Wipe tower") + _loop(tower)
    path.write_text(body)
    return str(path)


class _Slicer:
    """Draws what the profile it is handed asks for: ``brim_width``, and a
    skirt unless ``skirts = 0``.  Every call is kept, profile and file."""

    def __init__(self, tmp_path: Path, **drawn) -> None:
        self.tmp_path = tmp_path
        self.drawn = drawn
        self.profiles: list[dict[str, str]] = []
        self.files: list[str] = []

    def __call__(self, path: str, *, profile: str | None = None, **_kw) -> SliceResult:
        asked = ini_to_settings(profile) if profile else {}
        self.profiles.append(asked)
        out = _gcode(
            self.tmp_path / f"slice{len(self.files) + 1}.gcode",
            skirts=int(float(asked.get("skirts", "1"))),
            brim=float(asked.get("brim_width", "0")),
            **self.drawn,
        )
        self.files.append(out)
        return SliceResult(success=True, output_path=out, slicer="PrusaSlicer", message=f"Sliced {Path(path).name}")


def _profile(tmp_path: Path, **settings: str) -> str:
    path = tmp_path / "profile.ini"
    path.write_text("layer_height = 0.2\n" + "".join(f"{k} = {v}\n" for k, v in settings.items()))
    return str(path)


def _part_stl(tmp_path: Path) -> str:
    """The turned part, on the MK4 bed where the slice gate leaves it."""
    size = (_PART[2] - _PART[0], _PART[3] - _PART[1], 215.0)
    box = trimesh.creation.box(extents=size)
    box.apply_translation([_PART[0] + size[0] / 2, _PART[1] + size[1] / 2, size[2] / 2])
    path = tmp_path / "part.stl"
    box.export(str(path))
    return str(path)


