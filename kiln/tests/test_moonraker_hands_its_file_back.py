def _creality(fake: FakeMoonraker) -> CrealityAdapter:
    probe = mock.MagicMock(ok=True, status_code=200)
    probe.json.return_value = {"result": {"klippy_state": "ready", "moonraker_version": "v0.9.3"}}
    with mock.patch("kiln.printers.creality.requests.get", return_value=probe):
        adapter = CrealityAdapter("k1-max.local", api_key=KEY, timeout=5, retries=1)
    adapter._backend._session.mount("http://", fake)
    return adapter


class TestCreality:
    def test_creality_hands_back_the_file_its_moonraker_holds(self) -> None:
        fake = FakeMoonraker()
        fake.hold("CrealityPrint/cube.gcode", HOMED, modified=1_763_000_777.0)
        adapter = _creality(fake)
        assert adapter.read_print_file("CrealityPrint/cube.gcode") == HOMED
        assert adapter.print_file_identity("CrealityPrint/cube.gcode") == (len(HOMED), 1_763_000_777)
        downloads = [r.url for r in fake.sent if "/server/files/gcodes/" in (r.url or "")]
        assert downloads == ["http://k1-max.local:7125/server/files/gcodes/CrealityPrint/cube.gcode"]
        assert all(r.headers.get("X-Api-Key") == KEY for r in fake.sent)

    def test_creality_raises_read_failed_for_a_missing_file(self) -> None:
        fake = FakeMoonraker()
        adapter = _creality(fake)
        with pytest.raises(PrinterError) as caught:
            adapter.read_print_file("gone.gcode")
        assert caught.value.code == "PRINT_FILE_READ_FAILED"
        assert adapter.print_file_identity("gone.gcode") is None
