HOST = "http://klipper.local:7125"
KEY = "moonraker-test-key-5c1e"

def _sliced(body: str) -> bytes:
    """A G-code file as a slicer leaves it for Moonraker: a preview block,
    the moves, and the filament weight Mainsail and Fluidd read."""
    import base64

    from PIL import Image

    png = io.BytesIO()
    Image.new("RGB", (32, 32), (90, 90, 90)).save(png, format="PNG")
    encoded = base64.b64encode(png.getvalue()).decode()
    rows = "".join(f"; {encoded[i:i + 78]}\n" for i in range(0, len(encoded), 78))
    return (
        "; generated by PrusaSlicer 2.9.4\n"
        f"; thumbnail begin 32x32 {len(encoded)}\n{rows}; thumbnail end\n"
        f"{body}"
        "; filament used [mm] = 0.50\n; filament used [g] = 0.01\n"
    ).encode()


HOMED = _sliced("G28\nM190 S60\nM109 S215\nG21\nG90\nM83\n;LAYER_CHANGE\n;Z:0.2\nG1 Z.2 F3000\nG1 X100 Y100 E.5\n")
NOT_HOMED = _sliced("M190 S60\nM109 S215\nG21\nG90\nM83\n;LAYER_CHANGE\n;Z:0.2\nG1 Z.2 F3000\nG1 X100 Y100 E.5\n")


class FakeMoonraker(BaseAdapter):
    """Moonraker's file calls, at the transport the adapter's session sends through."""

    def __init__(self, api_key: str | None = KEY) -> None:
        super().__init__()
        self.api_key = api_key
        self.files: dict[str, tuple[bytes, float | None]] = {}
        self.sent: list[requests.PreparedRequest] = []
        self.timeouts: list[Any] = []
        self.list_status = 200
        self.download_status: int | None = None
        self.declares_length = True
        self.started: list[str] = []
        self.start_refusal: tuple[int, bytes] | None = None

    # -- what a test sets -----------------------------------------------
    def hold(self, path: str, data: bytes, modified: float | None = 1_763_000_000.25) -> None:
        self.files[path] = (data, modified)

    def paths(self) -> list[str]:
        return [urlsplit(r.url).path for r in self.sent]

    def downloads(self) -> list[str]:
        return [p for p in self.paths() if p.startswith("/server/files/gcodes/")]

    # -- the transport --------------------------------------------------
    def send(self, request: requests.PreparedRequest, stream: bool = False, timeout: Any = None, **_: Any) -> requests.Response:
        self.sent.append(request)
        self.timeouts.append(timeout)
        parts = urlsplit(request.url)
        query = {k: v[0] for k, v in parse_qs(parts.query).items()}
        if self.api_key and request.headers.get("X-Api-Key") != self.api_key:
            return self._json(request, 401, {"error": {"code": 401, "message": "Unauthorized"}})
        if request.method == "GET" and parts.path == "/server/files/list":
            if self.list_status != 200:
                return self._json(request, self.list_status, {"error": {"code": self.list_status, "message": "Internal Server Error"}})
            listing = [
                {"path": path, "size": len(data), "permissions": "rw", **({"modified": when} if when is not None else {})}
                for path, (data, when) in sorted(self.files.items(), key=lambda kv: kv[0].lower())
                if path.rsplit(".", 1)[-1].lower() in ("gcode", "g", "gco", "ufp", "nc")
            ]
            return self._json(request, 200, {"result": listing})
        if request.method == "GET" and parts.path == "/server/files/metadata":
            name = query.get("filename", "")
            return self._json(request, 404, {"error": {"code": 404, "message": f"Metadata not available for <{name}>"}})
        if request.method == "GET" and parts.path.startswith("/server/files/gcodes/"):
            path = unquote(parts.path[len("/server/files/gcodes/"):])
            if self.download_status is not None:
                return self._json(request, self.download_status, {"error": {"code": self.download_status, "message": "Refused"}})
            if path not in self.files:
                return self._json(request, 404, {"error": {"code": 404, "message": "Not Found"}})
            data = self.files[path][0]
            headers = {"Content-Type": "application/octet-stream"}
            if self.declares_length:
                headers["Content-Length"] = str(len(data))
            return self._response(request, 200, data, headers)
        if request.method == "POST" and parts.path == "/printer/print/start":
            if self.start_refusal is not None:
                status, body = self.start_refusal
                return self._response(request, status, body, {"Content-Type": "text/plain"})
            self.started.append(query.get("filename", ""))
            return self._json(request, 200, {"result": "ok"})
        return self._json(request, 404, {"error": {"code": 404, "message": "Not Found"}})

    def close(self) -> None:
        pass

    @staticmethod
    def _response(request: requests.PreparedRequest, status: int, body: bytes, headers: dict[str, str]) -> requests.Response:
        response = requests.Response()
        response.status_code = status
        response.headers = CaseInsensitiveDict(headers)
        response.raw = io.BytesIO(body)
        response.url = request.url or ""
        response.request = request
        response.reason = "OK" if status == 200 else "Error"
        return response

    def _json(self, request: requests.PreparedRequest, status: int, payload: dict[str, Any]) -> requests.Response:
        body = json.dumps(payload).encode()
        return self._response(request, status, body, {"Content-Type": "application/json", "Content-Length": str(len(body))})


def _printer(fake: FakeMoonraker | None = None, api_key: str | None = KEY) -> tuple[MoonrakerAdapter, FakeMoonraker]:
    fake = fake or FakeMoonraker(api_key=api_key)
    adapter = MoonrakerAdapter(host=HOST, api_key=api_key, timeout=5, retries=1)
    adapter._session.mount("http://", fake)
    return adapter, fake


