class TestWhenItCannot:
    def test_a_missing_file_raises_read_failed_without_a_download(self) -> None:
        adapter, fake = _printer()
        fake.hold("other.gcode", HOMED)
        with pytest.raises(PrinterError) as caught:
            adapter.read_print_file("missing.gcode")
        assert caught.value.code == "PRINT_FILE_READ_FAILED"
        assert "missing.gcode" in str(caught.value)
        assert fake.downloads() == []

    def test_a_file_gone_between_listing_and_download_raises_read_failed(self) -> None:
        adapter, fake = _printer()
        fake.hold("benchy.gcode", HOMED)
        fake.download_status = 404
        with pytest.raises(PrinterError) as caught:
            adapter.read_print_file("benchy.gcode")
        assert caught.value.code == "PRINT_FILE_READ_FAILED"

    def test_two_files_that_differ_only_in_capitals_are_not_guessed_between(self) -> None:
        adapter, fake = _printer()
        fake.hold("A/benchy.gcode", HOMED)
        fake.hold("a/Benchy.gcode", NOT_HOMED)
        with pytest.raises(PrinterError) as caught:
            adapter.read_print_file("a/benchy.gcode")
        assert caught.value.code == "PRINT_FILE_READ_FAILED"
        assert "capital letters" in str(caught.value)
        assert fake.downloads() == []

    def test_a_printer_that_does_not_answer_raises_read_failed(self) -> None:
        adapter, fake = _printer()
        fake.hold("benchy.gcode", HOMED)
        with mock.patch.object(fake, "send", side_effect=requests.ConnectionError("refused")), \
                pytest.raises(PrinterError) as caught:
            adapter.read_print_file("benchy.gcode")
        assert caught.value.code == "PRINT_FILE_READ_FAILED"

    def test_a_refused_download_raises_read_failed(self) -> None:
        adapter, fake = _printer()
        fake.hold("benchy.gcode", HOMED)
        fake.download_status = 403
        with pytest.raises(PrinterError) as caught:
            adapter.read_print_file("benchy.gcode")
        assert caught.value.code == "PRINT_FILE_READ_FAILED"
        assert "doesn't allow" in str(caught.value)

    def test_a_declared_size_past_the_ceiling_is_refused(self, monkeypatch: pytest.MonkeyPatch) -> None:
        monkeypatch.setattr(read_back, "READ_BACK_CAP_BYTES", 64)
        adapter, fake = _printer()
        fake.hold("huge.gcode", b"G1 X1\n" * 100)
        with pytest.raises(PrinterError) as caught:
            adapter.read_print_file("huge.gcode")
        assert caught.value.code == "PRINT_FILE_TOO_LARGE"

    def test_a_stream_with_no_declared_size_stops_at_the_ceiling(self, monkeypatch: pytest.MonkeyPatch) -> None:
        monkeypatch.setattr(read_back, "READ_BACK_CAP_BYTES", 64)
        adapter, fake = _printer()
        fake.declares_length = False
        fake.hold("huge.gcode", b"G1 X1\n" * 100)
        with pytest.raises(PrinterError) as caught:
            adapter.read_print_file("huge.gcode")
        assert caught.value.code == "PRINT_FILE_TOO_LARGE"
        fake.hold("small.gcode", b"G28\n")
        assert adapter.read_print_file("small.gcode") == b"G28\n"


