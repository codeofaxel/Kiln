class TestCredentials:
    def test_the_api_key_rides_in_the_header_like_every_other_call(self, caplog: pytest.LogCaptureFixture) -> None:
        caplog.set_level(logging.DEBUG)
        adapter, fake = _printer()
        fake.hold("jobs/clip.gcode", HOMED)
        assert [f.path for f in adapter.list_files()] == ["jobs/clip.gcode"]
        assert adapter.read_print_file("jobs/clip.gcode") == HOMED
        assert adapter.print_file_identity("jobs/clip.gcode") is not None
        assert len(fake.sent) == 4
        assert all(r.headers.get("X-Api-Key") == KEY for r in fake.sent)
        assert all(KEY not in (r.url or "") for r in fake.sent)
        assert KEY not in caplog.text

    def test_a_key_the_printer_refuses_raises_read_failed(self) -> None:
        fake = FakeMoonraker(api_key="the-printers-real-key")
        adapter, _ = _printer(fake, api_key=KEY)
        fake.hold("benchy.gcode", HOMED)
        with pytest.raises(PrinterError) as caught:
            adapter.read_print_file("benchy.gcode")
        assert caught.value.code == "PRINT_FILE_READ_FAILED"
        assert KEY not in str(caught.value)

    def test_a_printer_with_no_key_set_reads_without_one(self) -> None:
        adapter, fake = _printer(api_key=None)
        fake.hold("benchy.gcode", HOMED)
        assert adapter.read_print_file("benchy.gcode") == HOMED
        assert all("X-Api-Key" not in r.headers for r in fake.sent)


