class TestIdentity:
    def test_size_and_time_come_from_the_listing(self) -> None:
        adapter, fake = _printer()
        fake.hold("jobs/clip.gcode", HOMED, modified=1_763_000_123.9)
        assert adapter.print_file_identity("jobs/clip.gcode") == (len(HOMED), 1_763_000_123)
        assert fake.downloads() == []

    def test_a_file_with_no_scanned_metadata_still_has_an_identity(self) -> None:
        adapter, fake = _printer()
        fake.hold("fresh.gcode", HOMED, modified=1_763_000_500.0)
        assert adapter.print_file_identity("fresh.gcode") == (len(HOMED), 1_763_000_500)
        assert "/server/files/metadata" not in fake.paths()

    def test_identity_follows_the_file_klipper_opens(self) -> None:
        adapter, fake = _printer()
        fake.hold("Benchy.gcode", HOMED, modified=1_763_000_001.0)
        assert adapter.print_file_identity("/benchy.gcode") == (len(HOMED), 1_763_000_001)

    def test_a_listing_with_no_time_gives_the_size_alone(self) -> None:
        adapter, fake = _printer()
        fake.hold("benchy.gcode", HOMED, modified=None)
        assert adapter.print_file_identity("benchy.gcode") == (len(HOMED), None)

    def test_a_listing_that_fails_is_no_identity_and_does_not_raise(self) -> None:
        adapter, fake = _printer()
        fake.hold("benchy.gcode", HOMED)
        assert adapter.print_file_identity("benchy.gcode") is not None
        fake.list_status = 500
        assert adapter.print_file_identity("benchy.gcode") is None

    def test_a_printer_that_does_not_answer_is_no_identity(self) -> None:
        adapter, fake = _printer()
        fake.hold("benchy.gcode", HOMED)
        assert adapter.print_file_identity("benchy.gcode") is not None
        with mock.patch.object(fake, "send", side_effect=requests.ConnectionError("refused")):
            assert adapter.print_file_identity("benchy.gcode") is None

    def test_a_missing_file_is_no_identity(self) -> None:
        adapter, fake = _printer()
        fake.hold("other.gcode", HOMED)
        assert adapter.print_file_identity("other.gcode") is not None
        assert adapter.print_file_identity("missing.gcode") is None


