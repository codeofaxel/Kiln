"""A Moonraker printer hands the file a start would print back to Kiln.

The printer is faked at the HTTP transport the adapter's own session uses
(a ``requests`` transport adapter mounted on it), so the real session puts
the API key, the URL encoding and the timeout on every request.  The fake
answers the way Moonraker documents and implements its file calls:

* ``GET /server/files/list?root=gcodes`` -- ``{"result": [{"path",
  "modified", "size", "permissions"}, ...]}``, read off the disk at each
  call, only files with a G-code extension;
* ``GET /server/files/gcodes/<path>`` -- the file's bytes with a
  ``Content-Length``, the path percent-decoded; 404 for a file it lacks;
* ``GET /server/files/metadata?filename=<path>`` -- 404 "Metadata not
  available" for a file it has not scanned;
* any request without the right ``X-Api-Key`` -- 401.

A start (``POST /printer/print/start?filename=...``) goes to Klipper, which
opens the print file at exactly the given path, else the one that matches it
apart from capital letters; the fake records each start's file name.
"""

from __future__ import annotations

