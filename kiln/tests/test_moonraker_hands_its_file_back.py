class TestTheFileComesBack:
    def test_a_bare_name_is_downloaded_from_the_gcodes_root(self) -> None:
        adapter, fake = _printer()
        fake.hold("benchy.gcode", HOMED)
        assert adapter.read_print_file("benchy.gcode") == HOMED
        assert fake.downloads() == ["/server/files/gcodes/benchy.gcode"]

    def test_a_name_inside_a_folder_keeps_its_folder_and_encodes_spaces(self) -> None:
        adapter, fake = _printer()
        fake.hold("My Parts/bracket v2.gcode", HOMED)
        fake.hold("bracket v2.gcode", NOT_HOMED)
        assert adapter.read_print_file("My Parts/bracket v2.gcode") == HOMED
        assert [urlsplit(r.url).path for r in fake.sent if "/gcodes/" in r.url] == [
            "/server/files/gcodes/My%20Parts/bracket%20v2.gcode"
        ]

    def test_a_leading_slash_names_the_same_file_a_start_prints(self) -> None:
        adapter, fake = _printer()
        fake.hold("jobs/clip.gcode", HOMED)
        assert adapter.read_print_file("/jobs/clip.gcode") == HOMED
        assert fake.downloads() == ["/server/files/gcodes/jobs/clip.gcode"]

    def test_a_name_in_other_capitals_reads_the_file_klipper_opens(self) -> None:
        adapter, fake = _printer()
        fake.hold("Benchy.gcode", HOMED)
        assert adapter.read_print_file("benchy.gcode") == HOMED
        assert fake.downloads() == ["/server/files/gcodes/Benchy.gcode"]

    def test_the_exact_name_wins_over_a_match_in_other_capitals(self) -> None:
        adapter, fake = _printer()
        fake.hold("Benchy.gcode", NOT_HOMED)
        fake.hold("benchy.gcode", HOMED)
        assert adapter.read_print_file("benchy.gcode") == HOMED

    def test_a_file_klipper_will_not_open_by_its_own_name_reads_the_one_it_opens(self) -> None:
        # Klipper compares extensions with their capitals, so a start of
        # "Part.GCODE" opens "part.gcode", the only print file matching it.
        adapter, fake = _printer()
        fake.hold("Part.GCODE", NOT_HOMED)
        fake.hold("part.gcode", HOMED)
        assert adapter.read_print_file("Part.GCODE") == HOMED
        assert fake.downloads() == ["/server/files/gcodes/part.gcode"]

    def test_reading_changes_nothing_on_the_printer(self) -> None:
        adapter, fake = _printer()
        fake.hold("benchy.gcode", HOMED)
        adapter.read_print_file("benchy.gcode")
        adapter.print_file_identity("benchy.gcode")
        assert {r.method for r in fake.sent} == {"GET"}
        assert fake.started == []

    def test_the_download_has_a_time_limit(self) -> None:
        adapter, fake = _printer()
        fake.hold("benchy.gcode", HOMED)
        assert adapter.read_print_file("benchy.gcode") == HOMED
        assert fake.downloads() == ["/server/files/gcodes/benchy.gcode"]
        assert fake.timeouts and all(t is not None for t in fake.timeouts)


