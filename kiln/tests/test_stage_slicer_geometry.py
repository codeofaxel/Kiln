    def test_the_sidecar_is_the_mesh_frame_block(self, tmp_path, twin_dir):
        mesh = _box(tmp_path / "part.stl")
        gcode = _gcode_for_box(tmp_path / "part.gcode")
        monitor_twin.note_sliced(mesh, gcode)
        raw = sg.sidecar_for_mesh(mesh)
        block = sg.load_sidecar(raw)
        assert block["available"] and block["frame"] == "mesh"
        # Aligned to the FILE's bbox (corner at the origin), not a centred one.
        assert block["model_footprint"] == {"min": [0.0, 0.0], "max": [40.0, 30.0]}
        skirt = next(f for f in block["features"] if f["class"] == "skirt")
        assert skirt["bounds"]["min"][:2] == pytest.approx([-2.0, -2.0])

    def test_no_slice_means_no_sidecar(self, tmp_path, twin_dir):
        mesh = _box(tmp_path / "part.stl")
        assert sg.sidecar_for_mesh(mesh) is None

    def test_the_link_upload_carries_the_sidecar(self, tmp_path, twin_dir, monkeypatch):
        mesh = _box(tmp_path / "part.stl")
        gcode = _gcode_for_box(tmp_path / "part.gcode")
        monitor_twin.note_sliced(mesh, gcode)
        monkeypatch.setattr(stage_link, "_stage_printer_id", lambda: None)
        monkeypatch.setattr(
            "kiln.auth_session.resolve_api_bearer",
            lambda *a, **k: type("B", (), {"token": "bearer-abc", "state": "license"})(),
        )
        seen: list[dict] = []

        class _Resp:
            status_code = 200

            def json(self):
                return {"viewer_url": "https://app.kiln3d.com/view#v=tok",
                        "viewer_expires_at": time.time() + 1800}

        def _post(url, **kw):
            files = kw.get("files") or {}
            seen.append({k: (v[0], v[1] if isinstance(v[1], bytes) else b"<stream>")
                         for k, v in files.items()})
            return _Resp()

        import httpx

        monkeypatch.setattr(httpx, "post", _post)
        monkeypatch.setattr(stage_link, "_cache", {})
        link = stage_link.stage_link_for(mesh)
        assert link and link["viewer_url"].endswith("#v=tok")
        assert "slicer" in seen[-1], "the sidecar did not ride the upload"
        name, raw = seen[-1]["slicer"]
        assert name == "slicer.json"
        assert sg.load_sidecar(raw)["available"]

    def test_a_re_slice_is_a_new_link_not_a_stale_tower(self, tmp_path, twin_dir, monkeypatch):
        """The sidecar is part of the link's identity: the cache must not
        serve a link still wearing the previous slice's extras."""
        mesh = _box(tmp_path / "part.stl")
        first = _gcode_for_box(tmp_path / "first.gcode")
        monitor_twin.note_sliced(mesh, first)
        monkeypatch.setattr(stage_link, "_stage_printer_id", lambda: None)
        monkeypatch.setattr(
            "kiln.auth_session.resolve_api_bearer",
            lambda *a, **k: type("B", (), {"token": "bearer-abc", "state": "license"})(),
        )
        calls = []

        class _Resp:
            status_code = 200

            def json(self):
                return {"viewer_url": f"https://app.kiln3d.com/view#v={len(calls)}",
                        "viewer_expires_at": time.time() + 1800}

        def _post(url, **kw):
            calls.append(kw)
            return _Resp()

        import httpx

        monkeypatch.setattr(httpx, "post", _post)
        monkeypatch.setattr(stage_link, "_cache", {})
        one = stage_link.stage_link_for(mesh)
        again = stage_link.stage_link_for(mesh)
        assert again["cached"] and again["viewer_url"] == one["viewer_url"]
        second = _gcode_for_box(tmp_path / "second.gcode", tower=False)
        monitor_twin.note_sliced(mesh, second)
        fresh = stage_link.stage_link_for(mesh)
        assert not fresh["cached"]
        assert fresh["viewer_url"] != one["viewer_url"]
        assert len(calls) == 2


