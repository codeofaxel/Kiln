class TestModelOnlyIsUnchanged:
    def test_no_slice_means_a_byte_identical_payload(self, tmp_path, twin_dir, no_printer):
        from kiln.mesh_payload import mesh_to_viewer_payload

        mesh = _box(tmp_path / "part.stl")
