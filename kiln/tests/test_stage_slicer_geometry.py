class TestSameFrameAsThePart:
    def test_extras_are_laid_around_the_centred_part(self, tmp_path, no_printer):
        """The part arrives corner-at-origin, the slice put it at the bed
        centre; after the door, both are centred on the stage and the
        skirt wraps the part, the tower stands 20 mm to its right."""
        from kiln.mesh_payload import mesh_to_viewer_payload

        mesh = _box(tmp_path / "part.stl")
        gcode = _gcode_for_box(tmp_path / "part.gcode")
        payload = stage_plate.attach_stage_plate(
            mesh_to_viewer_payload(mesh), gcode_path=gcode,
        )
        # The part is centred on the plate (mesh x -20..20, y -15..15).
        assert payload["bbox"]["min"][:2] == pytest.approx([-20.0, -15.0])
        assert payload["bbox"]["max"][:2] == pytest.approx([20.0, 15.0])
        block = payload["slicer"]
        assert block["available"] and block["frame"] == "viewer"
        by_class = {f["class"]: f for f in block["features"]}
        skirt = _segments(by_class["skirt"])
        # Viewer frame: x is mesh x; z is -mesh y.  The skirt is 2 mm out.
        assert skirt[:, [0, 3]].min() == pytest.approx(-22.0, abs=1e-3)
        assert skirt[:, [0, 3]].max() == pytest.approx(22.0, abs=1e-3)
        assert skirt[:, [2, 5]].min() == pytest.approx(-17.0, abs=1e-3)
        assert skirt[:, [2, 5]].max() == pytest.approx(17.0, abs=1e-3)
        # ...and it lies on the part's floor (viewer y = mesh z).
        assert skirt[:, [1, 4]].min() == pytest.approx(0.2, abs=1e-3)
        tower = _segments(by_class["prime_tower"])
        assert tower[:, [0, 3]].min() == pytest.approx(40.0, abs=1e-3)
        assert tower[:, [0, 3]].max() == pytest.approx(50.0, abs=1e-3)
        # The part's own vertices agree — the tower is beside the part's
        # +x face, not beside where the file's corner used to be.
        pos = _positions(payload)
        assert pos[:, 0].max() == pytest.approx(20.0, abs=1e-3)
        assert by_class["skirt"]["bounds"]["min"][0] == pytest.approx(-22.0, abs=1e-3)

    def test_a_late_centring_moves_the_extras_with_the_part(self, tmp_path):
        """A block attached to an off-centre payload rides the same slide
        stand_on_plate gives the vertices — pinned by comparing deltas."""
        from kiln.mesh_payload import mesh_to_viewer_payload

        mesh = _box(tmp_path / "part.stl")
        gcode = _gcode_for_box(tmp_path / "part.gcode")
        payload = mesh_to_viewer_payload(mesh)          # corner at the origin
        sg.attach_to_payload(payload, gcode)            # aligned to THAT bbox
        before_pos = _positions(payload).copy()
        before = {f["class"]: _segments(f).copy() for f in payload["slicer"]["features"]}
        stage_plate.stand_on_plate(payload)
        delta = _positions(payload)[0] - before_pos[0]
        assert delta[0] == pytest.approx(-20.0) and delta[2] == pytest.approx(15.0)
        for f in payload["slicer"]["features"]:
            a, b = before[f["class"]], _segments(f)
            assert np.allclose(b[:, [0, 3]] - a[:, [0, 3]], delta[0], atol=1e-4)
            assert np.allclose(b[:, [2, 5]] - a[:, [2, 5]], delta[2], atol=1e-4)
            assert np.allclose(b[:, [1, 4]], a[:, [1, 4]])
        assert payload["slicer"]["features"][0]["bounds"]["min"][0] == pytest.approx(-22.0, abs=1e-3)

    def test_a_downgraded_payload_carries_no_extras(self, tmp_path):
        gcode = _gcode_for_box(tmp_path / "part.gcode")
        payload = {"kind": "kiln.mesh.v1", "downgraded": True,
                   "bbox": {"min": [0, 0, 0], "max": [40, 30, 10]}}
        sg.attach_to_payload(payload, gcode)
        assert "slicer" not in payload


