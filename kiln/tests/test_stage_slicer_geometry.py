class TestTheLedgerJoin:
    def test_the_slice_ledger_answers_by_exact_path(self, tmp_path, twin_dir):
        mesh = _box(tmp_path / "part.stl")
        gcode = _gcode_for_box(tmp_path / "part.gcode")
        monitor_twin.note_sliced(mesh, gcode)
        assert monitor_twin.sliced_output_for(mesh) == os.path.abspath(gcode)

    def test_a_stem_match_is_not_a_join(self, tmp_path, twin_dir):
        (tmp_path / "elsewhere").mkdir()
        other = _box(tmp_path / "elsewhere" / "part.stl")  # same stem, other file
        mesh = _box(tmp_path / "part.stl")
        gcode = _gcode_for_box(tmp_path / "part.gcode")
        monitor_twin.note_sliced(other, gcode)
        assert monitor_twin.sliced_output_for(mesh) is None

    def test_the_newest_surviving_slice_wins(self, tmp_path, twin_dir):
        mesh = _box(tmp_path / "part.stl")
        old = _gcode_for_box(tmp_path / "old.gcode")
        new = _gcode_for_box(tmp_path / "new.gcode")
        monitor_twin.note_sliced(mesh, old)
        monitor_twin.note_sliced(mesh, new)
        assert monitor_twin.sliced_output_for(mesh) == os.path.abspath(new)
        os.unlink(new)
        assert monitor_twin.sliced_output_for(mesh) == os.path.abspath(old)

    def test_a_slice_older_than_the_mesh_is_not_a_slice_of_it(self, tmp_path, twin_dir):
        """A file edited in place after slicing keeps its path and loses
        its G-code — the extras of the previous shape must not dress it."""
        mesh = _box(tmp_path / "part.stl")
        gcode = _gcode_for_box(tmp_path / "part.gcode")
        monitor_twin.note_sliced(mesh, gcode)
        stale = time.time() - 120
        os.utime(gcode, (stale, stale))
        assert monitor_twin.sliced_output_for(mesh) is None

    def test_the_retained_twin_copy_answers_too(self, tmp_path, twin_dir):
        """``note_print_started`` copies the pair under the twin dir; the
        copy is the mesh the print monitor hands the stage."""
        mesh = _box(tmp_path / "part.stl")
        gcode = _gcode_for_box(tmp_path / "part.gcode")
        monitor_twin.note_sliced(mesh, gcode)
        monitor_twin.note_print_started("bambu", "part.gcode")
        rec = monitor_twin.active_twin("bambu")
        assert rec["mesh"] and rec["gcode"]
        assert monitor_twin.sliced_output_for(rec["mesh"]) == rec["gcode"]

    def test_the_plate_door_reaches_the_ledger(self, tmp_path, twin_dir, no_printer):
        from kiln.mesh_payload import mesh_to_viewer_payload

        mesh = _box(tmp_path / "part.stl")
        gcode = _gcode_for_box(tmp_path / "part.gcode")
        monitor_twin.note_sliced(mesh, gcode)
        payload = stage_plate.attach_stage_plate(mesh_to_viewer_payload(mesh), mesh_path=mesh)
        assert payload["slicer"]["available"]
        assert [f["class"] for f in payload["slicer"]["features"]] == ["skirt", "prime_tower"]

    def test_an_explicit_gcode_outranks_the_ledger(self, tmp_path, twin_dir, no_printer):
        from kiln.mesh_payload import mesh_to_viewer_payload

        mesh = _box(tmp_path / "part.stl")
        ledger = _gcode_for_box(tmp_path / "ledger.gcode")
        held = _gcode_for_box(tmp_path / "held.gcode", tower=False)
        monitor_twin.note_sliced(mesh, ledger)
        payload = stage_plate.attach_stage_plate(
            mesh_to_viewer_payload(mesh), mesh_path=mesh, gcode_path=held,
        )
        assert [f["class"] for f in payload["slicer"]["features"]] == ["skirt"]
        assert payload["slicer"]["source"]["filename"] == "held.gcode"

    def test_the_hosted_process_never_reads_the_shared_ledger(
        self, tmp_path, twin_dir, monkeypatch,
    ):
        """One ~/.kiln, every customer: a hosted caller's mesh must never
        be dressed in another tenant's skirt."""
        from kiln.mesh_payload import mesh_to_viewer_payload

        mesh = _box(tmp_path / "part.stl")
        gcode = _gcode_for_box(tmp_path / "part.gcode")
        monitor_twin.note_sliced(mesh, gcode)
        monkeypatch.setenv("KILN_HOSTED_MULTITENANT", "1")
        monkeypatch.setattr(
            monitor_twin, "sliced_output_for",
            lambda *a, **k: pytest.fail("hosted resolution read the shared ledger"),
        )
        payload = stage_plate.attach_stage_plate(mesh_to_viewer_payload(mesh), mesh_path=mesh)
        assert "slicer" not in payload
        # An explicit slice the hosted door HOLDS (the print twin) still counts.
        payload = stage_plate.attach_stage_plate(
            mesh_to_viewer_payload(mesh), mesh_path=mesh, gcode_path=gcode,
        )
        assert payload["slicer"]["available"]

    def test_a_slice_of_something_else_rides_as_an_honest_refusal(
        self, tmp_path, twin_dir, no_printer,
    ):
        from kiln.mesh_payload import mesh_to_viewer_payload

        mesh = _box(tmp_path / "big.stl", extents=(400.0, 300.0, 10.0))
        gcode = _gcode_for_box(tmp_path / "big.gcode")
        monitor_twin.note_sliced(mesh, gcode)
        payload = stage_plate.attach_stage_plate(mesh_to_viewer_payload(mesh), mesh_path=mesh)
        assert payload["slicer"]["available"] is False
        assert "does not match" in payload["slicer"]["reason"]


