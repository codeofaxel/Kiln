"""The doors that put slicer-added geometry on the stage.

Every payload-producing door goes through ``attach_stage_plate``; that is
the one place plate and placement are decided, so it is where the skirt,
brim, prime tower and supports are laid around the part too.  Three things
have to hold or the extras lie:

* they land in the SAME coordinate frame as the part — built against the
  centred bbox and moved by the same centring offset, so a skirt can never
  wrap empty plate beside the model it was sliced around;
* the slice belongs to THIS mesh — joined through the machine's own slice
  ledger by exact path, never by stem, never on the hosted server whose
  ledger is nobody's;
* with no slice, nothing changes — the model-only payload is byte-identical
  to one built before extras existed, so every stage that predates the
  block renders exactly as it did.
"""

from __future__ import annotations

import base64
import copy
import json
import os
import time

import numpy as np
import pytest

from kiln import local_stage, monitor_twin, stage_link, stage_plate
from kiln import slicer_geometry as sg


def _box(path, extents=(40.0, 30.0, 10.0), origin_corner=True):
    trimesh = pytest.importorskip("trimesh")
    mesh = trimesh.creation.box(extents=extents)
    if origin_corner:
        mesh.apply_translation([extents[0] / 2, extents[1] / 2, extents[2] / 2])
    mesh.export(str(path))
    return str(path)


def _loop(x0, y0, x1, y1, z):
    return (
        f"G1 X{x0} Y{y0} Z{z} F6000\nG1 X{x1} Y{y0} E0.1\nG1 X{x1} Y{y1} E0.1\n"
        f"G1 X{x0} Y{y1} E0.1\nG1 X{x0} Y{y0} E0.1\n"
    )


def _gcode_for_box(path, *, tower=True):
    """The 40 x 30 box sliced at bed (100..140, 100..130): skirt 2 mm out,
    a 10 mm prime tower 20 mm to the right."""
    lines = ["; generated by OrcaSlicer 2.3.2 on 2026-09-03", "G90", "M83"]
    for i in range(2):
        z = 0.2 * (i + 1)
        lines += [";LAYER_CHANGE", f";Z:{z}"]
        if i == 0:
            lines += [";TYPE:Skirt", _loop(98, 98, 142, 132, z)]
        lines += [";TYPE:Outer wall", _loop(100, 100, 140, 130, z)]
        if tower:
            lines += [";TYPE:Prime tower", _loop(160, 100, 170, 110, z)]
    path.write_text("\n".join(lines) + "\n")
    return str(path)


def _positions(payload):
    return np.frombuffer(base64.b64decode(payload["positions"]), dtype="<f4").reshape(-1, 3)


def _segments(feature):
    return np.frombuffer(base64.b64decode(feature["segments"]), dtype="<f4").reshape(-1, 6)


