class TestTheMovesAreUntouched:
    def test_every_non_comment_line_is_byte_identical(self, tmp_path, preview):
        path = raw_gcode(tmp_path)
        before = Path(path).read_text(encoding="utf-8")
        complete(path, "moonraker", preview_png=preview)
        after = Path(path).read_text(encoding="utf-8")
        assert _moves_of(after) == _moves_of(before)

    def test_completion_is_idempotent(self, tmp_path, preview):
        path = raw_gcode(tmp_path)
        complete(path, "moonraker", preview_png=preview)
        once = Path(path).read_bytes()
        complete(path, "moonraker", preview_png=preview)
        assert Path(path).read_bytes() == once

    def test_it_can_write_beside_the_original(self, tmp_path, preview):
        path = raw_gcode(tmp_path)
        out = tmp_path / "copy.gcode"
        complete(path, "moonraker", preview_png=preview, output_path=str(out))
        assert Path(path).read_text(encoding="utf-8") == _HEADER + _moves() + _FOOTER
        assert gcode_complete.gcode_problems(str(out), "moonraker") == []


