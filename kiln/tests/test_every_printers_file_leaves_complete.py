_HEADER = (
    "; generated by PrusaSlicer 2.9.4 on 2026-09-19 at 03:47:35 UTC\n"
    "\n"
    "; external perimeters extrusion width = 0.45mm\n"
    "M104 S200 ; set temperature\n"
    "M190 S60\n"
    "G28 ; home all axes\n"
)

#: What PrusaSlicer wrote for a Kiln slice, verbatim from the measured run:
#: a length, no per-extruder grams line at all, and a zero total.
_FOOTER = (
    "M104 S0 ; turn off temperature\n"
    "M84     ; disable motors\n"
    "; filament used [mm] = 1493.99\n"
    "; filament used [cm3] = 3.59\n"
    "; total filament used [g] = 0.00\n"
    "; estimated printing time (normal mode) = 13m 54s\n"
    "\n"
    "; prusaslicer_config = begin\n"
    "; filament_density = 0\n"
    "; filament_diameter = 1.75\n"
    "; filament_type = PLA\n"
    "; prusaslicer_config = end\n"
)


def _moves(count: int = 40) -> str:
    out = ["M83\n"]
    for i in range(count):
        out.append(f"G1 X{10 + i} Y{10 + i} E1.2 F1800\n")
    return "".join(out)


def raw_gcode(tmp_path: Path, name: str = "part.gcode") -> str:
    """The file Kiln hands a non-Bambu printer today: no picture, no weight."""
    p = tmp_path / name
    p.write_text(_HEADER + _moves() + _FOOTER, encoding="utf-8")
    return str(p)


def png_bytes(width: int, height: int, rgb=(200, 60, 60)) -> bytes:
    from PIL import Image

    buf = io.BytesIO()
    Image.new("RGB", (width, height), rgb).save(buf, format="PNG")
    return buf.getvalue()


@pytest.fixture
def preview() -> bytes:
    """A picture of the plate, at the largest size any surface asks for."""
    return png_bytes(400, 300)


def complete(path: str, family: str | None = None, **kw) -> str:
    kw.setdefault("preview_png", png_bytes(400, 300))
    return gcode_complete.complete_gcode_for_printer(path, family, **kw)


def _png_size(data: bytes):
    return struct.unpack(">II", data[16:24]) if data[:8] == b"\x89PNG\r\n\x1a\n" else None


def _moves_of(text: str) -> list[str]:
    """Every line that is not a comment and not blank — what the printer
    actually executes.  A blank line is part of the block shape PrusaSlicer's
    own emitter writes (``"\\n;\\n; thumbnail begin ..."``)."""
    return [
        ln for ln in text.splitlines()
        if ln.strip() and not ln.lstrip().startswith(";")
    ]


