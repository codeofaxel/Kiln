class TestWeightFill:
    def test_the_weight_matches_what_the_usage_reader_computes(self, tmp_path):
        from kiln.printers.bambu_3mf import filament_usage_from_gcode

        path = raw_gcode(tmp_path)
        before = Path(path).read_text(encoding="utf-8")
        expected = filament_usage_from_gcode(before)
        assert expected.total_g > 0, "the fixture must extrude something"

        complete(path, "moonraker")
        text = Path(path).read_text(encoding="utf-8")
        total = float(re.search(r"; total filament used \[g\] = ([\d.]+)", text).group(1))
        assert total == pytest.approx(round(expected.total_g, 2), abs=0.01)

    def test_the_per_extruder_line_is_written_when_the_slicer_omitted_it(self, tmp_path):
        """PrusaSlicer writes ``filament used [g]`` only for multi-material,
        and PrusaLink reads exactly that key."""
        path = raw_gcode(tmp_path)
        assert "; filament used [g]" not in Path(path).read_text(encoding="utf-8")
        complete(path, "prusalink")
        text = Path(path).read_text(encoding="utf-8")
        grams = float(re.search(r"^; filament used \[g\] = ([\d.]+)$", text, re.M).group(1))
        assert grams > 0

    def test_the_length_the_slicer_knew_is_left_alone(self, tmp_path):
        path = raw_gcode(tmp_path)
        complete(path, "duet")
        text = Path(path).read_text(encoding="utf-8")
        assert "; filament used [mm] = 1493.99" in text

    def test_a_weight_the_slicer_worked_out_is_kept(self, tmp_path):
        path = tmp_path / "known.gcode"
        path.write_text(
            _HEADER + _moves()
            + _FOOTER.replace("used [g] = 0.00", "used [g] = 24.41"),
            encoding="utf-8",
        )
        complete(str(path), "moonraker")
        text = path.read_text(encoding="utf-8")
        assert "; total filament used [g] = 24.41" in text

    def test_a_file_that_extrudes_nothing_may_weigh_nothing(self, tmp_path):
        """A plate with no extrusion may honestly say 0.00 — the check is
        'it lays down filament and claims to weigh nothing', not 'it says
        zero'."""
        path = tmp_path / "empty.gcode"
        footer = _FOOTER.replace("; filament used [mm] = 1493.99\n", "")
        path.write_text(_HEADER + "G1 X10 Y10 F1800\n" + footer, encoding="utf-8")
        problems = gcode_complete.gcode_problems(str(path), "moonraker")
        assert not any("weight" in p for p in problems), problems


