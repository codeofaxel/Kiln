class TestThumbnailBlockFormat:
    def test_the_block_is_prusaslicers_own_shape(self, tmp_path, preview):
        path = raw_gcode(tmp_path)
        complete(path, "moonraker", preview_png=preview)
        text = Path(path).read_text(encoding="utf-8")

        begins = re.findall(r"^; thumbnail begin (\d+)x(\d+) (\d+)$", text, re.MULTILINE)
        assert [(w, h) for w, h, _ in begins] == [("400", "300"), ("32", "32")], begins
        assert text.count("; thumbnail end") == 2

    def test_moonrakers_own_regex_reads_it(self, tmp_path, preview):
        """The pattern copied verbatim from Moonraker's metadata.py, and the
        size check it applies: a declared length that is not the base64's
        own length is dropped with ``Thumbnail Size Mismatch``."""
        path = raw_gcode(tmp_path)
        complete(path, "moonraker", preview_png=preview)
        text = Path(path).read_text(encoding="utf-8")

        pattern = r"(thumbnail(?:_[A-Za-z0-9]+)?) begin([;/\+=\w\s]+?); \1 end"
        found = []
        for match in re.finditer(pattern, text):
            lines = re.split(r"\r?\n", match.group(2).replace("; ", ""))
            info = [int(n) for n in re.findall(r"\d+", lines[0])]
            data = "".join(lines[1:-1])
            assert len(info) == 3, lines[0]
            assert len(data) == info[2], "Moonraker would report a size mismatch"
            decoded = base64.b64decode(data.encode())
            assert _png_size(decoded) == (info[0], info[1])
            found.append((info[0], info[1]))
        assert found == [(400, 300), (32, 32)], found

    def test_moonraker_gets_the_32x32_it_makes_its_own_miniature_from(
        self, tmp_path, preview,
    ):
        path = raw_gcode(tmp_path)
        complete(path, "moonraker", preview_png=preview)
        assert (32, 32) in gcode_complete.gcode_thumbnails(
            Path(path).read_text(encoding="utf-8")
        )

    def test_no_base64_row_is_longer_than_the_emitter_writes(self, tmp_path, preview):
        path = raw_gcode(tmp_path)
        complete(path, "moonraker", preview_png=preview)
        for line in Path(path).read_text(encoding="utf-8").splitlines():
            if line.startswith("; ") and not line.startswith("; thumbnail"):
                assert len(line) <= 2 + 78, line[:40]

    def test_the_picture_precedes_the_first_extrusion(self, tmp_path, preview):
        """OctoPrint's reader stops at the first ``G1`` carrying an ``E``."""
        path = raw_gcode(tmp_path)
        complete(path, "octoprint", preview_png=preview)
        lines = Path(path).read_text(encoding="utf-8").splitlines()
        first_extrusion = next(
            i for i, ln in enumerate(lines)
            if ln.startswith("G1") and re.search(r"\bE[-\d.]", ln)
        )
        last_block_line = max(i for i, ln in enumerate(lines) if "thumbnail end" in ln)
        assert last_block_line < first_extrusion

    def test_octoprints_own_regex_reads_it(self, tmp_path, preview):
        path = raw_gcode(tmp_path)
        complete(path, "octoprint", preview_png=preview)
        text = Path(path).read_text(encoding="utf-8")
        regex = (
            r"(?:^; thumbnail(?:_JPG)* begin \d+[x ]\d+ \d+)(?:\n|\r\n?)"
            r"((?:.+(?:\n|\r\n?))+?)(?:^; thumbnail(?:_JPG)* end)"
        )
        assert re.findall(regex, text, re.MULTILINE)

    def test_prusalink_ignores_nothing_it_was_given(self, tmp_path, preview):
        """gcode-metadata drops any thumbnail under 50x50 and picks the one
        closest to 640x480; 400x300 shares that aspect ratio."""
        path = raw_gcode(tmp_path)
        complete(path, "prusalink", preview_png=preview)
        sizes = gcode_complete.gcode_thumbnails(Path(path).read_text(encoding="utf-8"))
        assert any(w >= 50 and h >= 50 for w, h in sizes), sizes


