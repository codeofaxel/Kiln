class TestThePictureCanComeFromTheFileItself:
    """Without this the refusal would name a remedy its owner could not
    reach: somebody's own Cura or Orca export has no mesh beside it, so
    there would be nothing to draw the preview from and the file would be
    stuck outside the door forever.  The toolpath in the file is the mesh."""

    def test_a_file_with_no_mesh_beside_it_still_completes(self, tmp_path):
        path = raw_gcode(tmp_path)
        gcode_complete.complete_gcode_for_printer(path, "moonraker")
        assert gcode_complete.gcode_problems(path, "moonraker") == []

    def test_the_picture_is_drawn_from_the_extrusion_moves(self, tmp_path):
        from PIL import Image

        text = Path(raw_gcode(tmp_path)).read_text(encoding="utf-8")
        png = gcode_complete._render_from_gcode(text, 400, 300)
        assert png is not None
        img = Image.open(io.BytesIO(png))
        assert img.size == (400, 300)
        inked = sum(1 for px in img.convert("RGBA").getdata() if px[3] > 0)
        assert inked > 50, "the toolpath drew nothing"

    def test_travel_only_moves_draw_nothing(self, tmp_path):
        text = _HEADER + "G1 X10 Y10 F1800\nG1 X50 Y50 F1800\n"
        assert gcode_complete._render_from_gcode(text, 400, 300) is None

    def test_a_file_that_prints_nothing_is_not_asked_for_a_picture(self, tmp_path):
        """A homing check or a levelling macro is not a print, and is not
        held to a print's standard."""
        path = tmp_path / "level.gcode"
        path.write_text("; generated by PrusaSlicer\nG28\nG29\n", encoding="utf-8")
        assert gcode_complete.gcode_problems(str(path), "moonraker") == []

    def test_a_file_that_cannot_be_read_is_the_adapters_own_error(self, tmp_path):
        assert gcode_complete.gcode_problems(str(tmp_path / "nope.gcode"), "duet") == []


