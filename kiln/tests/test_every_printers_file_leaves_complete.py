class TestTheThreePrintDoors:
    """``slice_and_print``, ``reslice_and_print`` and ``quick_print`` all
    hand their file to ``prepare_upload_for_adapter``.  A Bambu gets a
    wrapped archive there; everybody else used to get the raw G-code
    untouched and meet the upload refusal one step later, with nothing in
    between that could fix it."""

    def test_a_raw_gcode_printer_gets_a_complete_file(self, tmp_path):
        from kiln.printers.upload_prep import prepare_upload_for_adapter

        adapter = _Fake("moonraker")
        path = raw_gcode(tmp_path)
        upload_path, wrapped = prepare_upload_for_adapter(adapter, path)
        assert (upload_path, wrapped) == (path, False)
        assert gcode_complete.gcode_problems(path, "moonraker") == []
        assert adapter.upload_file(upload_path).success

    def test_the_bambu_wrap_path_is_untouched(self, tmp_path):
        """An adapter that wraps still wraps, and nothing writes into the
        G-code on its way there."""
        from kiln.printers.upload_prep import prepare_upload_for_adapter

        path = raw_gcode(tmp_path)
        before = Path(path).read_bytes()

        class _Wrapping(_Fake):
            def wrap_gcode_as_3mf(self, gcode_path, **kwargs):
                return gcode_path + ".3mf"

        upload_path, wrapped = prepare_upload_for_adapter(_Wrapping("bambu"), path)
        assert wrapped is True and upload_path.endswith(".3mf")
        assert Path(path).read_bytes() == before
