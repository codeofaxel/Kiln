"""The plate a start's safety checks read is the plate the printer prints.

A file whose plate 1 matches the printer's nozzle and whose plate 2 does
not, started as plate 2 under every spelling a caller could send.  Pinned:

* a plate number that is not a whole number from 1 up is refused, in plain
  words, before anything is sent;
* plate 2 is checked as plate 2, by the exact member the printer asks for;
* an archive in which two members could answer to plate 2 is refused, and so
  is a start of a plate the file does not hold;
* the Bambu command asks for the plate the gate checked.
"""

from __future__ import annotations

import zipfile

import pytest

from kiln.printers import print_gate as pg
from tests.test_bambu_adapter import _no_read_back, _pin_store_env, adapter_with_mqtt  # noqa: F401 -- fixtures
from tests.test_nozzle_size_check import _Adapter, _setting


def _plate(nozzle: str) -> str:
    return (
        "; HEADER_BLOCK_START\n; generated by BambuStudio 02.03.00.70\n; HEADER_BLOCK_END\n"
        f"; nozzle_diameter = {nozzle}\nG28\nG1 X10 Y10 E1\n"
    )


def _file(tmp_path, members: dict[str, str]) -> str:
    path = tmp_path / "two.gcode.3mf"
    with zipfile.ZipFile(path, "w") as zf:
        for name, body in members.items():
            zf.writestr(name, body)
    return str(path)


@pytest.fixture()
def two_plates(tmp_path):
    """Plate 1 sliced for the printer's 0.6 nozzle, plate 2 for 0.4."""
    return _file(tmp_path, {"Metadata/plate_1.gcode": _plate("0.6"), "Metadata/plate_2.gcode": _plate("0.4")})


@pytest.fixture(autouse=True)
def _clear_overrides():
    pg._oversize_grants.clear()
    yield
    pg._oversize_grants.clear()


@pytest.mark.parametrize("spelled", ["02", "2", 2.0, -1, 0, True])
def test_a_plate_number_that_is_not_one_is_refused_before_anything_is_sent(two_plates, spelled):
    printer = _Adapter(_setting(0.6))
    result = printer.start_print(two_plates, plate_number=spelled)

    assert result.success is False and printer.impl_calls == []
    assert result.code == pg.PLATE_NUMBER_REFUSED
    assert "whole number from 1 up" in result.message


@pytest.mark.parametrize("spelled", ["02", "2", 2.0, -1, 0])
def test_the_gate_refuses_an_odd_spelling_itself(two_plates, spelled):
    verdict = pg.run_adapter_gate(_Adapter(_setting(0.6)), two_plates, {"plate_number": spelled})
    assert verdict["blocked"] and verdict["code"] == pg.PLATE_NUMBER_REFUSED


def test_plate_two_is_checked_as_plate_two(two_plates):
    printer = _Adapter(_setting(0.6))
    result = printer.start_print(two_plates, plate_number=2)

    assert result.success is False and printer.impl_calls == []
    assert "0.4 mm" in result.message
    assert printer.start_print(two_plates, plate_number=1).success is True


def test_two_members_that_could_be_plate_two_are_refused(tmp_path):
    path = _file(tmp_path, {
        "Metadata/plate_1.gcode": _plate("0.6"),
        "Metadata/plate_2.gcode": _plate("0.4"),
        "metadata/Plate_2.gcode": _plate("0.6"),
    })
    printer = _Adapter(_setting(0.6))
    result = printer.start_print(path, plate_number=2)

    assert result.success is False and printer.impl_calls == []
    assert result.code == pg.PLATE_NOT_IN_FILE


def test_a_plate_spelled_with_a_leading_zero_inside_the_file_is_not_plate_two(tmp_path):
    path = _file(tmp_path, {"Metadata/plate_1.gcode": _plate("0.6"), "Metadata/plate_02.gcode": _plate("0.6")})
    printer = _Adapter(_setting(0.6))
    result = printer.start_print(path, plate_number=2)

    assert result.success is False and result.code == pg.PLATE_NOT_IN_FILE


def test_a_plate_the_file_does_not_hold_is_refused(two_plates):
    printer = _Adapter(_setting(0.6))
    result = printer.start_print(two_plates, plate_number=3)

    assert result.success is False and printer.impl_calls == []
    assert result.code == pg.PLATE_NOT_IN_FILE and "its plates: 1, 2" in result.message


@pytest.mark.parametrize(("spelled", "asked"), [(None, "Metadata/plate_1.gcode"), (2, "Metadata/plate_2.gcode")])
def test_the_bambu_command_asks_for_the_plate_the_gate_resolved(adapter_with_mqtt, spelled, asked):  # noqa: F811
    import json

    adapter = adapter_with_mqtt
    kwargs = {} if spelled is None else {"plate_number": spelled}
    adapter.start_print("model.3mf", **kwargs)
    payload = json.loads(adapter._mqtt_client.publish.call_args[0][1])
    assert payload["print"]["param"] == asked


def test_the_bambu_command_is_never_sent_for_an_odd_spelling(adapter_with_mqtt):  # noqa: F811
    adapter = adapter_with_mqtt
    result = adapter.start_print("model.3mf", plate_number="02")
    assert result.success is False and not adapter._mqtt_client.publish.called
