class TestTheComparison:
    def test_a_different_size_differs_and_refuses(self, tmp_path):
        check = check_nozzle_size(_Adapter(_setting(0.6)), _gcode_file(tmp_path, "0.4"))
        assert check.status == "differs"
        assert check.refuses is True
        assert (check.file_mm, check.printer_mm) == (pytest.approx(0.4), pytest.approx(0.6))

    def test_the_same_size_matches(self, tmp_path):
        check = check_nozzle_size(_Adapter(_setting(0.4)), _gcode_file(tmp_path, "0.40"))
        assert check.status == "match" and check.refuses is False

    def test_a_setting_the_host_software_keeps_differs_without_refusing(self, tmp_path):
        setting = _setting(0.6, material=None, source="octoprint_printer_profile", held_by="host")
        check = check_nozzle_size(_Adapter(setting), _gcode_file(tmp_path, "0.4"))
        assert check.status == "differs" and check.refuses is False

    @pytest.mark.parametrize(
        "setting",
        [
            None,  # this backend has no nozzle setting to read
            _setting(None),  # the machine reported a type and no size
            _setting(0.6, age_seconds=120.0, stale_after_seconds=60.0),  # a printer gone quiet
            RuntimeError("printer unreachable"),
            MagicMock(),  # not a reading at all
        ],
        ids=["no-door", "no-size", "stale", "read-raised", "not-a-reading"],
    )
    def test_a_printer_that_cannot_be_read_is_unchecked_never_a_match(self, tmp_path, setting):
        check = check_nozzle_size(_Adapter(setting), _gcode_file(tmp_path, "0.4"))
        assert check.status == "unchecked" and check.refuses is False and check.why

    @pytest.mark.parametrize("nozzle", [None, "0.4,0.6"], ids=["states-none", "states-two"])
    def test_a_file_with_no_one_size_is_unchecked(self, tmp_path, nozzle):
        check = check_nozzle_size(_Adapter(_setting(0.6)), _gcode_file(tmp_path, nozzle))
        assert check.status == "unchecked" and check.refuses is False and check.why

    def test_a_read_past_the_deadline_is_unchecked(self, tmp_path, monkeypatch):
        import kiln.printer_nozzle_reading as reading

        class _Slow(_Adapter):
            def read_nozzle_setting(self):
                time.sleep(0.5)
                return _setting(0.6)

        _Slow.__abstractmethods__ = frozenset()
        monkeypatch.setattr(reading, "LIVE_READ_DEADLINE_S", 0.05)
        check = check_nozzle_size(_Slow(), _gcode_file(tmp_path, "0.4"))
        assert check.status == "unchecked"


