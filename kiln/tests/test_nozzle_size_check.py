def _sliced(nozzle: str | None = "0.4") -> str:
    """A homed, on-bed slice the way PrusaSlicer writes one: the toolpath,
    then its settings block at the end."""
    settings = "; filament_type = PLA\n; layer_height = 0.2\n"
    if nozzle is not None:
        settings += f"; nozzle_diameter = {nozzle}\n"
    return (
        "; generated by PrusaSlicer 2.9.4\n"
        ";===== machine: A1 =====\nG28\n"
        "M190 S65\nM104 S220\nM109 S220\nG21\nG90\nM83\nM107\n"
        ";LAYER_CHANGE\n;Z:0.2\n"
        "G1 Z.4 F24000\nG1 X114.658 Y114.939\nG1 Z.2\n"
        ";TYPE:Skirt/Brim\nG1 F3000\nG1 X116.4 Y113.37 E.06961\n"
        + settings
        + "; printer_model = \n"
    )


def _gcode_file(tmp_path, nozzle: str | None = "0.4", name: str = "part.gcode") -> str:
    path = tmp_path / name
    path.write_text(_sliced(nozzle))
    return str(path)


def _setting(diameter: float | None, **changed) -> NozzleSetting:
    fields = {"material": "hardened_steel", "diameter_mm": diameter, "source": "bambu_mqtt_report"}
    fields.update(changed)
    return NozzleSetting(**fields)


class _Adapter(PrinterAdapter):
    """A printer that answers for its nozzle setting, and records a start."""

    printer_id = "bambu_a1"

    def __init__(self, setting: object = None) -> None:
        self.setting = setting
        self.impl_calls: list[str] = []

    def _start_print_impl(self, file_name: str, **kwargs) -> PrintResult:
        self.impl_calls.append(file_name)
        return PrintResult(success=True, message="IMPL")

    def read_nozzle_setting(self):
        if isinstance(self.setting, Exception):
            raise self.setting
        return self.setting


_Adapter.__abstractmethods__ = frozenset()


