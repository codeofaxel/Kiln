def _idle_state():
    from kiln.printers.base import PrinterStatus

    state = MagicMock()
    state.connected = True
    state.state = PrinterStatus.IDLE
    state.tool_temp_actual = 25.0
    state.tool_temp_target = 0.0
    state.bed_temp_actual = 25.0
    state.bed_temp_target = 0.0
    return state


class TestThePreflightNamesTheNozzleSize:
    def _preflight(self, setting, file_path):
        from kiln.server import preflight_check

        with (
            patch("kiln.server._get_adapter") as get_adapter,
            patch("kiln.server._get_temp_limits", return_value=(280.0, 120.0)),
        ):
            get_adapter.return_value.get_state.return_value = _idle_state()
            get_adapter.return_value.read_nozzle_setting.return_value = setting
            result = preflight_check(file_path=file_path)
        return result, {c["name"]: c for c in result["checks"]}

    def test_a_different_size_fails_the_preflight(self, tmp_path):
        result, checks = self._preflight(_setting(0.6), _gcode_file(tmp_path, "0.4"))
        row = checks["nozzle_size"]
        assert row["passed"] is False and result["ready"] is False
        assert "0.4 mm" in row["message"] and "0.6 mm" in row["message"]

    def test_the_same_size_passes(self, tmp_path):
        _, checks = self._preflight(_setting(0.4), _gcode_file(tmp_path, "0.4"))
        assert checks["nozzle_size"]["passed"] is True
        assert checks["nozzle_size"].get("checked", True) is True

    def test_a_printer_that_cannot_be_read_says_not_checked(self, tmp_path):
        _, checks = self._preflight(None, _gcode_file(tmp_path, "0.4"))
        row = checks["nozzle_size"]
        assert row["passed"] is True and row["checked"] is False and row["message"]

    def test_no_file_means_nothing_to_compare(self):
        _, checks = self._preflight(_setting(0.6), None)
        assert "nozzle_size" not in checks


