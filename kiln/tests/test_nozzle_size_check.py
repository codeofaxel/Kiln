"""The nozzle a file was sliced for, against the nozzle the printer says it has.

Two halves.  The package Kiln builds for a printer states the size the
slice was made for, never a fixed one.  And a start whose file and printer
state different sizes is refused, by the gate every door reaches; a printer
or a file that cannot say is never counted as agreeing, and never blocks.
"""

