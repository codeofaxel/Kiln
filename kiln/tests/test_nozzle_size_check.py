class TestTheFileStatesTheNozzleItWasSlicedFor:
    def test_every_statement_is_read_in_file_order(self):
        text = "; CONFIG_BLOCK_START\n; nozzle_diameter = 0.4\n; CONFIG_BLOCK_END\nG28\n; nozzle_diameter = 0.6\n"
        assert slicer_nozzle_diameters(text) == ((0.4,), (0.6,))

    def test_one_entry_per_extruder(self):
        assert slicer_nozzle_diameters("; nozzle_diameter = 0.4,0.4,0.6\n") == ((0.4, 0.4, 0.6),)

    def test_a_file_that_states_none_gives_none(self):
        assert slicer_nozzle_diameters(";FLAVOR:Marlin\n;Layer height: 0.2\nG28\n") == ()

    def test_only_a_setting_line_counts(self):
        text = "M104 S200 ; nozzle_diameter = 0.8\n; nozzle_diameter = abc\n; nozzle_diameter = 40\n"
        assert slicer_nozzle_diameters(text) == ()

    def test_one_size_stated_is_the_files_size(self, tmp_path):
        assert file_nozzle_mm(_gcode_file(tmp_path, "0.6,0.6")) == pytest.approx(0.6)

    def test_two_sizes_stated_is_no_answer(self, tmp_path):
        assert file_nozzle_mm(_gcode_file(tmp_path, "0.4,0.6")) is None

    def test_a_mesh_states_nothing(self, tmp_path):
        mesh = tmp_path / "part.stl"
        mesh.write_text("solid part\nendsolid part\n")
        assert file_nozzle_mm(str(mesh)) is None


