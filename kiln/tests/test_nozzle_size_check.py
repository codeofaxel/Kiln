def _threemf_bytes(gcode: str) -> bytes:
    """A plate the printer's own storage holds, with the previews a Bambu
    plate must carry so it is judged on its G-code."""
    from PIL import Image

    from kiln.printers.bambu_3mf import _BAMBU_THUMBNAIL_SPECS, _REQUIRED_TILE_SLOTS

    buf = io.BytesIO()
    with zipfile.ZipFile(buf, "w") as zf:
        zf.writestr("Metadata/plate_1.gcode", gcode)
        for slot in _REQUIRED_TILE_SLOTS:
            tile = io.BytesIO()
            Image.new("RGB", _BAMBU_THUMBNAIL_SPECS[slot], (90, 90, 90)).save(tile, format="PNG")
            zf.writestr(slot, tile.getvalue())
        tile = io.BytesIO()
        Image.new("RGB", (512, 512), (90, 90, 90)).save(tile, format="PNG")
        zf.writestr("Metadata/plate_no_light_1.png", tile.getvalue())
    return buf.getvalue()


class _OnThePrinter(_Adapter):
    """The same printer, started by the name of a file on its own storage."""

    def __init__(self, setting: object, data: bytes) -> None:
        super().__init__(setting)
        self._data = data

    def read_print_file(self, file_name: str) -> bytes | None:
        return self._data


_OnThePrinter.__abstractmethods__ = frozenset()


class TestAStartIsRefusedWhenTheSizesDiffer:
    def test_the_start_is_refused_and_nothing_is_sent(self, tmp_path):
        printer = _Adapter(_setting(0.6))
        job = _gcode_file(tmp_path, "0.4")
        result = printer.start_print(job)
        assert result.success is False
        assert printer.impl_calls == []
        assert "0.4 mm" in result.message and "0.6 mm" in result.message
        assert "force_print_oversize" in result.message

    def test_the_verdict_names_the_block(self, tmp_path):
        verdict = pg.run_adapter_gate(_Adapter(_setting(0.6)), _gcode_file(tmp_path, "0.4"), {})
        assert verdict["blocked"] is True and verdict["code"] == MISMATCH_CODE
        assert verdict["nozzle_size"]["file_mm"] == pytest.approx(0.4)
        assert verdict["nozzle_size"]["printer_mm"] == pytest.approx(0.6)

    def test_matching_sizes_start(self, tmp_path):
        printer = _Adapter(_setting(0.4))
        job = _gcode_file(tmp_path, "0.4")
        assert printer.start_print(job).success is True and printer.impl_calls == [job]

    @pytest.mark.parametrize(
        "setting",
        [None, _setting(None), _setting(0.6, age_seconds=120.0, stale_after_seconds=60.0), RuntimeError("down")],
        ids=["no-door", "no-size", "stale", "read-raised"],
    )
    def test_a_printer_that_cannot_be_read_never_blocks_a_start(self, tmp_path, setting):
        printer = _Adapter(setting)
        job = _gcode_file(tmp_path, "0.4")
        assert printer.start_print(job).success is True and printer.impl_calls == [job]

    def test_a_host_kept_setting_never_blocks_a_start(self, tmp_path):
        printer = _Adapter(_setting(0.6, material=None, source="octoprint_printer_profile", held_by="host"))
        job = _gcode_file(tmp_path, "0.4")
        assert printer.start_print(job).success is True

    def test_the_human_override_lets_one_start_through(self, tmp_path):
        printer = _Adapter(_setting(0.6))
        job = _gcode_file(tmp_path, "0.4")
        pg.grant_oversize_override("bambu_a1", ttl_seconds=300)
        assert printer.start_print(job).success is True
        # One start, not a window of them.
        assert printer.start_print(job).success is False
        assert printer.impl_calls == [job]

    def test_a_file_started_by_name_off_the_printer_is_judged_the_same(self):
        printer = _OnThePrinter(_setting(0.6), _threemf_bytes(_sliced("0.4")))
        result = printer.start_print("part.gcode.3mf")
        assert result.success is False and printer.impl_calls == []
        assert "0.4 mm" in result.message and "0.6 mm" in result.message
        # Nothing is wrong with the file; it is not told to be deleted.
        assert "delete" not in result.message.lower()

    def test_a_matching_file_on_the_printer_starts(self):
        printer = _OnThePrinter(_setting(0.4), _threemf_bytes(_sliced("0.4")))
        assert printer.start_print("part.gcode.3mf").success is True


