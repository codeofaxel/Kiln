_START = ";===== machine: A1 =====\nM104 S220\nM140 S65\nG28\nM109 S220\nM190 S65\n"
_END = "M104 S0\nM140 S0\n"


def _package(tmp_path, body: str, **settings) -> str:
    from kiln.printers.bambu_3mf import BambuPrintSettings, build_bambu_3mf

    out = str(tmp_path / "part.gcode.3mf")
    with (
        patch("kiln.printers.bambu_3mf._load_a1_start_gcode", return_value=_START),
        patch("kiln.printers.bambu_3mf._select_end_gcode", return_value=(_END, "bambu_a1")),
    ):
        build_bambu_3mf(body, out, settings=BambuPrintSettings(**settings) if settings else None)
    return out


def _what_the_printer_is_told(path: str) -> dict[str, float]:
    with zipfile.ZipFile(path) as zf:
        gcode = zf.read("Metadata/plate_1.gcode").decode()
        info = zf.read("Metadata/slice_info.config").decode()
        plate = json.loads(zf.read("Metadata/plate_1.json"))
    header = gcode.split("; CONFIG_BLOCK_END", 1)[0]
    return {
        "header": float(re.search(r"^; nozzle_diameter = (\S+)$", header, re.M).group(1)),
        "slice_info": float(re.search(r'key="nozzle_diameters" value="([^"]+)"', info).group(1)),
        "filament": float(re.search(r'nozzle_diameter="([^"]+)"', info).group(1)),
        "plate": float(plate["nozzle_diameter"]),
    }


_BODY = (
    "; generated by PrusaSlicer\nM83\nG28\nM104 S200\nM140 S60\n\n"
    ";BEFORE_LAYER_CHANGE\n;Z:0.2\n;LAYER_CHANGE\nG1 Z0.2 F600\nG1 X110 Y110 E0.5\n\n"
    ";BEFORE_LAYER_CHANGE\n;Z:0.4\n;LAYER_CHANGE\nG1 Z0.4 F600\nG1 X120 Y120 E0.5\n"
)


class TestThePackageStatesTheSizeTheSliceWasMadeFor:
    def test_a_slice_for_a_wider_nozzle_is_labelled_that_size(self, tmp_path):
        told = _what_the_printer_is_told(_package(tmp_path, _BODY + "; nozzle_diameter = 0.6\n"))
        assert told == {name: pytest.approx(0.6) for name in ("header", "slice_info", "filament", "plate")}

    def test_one_entry_per_extruder_labels_the_first(self, tmp_path):
        told = _what_the_printer_is_told(_package(tmp_path, _BODY + "; nozzle_diameter = 0.8,0.8\n"))
        assert told["slice_info"] == pytest.approx(0.8)

    def test_a_body_wrapped_once_already_is_labelled_by_its_slicer_not_its_old_header(self, tmp_path):
        # A plate lifted out of an earlier package carries that package's
        # header on top of the slicer's own settings.
        old_header = "; CONFIG_BLOCK_START\n; nozzle_diameter = 0.4\n; CONFIG_BLOCK_END\n"
        told = _what_the_printer_is_told(_package(tmp_path, old_header + _BODY + "; nozzle_diameter = 0.6\n"))
        assert told["slice_info"] == pytest.approx(0.6) and told["plate"] == pytest.approx(0.6)

    def test_a_slice_that_states_no_size_is_labelled_the_stock_one(self, tmp_path):
        told = _what_the_printer_is_told(_package(tmp_path, _BODY))
        assert told == {name: pytest.approx(0.4) for name in ("header", "slice_info", "filament", "plate")}

    def test_a_size_the_caller_states_wins(self, tmp_path):
        told = _what_the_printer_is_told(
            _package(tmp_path, _BODY + "; nozzle_diameter = 0.6\n", nozzle_diameter=0.2)
        )
        assert told["slice_info"] == pytest.approx(0.2)

    def test_the_package_agrees_with_itself_so_the_start_can_be_judged(self, tmp_path):
        # Labelled 0.4 over a 0.6 toolpath, the file stated two sizes and no
        # start could be judged against it.
        package = _package(tmp_path, _BODY + "; nozzle_diameter = 0.6\n")
        assert file_nozzle_mm(package) == pytest.approx(0.6)
        printer = _Adapter(_setting(0.4))
        result = printer.start_print(package)
        assert result.success is False and printer.impl_calls == []
        assert "0.6 mm" in result.message and "0.4 mm" in result.message


