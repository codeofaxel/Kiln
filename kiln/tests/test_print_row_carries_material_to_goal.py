def _sliced(tmp_path: Path, *, types: str = "PETG") -> Path:
    """A model and a G-code sliced from it for *types*, recorded in the slice
    ledger the way the slicer does."""
    from kiln.monitor_twin import note_sliced

    model = tmp_path / "dash_mount.stl"
    model.write_text("solid m\nendsolid m\n")
    gcode = tmp_path / "dash_mount.gcode"
    gcode.write_text(f"; generated by PrusaSlicer\nG28\nG1 X1\n; filament_type = {types}\n")
    note_sliced(str(model), str(gcode))
    return gcode


def _the_row(db: KilnDB) -> dict[str, Any]:
    rows = db.list_print_outcomes(limit=10, include_all=True)
    assert len(rows) == 1, rows
    return rows[0]


class TestTheRowsMaterialAtStart:
    def test_a_start_that_commands_no_filament_stamps_the_sliced_files(self, tmp_path, db):
        gcode = _sliced(tmp_path, types="PETG")
        assert _Bench().start_print(gcode.name, version_id="v-1").success
        row = _the_row(db)
        assert row["material_type"] == "PETG"
        assert row["version_id"] == "v-1"
        assert row["outcome"] == "pending"

    def test_the_commanded_filament_outranks_the_files(self, tmp_path, db):
        gcode = _sliced(tmp_path, types="PLA")
        _Bench().start_print(gcode.name, material="ASA")
        assert _the_row(db)["material_type"] == "ASA"

    def test_a_file_sliced_for_several_filaments_stamps_none(self, tmp_path, db):
        gcode = _sliced(tmp_path, types="PLA;PETG")
        _Bench().start_print(gcode.name)
        assert _the_row(db)["material_type"] is None

    def test_a_file_this_computer_never_sliced_stamps_none(self, db):
        _Bench().start_print("someone_elses.gcode")
        assert _the_row(db)["material_type"] is None


class TestTheRowOnItsWayToTheAccount:
    def test_the_account_row_carries_the_material_word(self, tmp_path, db):
        gcode = _sliced(tmp_path, types="PETG")
        _Bench().start_print(gcode.name, version_id="v-1")
        out = outcome_courier.account_row(_the_row(db), "a" * 32)
        assert out["material"] == "PETG"
        assert out["version_id"] == "v-1"
        assert "dash_mount" not in repr(out)

    def test_the_push_carries_the_material_and_the_version(self, tmp_path, db, monkeypatch):
        gcode = _sliced(tmp_path, types="PETG")
        _Bench().start_print(gcode.name, version_id="v-1")
        row = _the_row(db)
        db.save_print_outcome({
            "job_id": row["job_id"], "printer_name": row["printer_name"],
            "outcome": "success", "determined_by": "observed",
        })
        monkeypatch.setattr(
            auth_session, "resolve_api_bearer",
            lambda *a, **k: auth_session.ApiBearer(token="tok", state="license"),
        )
        monkeypatch.setattr(outcome_courier, "_kept_here", lambda rows: set())
        calls: list[dict[str, Any]] = []

        def fake_request(tool, method, path, body=None, **kw):
            calls.append({"path": path, "body": body})
            rows = (body or {}).get("rows") or []
            return {"status": "success", "success": True,
                    "kept": [r["source_job_id"] for r in rows], "held": [], "refused": 0}

        import kiln.history_courier as hc

        monkeypatch.setattr(hc, "_request", fake_request)

        assert outcome_courier.push_owed(db=db)["sent"] == 1
        (call,) = calls
        assert call["path"] == outcome_courier.PUSH_PATH
        (sent,) = call["body"]["rows"]
        assert sent["material"] == "PETG"
        assert sent["version_id"] == "v-1"
        assert sent["printer_model"] == "bambu_a1"
        assert sent["ending"] == "success"
