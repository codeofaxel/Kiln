"""A print's own record carries the filament it printed in to the person's account.

The row every print opens at its start (``print_outcomes``) is what the
courier copies to the account, and the account is where a saved goal learns
the filament its part really printed in.  So the row's material at the start
has to be what the goal would have been told: the filament the start
commanded, else the one the sliced file names -- never blank where that is
known, and never the loaded spool guessed.

Pinned, through a REAL adapter's inherited start template and the real
``KilnDB``:

* a start that commands no filament stamps the sliced file's on the row;
* a commanded filament outranks the file's;
* a file sliced for several filaments stamps none;
* the row as it goes to the account carries the material word;
* the courier's push for that row carries the material and the version.
"""

