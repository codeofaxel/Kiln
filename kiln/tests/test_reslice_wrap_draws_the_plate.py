"""The reslice pipeline's Bambu wrap is handed a mesh to draw its tiles from.

2026-11-03 lap: ``reslice_and_print`` (the pipeline behind ``multi_copy_print``
and every reslice-then-print door) called the shared upload helper with no
``stl_paths``, while ``quick_print`` beside it passed the model.  A Bambu
archive built that way carried no preview tiles, and the Bambu adapter
refuses to upload one (its screen would show a broken tile), so a fill of
copies never reached the printer.  The suite missed it because the
pipeline's wrapping tests stub ``wrap_gcode_as_3mf`` and never look at what
it was handed.  Fails at public 2b3c4cb2.
"""
from __future__ import annotations

import os
import zipfile
from pathlib import Path
from unittest.mock import MagicMock, patch

from kiln.printers.base import PrinterAdapter, PrinterState, PrinterStatus, UploadResult

_BAMBU_HEAD = "; HEADER_BLOCK_START\n; BambuStudio 01.09.00.00\n; HEADER_BLOCK_END\n"


class _Wrapping(PrinterAdapter):
    """A Bambu-like printer: wraps, records what the wrap was handed, and is
    offline at preflight so the run stops after the upload."""

    def __init__(self, tmp_path: Path) -> None:
        self.tmp_path = tmp_path
        self.wrap_kwargs: list[dict] = []
        self.uploads: list[str] = []

    @property
    def name(self) -> str:
        return "bambu"

    def get_state(self) -> PrinterState:
        return PrinterState(state=PrinterStatus.OFFLINE, connected=False)

    def upload_file(self, file_path: str) -> UploadResult:
        self.uploads.append(file_path)
        return UploadResult(success=True, file_name=os.path.basename(file_path), message="ok")

    def wrap_gcode_as_3mf(self, gcode_path: str, **kwargs) -> str:
        self.wrap_kwargs.append(dict(kwargs))
        out = self.tmp_path / "wrapped.gcode.3mf"
        with zipfile.ZipFile(out, "w") as zf:
            zf.writestr("Metadata/plate_1.gcode", _BAMBU_HEAD + Path(gcode_path).read_text())
        return str(out)


_Wrapping.__abstractmethods__ = frozenset()


def _gcode(tmp_path: Path) -> Path:
    out = tmp_path / "out.gcode"
    out.write_text("; generated by PrusaSlicer\nG28\nM104 S210\nG1 X10 Y10 Z0.2 E1\nM104 S0\n")
    return out


def _cube(path: Path) -> str:
    import numpy as np
    import trimesh

    trimesh.creation.box(extents=(20.0, 20.0, 20.0)).apply_translation((10.0, 10.0, 10.0)).export(str(path))
    assert np.isfinite(trimesh.load(str(path)).volume)
    return str(path)


def _run(tmp_path: Path, adapter: _Wrapping, **more):
    from kiln.pipelines import reslice_and_print

    slice_result = MagicMock(output_path=str(_gcode(tmp_path)), message="Sliced OK", slicer="prusaslicer")
    slice_result.stage_mesh_path = more.pop("stage_mesh_path", None)
    model = more.pop("model_path", None) or _cube(tmp_path / "model.stl")
    with (
        patch("kiln.slicer.slice_file", return_value=slice_result),
        patch("kiln.slicer_profiles.resolve_slicer_profile", return_value=str(tmp_path / "p.ini")),
        patch("kiln.server._resolve_adapter", return_value=adapter),
    ):
        return reslice_and_print(model_path=model, printer_name="p", printer_id="bambu_a1", skip_validation=True, **more)


def test_the_wrap_is_handed_the_model_to_draw(tmp_path):
    adapter = _Wrapping(tmp_path)
    result = _run(tmp_path, adapter)
    upload = [s for s in result.steps if s.name == "upload"]
    assert upload and upload[0].success, [s.message for s in result.steps]
    assert adapter.wrap_kwargs and adapter.wrap_kwargs[0].get("stl_paths") == [str(tmp_path / "model.stl")]


def test_a_staged_plate_wins_over_the_model(tmp_path):
    """A fill slices a merged plate of copies; the tiles show that plate,
    not one copy of the part."""
    adapter = _Wrapping(tmp_path)
    plate = _cube(tmp_path / "plate_multi.stl")
    _run(tmp_path, adapter, stage_mesh_path=plate)
    assert adapter.wrap_kwargs and adapter.wrap_kwargs[0].get("stl_paths") == [plate]
