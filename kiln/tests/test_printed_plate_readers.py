@pytest.fixture()
def printer_says_06(monkeypatch):
    from kiln import printer_nozzle_reading
    from kiln.printers.base import NozzleSetting

    monkeypatch.setattr(
        printer_nozzle_reading, "read_setting",
        lambda adapter: NozzleSetting(material=None, diameter_mm=0.6, source="test"),
    )


def test_the_nozzle_check_compares_the_printed_plate(tmp_path, printer_says_06):
    from kiln.nozzle_size_check import check_nozzle_size
    from kiln.printers import print_gate

    path = _project(tmp_path, {1: _plate(minutes=1, grams=1, mm=1, nozzle="0.4"),
                               2: _plate(minutes=1, grams=1, mm=1, nozzle="0.6")})
    assert check_nozzle_size(object(), path, 2).status == "match"
    assert check_nozzle_size(object(), path, 1).refuses
    assert print_gate._nozzle_size_verdict(object(), path, "f", None, False, 2) is None
    assert print_gate._nozzle_size_verdict(object(), path, "f", None, False, 1)["blocked"]


def test_with_no_plate_named_every_plate_is_compared(tmp_path, printer_says_06):
    from kiln.nozzle_size_check import check_nozzle_size

    path = _project(tmp_path, {1: _plate(minutes=1, grams=1, mm=1, nozzle="0.6"),
                               2: _plate(minutes=1, grams=1, mm=1, nozzle="0.4")})
    check = check_nozzle_size(object(), path)
    assert check.refuses and check.file_mm == 0.4


def test_the_start_gate_judges_the_plate_it_starts(tmp_path):
    from kiln.printers import print_gate
    from tests.test_nozzle_size_check import _Adapter, _setting

    path = _project(tmp_path, {1: _plate(minutes=1, grams=1, mm=1, nozzle="0.4"),
                               2: _plate(minutes=1, grams=1, mm=1, nozzle="0.6")})
    assert not (print_gate.run_adapter_gate(_Adapter(_setting(0.6)), path, {"plate_number": 2}) or {}).get("blocked")
    assert print_gate.run_adapter_gate(_Adapter(_setting(0.6)), path, {})["blocked"]


