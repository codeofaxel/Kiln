def test_an_experiment_on_any_plate_is_found_when_no_plate_is_named(tmp_path):
    from kiln.experimental_print import mixed_sizes_of_file

    path = _project(tmp_path, {1: _plate(minutes=1, grams=1, mm=1, nozzle="0.4"),
                               2: _plate(minutes=1, grams=1, mm=1, nozzle="0.4,0.8")})
    assert mixed_sizes_of_file(path) == (0.4, 0.8)
    assert mixed_sizes_of_file(path, 1) is None
    assert mixed_sizes_of_file(path, 2) == (0.4, 0.8)


