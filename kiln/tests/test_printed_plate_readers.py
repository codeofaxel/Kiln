"""Every reader of the file a start prints reads the plate that is printed.

A sliced 3MF can carry several plates, each with its own filament, nozzle,
stamps and figures.  Pinned here, reader by reader:

* the filament charged at a start is the printed plate's;
* the weight and cost of a print file are its printed plate's, and none when
  no plate is named and the file holds several;
* the nozzle-size check compares the printed plate, and with no plate named
  compares every plate and answers with the first that differs (a plate that
  would be refused is never passed because another was read);
* an experiment (nozzles of different sizes) is found on any plate when no
  plate is named, and on the printed plate when one is;
* what a start's lineage reads (stamps and stated facts) is the printed
  plate's, and nothing is stated for a file of several plates with none named;
* an object taken out of a plate carries no remaining time of the plate, and
  the 3MF it is wrapped in keeps that plate's record alone, with no predicted
  time and the object's own filament.

The last test slices a real two-plate project with Bambu Studio when it is
installed.
"""

from __future__ import annotations

import json
import os
import re
import shutil
import subprocess
import zipfile
from pathlib import Path

import pytest


def _plate(*, minutes: int, grams: float, mm: float, nozzle: str = "0.4", material: str = "PLA",
           stamp: str | None = None) -> str:
    stamped = f"; kiln_lineage = {stamp}\n" if stamp else ""
    return (
        "; HEADER_BLOCK_START\n; generated by BambuStudio 02.03.00.70\n"
        f"; model printing time: {minutes}m 0s; total estimated time: {minutes}m 0s\n"
        f"; total filament length [mm] : {mm}\n; total filament weight [g] : {grams}\n"
        "; HEADER_BLOCK_END\n"
        f"; filament_type = {material}\n; nozzle_diameter = {nozzle}\n{stamped}"
        "G28\nG1 X10 Y10 E1\n"
    )


def _project(tmp_path: Path, plates: dict[int, str], name: str = "project.gcode.3mf") -> str:
    path = tmp_path / name
    with zipfile.ZipFile(path, "w") as zf:
        for number, body in plates.items():
            zf.writestr(f"Metadata/plate_{number}.gcode", body)
    return str(path)


def _two(tmp_path: Path, **second: object) -> str:
    return _project(tmp_path, {
        1: _plate(minutes=60, grams=10.0, mm=3000.0),
        2: _plate(**{"minutes": 180, "grams": 40.0, "mm": 12000.0, **second}),
    })


# ---------------------------------------------------------------------------
# The filament charged at a start
# ---------------------------------------------------------------------------


def test_the_charge_reads_the_printed_plates_grams(tmp_path):
    from kiln import spool_usage

    path = _two(tmp_path)
    assert spool_usage._file_usage(path, 2).total == 40.0
    assert spool_usage._file_usage(path, 1).total == 10.0
    assert spool_usage._file_usage(path, None) is None


def test_the_start_charges_the_plate_it_names(tmp_path, monkeypatch):
    from kiln import spool_usage

    asked: list[tuple] = []
    monkeypatch.setattr(spool_usage, "_file_usage", lambda *a: asked.append(a))
    monkeypatch.setattr(spool_usage, "_forget", lambda printer: None)
    spool_usage._charge_worker(object(), "p", "f.gcode.3mf", {"plate_number": 2})
    spool_usage._charge_worker(object(), "p", "f.gcode.3mf", {})

    assert [a[1:] for a in asked] == [(2,), (1,)]


