def test_the_weight_is_the_printed_plates_from_its_gcode(tmp_path):
    from kiln.cost_estimator import CostEstimator

    path = _two(tmp_path)
    assert CostEstimator().filament_pricing(path, plate_number=2).length_mm == pytest.approx(12000.0)
    assert CostEstimator().filament_pricing(path) is None


def test_the_weight_is_the_printed_plates_from_the_slice_record(tmp_path):
    from kiln.cost_estimator import CostEstimator

    path = _two(tmp_path)
    with zipfile.ZipFile(path, "a") as zf:
        zf.writestr("Metadata/slice_info.config", (
            '<?xml version="1.0"?><config>'
            '<plate><metadata key="index" value="1"/><metadata key="prediction" value="3600"/>'
            '<filament id="1" type="PLA" used_m="3.00" used_g="10.00"/></plate>'
            '<plate><metadata key="index" value="2"/><metadata key="prediction" value="10800"/>'
            '<filament id="1" type="PLA" used_m="12.00" used_g="40.00"/></plate></config>'
        ))
    assert CostEstimator().filament_pricing(path, plate_number=2).weight_g == pytest.approx(40.0)
    assert CostEstimator().filament_pricing(path) is None


