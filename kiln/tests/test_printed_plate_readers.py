def test_the_lineage_reads_the_printed_plates_stamps_and_facts(tmp_path):
    from kiln import print_lineage

    path = _project(tmp_path, {1: _plate(minutes=1, grams=1, mm=1, material="PLA", stamp="a" * 16),
                               2: _plate(minutes=1, grams=1, mm=1, material="PETG", stamp="b" * 16)})
    assert print_lineage._stamps_of_print_file(path, 2) == ["b" * 16]
    assert print_lineage._stamps_of_print_file(path) == ["a" * 16, "b" * 16]
    assert print_lineage.stated_facts(path, 2)["material"] == "PETG"
    assert print_lineage.stated_facts(path)["material"] is None


def test_a_starts_lineage_is_asked_about_the_plate_it_starts(monkeypatch):
    from kiln import auto_record_hook, print_lineage

    asked: list[object] = []

    def resolve(file_name, **kw):
        asked.append(kw.get("plate_number"))
        return {"part": print_lineage.PART_UNKNOWN}

    monkeypatch.setattr(print_lineage, "resolve", resolve)
    auto_record_hook.print_identity_at_start(object(), {"plate_number": 2}, "f.gcode.3mf")
    auto_record_hook.print_identity_at_start(object(), {}, "f.gcode.3mf")

    assert asked == [2, 1]


