def _plate_of_two_objects(tmp_path: Path) -> str:
    from tests import test_plate_objects as fixtures

    gcode = (
        fixtures._GCODE.replace("M83 ; relative extrusion", "M83 ; relative extrusion\nM73 P0 R130")
        .replace("; CHANGE_LAYER\nG1 Z0.4", "M73 P50 R65\n; CHANGE_LAYER\nG1 Z0.4")
        .replace("; MACHINE_END_GCODE_START", "M73 P100 R0\n; MACHINE_END_GCODE_START")
    )
    source = tmp_path / "plate.gcode.3mf"
    with zipfile.ZipFile(source, "w") as zf:
        zf.writestr("Metadata/plate_1.json", json.dumps({"tag": "plate one", **fixtures._PLATE_JSON}))
        zf.writestr("Metadata/plate_2.json", json.dumps({"tag": "plate two", **fixtures._PLATE_JSON}))
        zf.writestr("Metadata/plate_1.gcode", gcode)
        zf.writestr("Metadata/plate_2.gcode", gcode)
        zf.writestr("Metadata/slice_info.config", (
            '<?xml version="1.0"?>\n<config>\n'
            '  <plate>\n    <metadata key="index" value="1"/>\n    <metadata key="prediction" value="7800"/>\n'
            '    <metadata key="weight" value="50.00"/>\n'
            '    <filament id="1" type="PLA" used_m="16.00" used_g="50.00"/>\n  </plate>\n'
            '  <plate>\n    <metadata key="index" value="2"/>\n    <metadata key="prediction" value="9000"/>\n'
            '    <metadata key="weight" value="60.00"/>\n'
            '    <filament id="1" type="PLA" used_m="20.00" used_g="60.00"/>\n  </plate>\n</config>\n'
        ))
    return str(source)


def test_an_object_taken_out_carries_no_remaining_time_of_the_plate(tmp_path):
    from kiln.generation.validation import extract_plate_object_gcode

    result = extract_plate_object_gcode(
        _plate_of_two_objects(tmp_path), "lid", output_path=str(tmp_path / "lid.gcode"), plate_number=2,
    )
    m73 = [line for line in Path(result["output_path"]).read_text().splitlines() if line.startswith("M73")]
    assert m73 and all(re.fullmatch(r"M73 P\d+", line) for line in m73)
    assert result["estimated_time_minutes"] is None and result["estimated_time_human"] is None


def test_the_wrapped_object_keeps_its_plates_record_with_no_time(tmp_path):
    from kiln.generation.validation import extract_plate_object_gcode
    from kiln.printers.bambu_3mf import repackage_gcode_as_bambu_3mf

    source = _plate_of_two_objects(tmp_path)
    taken = extract_plate_object_gcode(source, "lid", output_path=str(tmp_path / "lid.gcode"), plate_number=2)
    wrapped = repackage_gcode_as_bambu_3mf(
        taken["output_path"], str(tmp_path / "lid.gcode.3mf"), source_3mf_path=source, taken_from_plate=2,
    )
    with zipfile.ZipFile(wrapped) as zf:
        info = zf.read("Metadata/slice_info.config").decode()
        plate_json = json.loads(zf.read("Metadata/plate_1.json"))
    assert info.count("<plate>") == 1 and 'key="index" value="1"' in info
    assert "prediction" not in info
    assert 'used_m="20.00"' not in info and 'used_g="60.00"' not in info
    assert plate_json["tag"] == "plate two"


# ---------------------------------------------------------------------------
# A real two-plate project, sliced by Bambu Studio
# ---------------------------------------------------------------------------

_BAMBU = shutil.which("bambu-studio") or (
    "/Applications/BambuStudio.app/Contents/MacOS/BambuStudio"
    if os.access("/Applications/BambuStudio.app/Contents/MacOS/BambuStudio", os.X_OK) else None
)


@pytest.mark.skipif(_BAMBU is None, reason="Bambu Studio is not installed")
def test_a_real_two_plate_slice_is_read_plate_by_plate(tmp_path, monkeypatch):
    trimesh = pytest.importorskip("trimesh")
    from kiln.cost_estimator import CostEstimator
    from kiln.file_metadata import printed_gcode_lines
    from kiln.gcode import slicer_print_time
    from kiln.slicer_estimate import read_estimate
    from kiln.slicer_orca import ini_to_settings, write_orca_presets
    from kiln.slicer_profiles import resolve_slicer_profile

    monkeypatch.setenv("KILN_HOME", str(tmp_path / "home"))
    # Two slabs too wide to share a bed, of different heights: two plates, two times.
    for name, side, height in (("first", 150.0, 1.0), ("second", 140.0, 3.0)):
        trimesh.creation.box(extents=(side, side, height)).export(str(tmp_path / f"{name}.stl"))
    presets = write_orca_presets(ini_to_settings(resolve_slicer_profile("bambu_a1")), str(tmp_path), name="a1")
    sliced = tmp_path / "sliced.gcode.3mf"
    subprocess.run(
        [_BAMBU, "--load-settings", f"{presets.machine_path};{presets.process_path}",
         "--load-filaments", ";".join(presets.filament_paths), "--arrange", "1", "--slice", "0",
         "--export-3mf", str(sliced), str(tmp_path / "first.stl"), str(tmp_path / "second.stl")],
        capture_output=True, text=True, timeout=600, cwd=str(tmp_path),
    )
    assert sliced.is_file(), "Bambu Studio wrote no sliced project"
    import xml.etree.ElementTree as ET

    with zipfile.ZipFile(sliced) as zf:
        root = ET.fromstring(zf.read("Metadata/slice_info.config"))
    predicted: dict[int, int] = {}
    used_m: list[float] = []
    for plate in root.findall("plate"):
        meta = {md.get("key"): md.get("value") for md in plate.findall("metadata")}
        predicted[int(meta["index"])] = int(meta["prediction"])
        used_m.append(sum(float(f.get("used_m") or 0) for f in plate.findall("filament")))
    assert sorted(predicted) == [1, 2] and predicted[1] != predicted[2] and len(used_m) == 2

    stated = {n: slicer_print_time("\n".join(printed_gcode_lines(str(sliced), n))).seconds for n in (1, 2)}
    assert stated == {1: pytest.approx(predicted[1], abs=1), 2: pytest.approx(predicted[2], abs=1)}
    assert printed_gcode_lines(str(sliced), None) is None
    assert read_estimate(str(sliced))["seconds"] == pytest.approx(predicted[1] + predicted[2], abs=2)
    assert CostEstimator().filament_pricing(str(sliced), plate_number=2).length_mm == pytest.approx(used_m[1] * 1000)
    assert CostEstimator().filament_pricing(str(sliced)) is None
