class TestTheDoors:
    def test_the_start_template_files_the_plan(self, tmp_path, monkeypatch):
        import kiln.printers.base as base

        monkeypatch.setattr("kiln.printers.print_gate.run_adapter_gate", lambda *a, **k: None)
        monkeypatch.setattr(base, "_PRINT_STARTED_HOOKS", ())
        m = _Machine()
        assert m.start_print(_job_file(tmp_path)).success
        assert hs.has_plan(m)
        m.status, m.layer = PrinterStatus.PAUSED, 29
        assert hs.observe(m, m.get_state(), m.get_job())["stage"] == "now"

    def test_the_gate_reads_the_plan_from_the_copy_it_judges(self, tmp_path, monkeypatch):
        from kiln.printers.print_gate import run_adapter_gate

        seen = []
        monkeypatch.setattr(hs, "stage", lambda adapter, file_name, path: seen.append((file_name, path)))
        path = _job_file(tmp_path)
        run_adapter_gate(_Machine(), path, {})
        assert seen == [(path, path)]

    def test_printer_status_carries_the_block(self, machine):
        from kiln.server import printer_status

        machine.status, machine.layer = PrinterStatus.PAUSED, 29
        with patch("kiln.server._get_adapter", return_value=machine):
            lite = printer_status(detail="lite")
        assert lite["hardware"]["stage"] == "now" and lite["hardware"]["insert"] == "2x M3 nut in S1, S2"

    def test_the_monitor_report_says_what_goes_in(self, machine):
        from kiln.server import monitor_print

        machine.status, machine.layer = PrinterStatus.PAUSED, 29
        with patch("kiln.server._get_adapter", return_value=machine):
            report = monitor_print(include_snapshot=False)
        assert "- Hardware: Now is the time to put in 2x M3 nut in S1, S2." in report
        assert "  2. Put in: 2x M3 nut in S1, S2." in report

    def test_resume_print_refuses_then_resumes_on_the_persons_word(self, machine, monkeypatch):
        import kiln.server as server

        monkeypatch.setattr(server, "_check_rate_limit", lambda name: None)
        machine.status, machine.layer = PrinterStatus.PAUSED, 29
        with patch("kiln.server._get_adapter", return_value=machine):
            refused = server.resume_print()
            assert refused["success"] is False and refused["code"] == hs.NOT_CONFIRMED
            assert refused["hardware"]["stage"] == "now" and machine.resumed == 0
            assert server.resume_print(hardware_confirmed=True)["success"] is True
        assert machine.resumed == 1

    def test_the_wait_tool_comes_back_at_the_stop(self, machine):
        from kiln.server import await_print_completion

        machine.status, machine.layer = PrinterStatus.PAUSED, 29
        with patch("kiln.server._get_adapter", return_value=machine):
            result = await_print_completion(timeout=5, poll_interval=0)
        assert result["outcome"] == "hardware_stop" and result["hardware"]["stage"] == "now"

    def test_the_wait_tool_names_the_after_print_step(self, machine):
        from kiln.server import await_print_completion

        machine.status, machine.ended = PrinterStatus.IDLE, JobResult.COMPLETED
        with patch("kiln.server._get_adapter", return_value=machine):
            result = await_print_completion(timeout=5, poll_interval=0)
        assert result["outcome"] == "completed" and result["hardware"]["stage"] == "after_print"

    def test_the_watcher_hands_the_stop_back_instead_of_inviting_a_resume(self, machine):
        from kiln.plugins.monitoring_tools import _PrintWatcher

        machine.status, machine.layer = PrinterStatus.PAUSED, 29
        watcher = _PrintWatcher("w1", machine, "bench", poll_interval=0)
        watcher._start_time = time.time()
        watcher._run()
        assert watcher._result["outcome"] == "hardware_stop"
        assert watcher._result["message"].startswith("Now is the time to put in")
        assert "Call resume_print" not in watcher._result["message"]

    def test_the_watcher_says_a_close_stop_once(self, machine):
        from kiln.plugins.monitoring_tools import _PrintWatcher

        machine.status, machine.layer = PrinterStatus.PRINTING, 26
        watcher = _PrintWatcher("w2", machine, "bench", poll_interval=0)
        watcher._start_time = time.time()
        watcher._run()
        assert watcher._result["outcome"] == "hardware_stop"
        assert watcher._result["hardware"]["stage"] == "coming_up"

    def test_the_cli_carries_the_persons_word(self):
        from click.testing import CliRunner

        from kiln.cli.main import cli

        with patch("kiln.cli.main._get_adapter_from_ctx") as get, \
                patch("kiln.cli.main._emergency_latch_status", return_value=None):
            get.return_value.resume_print.return_value = PrintResult(success=True, message="Print resumed.")
            result = CliRunner().invoke(cli, ["resume", "--hardware-in", "--json"])
        assert result.exit_code == 0, result.output
        get.return_value.resume_print.assert_called_once_with(force=False, hardware_confirmed=True)
