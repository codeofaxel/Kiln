class TestResume:
    def test_a_resume_at_the_stop_waits_for_the_persons_word(self, machine):
        machine.status, machine.layer = PrinterStatus.PAUSED, 29
        refused = machine.resume_print()
        assert isinstance(refused, HardwareStopRefusal) and refused.success is False
        assert refused.code == hs.NOT_CONFIRMED and refused.hardware["stage"] == "now"
        assert "2x M3 nut" in refused.message and machine.resumed == 0
        assert refused.to_dict()["hardware"]["before_layer"] == 29

        assert machine.resume_print(hardware_confirmed=True).success is True
        assert machine.resumed == 1
        assert hs._read_store()[hs.machine_key(machine)]["stops"]["1"]["confirmed_at"]

    def test_force_does_not_stand_in_for_the_persons_word(self, machine):
        machine.status, machine.layer = PrinterStatus.PAUSED, 29
        assert machine.resume_print(force=True).success is False and machine.resumed == 0

    def test_without_a_layer_counter_every_pause_asks_and_the_word_moves_on(self, machine):
        machine.status = PrinterStatus.PAUSED
        first = machine.resume_print()
        assert first.hardware["stop"] == 1 and first.hardware["certain"] is False
        assert first.message.startswith("The printer has paused. If this is the planned stop")
        assert machine.resume_print(hardware_confirmed=True).success is True
        machine.status = PrinterStatus.PAUSED
        assert machine.resume_print().hardware["stop"] == 2

    def test_a_pause_that_is_not_a_stop_resumes_as_usual(self, machine):
        machine.status, machine.layer = PrinterStatus.PAUSED, 12
        assert machine.resume_print().success is True and machine.resumed == 1

    def test_an_ordinary_print_resumes_as_before(self):
        plain = _Machine()
        plain.status = PrinterStatus.PAUSED
        assert plain.resume_print().success is True


