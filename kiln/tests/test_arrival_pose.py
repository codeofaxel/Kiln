class TestTurnFile:
    @pytest.mark.parametrize("kind", ["stl", "ply"])
    def test_a_mesh_file_is_turned_in_place_and_rests_on_the_bed(self, tmp_path, kind):
        path = _write(tmp_path / f"part.{kind}", _on_its_back(_figure_standing()))
        before = _extents(path)
        arrival_pose.turn_file(path, _STAND)
        after = _extents(path)
        assert after[2] == pytest.approx(53.0, abs=0.01)
        assert before[2] != after[2]
        from kiln.mesh_frame import load_mesh

        assert float(load_mesh(path, force="mesh").bounds[0][2]) == pytest.approx(0.0, abs=1e-6)

    def test_an_obj_keeps_its_material_lines_and_texture_coordinates(self, tmp_path):
        path = tmp_path / "part.obj"
        path.write_text(
            "mtllib part.mtl\no part\nv 0 0 0\nv 10 0 0\nv 10 0 20\nv 0 0 20\n"
            "vt 0 0\nvt 1 0\nvt 1 1\nvt 0 1\nvn 0 -1 0\nusemtl skin\n"
            "f 1/1/1 2/2/1 3/3/1\nf 1/1/1 3/3/1 4/4/1\n",
            encoding="utf-8",
        )
        arrival_pose.turn_file(str(path), _STAND)
        text = path.read_text(encoding="utf-8")
        assert "mtllib part.mtl" in text and "usemtl skin" in text
        assert text.count("\nvt ") == 4 and "f 1/1/1 2/2/1 3/3/1" in text
        # (x, y, z) -> (x, -z, y), then lifted to the bed: the 20-tall wall
        # along Z becomes depth along -Y, and nothing changes in X.
        verts = [line.split() for line in text.splitlines() if line.startswith("v ")]
        assert [float(v[1]) for v in verts] == [0.0, 10.0, 10.0, 0.0]
        assert min(float(v[3]) for v in verts) == pytest.approx(0.0)
        assert {float(v[2]) for v in verts} == {0.0, -20.0}

    def test_a_format_kiln_does_not_rewrite_is_refused(self, tmp_path):
        path = tmp_path / "part.glb"
        trimesh.Scene(trimesh.creation.box()).export(str(path))
        with pytest.raises(ValueError):
            arrival_pose.turn_file(str(path), _STAND)

    def test_the_words_and_the_undo(self):
        assert arrival_pose.turn_words(_STAND) == "90° front over back"
        assert arrival_pose.turn_words({"x": 0, "y": -90, "z": 0}) == "-90° side over side"
        assert arrival_pose.undo_of(_STAND) == {"rotation_x": -90.0}


