class TestMeasure:
    def test_a_box_stands_on_a_whole_face(self):
        facts = arrival_pose.measure(trimesh.creation.box(extents=(20.0, 30.0, 10.0)))
        assert [p["up"] for p in facts["poses"]] == [up for up, _x, _y in arrival_pose.AXIS_POSES]
        as_written = facts["poses"][0]
        assert as_written["height_mm"] == pytest.approx(10.0)
        assert as_written["contact_mm2"] == pytest.approx(600.0)
        assert as_written["footprint_mm2"] == pytest.approx(600.0)
        assert as_written["balance_mm"] > 0
        assert sorted(as_written["base_size_mm"], reverse=True) == pytest.approx([30.0, 20.0])

    def test_each_pose_is_the_turn_it_names(self):
        """Turned by its own ``turn``, the box stands at that pose's height."""
        box = trimesh.creation.box(extents=(20.0, 30.0, 10.0))
        facts = arrival_pose.measure(box)
        for pose in facts["poses"]:
            turned = box.copy()
            t = np.eye(4)
            t[:3, :3] = arrival_pose.rotation(pose["turn"]["x"], pose["turn"]["y"])
            turned.apply_transform(t)
            assert float(turned.extents[2]) == pytest.approx(pose["height_mm"], abs=1e-6)

    def test_a_plate_on_its_edge_rests_on_a_strip_and_lies_flat_on_a_face(self):
        plate = trimesh.creation.box(extents=(60.0, 3.0, 40.0))  # standing on its 3 mm edge
        facts = arrival_pose.measure(plate)
        by_up = {p["up"]: p for p in facts["poses"]}
        assert by_up["+Z"]["contact_mm2"] == pytest.approx(180.0)
        flat = [p for p in facts["poses"] if p["height_mm"] == pytest.approx(3.0)]
        assert {p["up"] for p in flat} == {"+Y", "-Y"}
        assert all(p["contact_mm2"] == pytest.approx(2400.0) for p in flat)

    def test_a_file_written_inside_out_measures_the_same(self):
        box = trimesh.creation.box(extents=(20.0, 30.0, 10.0))
        inside_out = trimesh.Trimesh(box.vertices.copy(), box.faces[:, ::-1].copy(), process=False)
        a = arrival_pose.measure(box)["poses"][0]
        b = arrival_pose.measure(inside_out)["poses"][0]
        assert b["contact_mm2"] == pytest.approx(a["contact_mm2"])

    def test_the_figure_on_its_back_touches_nothing_and_its_base_is_found(self):
        facts = arrival_pose.measure(_on_its_back(_figure_standing()))
        by_up = {p["up"]: p for p in facts["poses"]}
        assert by_up["+Z"]["contact_mm2"] == pytest.approx(0.0, abs=1e-6)
        assert by_up["+Y"]["contact_mm2"] == pytest.approx(np.pi * 15.0**2, rel=0.05)
        assert by_up["+Y"]["balance_mm"] > 0

    def test_the_measurements_scale_with_the_part(self):
        """The slab on the bed is a share of the height, so a part written
        in metres (0.02 across) is read as the same shape as one in
        millimetres."""
        small = trimesh.creation.box(extents=(0.02, 0.03, 0.01))
        facts = arrival_pose.measure(small)["poses"][0]
        assert facts["contact_mm2"] == pytest.approx(0.0006)

    def test_a_file_is_read_in_kilns_frame(self, tmp_path):
        """A GLB's own frame puts up on +Y; measured, it is already standing."""
        path = tmp_path / "box.glb"
        trimesh.Scene(trimesh.creation.box(extents=(40.0, 10.0, 20.0))).export(str(path))
        facts = arrival_pose.measure_file(str(path))
        assert facts["format"] == "glb" and facts["frame_known"] is True
        assert facts["poses"][0]["height_mm"] == pytest.approx(10.0)

    def test_an_empty_mesh_is_refused(self, tmp_path):
        path = tmp_path / "empty.stl"
        path.write_bytes(b"solid x\nendsolid x\n")
        with pytest.raises(ValueError):
            arrival_pose.measure_file(str(path))


