"""A model that arrives stands on the bed the right way up, and says what was done.

Measured 2026-10-26: a first user's figure, generated by Meshy and sent
through an agent in a browser, arrived on Kiln's stage lying on its back,
then, after the agent's own guess at a turn, on its side.  Its flat base
faced sideways both times.  Nothing stood it up, nothing said which way up
it had arrived, and the agent's turn left no record.

Pinned here:

* :func:`kiln.arrival_pose.measure` reads what a ruler would: a box stands
  on a whole face, a plate on its edge rests on a strip;
* :func:`kiln.arrival_pose.turn_file` rewrites a file turned, in its own
  format, resting on the bed, and an OBJ keeps its material lines;
* :func:`kiln.arrival_pose.stand_up` applies a turn Kiln is sure of, keeps
  the record beside the file with where it came from, and never rewrites a
  file a door only shows; a judgement that did not arrive leaves the part as
  it is and says why in the one served voice;
* the doors: a generated download stands up before the stage opens on it,
  and the stage on an existing file advises and writes nothing.

The judgement itself is Kiln's and lives on its servers; here it is stood
in for, so what is pinned is the floor every install runs.
"""

