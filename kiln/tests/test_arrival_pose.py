trimesh = pytest.importorskip("trimesh")

#: ``rotate_model``'s turn that stands a file written with up along Y.
_STAND = {"x": 90.0, "y": 0.0, "z": 0.0}


def _figure_standing() -> trimesh.Trimesh:
    """A figure on a base: a 30 mm disc, 3 mm thick, under a 20 x 10 x 50 body."""
    base = trimesh.creation.cylinder(radius=15.0, height=3.0)
    base.apply_translation((0, 0, 1.5))
    body = trimesh.creation.box(extents=(20.0, 10.0, 50.0))
    body.apply_translation((0, 0, 3.0 + 25.0))
    return trimesh.util.concatenate([base, body])


def _on_its_back(mesh: trimesh.Trimesh) -> trimesh.Trimesh:
    """*mesh* as a file with up along Y writes it: lying on its back once
    read as Z-up, so :data:`_STAND` stands it."""
    out = mesh.copy()
    t = np.eye(4)
    t[:3, :3] = arrival_pose.rotation(-90.0, 0.0)
    out.apply_transform(t)
    return out


def _write(path: Path, mesh: trimesh.Trimesh) -> str:
    mesh.export(str(path))
    return str(path)


def _extents(path: str) -> tuple[float, ...]:
    from kiln.mesh_frame import load_mesh

    return tuple(round(float(v), 2) for v in load_mesh(path, force="mesh").extents)


def _turn_verdict() -> Verdict:
    return Verdict("turn", "+Y", dict(_STAND), "It arrived on its back; Kiln stood it on its base.")


def _keep_verdict() -> Verdict:
    return Verdict("keep", "+Z", None, "It stands as it arrived.")


@pytest.fixture()
def judge(monkeypatch):
    """Kiln's judgement, stood in for: ``judge.verdict`` is what it answers,
    ``judge.miss`` the miss instead."""

    class _Judge:
        verdict: Verdict | None = _turn_verdict()
        miss: Miss | None = None
        asked: list[dict] = []

    def fake(facts):
        _Judge.asked.append(facts)
        if _Judge.miss is not None:
            return None, _Judge.miss
        return _Judge.verdict, None

    monkeypatch.setattr("kiln._pro_arrival_pose_bridge.judge", fake)
    return _Judge


