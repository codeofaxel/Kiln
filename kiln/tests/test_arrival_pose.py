class _FigureCloud(_Cloud):
    """A cloud generator whose file arrives on its back."""

    def download_result(self, job_id, output_dir=""):
        self._out.mkdir(parents=True, exist_ok=True)
        path = _write(self._out / f"{job_id}.stl", _on_its_back(_figure_standing()))
        return GenerationResult(job_id, self.name, path, "stl", os.path.getsize(path), _PROMPT)


class TestTheDoors:
    def test_a_generated_download_stands_up_before_the_stage_opens(self, tmp_path, judge, monkeypatch):
        monkeypatch.setattr("kiln.server._get_generation_provider", lambda name: _FigureCloud(tmp_path / "gen"))
        out = _call(_generation_door(), "download_generated_model", job_id="job-1", provider="cloudgen")
        assert out["success"] is True, out
        assert out["pose"]["status"] == arrival_pose.TURNED
        assert out["pose"]["said"].startswith("It arrived on its back")
        assert _extents(out["result"]["local_path"])[2] == pytest.approx(53.0, abs=0.01)
        assert out["dimensions"]["height_mm"] == pytest.approx(53.0, abs=0.01)
        assert out["came_from"].startswith("Generated with CloudGen")

    def test_the_stage_on_an_existing_file_advises_and_writes_nothing(self, tmp_path, judge):
        from kiln.plugins.mesh_tools import plugin

        tools: dict = {}

        class _Mcp:
            def tool(self, *_a, **_k):
                def keep(fn):
                    tools[fn.__name__] = fn
                    return fn

                return keep

        plugin.register(_Mcp())
        path = _write(tmp_path / "figure.stl", _on_its_back(_figure_standing()))
        bytes_before = Path(path).read_bytes()
        out = tools["show_on_stage"](path)
        assert out["success"] is True, out
        assert out["pose"]["status"] == arrival_pose.ADVISED and out["pose"]["turn"] == _STAND
        assert "rotate_model(rotation_x=90)" in out["pose"]["said"] and "puts it back" not in out["pose"]["said"]
        assert Path(path).read_bytes() == bytes_before

    def test_the_bridge_is_on_the_hosted_doors_roster(self):
        from kiln.served_answer import HOSTED_DOORS

        assert HOSTED_DOORS["kiln._pro_arrival_pose_bridge"][0] == "served_answer"

    def test_only_the_verdict_is_read_off_an_answer(self):
        from kiln import _pro_arrival_pose_bridge as bridge

        good = {"success": True, "known": True, "verdict": "turn", "up": "+Y", "turn": _STAND, "said": "Stood up.", "scores": [1, 2]}
        v = bridge._verdict_in(good)
        assert v is not None and v.turn == _STAND and not hasattr(v, "scores")
        assert bridge._verdict_in({**good, "turn": None}) is None
        assert bridge._verdict_in({**good, "verdict": "flip"}) is None
        assert bridge._verdict_in({**good, "known": False}) is None
        assert bridge._verdict_in({**good, "turn": {"x": 720}}) is None
        keep = bridge._verdict_in({"success": True, "known": True, "verdict": "keep", "said": "Stands."})
        assert keep is not None and keep.turn is None


