class TestStandUp:
    def test_a_turn_kiln_is_sure_of_is_applied_and_recorded(self, tmp_path, judge):
        path = _write(tmp_path / "figure.stl", _on_its_back(_figure_standing()))
        arrival.record(path, arrival.Arrival(kind=arrival.GENERATED, by="CloudGen", prompt=_PROMPT))
        record = arrival_pose.stand_up(path, source="cloudgen")
        assert record["status"] == arrival_pose.TURNED and record["by"] == "kiln"
        assert record["turn"] == _STAND and record["undo"] == {"rotation_x": -90.0}
        assert _extents(path)[2] == pytest.approx(53.0, abs=0.01)
        # The record sits beside the file, with where it came from still
        # readable though the bytes changed.
        kept = arrival.read_pose(path)
        assert kept and kept["status"] == arrival_pose.TURNED and kept["said"] == record["said"]
        assert arrival.read(path) is not None and arrival.read(path).by == "CloudGen"
        assert judge.asked[-1]["format"] == "stl" and judge.asked[-1]["source"] == "cloudgen"

    def test_a_door_that_only_shows_advises_and_writes_nothing(self, tmp_path, judge):
        path = _write(tmp_path / "figure.stl", _on_its_back(_figure_standing()))
        bytes_before = Path(path).read_bytes()
        record = arrival_pose.stand_up(path, may_turn=False)
        assert record["status"] == arrival_pose.ADVISED and record["turn"] == _STAND
        # Advice, never a claim: nothing was turned, so nothing "puts it back".
        assert "rotate_model(rotation_x=90)" in record["said"] and "stood it" not in record["said"]
        assert "undo" not in record
        assert Path(path).read_bytes() == bytes_before
        assert arrival.read_pose(path) is None, "a door that only shows writes nothing beside the file"
        assert sorted(os.listdir(tmp_path)) == ["figure.stl"]

    def test_a_part_that_stands_is_left_as_it_is(self, tmp_path, judge):
        judge.verdict = _keep_verdict()
        path = _write(tmp_path / "figure.stl", _figure_standing())
        bytes_before = Path(path).read_bytes()
        record = arrival_pose.stand_up(path)
        assert record["status"] == arrival_pose.STANDING and record["turn"] is None
        assert Path(path).read_bytes() == bytes_before

    def test_a_judgement_that_did_not_arrive_leaves_the_part_and_says_why(self, tmp_path, judge):
        judge.miss = Miss("signed_out", code="ACCOUNT_REQUIRED")
        path = _write(tmp_path / "figure.stl", _on_its_back(_figure_standing()))
        bytes_before = Path(path).read_bytes()
        record = arrival_pose.stand_up(path)
        assert record["status"] == arrival_pose.UNJUDGED and record["why"] == "signed_out"
        assert "Kiln can't" in record["said"] and "sign in" in record["said"]
        assert Path(path).read_bytes() == bytes_before

    def test_an_unreadable_file_is_left_and_says_so(self, tmp_path, judge):
        path = tmp_path / "junk.stl"
        path.write_bytes(b"not a mesh")
        record = arrival_pose.stand_up(str(path))
        assert record["status"] == arrival_pose.UNJUDGED and "could not read" in record["said"]
        assert judge.asked == []

    def test_announce_carries_the_pose(self, tmp_path, judge):
        path = _write(tmp_path / "figure.stl", _on_its_back(_figure_standing()))
        arrival_pose.stand_up(path)
        result = arrival.announce({"success": True}, path)
        assert result["pose"]["status"] == arrival_pose.TURNED
        assert "judged_at" not in result["pose"]

    def test_a_conversion_carries_the_pose(self, tmp_path, judge):
        path = _write(tmp_path / "figure.stl", _on_its_back(_figure_standing()))
        arrival_pose.stand_up(path)
        other = str(tmp_path / "figure_copy.stl")
        Path(other).write_bytes(Path(path).read_bytes())
        arrival.carry(path, other)
        assert arrival.read_pose(other)["status"] == arrival_pose.TURNED


