def test_a_reading_that_says_nothing_is_no_reading():
    assert print_evidence.progress_reading(JobProgress(completion=250.0)) == (None, None)
    assert print_evidence.progress_reading(JobProgress(completion=0.0, current_layer=9)) == (None, 9)
    assert print_evidence.progress_reading(JobProgress(completion=0.0)) == (0.0, None)
    assert print_evidence.progress_reading(JobProgress()) == (None, None)


def test_a_row_keeps_the_first_progress_it_was_given(db):
    db.open_pending_outcome(job_id="start:p:1", printer_name="p", file_name="a.gcode")
    assert db.record_progress_at_end(["p"], "a", fraction=0.4, layer=10)
    assert not db.record_progress_at_end(["p"], "a", fraction=0.9, layer=99)
    assert not db.record_progress_at_end(["p"], "a", fraction=1.4, layer=None)
    row = db.get_print_outcome("start:p:1")
    assert (row["progress_at_end"], row["layer_at_end"]) == (0.4, 10)


def test_a_bambu_push_that_ends_a_print_writes_its_progress(kiln_env, monkeypatch):  # noqa: F811
    from kiln.persistence import get_db
    from kiln.printers.bambu import BambuAdapter

    monkeypatch.setattr(print_evidence, "_hosted", lambda: False)
    monkeypatch.setattr(BambuAdapter, "_ensure_mqtt", lambda self: None)
    adapter = BambuAdapter(host="192.0.2.20", access_code="00000000", serial="00M09A000000000")
    get_db().open_pending_outcome(job_id="start:bambu:1", printer_name="bambu", file_name="bracket.3mf")

    def push(state: str, percent: int, layer: int) -> None:
        payload = {"print": {"command": "push_status", "gcode_state": state, "subtask_name": "bracket",
                             "gcode_file": "/sdcard/bracket.3mf", "print_error": 0,
                             "mc_percent": percent, "layer_num": layer}}
        adapter._on_message(None, None, SimpleNamespace(payload=json.dumps(payload).encode()))

    push("RUNNING", 10, 5)
    push("RUNNING", 62, 31)
    push("FAILED", 62, 31)
    row = _row("bambu")
    assert row["outcome"] != "pending"
    assert (row["progress_at_end"], row["layer_at_end"]) == (0.62, 31)


# ─────────────────────────── what leaves ─────────────────────────────────────

def test_the_courier_sends_the_four_facts_and_never_the_spools_id(db, signed_in, sent):  # noqa: F811
    _print(db, outcome="pending")
    code = "ab" * 16
    assert db.set_outcome_evidence("start:a1:1", "settings_code", code)
    assert db.set_outcome_evidence("start:a1:1", "spool_id", "spool-7f3a-sarahs-red")
    assert db.set_outcome_evidence("start:a1:1", "firmware_version", "01.07.00.00")
    assert db.record_progress_at_end(["Shop A1"], "my_secret_bracket", fraction=0.375, layer=42)
    db.save_print_outcome({"job_id": "start:a1:1", "printer_name": "Shop A1", "outcome": "failed",
                           "failure_mode": "warping", "determined_by": "observed"})
    assert outcome_courier.push_owed(db=db)["sent"] == 1
    (row,) = sent[-1]["body"]["rows"]
    assert row["settings_code"] == code
    assert (row["progress_at_end"], row["layer_at_end"]) == (0.375, 42)
    assert row["firmware"] == "01.07.00.00"
    assert row["spool_code"] == outbound_guard.spool_code("spool-7f3a-sarahs-red")
    assert re.fullmatch(r"sp:[0-9a-f]{24}", row["spool_code"])
    assert "sarahs" not in repr(row) and "spool_id" not in row and "firmware_version" not in row


def test_a_row_without_the_facts_sends_none_of_their_keys(db):
    row = {"version_id": "v", "outcome": "success", "settings_code": "NOT HEX", "progress_at_end": 1.7,
           "layer_at_end": -3, "spool_id": "", "firmware_version": "1.0 (build; rm -rf)"}
    out = outcome_courier.account_row(row, "0" * 32)
    assert not {"settings_code", "progress_at_end", "layer_at_end", "spool_code", "firmware"} & set(out)
    assert outcome_courier.account_row({**row, "firmware_version": "x" * 41}, "0" * 32).get("firmware") is None
    assert outcome_courier.account_row({**row, "firmware_version": "Marlin 2.1.2"}, "0" * 32)["firmware"] == "Marlin 2.1.2"


_OWN_SERIAL = "01P00A123456789"
_OWN_ADDRESS = "192.168.1.50"


@pytest.mark.parametrize("said", [
    "printer-garage.local",                  # a host name
    "sarahs-voron",                          # a word, no version
    _OWN_ADDRESS,                            # this computer's printer's own address
    f"1.2.3-{_OWN_SERIAL[:12]}",             # a version carrying part of a serial as written
    f"2.1 {_OWN_SERIAL}",                    # a version beside a whole serial
    "1.0.0 /dev/ttyUSB0",                    # a device path
    "v1.2.3 token=abc123",                   # anything after the version that is not a short suffix
])
def test_a_firmware_reading_that_is_not_a_bare_version_never_leaves(db, signed_in, sent, monkeypatch, said):  # noqa: F811
    monkeypatch.setattr(outbound_guard, "_own_printer_values", lambda: [
        ("the printer's serial number", _OWN_SERIAL),
        ("the printer's serial number", _OWN_SERIAL[:12]),
        ("the printer's network address", _OWN_ADDRESS),
    ])
    _print(db, outcome="pending")
    assert db.set_outcome_evidence("start:a1:1", "firmware_version", said)
    db.save_print_outcome({"job_id": "start:a1:1", "printer_name": "Shop A1", "outcome": "success",
                           "determined_by": "observed"})
    assert outcome_courier.push_owed(db=db)["sent"] == 1
    (row,) = sent[-1]["body"]["rows"]
    assert "firmware" not in row
    flat = repr(row)
    for leak in (_OWN_SERIAL[:12], _OWN_ADDRESS, "garage", "ttyUSB", "abc123", "sarahs"):
        assert leak not in flat


def test_a_field_that_skipped_the_version_test_is_dropped_at_the_guard(monkeypatch):
    """The guard judges the declared field itself: a sender that offered it
    something else sends nothing under that key."""
    keys = outbound_guard.VERSION_FIELDS[outcome_courier.SENDER]
    out = outbound_guard.scrub([{"firmware": "printer-garage.local", "ending": "success"},
                                {"firmware": "01.07.00.00"}], version_keys=keys)
    assert out == [{"ending": "success"}, {"firmware": "01.07.00.00"}]


def test_a_row_the_account_holds_is_not_owed_again_for_these_columns(db, signed_in, sent):  # noqa: F811
    _print(db)
