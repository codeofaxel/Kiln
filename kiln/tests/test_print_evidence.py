_SETTINGS = {
    "layer_height": "0.2",
    "nozzle_diameter": "0.4",
    "temperature": "215",
    "bed_temperature": "60",
    "fill_density": "15%",
    "perimeter_speed": "45",
}


def _prusa_lines(settings: dict[str, str], *, extra: dict[str, str] | None = None) -> list[str]:
    body = [f"; {k} = {v}" for k, v in {**settings, **(extra or {})}.items()]
    return ["; generated by PrusaSlicer 2.8.1", "G1 X0 Y0",
            "; estimated printing time (normal mode) = 1h 0m 0s",
            "; prusaslicer_config = begin", *body, "; prusaslicer_config = end"]


@pytest.fixture
def db(tmp_path):
    instance = KilnDB(db_path=str(tmp_path / "kiln.db"))
    yield instance
    instance.close()


# ─────────────────────────── the settings code ───────────────────────────────

def test_the_same_settings_give_the_same_code_in_any_order():
    code = print_evidence.settings_code(_prusa_lines(_SETTINGS))
    assert re.fullmatch(r"[0-9a-f]{32}", code)
    assert print_evidence.settings_code(_prusa_lines(dict(reversed(list(_SETTINGS.items()))))) == code
    assert print_evidence.settings_code(_prusa_lines({**_SETTINGS, "temperature": "220"})) != code


def test_a_key_that_names_a_person_a_file_or_a_preset_is_not_in_the_code():
    code = print_evidence.settings_code(_prusa_lines(_SETTINGS))
    named = {
        "output_filename_format": "sarahs_bracket_{print_time}.gcode",
        "printer_settings_id": "Sarah's MK4",
        "print_host": "192.0.2.7",
        "printhost_apikey": "SECRET",
        "printer_notes": "the one by the window",
        "post_process": "/Users/sarah/fix.py",
        "compatible_printers": "Sarah's MK4",
        "inherits": "0.20mm QUALITY",
    }
    assert print_evidence.settings_code(_prusa_lines(_SETTINGS, extra=named)) == code


def test_a_file_with_no_whole_settings_block_has_no_code():
    whole = _prusa_lines(_SETTINGS)
    assert print_evidence.settings_code(whole[:-1]) is None          # never closed
    assert print_evidence.settings_code(whole[:3]) is None           # no block
    assert print_evidence.settings_code(_prusa_lines({"layer_height": "0.2"})) is None  # too few
    assert print_evidence.settings_code(None) is None
    assert print_evidence.settings_code([]) is None


def test_an_orca_block_counts_and_a_header_kiln_wrote_does_not():
    from kiln.gcode import PACKAGED_BY_KILN

    block = ["; CONFIG_BLOCK_START", *[f"; {k} = {v}" for k, v in _SETTINGS.items()], "; CONFIG_BLOCK_END"]
    code = print_evidence.settings_code(["; HEADER_BLOCK_START", "; HEADER_BLOCK_END", *block])
    assert re.fullmatch(r"[0-9a-f]{32}", code)
    assert print_evidence.settings_code([PACKAGED_BY_KILN, *block]) is None
    # Kiln's header over a PrusaSlicer body: the slicer's own block is read.
    packaged = [PACKAGED_BY_KILN, *block, *_prusa_lines({**_SETTINGS, "temperature": "240"})]
    assert print_evidence.settings_code(packaged) == print_evidence.settings_code(
        _prusa_lines({**_SETTINGS, "temperature": "240"}))


# ─────────────────────────── the start ───────────────────────────────────────

class _Reporting(_Adapter):
    firmware: str | None = "v0.12.0-85-gd785b396"
    end_completion: float | None = None
    end_layer: int | None = None

    def reported_firmware_version(self) -> str | None:
        return self.firmware

    def get_job(self) -> JobProgress:
        job = super().get_job()
        if self.status != PrinterStatus.PRINTING:
            job.completion = self.end_completion
        job.current_layer = self.end_layer
        return job


def _sliced_file(tmp_path, settings: dict[str, str] | None = _SETTINGS) -> str:
    path = tmp_path / "bracket.gcode"
    lines = _prusa_lines(settings) if settings is not None else _prusa_lines(_SETTINGS)[:3]
    path.write_text("\n".join(lines) + "\n")
    return str(path)


def test_the_start_writes_the_settings_code_and_the_firmware(kiln_env):  # noqa: F811
    adapter = _Reporting()
    assert adapter.start_print(_sliced_file(kiln_env)).success
    row = _row()
    assert row["outcome"] == "pending"
    assert row["settings_code"] == print_evidence.settings_code(_prusa_lines(_SETTINGS))
    assert row["firmware_version"] == "v0.12.0-85-gd785b396"
    assert "0.2" not in row["settings_code"] and "215" not in row["settings_code"]


def test_a_file_kiln_cannot_read_and_a_printer_that_says_nothing_leave_blanks(kiln_env):  # noqa: F811
    adapter = _Reporting()
    adapter.firmware = None
    adapter.start_print("only_on_the_printer.gcode")
    row = _row()
    assert (row["settings_code"], row["firmware_version"], row["spool_id"]) == (None, None, None)

    other = _Reporting("ender")
    other.start_print(_sliced_file(kiln_env, settings=None))
    assert _row("ender")["settings_code"] is None


# ─────────────────────────── the ending ──────────────────────────────────────

def _end(adapter: _Reporting, *, gap_seconds: float, result: JobResult = JobResult.FAILED) -> None:
    adapter.get_state()  # was printing
    pm._last_looks[pm.observation_key(adapter)] = time.monotonic() - gap_seconds
    adapter.status = PrinterStatus.IDLE
    adapter.job_result = result
    adapter.get_state()  # notices the ending


def test_a_watched_ending_writes_how_far_the_print_got(kiln_env):  # noqa: F811
    adapter = _Reporting()
    adapter.start_print(_sliced_file(kiln_env))
    adapter.end_completion, adapter.end_layer = 37.5, 42
    _end(adapter, gap_seconds=5.0)
    row = _row()
    assert row["outcome"] != "pending"
    assert (row["progress_at_end"], row["layer_at_end"]) == (0.375, 42)


def test_an_ending_found_out_afterwards_writes_no_progress(kiln_env):  # noqa: F811
    adapter = _Reporting()
    adapter.start_print(_sliced_file(kiln_env))
    adapter.end_completion, adapter.end_layer = 37.5, 42
    _end(adapter, gap_seconds=3 * 3600)
    row = _row()
    assert row["outcome"] != "pending"
    assert (row["progress_at_end"], row["layer_at_end"]) == (None, None)


def test_a_print_kiln_did_not_start_takes_its_progress_after_it_settles(kiln_env):  # noqa: F811
    adapter = _Reporting()
    adapter.job_label = "from_the_screen.gcode"
    adapter.status = PrinterStatus.PRINTING
    adapter.end_completion, adapter.end_layer = 100.0, 120
    _end(adapter, gap_seconds=5.0, result=JobResult.COMPLETED)
