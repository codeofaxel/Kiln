def test_a_spool_and_a_machine_never_share_a_code():
    a = outbound_guard.spool_code("ABC-1")
    assert a == outbound_guard.spool_code(" abc-1") and a != outbound_guard.spool_code("abc-2")
    assert a[3:] != outbound_guard.machine_code("abc-1")[3:]
    assert outbound_guard.spool_code("") is None


# ─────────────────────────── an existing database ────────────────────────────

def test_a_database_made_before_these_columns_gains_them(tmp_path):
    path = str(tmp_path / "old.db")
    first = KilnDB(db_path=path)
    first.close()
    conn = sqlite3.connect(path)
    for column in KilnDB.PRINT_EVIDENCE_COLUMNS:
        conn.execute(f"ALTER TABLE print_outcomes DROP COLUMN {column}")
    conn.commit()
    conn.close()
    db = KilnDB(db_path=path)
    try:
        have = {row[1] for row in db._conn.execute("PRAGMA table_info(print_outcomes)").fetchall()}
        assert set(KilnDB.PRINT_EVIDENCE_COLUMNS) <= have
    finally:
        db.close()
