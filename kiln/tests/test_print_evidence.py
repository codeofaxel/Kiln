"""Four facts a print's row keeps beside its ending, and what of them leaves.

Pinned through the real adapter template, the real lifecycle and the real
database:

* a one-way code of the settings the sent file was sliced with: the same for
  the same settings in any order, blind to keys that name a person, a file
  or a preset, and empty for a file with no whole settings block;
* how far the print had got, from an ending Kiln watched; an ending found
  out afterwards writes nothing;
* the firmware version the printer reports;
* what the courier sends of them: the settings code, the progress, the spool
  as a one-way code and a plain firmware version -- never the spool's id --
  and a row the account already holds is not owed again for them.

The spool half is pinned in ``test_spool_usage.py``, beside the count it
rides.
"""

