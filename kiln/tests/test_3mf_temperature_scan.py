def test_the_plate_inside_a_3mf_is_what_the_scanner_reads(tmp_path) -> None:
    hot = scan_print_file(str(_plate(tmp_path, 330)), printer_id="bambu_a1", dialect=GCodeDialect.BAMBU)
    assert hot is not None and hot.valid is False
    assert HOT_LINE in hot.errors, hot.errors
    assert hot.blocked_commands == ["M104 S330"]
    cool = scan_print_file(str(_plate(tmp_path, 220)), printer_id="bambu_a1", dialect=GCodeDialect.BAMBU)
    assert cool is not None and cool.valid is True, cool.errors


def test_a_project_3mf_has_nothing_to_scan_and_says_so(tmp_path) -> None:
    assert scan_print_file(str(_project(tmp_path)), printer_id="bambu_a1", dialect=GCodeDialect.BAMBU) is None
    assert scan_print_file(str(tmp_path / "part.stl"), printer_id="bambu_a1", dialect=GCodeDialect.BAMBU) is None


def test_a_3mf_plate_is_read_in_the_bambu_dialect_whatever_the_backend_calls_itself() -> None:
    assert dialect_for("bambu", path="x.gcode") is GCodeDialect.BAMBU
    assert dialect_for("kilntest", path="x.gcode.3mf") is GCodeDialect.BAMBU
    assert dialect_for("moonraker", path="x.gcode") is GCodeDialect.KLIPPER
    assert dialect_for("octoprint", path="x.gcode") is GCodeDialect.GENERIC


