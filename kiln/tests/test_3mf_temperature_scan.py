def test_the_real_bambu_adapter_refuses_a_hot_plate_at_both_of_its_doors(tmp_path, monkeypatch) -> None:
    hot = _plate(tmp_path, 330)
    a1 = _bambu(tmp_path, monkeypatch, model="bambu_a1", ams=AMS_LITE)
    result = a1.start_print(hot.name, local_file_path=str(hot))
    assert result.success is False and result.refused_before_send is True
    assert HOT_LINE in result.message
    assert _started(a1) is None
    with pytest.raises(PrinterError, match="GCODE_BLOCKED"):
        a1.upload_file(str(hot))
    cool = _plate(tmp_path, 220)
    assert a1.start_print(cool.name, local_file_path=str(cool)).success is True


@needs_prusaslicer
def test_a_reslice_at_330_is_refused_at_the_upload_door_not_just_warned_about(tmp_path, generic_profile, aimed, monkeypatch) -> None:  # noqa: F811
    """End to end with a real slicer: ``reslice_with_overrides`` already said
    the profile was over the ceiling in its reply; the wrapped 3MF it made
    still went to the printer.  Now the upload refuses it, with the
    scanner's own line, and the same reslice at a sane temperature uploads."""
    monkeypatch.setattr(srv, "_resolve_target_printer_model", lambda printer_name=None: "bambu_a1")
    binary = _prusaslicer() or ""
    hot = _reslice(tmp_path, binary, {"temperature": "330", "first_layer_temperature": "330"}, printer_id="bambu_a1", out="hot")
    assert hot.get("success") is True, hot
    assert hot["output_path"].endswith(".gcode.3mf")
    assert "temperature=330" in hot["profile_validation_warning"]
    refused = rx.call(srv.mcp, "upload_file", {"file_path": hot["output_path"]})
    assert refused.get("success") is False and refused["error"]["code"] == REFUSAL_CODE, refused
    # The plain install of ``generic_profile`` holds no record for the A1,
    # so the ceiling named is the generic 300 C floor; the line is refused
    # either way.
    assert any(e.startswith("M104 S330 exceeds") for e in refused["errors"]), refused["errors"]
    assert aimed.uploads == []

    cool = _reslice(tmp_path, binary, {"temperature": "215", "first_layer_temperature": "215"}, printer_id="bambu_a1", out="cool")
    assert cool.get("success") is True, cool
    sent = rx.call(srv.mcp, "upload_file", {"file_path": cool["output_path"]})
    assert sent.get("success") is True, sent
    assert aimed.uploads == [cool["output_path"]]


