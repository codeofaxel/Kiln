def _vendor_preset(folder: str, prefix: str, tags: list[str]) -> str | None:
    for tag in tags:
        for name in (f"{prefix} @BBL {tag}.json", f"{prefix} @BBL {tag} 0.4 nozzle.json"):
            if os.path.isfile(os.path.join(folder, name)):
                return os.path.join(folder, name)
    return None


def _cube(path: Path) -> str:
    import struct

    s = 20.0
    v = [(0, 0, 0), (s, 0, 0), (s, s, 0), (0, s, 0), (0, 0, s), (s, 0, s), (s, s, s), (0, s, s)]
    faces = [(0, 3, 2), (0, 2, 1), (4, 5, 6), (4, 6, 7), (0, 1, 5), (0, 5, 4),
             (1, 2, 6), (1, 6, 5), (2, 3, 7), (2, 7, 6), (3, 0, 4), (3, 4, 7)]
    with open(path, "wb") as fh:
        fh.write(b"\0" * 80)
        fh.write(struct.pack("<I", len(faces)))
        for face in faces:
            fh.write(struct.pack("<3f", 0, 0, 0))
            for i in face:
                fh.write(struct.pack("<3f", *v[i]))
            fh.write(struct.pack("<H", 0))
    return str(path)


@pytest.fixture(scope="module")
def vendor_slices(tmp_path_factory):
    """One slice per (slicer, model, material) through the vendor's OWN
    system presets -- the file a Bambu Studio or OrcaSlicer user uploads --
    made on first use and kept for the module."""
    root = tmp_path_factory.mktemp("vendor")
    cube = _cube(root / "cube20.stl")
    made: dict[tuple[str, str, str], Path] = {}

    def slice_one(slicer: str, model: str, material: str) -> Path:
        key = (slicer, model, material)
        if key in made:
            return made[key]
        binary, res = _VENDOR[slicer]
        if not (os.path.isfile(binary) and os.access(binary, os.X_OK)):
            pytest.skip(f"{slicer} not installed")
        machine, process_tag, tags = _VENDOR_MODELS[slicer][model]
        machine_path = os.path.join(res, "machine", machine + ".json")
        process = _vendor_preset(os.path.join(res, "process"), "0.20mm Standard", [process_tag] + tags)
        filament = _vendor_preset(os.path.join(res, "filament"), _VENDOR_FILAMENTS[material], tags)
        if not (os.path.isfile(machine_path) and process and filament):
            pytest.skip(f"{slicer} has no system preset for {model} {material}")
        out = root / slicer / f"{model}_{material}"
        out.mkdir(parents=True)
        run = subprocess.run(
            [binary, "--slice", "0", "--outputdir", str(out),
             "--load-settings", f"{machine_path};{process}", "--load-filaments", filament,
             "--export-3mf", f"{model}_{material}.3mf", cube],
            capture_output=True, text=True, timeout=120,
        )
        plate = out / f"{model}_{material}.3mf"
        if not plate.is_file():
            pytest.skip(f"{slicer} wrote no 3MF for {model} {material} (exit {run.returncode})")
        made[key] = plate
        return plate

    return slice_one


@pytest.mark.parametrize("slicer, model, material", _VENDOR_CASES, ids=["-".join(c) for c in _VENDOR_CASES])
def test_a_plate_sliced_with_the_vendors_own_presets_passes(vendor_slices, slicer, model, material) -> None:
    plate = vendor_slices(slicer, model, material)
    scan = scan_print_file(str(plate), printer_id=model, dialect=dialect_for("bambu", path=str(plate)))
    assert scan is not None, "the vendor's 3MF carries a plate"
    assert scan.valid is True, (slicer, model, material, scan.errors)
