#: The scanner's own wording for the hot plate every refusal test sends.
HOT_LINE = "M104 S330 exceeds Bambu Lab A1 max hotend temperature (300°C)"

_BODY = """; generated by PrusaSlicer
M83
G28
M104 S{hotend}
M140 S60

;BEFORE_LAYER_CHANGE
;Z:0.2
;LAYER_CHANGE
G1 Z0.2 F600
G1 X10 Y10 E0.5

;BEFORE_LAYER_CHANGE
;Z:0.4
;LAYER_CHANGE
G1 Z0.4 F600
G1 X20 Y20 E0.5
"""


def _plate(tmp_path: Path, hotend: int, *, model: str = "bambu_a1", material: str = "PLA", bed: int = 65) -> Path:
    """A plate through Kiln's own Bambu wrap at *hotend*, with the preview
    set a slice from a mesh carries, so the Bambu archive checks pass and
    the temperature is the only thing left to refuse."""
    path = tmp_path / f"{model}_{material}_{hotend}.gcode.3mf"
    build_bambu_3mf(
        _BODY.format(hotend=hotend), str(path),
        settings=BambuPrintSettings(hotend_temp=hotend, bed_temp=bed, filament_type=material),
        printer_model=model,
    )
    with zipfile.ZipFile(path, "a") as zf:
        present = set(zf.namelist())
        for name, data in _tiles().items():
            if name not in present:
                zf.writestr(name, data)
    return path


def _project(tmp_path: Path) -> Path:
    """A 3MF with a model and no plate: nothing has been sliced."""
    path = tmp_path / "project.3mf"
    with zipfile.ZipFile(path, "w") as zf:
        zf.writestr("3D/3dmodel.model", "<model/>")
    return path


class _Printer(PrinterAdapter):
    """A backend declared as an A1, with the upload and start doors every
    adapter inherits; its printer-side storage may hold one file."""

    name = "kilntest"
    printer_id = "bambu_a1"
    _safety_profile_id = "bambu_a1"

    def __init__(self, on_printer: Path | None = None) -> None:
        self.uploads: list[str] = []
        self.impl_calls: list[str] = []
        self._on_printer = on_printer.read_bytes() if on_printer else None

    def upload_file(self, file_path: str) -> UploadResult:
        self.uploads.append(file_path)
        return UploadResult(success=True, file_name=os.path.basename(file_path), message="ok")

    def _start_print_impl(self, file_name: str, **kwargs) -> PrintResult:
        self.impl_calls.append(file_name)
        return PrintResult(success=True, message="IMPL")

    def read_print_file(self, file_name: str) -> bytes | None:
        return self._on_printer


_Printer.__abstractmethods__ = frozenset()


