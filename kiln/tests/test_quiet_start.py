class TestThePlateHoldsMoreThanOnePart:
    def test_a_quiet_start_joins_the_part_to_what_was_there(self):
        m = _machine()
        mark_occupied(m, JAR)
        mark_occupied(m, COASTER, keep_previous=True)
        state = read(m)
        assert [j.file for j in state.jobs] == ["jar_v2.gcode.3mf", "coaster.gcode.3mf"]
        assert state.job == COASTER, "the last part is the job every reader knew"
        assert state.tallest_mm == 42.0
        assert [o["name"] for o in state.occupancy([256, 256])["occupied"]] == ["jar v2", "coaster"], "as a person says them"

    def test_an_ordinary_start_replaces_what_was_there(self):
        m = _machine()
        mark_occupied(m, JAR)
        mark_occupied(m, JAR, keep_previous=True)
        mark_occupied(m, COASTER)
        assert [j.file for j in read(m).jobs] == ["coaster.gcode.3mf"]

    def test_a_print_seen_ending_keeps_every_part(self):
        m = _machine()
        mark_occupied(m, JAR)
        mark_occupied(m, COASTER, keep_previous=True)
        mark_occupied(m, None, source="print_ended")
        assert len(read(m).jobs) == 2

    def test_the_sentence_names_them_all_and_the_tallest(self, monkeypatch):
        m = _machine()
        mark_occupied(m, JAR)
        mark_occupied(m, COASTER, keep_previous=True)
        monkeypatch.setattr(PlateState, "since_clock", lambda self: "18:12")
        assert read(m).holds_sentence() == (
            "The last prints, jar v2 and coaster, are still on the plate (since 18:12, the tallest about 42 mm)."
        )

    def test_the_old_record_shape_still_reads(self):
        state = PlateState.from_dict("m", {"status": "occupied", "source": "kiln_started_print", "since": None, "job": JAR.to_dict()})
        assert state.jobs == (JAR,) and state.job == JAR
        assert PlateState.from_dict("m", {"status": "clear", "source": "human", "since": None, "job": None}).jobs == ()

    def test_the_fingerprint_is_the_parts_not_the_moment(self):
        m = _machine()
        mark_occupied(m, JAR)
        first = fingerprint(read(m))
        assert re.fullmatch(r"[0-9a-f]{16}", first)
        mark_occupied(m, None, source="print_ended")
        assert fingerprint(read(m)) == first, "a print seen ending re-stamps the moment, not the parts"
        mark_occupied(m, COASTER, keep_previous=True)
        assert fingerprint(read(m)) != first
        mark_occupied(m, PlateJob(file="jar_v2.gcode.3mf", footprint_mm=[90, 90, 160, 160], max_z_mm=60.0))
        assert fingerprint(read(m)) != first, "a taller jar is another plate"
        assert read(m).to_dict()["fingerprint"] == fingerprint(read(m))

    def test_beside_from_the_start_door(self, tmp_path):
        m = _machine()
        mark_occupied(m, JAR)
        gcode = tmp_path / "part.gcode"
        gcode.write_text(_body())
        mark_occupied_by_start(m, str(gcode), beside=True)
        assert len(read(m).jobs) == 2 and read(m).job.file == "part.gcode"


