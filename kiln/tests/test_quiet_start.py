class TestTheWrap:
    def test_the_file_opens_with_the_contract_and_the_absolute_lift_and_nothing_of_the_vendors(self, tmp_path):
        m = _machine()
        mark_occupied(m, JAR)
        path = _quiet_file(tmp_path, m)
        assert path.endswith("_quiet.gcode.3mf")
        gcode = _gcode_of(path)
        lines = gcode.split("\n")
        head = lines.index(QUIET_START_HEADER_START)
        end = lines.index(QUIET_START_HEADER_END)
        assert 0 < head < end
        motions = [line for line in lines[end:] if re.match(r"^G[01]\b.*[XYZ]-?\d", line.split(";", 1)[0])]
        assert motions[0].startswith("G1 Z47.00 F600"), "the first motion is the absolute lift"
        assert motions[1].startswith("G1 X-48.20 F6000"), "then the chute, before anything heats over the plate"
        assert lines.index("M109 S220  ; wait for the hotend") < lines.index("G1 X215.00 Y35.00 F6000  ; over the new part's own footprint, still clear")
        assert "M620 M" not in gcode and "G29" not in gcode and "G380" not in gcode and "M73 P0 R" not in gcode.split(";LAYER_CHANGE")[0]
        homes = [line for line in lines if line.split(";", 1)[0].strip().startswith("G28")]
        assert homes and all(line.split(";", 1)[0].strip() == "G28 X Y" for line in homes)
        with zipfile.ZipFile(path) as zf:
            names = zf.namelist()
        assert KILN_QUIET_START_MARKER in names and "Metadata/plate_1.gcode" in names

    def test_a_colour_change_lifts_to_the_floor_goes_to_the_cutter_and_comes_back_before_it_descends(self, tmp_path):
        m = _machine()
        mark_occupied(m, JAR)
        body = _body(layers=4, change_at=1)
        path = str(tmp_path / "two_quiet.gcode.3mf")
        build_bambu_3mf(
            body, path, settings=BambuPrintSettings(num_filaments=2, filament_colors=["#FFFFFF", "#FF0000"]),
            quiet_start=_plan(m), printer_model="bambu_a1",
        )
        lines = [line.split(";", 1)[0].strip() for line in _gcode_of(path).split("\n")]
        i = lines.index("M620 S1A")
        assert lines[i - 1] == "G1 Z47.00 F600", "lifted to the floor before the block"
        j = lines.index("M621 S1A")
        assert lines[j + 1] == "G1 X200.000 Y50.000 F6000", "back over the part at the floor"
        assert lines[j + 2] == "G1 Z0.40 F600", "then down to the layer it left"
        assert "G1 X-48.20 F3000" in lines[i:j], "the A1's own chute, spelled by the one shared helper"

    def test_the_end_block_never_dips_below_the_floor(self, tmp_path):
        m = _machine()
        mark_occupied(m, JAR)
        gcode = _gcode_of(_quiet_file(tmp_path, m))
        end = gcode.split("; filament used [g]")[1]
        zs = [float(mm.group(1)) for mm in re.finditer(r"^\s*G1 Z(\d+\.?\d*)", end, re.MULTILINE)]
        assert zs and min(zs) >= 47.0, zs
        assert any(line.strip().startswith("G1 X0 Y128") for line in end.split("\n")), "the vendor's path is kept"
        assert "G1 X-48 Y180 F3600" in end, "and its park"

    def test_a_floor_without_the_plan_writes_no_file_and_says_to_clear_the_plate(self, tmp_path):
        """A floor means a part is on the plate.  Without the plan, a file
        with the vendor's start would home Z onto that part from the
        printer's own screen -- so Kiln writes nothing and says what to do.
        It names no tier: the wrap cannot tell a plan the caller's tier
        withheld from one no tier would give (a printer Kiln has not seen
        start quietly, a lift its travel cannot reach), and the verdict's
        own start sentence on the same response says which."""
        from kiln.plate_state import PRINT_AROUND_SENTENCE

        out = str(tmp_path / "floor.gcode.3mf")
        with pytest.raises(ValueError) as caught:
            build_bambu_3mf(
                _body(layers=4, change_at=1), out,
                settings=BambuPrintSettings(num_filaments=2, filament_colors=["#FFFFFF", "#FF0000"]),
                lift_floor_mm=30.0, printer_model="bambu_a1",
            )
        assert str(caught.value) == PRINT_AROUND_SENTENCE == (
            "Kiln won't write a printer file while the plate still holds the last print: clear the plate and say so "
            "to print again."
        )
        assert not os.path.exists(out)
        from kiln.plugins.slicer_tools import _auto_wrap_bambu_3mf

        gcode = tmp_path / "part.gcode"
        gcode.write_text(_body())
        threemf, warning = _auto_wrap_bambu_3mf(str(gcode), "bambu_a1", None, lift_floor_mm=30.0)
        assert threemf is None and PRINT_AROUND_SENTENCE in str(warning)
        assert not list(tmp_path.glob("*.3mf"))

    def test_raising_absolute_z_leaves_relative_stretches_and_xy_lines_alone(self):
        text = "G90\nG1 Z5.5 F900\nG1 X0 Y128 F18000\nG91\nG1 Z2 F600\nG90\nG1 Z165 F600\nG1 Z163\nG1 X-48 Y180 F3600\nG0 Z1 ; comment\n"
        out = _raise_absolute_z_to_floor(text, 47.0).split("\n")
        assert out[1] == "G1 Z47.00 F900" and out[2] == "G1 X0 Y128 F18000"
        assert out[4] == "G1 Z2 F600", "a relative Z is a distance"
        assert out[6] == "G1 Z165 F600" and out[7] == "G1 Z163"
        assert out[9] == "G0 Z47.00 ; comment"

    def test_the_end_template_keeps_its_first_lift_rule_and_adds_the_floor(self):
        template = "G1 Z65.5 F900 ; lower z a little\nG1 X0 Y128 F18000\n    G1 Z165 F600\n    G1 Z163\nG1 X-48 Y180 F3600\n"
        plain = _resolve_end_gcode(template, max_z=10.0, printer_model="bambu_a1")
        assert plain.startswith("G1 Z15.0 F900")
        floored = _resolve_end_gcode(template, max_z=10.0, printer_model="bambu_a1", lift_floor_mm=200.0)
        assert floored.split("\n")[0] == "G1 Z200.00 F900 ; lower z a little"
