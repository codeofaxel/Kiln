def _body(x0: float = 200.0, y0: float = 20.0, size: float = 30.0, layers: int = 3, *, change_at: int | None = None) -> str:
    out = "; generated by PrusaSlicer 2.9.4\nM190 S65\nM104 S220\nG21\nG90\nM83\n"
    for i in range(layers):
        z = round(0.2 * (i + 1), 2)
        out += f";LAYER_CHANGE\n;Z:{z}\nG1 Z{z + 0.2:.2f} F24000\nG1 X{x0} Y{y0}\nG1 Z{z}\n;TYPE:Skirt/Brim\n"
        out += f"G1 X{x0 + size} Y{y0} E1\nG1 X{x0 + size} Y{y0 + size} E1\nG1 X{x0} Y{y0 + size} E1\n"
        if change_at is not None and i == change_at:
            out += "T1\n"
        out += f"G1 X{x0} Y{y0} E1\n"
    return out + "; filament used [g] = 4.26\n"


def _plan(machine: Any, **over: Any) -> dict[str, Any]:
    plan = {
        "mode": "quiet_start", "ok": True, "available": True, "refusals": [],
        "clear_z_mm": 47.0, "lift_floor_mm": 47.0, "travel_to_mm": [215.0, 35.0], "first_layer_z_mm": 0.2,
        "approach_mm": 5.0, "z_travel_mm": 256.0, "home_xy_gcode": "G28 X Y", "purge_at_mm": [-48.2, None],
        "flags": {"bed_leveling": False, "flow_cali": False, "vibration_cali": False, "timelapse": False, "layer_inspect": False},
        "switched_off": {"clog_probe": "nozzle_clog_detect=False"},
        "planned_for_machine": same_bed_machine_id(machine),
        "plate_fingerprint": fingerprint(read(machine)),
    }
    plan.update(over)
    return plan


def _quiet_file(tmp_path: Path, machine: Any, *, body: str | None = None, name: str = "part.gcode", **over: Any) -> str:
    """A quiet-start 3MF built by the real wrap, for this machine's plate as it stands."""
    out = str(tmp_path / f"{Path(name).stem}_quiet.gcode.3mf")
    build_bambu_3mf(body or _body(), out, settings=BambuPrintSettings(), quiet_start=_plan(machine, **over), printer_model="bambu_a1")
    return out


def _gcode_of(path: str) -> str:
    with zipfile.ZipFile(path) as zf:
        return zf.read("Metadata/plate_1.gcode").decode("utf-8")


