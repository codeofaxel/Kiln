"""The quiet start: a print started beside a part still on the plate.

THE GAP
-------
A part could be sliced beside what the plate still held, checked by the
placement verdict, and then not started: every start door refused onto an
occupied plate, because the file it would start carries the vendor's own
start -- a Z home on the plate, a bed probe, a purge line across it.  The
placed slice could only be printed from the printer's screen.

WHAT THIS PINS
--------------
* the plate record holds MORE than one part, and a fingerprint of them;
* the file's contract (Kiln's quiet-start header) and the start gate that
  lets a file planned for THIS plate through to the live judge, and
  refuses one planned for a plate that has changed;
* the prologue's order -- an absolute lift first, the X/Y home at that
  height, the travel over the new footprint, the waits, the descent;
* the wrap: the contract header, the prologue in place of the vendor's
  start, every colour change and the end block lifted to the floor, and
  the builder refusing its own output if a vendor motion slipped in;
* the live judge, condition by condition, against a machine that answers;
* the adapter template forcing a quiet file's switches off, refusing when
  its gate cannot run, and recording the part beside the others;
* every slicing door handing the plan to the wrap, and every start door
  naming the file to the gate.
"""

