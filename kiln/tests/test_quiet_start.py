class _QuietAdapter(PrinterAdapter):
    """Registry-shaped, with a serial (the plate record's key): answers the
    judge's questions from attributes a test sets and records every start."""

    printer_id = "bambu_a1"
    serial = "01P00A000000001"

    def __init__(self) -> None:
        self._kiln_registered_name = "bench-a1"
        self._printer_model = "bambu_a1"
        self.homed: set[str] | None = {"x", "y", "z"}
        self.state = PrinterStatus.IDLE
        self.impl_calls: list[tuple[str, dict[str, Any]]] = []

    @property
    def name(self) -> str:
        return "bambu"

    def get_state(self) -> PrinterState:
        return PrinterState(connected=True, state=self.state)

    def homed_axes_now(self) -> set[str] | None:
        return None if self.homed is None else set(self.homed)

    def homed_axes_field(self) -> str | None:
        return "print.home_flag[bits 0-2]"

    def _start_print_impl(self, file_name: str, **kwargs: Any) -> PrintResult:
        self.impl_calls.append((file_name, dict(kwargs)))
        return PrintResult(success=True, message="IMPL")


