"""The slicer's time Kiln keeps and says is the time of what is printed.

A sliced 3MF can carry several plates, each with its own time.  Pinned here:

* a start writes the time of the plate it printed onto the print's row, and
  nothing when the plate it names is not in the file;
* a version's record of a 3MF of several plates keeps every plate's time
  together and says so, and nothing when a plate states no time;
* the card asking to start a print says no time for a 3MF of several plates
  when no plate is named;
* an object taken out of a plate carries none of the plate's time lines.
"""

from __future__ import annotations

import json
import os
import zipfile

import pytest

from kiln.gcode import slicer_print_time
from kiln.slicer_estimate import estimate_sentence, read_estimate
from tests.test_learned_print_time import _Adapter, _row, kiln_env  # noqa: F401 -- the fixture is used by name


def _plate(time_words: str | None) -> str:
    stated = f"; model printing time: {time_words}; total estimated time: {time_words}\n" if time_words else ""
    return (
        "; HEADER_BLOCK_START\n; generated by BambuStudio 02.03.00.70\n"
        f"{stated}; HEADER_BLOCK_END\nG28\nG1 X10 Y10\n"
    )


def _project(tmp_path, plates: dict[int, str | None], name: str = "project.gcode.3mf") -> str:
    path = tmp_path / name
    with zipfile.ZipFile(path, "w") as zf:
        for number, time_words in plates.items():
            zf.writestr(f"Metadata/plate_{number}.gcode", _plate(time_words))
    return str(path)


# ---------------------------------------------------------------------------
# The start: the plate printed
# ---------------------------------------------------------------------------


def test_a_start_of_plate_two_writes_plate_twos_time(kiln_env):  # noqa: F811 -- the imported fixture
    path = _project(kiln_env, {1: "1h 0m 0s", 2: "3h 0m 0s"})
    assert _Adapter().start_print(path, plate_number=2).success

    assert _row()["estimated_seconds"] == 3 * 3600


def test_plate_ten_is_read_as_plate_ten_not_by_name_order(kiln_env):  # noqa: F811 -- the imported fixture
    path = _project(kiln_env, {1: "1h 0m 0s", 2: "2h 0m 0s", 10: "5h 0m 0s"})
    assert _Adapter().start_print(path, plate_number=10).success

    assert _row()["estimated_seconds"] == 5 * 3600


def test_a_plate_the_file_does_not_hold_writes_no_time(kiln_env):  # noqa: F811 -- the imported fixture
    path = _project(kiln_env, {1: "1h 0m 0s", 2: "3h 0m 0s"})
    _Adapter().start_print(path, plate_number=3)

    assert _row()["estimated_seconds"] is None


def test_with_no_plate_named_several_plates_give_no_ones_lines(tmp_path):
    from kiln.file_metadata import printed_gcode_lines

    path = _project(tmp_path, {1: "1h 0m 0s", 2: "3h 0m 0s"})

    assert printed_gcode_lines(path, None) is None
    assert slicer_print_time("\n".join(printed_gcode_lines(path, 2))).seconds == 3 * 3600


# ---------------------------------------------------------------------------
# A version's record: every plate together
# ---------------------------------------------------------------------------


def test_a_versions_record_keeps_every_plates_time_together(tmp_path):
    estimate = read_estimate(_project(tmp_path, {1: "1h 0m 0s", 2: "3h 0m 0s"}))

    assert estimate is not None
    assert (estimate["seconds"], estimate["plates"]) == (4 * 3600, 2)
    assert "all 2 plates" in estimate_sentence({"slicer_estimate": estimate})


def test_a_plate_stating_no_time_leaves_the_record_without_one(tmp_path):
    assert read_estimate(_project(tmp_path, {1: "1h 0m 0s", 2: None})) is None


# ---------------------------------------------------------------------------
# The card asking to start: no plate is named there
# ---------------------------------------------------------------------------


def test_the_ask_says_no_time_for_a_file_of_several_plates(tmp_path):
    from kiln.server import _figures_for_ask

    assert "print_time_s" not in _figures_for_ask(_project(tmp_path, {1: "1h 0m 0s", 2: "3h 0m 0s"}))
    assert _figures_for_ask(_project(tmp_path, {1: "1h 0m 0s"}, name="one.gcode.3mf"))["print_time_s"] == 3600


# ---------------------------------------------------------------------------
# An object taken out of a plate
# ---------------------------------------------------------------------------


@pytest.mark.parametrize("tail", ["", "; estimated printing time (normal mode) = 2h 10m 0s\n"])
def test_an_object_taken_out_of_a_plate_states_no_time_of_the_plates(tmp_path, tail):
    from kiln.file_metadata import sliced_gcode_lines
    from kiln.generation.validation import extract_plate_object_gcode
    from tests import test_plate_objects as fixtures

    gcode = (
        fixtures._GCODE.replace(
            "; HEADER_BLOCK_END", "; model printing time: 2h 0m 0s; total estimated time: 2h 10m 0s\n; HEADER_BLOCK_END"
        )
        .replace("; CHANGE_LAYER\nG1 Z0.4", "M73 P50 R65\n; CHANGE_LAYER\nG1 Z0.4")
        .replace("; MACHINE_END_GCODE_START", "M73 P100 R0\n; MACHINE_END_GCODE_START")
        + tail
    )
    source = tmp_path / "plate.gcode.3mf"
    with zipfile.ZipFile(source, "w") as zf:
        zf.writestr("Metadata/plate_1.json", json.dumps(fixtures._PLATE_JSON))
        zf.writestr("Metadata/plate_1.gcode", gcode)

    result = extract_plate_object_gcode(str(source), "lid", output_path=os.path.join(tmp_path, "lid.gcode"))

    assert slicer_print_time("\n".join(sliced_gcode_lines(result["output_path"]))) is None
