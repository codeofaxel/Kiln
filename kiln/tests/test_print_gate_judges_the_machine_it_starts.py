class _Machine(PrinterAdapter):
    """A generic printer, set up the way every setup door sets one up."""

    def __init__(self, model: str | None = None) -> None:
        self.started: list[str] = []
        if model:
            self.set_safety_profile(model)

    def _start_print_impl(self, file_name: str, **kwargs) -> PrintResult:
        self.started.append(file_name)
        return PrintResult(success=True, message="started")


_Machine.__abstractmethods__ = frozenset()


def _box(tmp_path: Path, size_mm: float) -> str:
    mesh = trimesh.creation.box(extents=[size_mm, size_mm / 4, 10.0])
    mesh.apply_translation([size_mm / 2, size_mm / 8, 5.0])
    path = tmp_path / f"part{int(size_mm)}.stl"
    mesh.export(str(path))
    return str(path)


@pytest.fixture
def default_printer_is_the_big_one(monkeypatch):
    """The install's default printer is the 350 mm one -- what the global
    resolver answers, whichever machine a start is aimed at."""
    import kiln.printer_model_resolver as resolver

    monkeypatch.setattr(resolver, "resolve_printer_model", lambda: "kilntest_big")


class TestTheBedIsTheTargetPrintersOwn:
    def test_a_plate_too_big_for_the_second_printer_is_refused(self, tmp_path, default_printer_is_the_big_one):
        small = _Machine("kilntest_small")  # 120 mm bed
        result = small.start_print(_box(tmp_path, 200.0))
        assert result.success is False
        assert result.refused_before_send is True
        assert small.started == []
        assert "exceeds the printer's build volume (120" in result.message

    def test_the_same_plate_starts_on_the_printer_it_fits(self, tmp_path, default_printer_is_the_big_one):
        big = _Machine("kilntest_big")
        part = _box(tmp_path, 200.0)
        assert big.start_print(part).success is True
        assert big.started == [part]

    def test_a_printer_that_declares_nothing_is_still_judged_by_the_default(self, tmp_path, monkeypatch):
        """The single-printer install, unchanged: no declared model, so the
        configured default answers, as it always did."""
        import kiln.printer_model_resolver as resolver

        monkeypatch.setattr(resolver, "resolve_printer_model", lambda: "kilntest_small")
        anon = _Machine()
        assert anon.start_print(_box(tmp_path, 200.0)).success is False
        assert anon.started == []

    def test_the_override_is_asked_for_by_the_printer_it_unlocks(self, tmp_path, default_printer_is_the_big_one):
        """force_print_oversize grants by printer model; a grant for the
        machine being started is the one that counts."""
        small = _Machine("kilntest_small")
        part = _box(tmp_path, 200.0)
        pg.grant_oversize_override("kilntest_small", ttl_seconds=60)
        assert small.start_print(part).success is True


