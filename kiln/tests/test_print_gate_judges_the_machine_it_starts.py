"""The print-start gate judges a file against the printer it is starting.

``PrinterAdapter.start_print`` runs one gate for every door that starts a
print -- the start tool, slice-and-print, the queue, a watched start, the
CLI -- so whatever it misses, every door misses.  Three misses, each
measured through the real start template before this was written:

* **Whose bed.**  The gate asked the global resolver for the printer model,
  which answers for the DEFAULT printer.  With two machines registered, a
  200 mm plate started on a 120 mm printer was judged against the default
  printer's 350 mm bed and sent.
* **More filaments than the unit has slots.**  The only slot check lived in
  the Bambu adapter and read a local copy the door had to hand over.  A
  door that starts a plate by its printer-side name hands none, so a
  nine-colour plate went to a four-slot AMS Lite with a one-tray mapping.
* **A colour change written for another machine.**  Kiln will not write a
  colour change for a Bambu whose waste chute it has no position for: the
  block sends the head to a chute before it purges.  A plate Kiln wrote for
  an A1 still started on a printer declared as a P1S, sending the P1S head to
  the A1's chute.

Each test drives the real start template (and, for a Bambu, the real
adapter with its MQTT client stubbed), and asserts on what reached the
printer -- the published start command -- not on a helper's return value.
"""

