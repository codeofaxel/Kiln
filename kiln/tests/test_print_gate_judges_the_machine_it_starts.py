def _vendor_two_colour_plate(tmp_path: Path) -> Path:
    """A two-colour plate as the maker's slicer writes one for a P1S: its own
    colour change, which purges where that slicer worked out, and no Kiln
    colour change in it."""
    gcode = "\n".join([
        ";===== machine: P1S =====", "G28", "G90", "M83",
        ";LAYER_CHANGE", ";Z:0.2", "G1 Z0.2 F600", ";TYPE:Outer wall",
        "G1 X40 Y40 F6000", "G1 X90 Y40 E2.0 F1800", "G1 X90 Y90 E2.0",
        "M620 S1A", "M204 S9000", "G1 Z3.2 F1200", "G1 X70 F21000", "G1 Y245", "G1 Y265 F3000",
        "T1", "M621 S1A",
        "G1 X120 Y40 F6000", "G1 X170 Y40 E2.0 F1800",
        "; filament_colour = #E53935;#1E88E5", "; filament_type = PLA;PLA",
    ]) + "\n"
    path = tmp_path / "vendor.gcode.3mf"
    with zipfile.ZipFile(path, "w") as zf:
        zf.writestr("Metadata/plate_1.gcode", gcode)
        zf.writestr("Metadata/plate_1.json", json.dumps({
            "filament_colors": ["#E53935", "#1E88E5"], "filament_ids": [0, 1],
        }))
        for name, data in _tiles().items():
            zf.writestr(name, data)
    return path


P1S_AMS = _ams("ams", ["#E53935", "#1E88E5", "#F2F2F2", "#1A1A1A"])


class TestAColourChangeWrittenForAnotherMachine:
    def test_an_a1_colour_change_is_refused_on_a_p1s(self, tmp_path, monkeypatch):
        plate = _kiln_plate(tmp_path, ["#E53935", "#1E88E5"])
        p1s = _bambu(tmp_path, monkeypatch, model="bambu_p1s", ams=P1S_AMS)
        result = p1s.start_print(plate.name, local_file_path=str(plate))
        assert result.success is False
        assert result.refused_before_send is True
        assert _started(p1s) is None
        assert CHUTE_REFUSAL in result.message
        assert "X-48.2" in result.message

    def test_started_by_name_it_is_refused_too(self, tmp_path, monkeypatch):
        plate = _kiln_plate(tmp_path, ["#E53935", "#1E88E5"])
        p1s = _bambu(tmp_path, monkeypatch, model="bambu_p1s", ams=P1S_AMS, on_printer=plate)
        result = p1s.start_print(plate.name)
        assert result.success is False and CHUTE_REFUSAL in result.message
        assert "delete_file" not in result.message
        assert _started(p1s) is None

    def test_the_same_plate_starts_on_the_a1_it_was_made_for(self, tmp_path, monkeypatch):
        plate = _kiln_plate(tmp_path, ["#E53935", "#1E88E5"])
        a1 = _bambu(tmp_path, monkeypatch, model="bambu_a1", ams=AMS_LITE)
        assert a1.start_print(plate.name, local_file_path=str(plate)).success is True
        assert _started(a1) is not None

    def test_a_printer_nobody_declared_keeps_the_a1_default(self, tmp_path, monkeypatch):
        """The wrap's own rule: an undeclared Bambu gets the A1's chute,
        because nothing says it is not an A1."""
        plate = _kiln_plate(tmp_path, ["#E53935", "#1E88E5"])
        anon = _bambu(tmp_path, monkeypatch, model="", ams=AMS_LITE)
        assert anon.start_print(plate.name, local_file_path=str(plate)).success is True

    def test_the_makers_own_colour_change_is_not_judged(self, tmp_path, monkeypatch):
        plate = _vendor_two_colour_plate(tmp_path)
        p1s = _bambu(tmp_path, monkeypatch, model="bambu_p1s", ams=P1S_AMS, on_printer=plate)
        assert p1s.start_print(plate.name).success is True
        assert _started(p1s) is not None
