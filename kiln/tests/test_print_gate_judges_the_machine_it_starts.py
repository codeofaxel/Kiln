class TestAPlateTheUnitCannotFeed:
    def test_nine_colours_started_by_name_on_a_four_slot_unit_are_refused(self, tmp_path, monkeypatch):
        plate = _kiln_plate(tmp_path, NINE)
        a1 = _bambu(tmp_path, monkeypatch, model="bambu_a1", ams=AMS_LITE, on_printer=plate)
        # What the start tool sends when this process holds no local copy:
        # the auto-routing's one-tray mapping.
        result = a1.start_print(plate.name, use_ams=True, ams_mapping=[0])
        assert result.success is False
        assert result.refused_before_send is True
        assert _started(a1) is None
        assert SLOTS_REFUSAL in result.message
        assert "uses 9 different filament colours" in result.message
        assert "has 4 slots" in result.message
        # Nothing about the file itself is wrong, so it is not told to be
        # deleted from the printer.
        assert "delete_file" not in result.message

    def test_a_bare_start_by_name_is_refused_too(self, tmp_path, monkeypatch):
        """The queue, a watched start and a marketplace auto-print start a
        file by name with no arguments at all."""
        plate = _kiln_plate(tmp_path, NINE)
        a1 = _bambu(tmp_path, monkeypatch, model="bambu_a1", ams=AMS_LITE, on_printer=plate)
        result = a1.start_print(plate.name)
        assert result.success is False and SLOTS_REFUSAL in result.message
        assert _started(a1) is None

    def test_the_door_with_a_local_copy_refuses_it_before_anything_is_sent(self, tmp_path, monkeypatch):
        """Refused before too, by the Bambu adapter after the template had
        let it through -- so not flagged as refused before sending.  Now the
        one gate refuses it, the same way for both doors."""
        plate = _kiln_plate(tmp_path, NINE)
        a1 = _bambu(tmp_path, monkeypatch, model="bambu_a1", ams=AMS_LITE)
        result = a1.start_print(plate.name, local_file_path=str(plate))
        assert result.success is False and result.refused_before_send is True
        assert SLOTS_REFUSAL in result.message
        assert _started(a1) is None

    def test_four_colours_on_four_slots_start(self, tmp_path, monkeypatch):
        plate = _kiln_plate(tmp_path, NINE[:4])
        a1 = _bambu(tmp_path, monkeypatch, model="bambu_a1", ams=AMS_LITE, on_printer=plate)
        assert a1.start_print(plate.name).success is True
        assert _started(a1) is not None

    def test_a_colour_listed_twice_is_one_spool(self, tmp_path, monkeypatch):
        """Five filament entries, two of them the same white: four spools."""
        colours = ["#E53935", "#F2F2F2", "#1E88E5", "#F2F2F2", "#1A1A1A"]
        plate = _kiln_plate(tmp_path, colours)
        a1 = _bambu(tmp_path, monkeypatch, model="bambu_a1", ams=AMS_LITE, on_printer=plate)
        assert a1.start_print(plate.name).success is True
        assert _started(a1) is not None

    def test_a_printer_with_no_unit_is_not_judged(self, tmp_path, monkeypatch):
        """No multi-material unit reported: Kiln cannot count slots it cannot
        see, so it does not refuse on a count."""
        plate = _kiln_plate(tmp_path, NINE)
        a1 = _bambu(tmp_path, monkeypatch, model="bambu_a1", ams=NO_AMS, on_printer=plate)
        assert a1.start_print(plate.name).success is True

    def test_a_unit_that_could_not_be_read_is_not_judged(self, tmp_path, monkeypatch):
        plate = _kiln_plate(tmp_path, NINE)
        a1 = _bambu(
            tmp_path, monkeypatch, model="bambu_a1", ams=PrinterError("MQTT timeout"), on_printer=plate,
        )
        assert a1.start_print(plate.name).success is True


