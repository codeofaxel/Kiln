def _multitool_body(colours: list[str]) -> str:
    """A sliced body the way Orca writes one: a ``T`` per change, one
    ``filament_colour`` entry per tool, layer markers, extrusion on the bed."""
    lines = ["; generated by OrcaSlicer 2.3.0", "G90", "M83"]
    for layer in range(2):
        z = 0.2 * (layer + 1)
        lines += [";LAYER_CHANGE", f";Z:{z:.1f}", f"G1 Z{z:.1f} F600"]
        for tool in range(len(colours)):
            x0, y0 = 20 + (tool % 3) * 70, 20 + (tool // 3) * 70
            if len(colours) > 1:
                lines.append(f"T{tool}")
            lines += [
                ";TYPE:Outer wall", f"G1 X{x0} Y{y0} F6000",
                f"G1 X{x0 + 50} Y{y0} E2.0 F1800", f"G1 X{x0 + 50} Y{y0 + 50} E2.0",
                f"G1 X{x0} Y{y0 + 50} E2.0", f"G1 X{x0} Y{y0} E2.0",
            ]
    lines.append("; filament_colour = " + ";".join(colours))
    lines.append("; filament_type = " + ";".join(["PLA"] * len(colours)))
    lines.append("; nozzle_diameter = 0.4")
    return "\n".join(lines) + "\n"


def _tiles() -> dict[str, bytes]:
    """The preview set a sliced Bambu plate carries, with the slicer's own
    witness that it was drawn in the plate's colours -- what a start by
    name checks before anything else is asked of the file."""
    from PIL import Image

    from kiln.printers.bambu_3mf import _BAMBU_THUMBNAIL_SPECS, _REQUIRED_TILE_SLOTS

    out: dict[str, bytes] = {}
    for slot in _REQUIRED_TILE_SLOTS:
        buf = io.BytesIO()
        Image.new("RGB", _BAMBU_THUMBNAIL_SPECS[slot], (90, 90, 90)).save(buf, format="PNG")
        out[slot] = buf.getvalue()
    buf = io.BytesIO()
    Image.new("RGB", (512, 512), (90, 90, 90)).save(buf, format="PNG")
    out["Metadata/plate_no_light_1.png"] = buf.getvalue()
    return out


def _kiln_plate(tmp_path: Path, colours: list[str], *, made_for: str = "bambu_a1") -> Path:
    """A plate through Kiln's own Bambu wrap: its plate JSON and -- for more
    than one colour -- the colour-change blocks it writes, plus the preview
    set a slice from a mesh carries (built here without a mesh to draw)."""
    path = tmp_path / f"plate{len(colours)}.gcode.3mf"
    build_bambu_3mf(
        _multitool_body(colours), str(path), settings=BambuPrintSettings(), printer_model=made_for,
    )
    with zipfile.ZipFile(path, "a") as zf:
        present = set(zf.namelist())
        for name, data in _tiles().items():
            if name not in present:
                zf.writestr(name, data)
    return path


def _ams(module: str, colours: list[str]) -> dict:
    """An ``ams_status`` reading: one unit, four trays, *colours* loaded."""
    trays = []
    for slot in range(4):
        tray = {"slot": slot, "tray_type": "", "tray_color": ""}
        if slot < len(colours):
            tray.update(tray_type="PLA", tray_color=colours[slot].lstrip("#") + "FF")
        trays.append(tray)
    return {
        "units": [{"unit_id": 0, "module_name": f"{module}/0", "trays": trays}],
        "ams_exist_bits": "1", "tray_exist_bits": "f",
    }


AMS_LITE = _ams("ams_f1", ["#E53935", "#1E88E5", "#F2F2F2", "#1A1A1A"])
NO_AMS = {"units": [], "ams_exist_bits": "0", "tray_exist_bits": "0"}


def _bambu(tmp_path, monkeypatch, *, model: str, ams, on_printer: Path | None = None) -> BambuAdapter:
    """The real Bambu adapter with its MQTT client stubbed, so a start runs
    the whole template and stops at the command it would publish.  The
    printer's storage holds *on_printer*, read back for a start by name."""
    monkeypatch.setenv("KILN_BAMBU_TLS_PIN_FILE", str(tmp_path / "pins.json"))
    a = BambuAdapter(
        host="192.0.2.10", access_code="12345678", serial="03919A000000000",
        timeout=2, printer_model=model,
    )
    a._mqtt_connected.set()
    a._connected = True
    a._mqtt_client = mock.MagicMock()
    sent = mock.MagicMock()
    sent.rc = mqtt.MQTT_ERR_SUCCESS
    a._mqtt_client.publish.return_value = sent
    a._confirm_window_s = 0.0
    a._last_status = {"gcode_state": "running"}
    a._last_state_time = float("inf")

    def _status():
        if isinstance(ams, Exception):
            raise ams
        return ams

    a.get_ams_status = _status  # type: ignore[method-assign]
    a._peek_loaded_ams_trays = lambda: [  # type: ignore[method-assign]
        {"tray_id": 0, "name": "A1", "tray_type": "PLA"}
    ]
    if on_printer is not None:
        data = on_printer.read_bytes()
        a.read_print_file = lambda name: data  # type: ignore[method-assign]
    return a


def _started(a: BambuAdapter) -> dict | None:
    """The start command the printer was sent, or ``None`` when none was."""
    for call in a._mqtt_client.publish.call_args_list:
        command = json.loads(call[0][1]).get("print", {})
        if command.get("command") == "project_file":
            return command
    return None


