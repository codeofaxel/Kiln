# --- Every other file keeps the old rule ---------------------------------


def test_an_ordinary_no_homing_file_is_refused_exactly_as_before(tmp_path):
    path = tmp_path / "raw.gcode"
    path.write_text(_ORDINARY_NO_HOMING)
    adapter = _RetryAdapter()  # homed, idle, unlatched -- none of it matters
    blocked = pg.run_adapter_gate(adapter, str(path), {})
    assert blocked is not None and blocked["code"] == "NO_HOMING_SEQUENCE"
    assert "G28" in blocked["reason"]
    assert adapter.homed_reads == 0, "an ordinary file never asks the machine"
    result = adapter.start_print(str(path))
    assert result.success is False and adapter.impl_calls == []


def test_a_homed_file_never_consults_the_contract(tmp_path):
    path = tmp_path / "homed.gcode"
    path.write_text("G28\n" + _ORDINARY_NO_HOMING)
    adapter = _RetryAdapter()
    assert pg.run_adapter_gate(adapter, str(path), {}) is None
    assert adapter.homed_reads == 0


# --- All five hold: accepted, with the evidence written down --------------


def test_all_conditions_true_is_accepted_and_the_evidence_is_recorded(retry_file, caplog):
    adapter = _RetryAdapter()
    path = retry_file()
    with caplog.at_level(logging.INFO, logger="kiln.printers.print_gate"):
        verdict = pg.evaluate_same_bed_retry(adapter, path)
        assert pg.run_adapter_gate(adapter, path, {}) is None
    assert verdict["blocked"] is False and verdict["accepted"] is True
    evidence = verdict["homed_evidence"]
    assert evidence["axes"] == ["x", "y", "z"]
    assert evidence["field"] == "toolhead.homed_axes"
    assert evidence["read_at"].endswith("+00:00")  # an ISO-8601 UTC timestamp
    assert verdict["machine"] == MACHINE
    assert verdict["contract"]["safe_startup_policy_version"] == "same-bed-safe-prologue-v2"
    audit = [r.getMessage() for r in caplog.records if "same-bed retry" in r.getMessage()]
    assert audit, "no audit line"
    assert all(s in audit[-1] for s in ("accepted", MACHINE, "x,y,z", "toolhead.homed_axes", evidence["read_at"]))

    result = adapter.start_print(path)
    assert result.success is True and adapter.impl_calls == [path]


# --- Each condition refuses on its own, naming itself and the remedy ------


@pytest.mark.parametrize(
    "missing, named",
    [
        ({"policy_id": None}, "safe_startup_policy_id"),
        ({"policy_version": None}, "safe_startup_policy_version"),
        ({"contract": "xyz_motion"}, "safe_startup_motion_contract"),
        ({"machine": None}, "baked_for_machine"),
    ],
)
def test_a_contract_with_a_line_missing_or_wrong_is_refused(retry_file, missing, named):
    adapter = _RetryAdapter()
    verdict = pg.evaluate_same_bed_retry(adapter, retry_file(**missing))
    assert verdict["blocked"] is True
    assert verdict["code"] == "SAME_BED_RETRY_NO_CONTRACT"
    assert named in verdict["reason"]
    assert "reslice" in verdict["reason"].lower()
    assert adapter.homed_reads == 0


def test_baked_for_another_machine_is_refused(retry_file):
    adapter = _RetryAdapter()
    verdict = pg.evaluate_same_bed_retry(adapter, retry_file(machine="other-a1"))
    assert verdict["blocked"] is True
    assert verdict["code"] == "SAME_BED_RETRY_WRONG_MACHINE"
    assert "other-a1" in verdict["reason"] and MACHINE in verdict["reason"]
    assert adapter.homed_reads == 0
    assert adapter.start_print(retry_file(machine="other-a1")).success is False


