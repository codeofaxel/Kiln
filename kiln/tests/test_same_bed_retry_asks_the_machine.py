def test_conditions_are_checked_in_order_and_the_first_failure_is_named(retry_file, latch):
    latch.status = {"latched": True, "critical_interlocks_pending": []}
    adapter = _RetryAdapter()
    adapter.state = PrinterStatus.PRINTING
    adapter.homed = None
    # (a) holds, (b) fails, (c) (d) (e) would all fail too: (b) is the answer.
    verdict = pg.evaluate_same_bed_retry(adapter, retry_file(machine="other-a1"))
    assert verdict["code"] == "SAME_BED_RETRY_WRONG_MACHINE"
    assert latch.asked == [] and adapter.homed_reads == 0
    # (b) holds, (c) fails: the latch is named, the state and the axes are never read.
    verdict = pg.evaluate_same_bed_retry(adapter, retry_file())
    assert verdict["code"] == "SAME_BED_RETRY_EMERGENCY_LATCHED"
    assert adapter.homed_reads == 0
    # (c) holds, (d) fails: still no homed read.
    latch.status = {"latched": False, "critical_interlocks_pending": []}
    verdict = pg.evaluate_same_bed_retry(adapter, retry_file())
    assert verdict["code"] == "SAME_BED_RETRY_PRINTER_BUSY"
    assert adapter.homed_reads == 0


