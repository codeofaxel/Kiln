# --- A same-bed retry artifact, exactly as kiln-pro bakes it -------------

_BODY = (
    ";LAYER_CHANGE\n;Z:0.2\n"
    "G1 Z.4 F24000\nG1 X114.658 Y114.939\nG1 Z.2\n"
    ";TYPE:Skirt/Brim\nG1 F3000\nG1 X116.4 Y113.37 E.06961\n"
)

_ORDINARY_NO_HOMING = (
    "; generated by PrusaSlicer 2.9.4\n"
    "M190 S65\nM104 S220\nM109 S220\nG21\nG90\nM83\nM107\n" + _BODY
)

MACHINE = "bench-a1"


def _header(
    *,
    machine: str | None = MACHINE,
    policy_id: str | None = "same-bed-safe-prologue-v2:bambu",
    policy_version: str | None = "same-bed-safe-prologue-v2",
    contract: str | None = "no_xyz_motion",
) -> str:
    lines = [
        "; --- Kiln same-bed retry safe startup ---",
        "; source_gcode: benchy.gcode",
        "; baked_xy_offset_mm: X70.000 Y70.000",
        "; no homing, bed-scan, or extrusion-line motion is emitted by this header",
        "; printer_profile: bambu",
    ]
    if policy_id is not None:
        lines.append(f"; safe_startup_policy_id: {policy_id}")
    if policy_version is not None:
        lines.append(f"; safe_startup_policy_version: {policy_version}")
    if contract is not None:
        lines.append(f"; safe_startup_motion_contract: {contract}")
    if machine is not None:
        lines.append(f"; baked_for_machine: {machine}")
    lines += [
        "; prohibited_startup_actions: xy_motion,z_motion,homing",
        "G21 ; Kiln same-bed retry units: mm",
        "G90 ; Kiln same-bed retry absolute XY",
        "M140 S60 ; preserved bed target",
        "; --- End Kiln same-bed retry safe startup ---",
    ]
    return "\n".join(lines) + "\n"


@pytest.fixture
def retry_file(tmp_path):
    def _write(name: str = "benchy_same_bed_retry.gcode", **header_kw: Any) -> str:
        path = tmp_path / name
        path.write_text(_header(**header_kw) + _BODY)
        return str(path)

    return _write


# --- A real adapter running the real start template ----------------------


class _RetryAdapter(PrinterAdapter):
    """Registry-shaped: named by its owner, no serial, answers the gate's
    questions from attributes a test sets, records every start."""

    printer_id = "bambu_a1"

    def __init__(self, registered_name: str | None = MACHINE) -> None:
        if registered_name is not None:
            self._kiln_registered_name = registered_name
        self.homed: set[str] | None = {"x", "y", "z"}
        self.homed_field: str | None = "toolhead.homed_axes"
        self.homed_reads = 0
        self.state = PrinterStatus.IDLE
        self.impl_calls: list[str] = []

    @property
    def name(self) -> str:
        return "stub"

    def get_state(self) -> PrinterState:
        return PrinterState(connected=True, state=self.state)

    def homed_axes_now(self) -> set[str] | None:
        self.homed_reads += 1
        return None if self.homed is None else set(self.homed)

    def homed_axes_field(self) -> str | None:
        return self.homed_field

    def _start_print_impl(self, file_name: str, **kwargs: Any) -> PrintResult:
        self.impl_calls.append(file_name)
        return PrintResult(success=True, message="IMPL")


_RetryAdapter.__abstractmethods__ = frozenset()


class _Unlatched:
    def __init__(self) -> None:
        self.asked: list[str] = []
        self.status: dict[str, Any] = {"latched": False, "critical_interlocks_pending": []}

    def get_latch_status(self, printer_id: str) -> dict[str, Any]:
        self.asked.append(printer_id)
        return dict(self.status)


