class TestClassification:
    @pytest.mark.parametrize(
        ("label", "cls"),
        [
            # PrusaSlicer / SuperSlicer
            ("Skirt/Brim", "skirt"),
            ("Skirt", "skirt"),
            ("Brim", "brim"),
            ("Wipe tower", "prime_tower"),
            ("Support material", "support"),
            ("Support material interface", "support_interface"),
            # OrcaSlicer / Bambu Studio
            ("Prime tower", "prime_tower"),
            ("Support", "support"),
            ("Support interface", "support_interface"),
            ("Support transition", "support"),
            # Cura
            ("SKIRT", "skirt"),
            ("PRIME-TOWER", "prime_tower"),
            ("SUPPORT", "support"),
            ("SUPPORT-INTERFACE", "support_interface"),
            # Simplify3D
            ("skirt", "skirt"),
            ("prime pillar", "prime_tower"),
            ("raft", "raft"),
            ("ooze shield", "shield"),
            ("support", "support"),
        ],
    )
    def test_every_slicer_dialect_lands_in_its_class(self, label, cls):
        assert sg.classify_feature(label) == cls

    @pytest.mark.parametrize(
        "label",
        ["External perimeter", "Outer wall", "WALL-OUTER", "Sparse infill",
         "Top solid infill", "Bridge infill", "outer perimeter", "Ironing",
         "Something Nobody Has Seen"],
    )
    def test_part_features_and_unknown_labels_are_the_model(self, label):
        """The conservative reading: hiding real part geometry under an
        extras toggle would be worse than showing an extra as part."""
        assert sg.classify_feature(label) == "model"

    def test_the_contact_layer_is_its_own_class_and_plain_support_is_not(self):
        """The interface — the layer that touches the part, where it will
        scar — is drawn apart from the lattice under it, on every slicer's
        spelling.  A support with no such word stays a support."""
        assert sg.classify_feature("Support interface") == "support_interface"
        assert sg.classify_feature("Support material interface") == "support_interface"
        assert sg.classify_feature("SUPPORT-INTERFACE") == "support_interface"
        assert sg.classify_feature("Support transition") == "support"
        assert sg.classify_feature("Support material") == "support"
        assert "support_interface" in sg.EXTRA_CLASSES
        assert sg.SCAFFOLD_CLASSES == ("support", "support_interface", "raft", "shield")

    def test_start_gcode_blocks_are_neither(self):
        """A purge line at the bed edge is the printer's start G-code,
        not a slicer feature — it must not widen the model footprint."""
        assert sg.classify_feature("Custom") == "ignore"

    def test_no_label_at_all_reads_as_model(self):
        assert sg.classify_feature(None) == "model"
        assert sg.classify_feature("") == "model"


