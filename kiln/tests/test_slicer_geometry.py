class TestBlock:
    def test_features_land_in_the_mesh_frame_beside_the_part(self, tmp_path):
        g = tmp_path / "job.gcode"
        g.write_text(_orca_job(layers=2, support=True))
        block = sg.slicer_features_block(g, (0.0, 0.0, 0.0), (40.0, 30.0, 10.0))
        assert block["kind"] == sg.FEATURE_KIND
        assert block["available"] is True
        assert block["frame"] == "mesh"
        assert block["offset_mm"] == pytest.approx([-100.0, -100.0, 0.0])
        classes = [f["class"] for f in block["features"]]
        assert classes == ["skirt", "prime_tower", "support"], "plate first, then beside and under"
        skirt = next(f for f in block["features"] if f["class"] == "skirt")
        assert skirt["bounds"]["min"][:2] == pytest.approx([-2.0, -2.0])
        assert skirt["bounds"]["max"][:2] == pytest.approx([42.0, 32.0])
        assert skirt["label"] == "Skirt" and skirt["layers"] == 1
        tower = next(f for f in block["features"] if f["class"] == "prime_tower")
        assert tower["bounds"]["min"][:2] == pytest.approx([60.0, 0.0])
        assert tower["bounds"]["max"][:2] == pytest.approx([70.0, 10.0])
        assert tower["layers"] == 2
        assert block["model_footprint"] == {"min": [0.0, 0.0], "max": [40.0, 30.0]}
        assert block["source"]["filename"] == "job.gcode"
        assert "/" not in block["source"]["filename"]
        assert block["source"]["labels"]["Prime tower"] == "prime_tower"
        assert block["segments_total"] == sum(f["count"] for f in block["features"])
        assert block["sampled_layer_stride"] == 1
        assert block["truncated"] is False

    def test_segments_decode_to_the_declared_count(self, tmp_path):
        g = tmp_path / "job.gcode"
