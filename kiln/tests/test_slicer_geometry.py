class TestAlignment:
    def test_footprint_centre_maps_to_the_mesh_centre_and_floor(self, tmp_path):
        g = tmp_path / "job.gcode"
        g.write_text(_orca_job(layers=1))
        parsed = sg.parse_slicer_features(g)
        # The same 40 x 30 part, in ITS file at the origin corner, floating 5 up.
        offset, reason = sg.align_to_mesh(parsed, (0.0, 0.0, 5.0), (40.0, 30.0, 25.0))
        assert reason is None
        assert offset == pytest.approx((-100.0, -100.0, 5.0))

    def test_a_slice_of_a_different_part_is_refused_with_a_reason(self, tmp_path):
        g = tmp_path / "job.gcode"
        g.write_text(_orca_job(layers=1))
        parsed = sg.parse_slicer_features(g)
        offset, reason = sg.align_to_mesh(parsed, (0.0, 0.0, 0.0), (80.0, 60.0, 20.0))
        assert offset is None
        assert "does not match" in reason
        assert "40.0 × 30.0" in reason and "80.0 × 60.0" in reason

    def test_half_a_line_width_of_shrink_is_within_tolerance(self, tmp_path):
        """An extrusion centreline sits inside the surface; the toolpath
        box is always a hair smaller than the mesh.  Measured on the jar:
        114.5 mm mesh, 113.9 mm footprint."""
        g = tmp_path / "job.gcode"
        g.write_text(_orca_job(layers=1))
        parsed = sg.parse_slicer_features(g)
        offset, reason = sg.align_to_mesh(parsed, (0.0, 0.0, 0.0), (40.45, 30.45, 20.0))
        assert reason is None and offset is not None

    def test_an_unlabelled_file_is_refused_rather_than_guessed(self, tmp_path):
        g = tmp_path / "old.gcode"
        g.write_text("G90\nM83\nG1 X0 Y0 Z0.2\nG1 X10 Y0 E1\nG1 X10 Y10 E1\n")
        parsed = sg.parse_slicer_features(g)
        offset, reason = sg.align_to_mesh(parsed, (0.0, 0.0, 0.0), (10.0, 10.0, 1.0))
        assert offset is None
        assert "no feature labels" in reason

    def test_a_file_with_only_extras_has_no_footprint_to_align(self, tmp_path):
        g = tmp_path / "skirt_only.gcode"
        g.write_text("G90\nM83\n;TYPE:Skirt\nG1 X0 Y0 Z0.2\nG1 X10 Y0 E1\n")
        parsed = sg.parse_slicer_features(g)
        offset, reason = sg.align_to_mesh(parsed, (0.0, 0.0, 0.0), (10.0, 10.0, 1.0))
        assert offset is None
        assert "no model toolpaths" in reason


