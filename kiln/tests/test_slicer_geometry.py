def _u16(b64: str) -> np.ndarray:
    return np.frombuffer(base64.b64decode(b64), dtype="<u2")


def _u8(b64: str) -> np.ndarray:
    return np.frombuffer(base64.b64decode(b64), dtype="u1")


class TestFilamentsAndTools:
    def test_the_slicers_filament_colours_are_read_from_the_config_block(self, tmp_path):
        """Orca / Bambu / Prusa write ``filament_colour`` at the END of the
        file, one entry per tool — so the whole file is scanned."""
        g = tmp_path / "job.gcode"
        g.write_text(_orca_job(layers=1) + "; CONFIG_BLOCK_START\n; filament_colour = #FFFFFF;#C81E1E;#161616\n")
        parsed = sg.parse_slicer_features(g)
        assert parsed.filament_colors == ["#FFFFFF", "#C81E1E", "#161616"]
        block = sg.slicer_features_block(g, (0.0, 0.0, 0.0), (40.0, 30.0, 10.0))
        assert block["filaments"] == ["#FFFFFF", "#C81E1E", "#161616"]

    def test_a_file_that_names_no_colours_names_none(self, tmp_path):
        g = tmp_path / "job.gcode"
        g.write_text(_orca_job(layers=1))
        assert sg.parse_slicer_features(g).filament_colors == []

    def test_a_colour_list_with_junk_is_dropped_whole_never_guessed(self, tmp_path):
        g = tmp_path / "job.gcode"
        g.write_text(_orca_job(layers=1) + "; filament_colour = #FFFFFF;;#161616\n")
        assert sg.parse_slicer_features(g).filament_colors == []
        g.write_text(_orca_job(layers=1) + "; filament_colour = white;red\n")
        assert sg.parse_slicer_features(g).filament_colors == []

    def test_every_segment_carries_the_tool_that_laid_it(self, tmp_path):
        g = tmp_path / "job.gcode"
        g.write_text(
            "; generated by OrcaSlicer 2.3.2\nG90\nM83\n;LAYER_CHANGE\n;Z:0.2\n"
            ";TYPE:Skirt\n" + _square_loop(98, 98, 142, 132, 0.2) +
            ";TYPE:Outer wall\n" + _square_loop(100, 100, 140, 130, 0.2) +
            "T1\n;TYPE:Prime tower\n" + _square_loop(160, 100, 170, 110, 0.2) +
            "T2\nG1 X165 Y105 E0.05\n"
        )
        block = sg.slicer_features_block(g, (0.0, 0.0, 0.0), (40.0, 30.0, 10.0))
        by = {f["class"]: f for f in block["features"]}
        assert _u8(by["skirt"]["tool_index"]).tolist() == [0, 0, 0, 0]
        tower = by["prime_tower"]
        assert _u8(tower["tool_index"]).tolist() == [1, 1, 1, 1, 2]
        assert len(_u16(tower["layer_index"])) == tower["count"]
        assert _u16(tower["layer_index"]).tolist() == [1] * 5

    def test_each_class_carries_the_width_the_slicer_drew_it_at(self, tmp_path):
        """``;WIDTH:`` precedes the paths it applies to; a class reports the
        width most of its segments were laid at, and a file with none
        reports the common default rather than nothing."""
        g = tmp_path / "job.gcode"
        g.write_text(
            "; generated by OrcaSlicer 2.3.2\nG90\nM83\n;LAYER_CHANGE\n;Z:0.2\n"
            ";TYPE:Skirt\n;WIDTH:0.5\n" + _square_loop(98, 98, 142, 132, 0.2) +
            ";TYPE:Outer wall\n;WIDTH:0.42\n" + _square_loop(100, 100, 140, 130, 0.2) +
            ";TYPE:Prime tower\n;WIDTH:0.6\n" + _square_loop(160, 100, 170, 110, 0.2) +
            ";WIDTH:0.5\nG1 X165 Y105 E0.05\n"
        )
        block = sg.slicer_features_block(g, (0.0, 0.0, 0.0), (40.0, 30.0, 10.0))
        by = {f["class"]: f for f in block["features"]}
        assert by["skirt"]["line_width_mm"] == 0.5
        assert by["prime_tower"]["line_width_mm"] == 0.6   # 4 segments at 0.6, 1 at 0.5
        bare = tmp_path / "bare.gcode"
        bare.write_text(_orca_job(layers=1))
        block = sg.slicer_features_block(bare, (0.0, 0.0, 0.0), (40.0, 30.0, 10.0))
        assert all(f["line_width_mm"] == sg.DEFAULT_LINE_WIDTH_MM for f in block["features"])

    def test_prusaslicers_joint_label_is_kept_as_written(self, tmp_path):
        """One label for both loops — calling it "Skirt" would hide the brim."""
        g = tmp_path / "prusa.gcode"
        g.write_text(
            "; generated by PrusaSlicer 2.9.4\nG90\nM83\n;LAYER_CHANGE\n;Z:0.2\n"
            ";TYPE:Skirt/Brim\n" + _square_loop(98, 98, 142, 132, 0.2) +
            ";TYPE:External perimeter\n" + _square_loop(100, 100, 140, 130, 0.2)
        )
        block = sg.slicer_features_block(g, (0.0, 0.0, 0.0), (40.0, 30.0, 10.0))
        assert block["features"][0]["class"] == "skirt"
        assert block["features"][0]["label"] == "Skirt/Brim"

    def test_layer_index_survives_the_budget_sampling(self, tmp_path):
        g = tmp_path / "tall.gcode"
        g.write_text(_orca_job(layers=40))
        tight = sg.slicer_features_block(
            g, (0.0, 0.0, 0.0), (40.0, 30.0, 10.0), max_segments=60,
        )
        for f in tight["features"]:
            assert len(_u16(f["layer_index"])) == f["count"]
            assert len(_u8(f["tool_index"])) == f["count"]
            assert len(set(_u16(f["layer_index"]).tolist())) == f["layers"]


