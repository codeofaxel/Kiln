class TestRaftAndCost:
    def _raft_job(self) -> str:
        """Two raft layers labelled as every slicer labels them — Support —
        under a part whose first layer stands at 0.8 mm, then a support
        column beside the part from that layer up."""
        out = ["; generated by OrcaSlicer 2.3.2", "G90", "M83", "G28"]
        for z in (0.2, 0.4):
            out += [";LAYER_CHANGE", f";Z:{z}", ";TYPE:Support", ";WIDTH:0.5", _square_loop(95, 95, 145, 135, z)]
        out += [";LAYER_CHANGE", ";Z:0.4", ";TYPE:Support interface", ";WIDTH:0.5", _square_loop(96, 96, 144, 134, 0.4)]
        for z in (0.8, 1.0):
            out += [";LAYER_CHANGE", f";Z:{z}", ";TYPE:Outer wall", ";WIDTH:0.42", _square_loop(100, 100, 140, 130, z)]
            out += [";TYPE:Support", ";WIDTH:0.42", _square_loop(150, 100, 156, 106, z)]
        return "\n".join(out) + "\n"

    def test_support_under_the_parts_first_layer_is_the_raft(self, tmp_path):
        """Orca, Bambu Studio and PrusaSlicer label raft layers as support;
        the height says what the label cannot.  Support at the part's own
        first layer and above stays support."""
        g = tmp_path / "raft.gcode"
        g.write_text(self._raft_job())
        parsed = sg.parse_slicer_features(g)
        assert parsed.model_z_min == pytest.approx(0.8)
        assert set(parsed.buckets) == {"raft", "support"}
        raft, support = parsed.buckets["raft"], parsed.buckets["support"]
        assert raft.count == 12                      # 3 loops × 4 sides, both classes under the floor
        assert raft.z_max == pytest.approx(0.4)
        assert raft.label == "Raft"
        assert support.count == 8                    # 2 loops × 4 sides beside the part
        assert support.z_min == pytest.approx(0.8)
        block = sg.slicer_features_block(g, (100, 100, 0), (140, 130, 1))
        assert [f["class"] for f in block["features"]] == ["raft", "support"]

    def test_a_job_without_a_raft_moves_nothing(self, tmp_path):
        g = tmp_path / "job.gcode"
        g.write_text(_orca_job(layers=3, support=True))
        parsed = sg.parse_slicer_features(g)
        assert "raft" not in parsed.buckets
        assert "support" in parsed.buckets

    def test_every_entry_says_what_it_costs(self, tmp_path):
        """Path length and a grams estimate at the file's own width and
        layer height, the way the slicer's legend gives them — a person
        deciding whether to keep supports wants the number."""
        g = tmp_path / "raft.gcode"
        g.write_text(self._raft_job())
        block = sg.slicer_features_block(g, (100, 100, 0), (140, 130, 1))
        by = {f["class"]: f for f in block["features"]}
        # raft: two 50×40 loops (180 mm each) + one 48×38 loop (172 mm)
        assert by["raft"]["length_mm"] == pytest.approx(532, abs=0.5)
        # at 0.5 mm wide, 0.2 mm layers, 1.24 g/cm³: 532 × 0.5 × 0.2 × 1.24 / 1000
        assert by["raft"]["filament_g_est"] == pytest.approx(0.066, abs=0.005)
        assert by["support"]["length_mm"] == pytest.approx(48, abs=0.5)
        assert by["support"]["filament_g_est"] > 0
