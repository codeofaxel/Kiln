class TestFrames:
    def _block(self, tmp_path):
        g = tmp_path / "job.gcode"
        g.write_text(_orca_job(layers=1))
        return sg.slicer_features_block(g, (0.0, 0.0, 0.0), (40.0, 30.0, 10.0))

    def test_viewer_frame_is_the_payload_rotation(self, tmp_path):
        """``(x, y, z)_mesh → (x, z, -y)_viewer`` — the rule mesh_payload
        bakes into positions, applied to every segment and its bounds."""
        mesh = self._block(tmp_path)
        viewer = sg.to_viewer_frame(mesh)
        assert viewer["frame"] == "viewer"
        assert mesh["frame"] == "mesh", "conversion returns a copy"
        for fm, fv in zip(mesh["features"], viewer["features"], strict=True):
            a, b = _segments(fm), _segments(fv)
            assert np.allclose(b[:, 0], a[:, 0])
            assert np.allclose(b[:, 1], a[:, 2])
            assert np.allclose(b[:, 2], -a[:, 1])
            assert np.allclose(b[:, 3], a[:, 3])
            assert np.allclose(b[:, 4], a[:, 5])
            assert np.allclose(b[:, 5], -a[:, 4])
            lo, hi = fm["bounds"]["min"], fm["bounds"]["max"]
            assert fv["bounds"]["min"] == pytest.approx([lo[0], lo[2], -hi[1]])
            assert fv["bounds"]["max"] == pytest.approx([hi[0], hi[2], -lo[1]])
        # The footprint names the plate axes and stays in mesh XY.
        assert viewer["model_footprint"] == mesh["model_footprint"]

    def test_converting_twice_is_a_no_op(self, tmp_path):
        viewer = sg.to_viewer_frame(self._block(tmp_path))
        assert sg.to_viewer_frame(viewer) is viewer

    def test_shift_moves_mesh_frame_geometry_and_its_bounds(self, tmp_path):
        block = self._block(tmp_path)
        before = {f["class"]: _segments(f).copy() for f in block["features"]}
        sg.shift_block(block, 7.0, -3.0)
        for f in block["features"]:
            a = before[f["class"]]
            b = _segments(f)
            assert np.allclose(b[:, [0, 3]], a[:, [0, 3]] + 7.0)
            assert np.allclose(b[:, [1, 4]], a[:, [1, 4]] - 3.0)
            assert np.allclose(b[:, [2, 5]], a[:, [2, 5]])
        skirt = next(f for f in block["features"] if f["class"] == "skirt")
        assert skirt["bounds"]["min"][:2] == pytest.approx([5.0, -5.0])
        assert block["model_footprint"]["min"] == pytest.approx([7.0, -3.0])
        assert block["offset_mm"][:2] == pytest.approx([-93.0, -103.0])

    def test_shift_in_the_viewer_frame_moves_z_the_way_positions_move(self, tmp_path):
        """Mesh +y is viewer −z — the exact line stand_on_plate applies."""
        block = sg.to_viewer_frame(self._block(tmp_path))
        before = {f["class"]: _segments(f).copy() for f in block["features"]}
        sg.shift_block(block, 7.0, -3.0)
        for f in block["features"]:
            a = before[f["class"]]
            b = _segments(f)
            assert np.allclose(b[:, [0, 3]], a[:, [0, 3]] + 7.0)
            assert np.allclose(b[:, [1, 4]], a[:, [1, 4]])
            assert np.allclose(b[:, [2, 5]], a[:, [2, 5]] + 3.0)

    def test_an_unavailable_block_passes_through_both(self):
        block = sg.unavailable_block("nothing here")
        assert sg.to_viewer_frame(block) is block
        assert sg.shift_block(block, 1.0, 1.0) is block


