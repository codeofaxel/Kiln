"""Slicer-added geometry — what prints that the model never contained.

The stage draws the model; the printer prints the model plus a skirt, a
brim, a prime tower, supports.  Measured 2026-09-03 on a Bambu Lab A1: a
three-colour jar's first layer carried a 157 mm skirt loop and a 30 mm prime
tower that had never appeared on any stage.  This file pins the engine that
reads them out of the slice:

* every slicer dialect Kiln drives lands in the right class by keyword —
  PrusaSlicer, SuperSlicer, OrcaSlicer, Bambu Studio, Cura, Simplify3D —
  and an unknown label is the PART, never an extra;
* a segment is an extrusion while moving.  A ``G1 E0.8`` unretract at a
  travel destination is not a toolpath: on the jar those alone pushed the
  "outer wall" footprint 35 mm into the tower and would have mis-aligned
  everything;
* the join to the mesh is the model's own footprint, and it is CHECKED —
  a slice of a different or rescaled part is refused with a reason rather
  than drawn around the wrong object;
* the budget samples layers, never silently drops a class, and says so;
* the viewer-frame rotation and the plate-centring shift are the same
  rules the payload's positions follow.
"""

from __future__ import annotations

import base64
import math

import numpy as np
import pytest

from kiln import slicer_geometry as sg


def _segments(feature: dict) -> np.ndarray:
    return np.frombuffer(base64.b64decode(feature["segments"]), dtype="<f4").reshape(-1, 6)


def _square_loop(x0: float, y0: float, x1: float, y1: float, z: float, e_step: float = 0.1) -> str:
    """One closed rectangular extrusion loop, relative E."""
    return (
        f"G1 X{x0} Y{y0} Z{z} F6000\n"
        f"G1 X{x1} Y{y0} E{e_step}\n"
        f"G1 X{x1} Y{y1} E{e_step}\n"
        f"G1 X{x0} Y{y1} E{e_step}\n"
        f"G1 X{x0} Y{y0} E{e_step}\n"
    )


def _orca_job(
    *, layers: int = 3, tower: bool = True, support: bool = False, skirt: bool = True,
) -> str:
    """A tiny OrcaSlicer-flavoured file: a 40 x 30 part placed at bed
    (100..140, 100..130), a skirt 2 mm out on layer 1, a 10 mm tower to
    the right on every layer, optional supports."""
    out = ["; generated by OrcaSlicer 2.3.2 on 2026-09-03 at 12:37:11", "G90", "M83", "G28"]
    for i in range(layers):
        z = 0.2 * (i + 1)
        out.append(";LAYER_CHANGE")
        out.append(f";Z:{z}")
        if i == 0 and skirt:
            out.append(";TYPE:Skirt")
            out.append(_square_loop(98, 98, 142, 132, z))
        # The unretract-at-destination pattern every slicer emits before a
        # feature change: a travel, then E-only, still under the OLD type.
        out.append(";TYPE:Outer wall")
        out.append(_square_loop(100, 100, 140, 130, z))
        out.append(";TYPE:Inner wall")
        out.append(_square_loop(101, 101, 139, 129, z))
        if tower:
            out.append("G1 E-.8 F1800")
            out.append(f"G1 X160 Y100 Z{z + 0.2}")   # travel to the tower...
            out.append(f"G1 Z{z}")
            out.append("G1 E.8 F1800")                # ...unretract, type still 'Inner wall'
            out.append(";TYPE:Prime tower")
            out.append(_square_loop(160, 100, 170, 110, z))
            out.append("G1 X165 Y105 E0.05")          # a purge stroke inside it
        if support:
            out.append(";TYPE:Support")
            out.append(_square_loop(120, 140, 130, 150, z))
    return "\n".join(out) + "\n"


