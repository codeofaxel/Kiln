class TestParsing:
    def test_reads_orca_labels_skirt_and_tower(self, tmp_path):
        g = tmp_path / "job.gcode"
        g.write_text(_orca_job(layers=2))
        parsed = sg.parse_slicer_features(g)
        assert parsed.slicer == "OrcaSlicer 2.3.2"
        assert parsed.labelled
        assert set(parsed.buckets) == {"skirt", "prime_tower"}
        assert parsed.buckets["skirt"].count == 4
        assert parsed.buckets["skirt"].z_min == parsed.buckets["skirt"].z_max == pytest.approx(0.2)
        # 4 loop sides + 1 purge stroke, on both layers
        assert parsed.buckets["prime_tower"].count == 10
        assert len(set(parsed.buckets["prime_tower"].layers)) == 2

    def test_the_unretract_at_a_travel_destination_is_not_a_toolpath(self, tmp_path):
        """The regression, named: ``G1 E.8`` at (160, 100) under 'Inner
        wall' used to drag the model footprint into the tower."""
        g = tmp_path / "job.gcode"
        g.write_text(_orca_job(layers=1))
        parsed = sg.parse_slicer_features(g)
        x0, y0, x1, y1 = parsed.model_footprint
        assert (x0, y0, x1, y1) == pytest.approx((100.0, 100.0, 140.0, 130.0))

    def test_travels_and_z_only_moves_never_become_segments(self, tmp_path):
        g = tmp_path / "job.gcode"
        g.write_text(
            "G90\nM83\n;LAYER_CHANGE\n;TYPE:Skirt\n"
            "G1 X10 Y10 Z0.2 F3000\n"   # travel
            "G1 Z0.6\n"                  # lift
            "G1 E-0.8\n"                 # retract in place
            "G1 X20 Y10 E0.1\n"          # the one real segment
        )
        parsed = sg.parse_slicer_features(g)
        assert parsed.buckets["skirt"].count == 1

    def test_absolute_extrusion_and_g92_resets(self, tmp_path):
        """Cura-style M82 with periodic G92 E0 — the delta is what counts."""
        g = tmp_path / "cura.gcode"
        g.write_text(
            ";Generated with Cura_SteamEngine 5.8.0\nG90\nM82\n;LAYER:0\n;TYPE:SKIRT\n"
            "G1 X0 Y0 Z0.2\nG1 X10 Y0 E1.0\nG92 E0\nG1 X10 Y10 E1.0\n"
            "G1 X10 Y10 E0.2\n"          # unretract, no motion — not a segment
            ";TYPE:WALL-OUTER\nG1 X20 Y20 E2\n"
        )
        parsed = sg.parse_slicer_features(g)
        assert parsed.slicer.startswith("Cura_SteamEngine")
        assert parsed.buckets["skirt"].count == 2
        assert parsed.model_footprint == pytest.approx((10.0, 10.0, 20.0, 20.0))

    def test_simplify3d_feature_comments(self, tmp_path):
        g = tmp_path / "s3d.gcode"
        g.write_text(
            "; G-Code generated by Simplify3D(R) Version 5.1.2\nG90\nM82\n"
            "; layer 1, Z = 0.200\n; feature skirt\nG1 X0 Y0 Z0.2\nG1 X5 Y0 E0.5\n"
            "; feature prime pillar\nG1 X30 Y30\nG1 X35 Y30 E1.0\n"
            "; feature outer perimeter\nG1 X10 Y10\nG1 X20 Y10 E1.5\n"
        )
        parsed = sg.parse_slicer_features(g)
        assert set(parsed.buckets) == {"skirt", "prime_tower"}
        assert parsed.labels == {
            "skirt": "skirt", "prime pillar": "prime_tower", "outer perimeter": "model",
        }

    def test_prusa_wipe_tower_and_support_material(self, tmp_path):
        g = tmp_path / "prusa.gcode"
        g.write_text(
            "; generated by PrusaSlicer 2.9.4 on 2026-09-03 at 21:50:01 UTC\nG90\nM83\n"
            ";LAYER_CHANGE\n;Z:0.2\n;TYPE:Skirt/Brim\nG1 X0 Y0 Z0.2\nG1 X5 Y0 E0.5\n"
            ";TYPE:Wipe tower\nG1 X40 Y40\nG1 X45 Y40 E0.5\n"
            ";TYPE:Support material\nG1 X10 Y30\nG1 X12 Y30 E0.1\n"
            ";TYPE:External perimeter\nG1 X10 Y10\nG1 X20 Y10 E1\nG1 X20 Y20 E1\n"
        )
        parsed = sg.parse_slicer_features(g)
        assert parsed.slicer == "PrusaSlicer 2.9.4"
        assert set(parsed.buckets) == {"skirt", "prime_tower", "support"}
        assert parsed.buckets["skirt"].label == "Skirt/Brim", "the joint label is kept as written"

    def test_arcs_are_expanded_to_chords(self, tmp_path):
        """A skirt fitted with G2/G3 stays a loop, not a chord across it."""
        g = tmp_path / "arc.gcode"
        g.write_text(
            "G90\nM83\n;LAYER_CHANGE\n;TYPE:Skirt\n"
            "G1 X10 Y0 Z0.2\n"
            "G3 X0 Y10 I-10 J0 E1.0\n"   # quarter circle, CCW, radius 10
        )
        parsed = sg.parse_slicer_features(g)
        seg = np.asarray(parsed.buckets["skirt"].segments).reshape(-1, 6)
        assert len(seg) >= 8
        radii = np.hypot(seg[:, 0], seg[:, 1])
        assert np.allclose(radii, 10.0, atol=1e-6)
        assert seg[0, :2] == pytest.approx((10.0, 0.0))
        assert seg[-1, 3:5] == pytest.approx((0.0, 10.0))

    def test_layers_are_inferred_from_z_when_a_file_has_no_markers(self, tmp_path):
        g = tmp_path / "bare.gcode"
        g.write_text(
            "G90\nM83\n;TYPE:Support\n"
            "G1 X0 Y0 Z0.2\nG1 X5 Y0 E0.1\n"
            "G1 X0 Y0 Z0.4\nG1 X5 Y0 E0.1\n"
            "G1 X0 Y0 Z0.6\nG1 X5 Y0 E0.1\n"
        )
        parsed = sg.parse_slicer_features(g)
        assert len(set(parsed.buckets["support"].layers)) == 3

    def test_prusaslicers_before_and_after_markers_do_not_double_count_layers(self, tmp_path):
        """PrusaSlicer brackets each change with ;BEFORE_LAYER_CHANGE and
        ;AFTER_LAYER_CHANGE around the ;LAYER_CHANGE itself — one layer."""
        g = tmp_path / "prusa.gcode"
        g.write_text(
            "G90\nM83\n"
            ";LAYER_CHANGE\n;Z:0.2\n;BEFORE_LAYER_CHANGE\nG1 Z0.2\n;AFTER_LAYER_CHANGE\n;0.2\n"
            ";TYPE:Support material\nG1 X0 Y0\nG1 X5 Y0 E0.1\n"
            ";LAYER_CHANGE\n;Z:0.4\n;BEFORE_LAYER_CHANGE\nG1 Z0.4\n;AFTER_LAYER_CHANGE\n;0.4\n"
            ";TYPE:Support material\nG1 X0 Y0\nG1 X5 Y0 E0.1\n"
        )
        parsed = sg.parse_slicer_features(g)
        assert sorted(set(parsed.buckets["support"].layers)) == [1, 2]

    def test_a_missing_file_raises(self, tmp_path):
        with pytest.raises(FileNotFoundError):
            sg.parse_slicer_features(tmp_path / "nope.gcode")


