def _cube(path: Path, w: float, d: float, h: float) -> str:
    """A binary STL box on the bed, its corner at the origin."""
    v = [(0, 0, 0), (w, 0, 0), (w, d, 0), (0, d, 0), (0, 0, h), (w, 0, h), (w, d, h), (0, d, h)]
    faces = [(0, 3, 2), (0, 2, 1), (4, 5, 6), (4, 6, 7), (0, 1, 5), (0, 5, 4),
             (1, 2, 6), (1, 6, 5), (2, 3, 7), (2, 7, 6), (3, 0, 4), (3, 4, 7)]
    with open(path, "wb") as fh:
        fh.write(b"\0" * 80)
        fh.write(struct.pack("<I", len(faces)))
        for a, b, c in faces:
            fh.write(struct.pack("<3f", 0, 0, 0))
            for i in (a, b, c):
                fh.write(struct.pack("<3f", *v[i]))
            fh.write(struct.pack("<H", 0))
    return str(path)


def _plate(path: Path, span_mm: float) -> str:
    """A sliced .gcode.3mf that homes and prints a square *span_mm* wide."""
    gcode = "\n".join([
        "; generated by OrcaSlicer 2.3.0", "G28", "G90", "M83", "G1 Z0.2 F600",
        "G1 X5 Y5 F3000", f"G1 X{span_mm} Y5 E5", f"G1 X{span_mm} Y{span_mm} E5", f"G1 X5 Y{span_mm} E5",
    ])
    with zipfile.ZipFile(path, "w") as zf:
        zf.writestr("Metadata/plate_1.gcode", gcode)
    return str(path)


class _Machine(PrinterAdapter):
    """A generic printer, set up the way every setup door sets one up, that
    can be told what it reports about itself and what its configuration says."""

    def __init__(self, model: str | None = None, *, reports: str | None = None, travel=None) -> None:
        self.started: list[str] = []
        self._reports = reports
        self._travel = travel
        self._kiln_registered_name = "workshop"
        if model:
            self.set_safety_profile(model)

    def _start_print_impl(self, file_name: str, **kwargs) -> PrintResult:
        self.started.append(file_name)
        return PrintResult(success=True, message="started")

    def get_printer_info(self):
        from kiln.printers.base import PrinterInfo

        return PrinterInfo(model=self._reports) if self._reports else None

    def read_machine_limits(self):
        if self._travel is None:
            return None
        return {
            "profile": {"build_volume": list(self._travel)},
            "read": {"build_volume": f"[stepper_x] position_max: {self._travel[0]:g}"},
            "missing": [],
        }


_Machine.__abstractmethods__ = frozenset()


