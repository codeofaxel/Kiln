class TestOneBedReaderWithItsSource:
    def test_a_confirmed_bed_is_what_every_fit_door_reads(self, tmp_path):
        """Main: an owner's bed reached the slicer's layout but not the
        fit validators, which read the catalogue alone."""
        sp.set_local_printer_bed(
            "prusa_core_one", [250, 220, 270], kind=sp.BED_FROM_MAKER_SPEC, where="https://www.prusa3d.com/core-one",
        )
        bed = bed_fit.printer_bed("prusa_core_one")
        assert bed is not None and bed.volume == (250.0, 220.0, 270.0)
        assert bed.source == sp.BED_FROM_MAKER_SPEC
        fit = bed_fit.validate_mesh_for_printer(_cube(tmp_path / "big.stl", 300, 300, 20), "prusa_core_one")
        assert fit["error_code"] == "EXCEEDS_BED"
        assert "the bed its maker publishes (https://www.prusa3d.com/core-one), confirmed by its owner" in fit[
            "error_message"
        ]

    def test_a_catalogue_printer_never_reads_a_recorded_bed(self):
        sp.set_local_printer_bed("kilntest_small", [999, 999, 999], kind=sp.BED_FROM_OWNER)
        bed = bed_fit.printer_bed("kilntest_small")
        assert bed is not None and bed.source == bed_fit.BED_FROM_CATALOGUE
        assert bed.volume != (999.0, 999.0, 999.0)

    def test_the_source_survives_a_restart(self):
        sp.set_local_printer_bed("acme_one", [200, 200, 200], kind=sp.BED_FROM_PRINTER, where="[stepper_x] 200")
        sp._local_overrides_loaded = False
        sp._local_override_cache.clear()
        assert sp.local_printer_bed_source("acme_one") == (sp.BED_FROM_PRINTER, "[stepper_x] 200")

    def test_a_bed_added_to_typed_limits_keeps_them(self):
        sp.set_local_printer_override(
            "acme_two", {"max_hotend_temp": 230, "max_bed_temp": 70, "max_feedrate": 6000, "build_volume": [1, 1, 1]},
        )
        sp.set_local_printer_bed("acme_two", [220, 220, 250], kind=sp.BED_FROM_MAKER_SPEC, where="https://acme")
        profile = sp.get_profile("acme_two")
        assert profile.max_hotend_temp == 230 and profile.build_volume == [220.0, 220.0, 250.0]


