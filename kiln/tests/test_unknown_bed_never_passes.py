class TestEveryFitDoorSaysTheBedIsUnknown:
    def test_the_mesh_check_says_so(self, tmp_path):
        """Main: ``error_message`` "bed-fit check skipped", nothing a person
        reads would tell them their part was never measured."""
        fit = bed_fit.validate_mesh_for_printer(_cube(tmp_path / "big.stl", 300, 300, 20), "acme_mystery_one")
        assert fit["ok"] is True and fit["error_code"] == "VOLUME_UNKNOWN"
        assert fit["bed_checked"] is False
        assert UNCHECKED in fit["error_message"]
        assert "bed_mm=[x, y, z]" in fit["error_message"]
        assert "never ask the person to know it" in fit["error_message"]

    def test_the_plate_verification_names_the_unchecked_check(self, tmp_path):
        """Main: ``verify_3mf_is_safe_to_print`` returned ok with no word that
        the bed was never checked."""
        verdict = bed_fit.verify_3mf_is_safe_to_print(_plate(tmp_path / "p.gcode.3mf", 300), "acme_mystery_one")
        assert verdict["ok"] is True
        assert verdict["unchecked"] == ["bed_fit"]
        assert any(UNCHECKED in w for w in verdict["warnings"])

    def test_the_slice_reply_carries_it_in_warnings(self):
        from kiln.plugins.slicer_tools import _attach_bed_fit

        response: dict = {}
        _attach_bed_fit(response, {"ok": True, "error_code": "VOLUME_UNKNOWN", "error_message": "Kiln does not "
                                   "know the bed size of 'x', so this part was not checked against it."})
        assert any(UNCHECKED in w for w in response["warnings"])

    def test_the_validation_pipeline_guesses_no_bed(self):
        """Main: the generic profile's 200 mm cube, labelled a generic
        fallback, judged a part for a machine nobody named."""
        from kiln.plugins._validation_pipeline_internals import _resolve_build_volume

        assert _resolve_build_volume("acme_mystery_one") is None

    def test_printability_does_not_borrow_another_printers_plate(self, monkeypatch):
        """Main: a named printer with no bed was graded against the plate
        the install's 3D stage draws -- another machine's."""
        from kiln import printability

        monkeypatch.setattr(
            "kiln.stage_plate.resolve_stage_plate", lambda *a, **k: {"x_mm": 500.0, "y_mm": 500.0, "z_mm": 500.0},
        )
        assert printability._resolve_placement_volume(None, "acme_mystery_one") is None
        recs: list[str] = []
        bbox = {"x_min": 0, "x_max": 300, "y_min": 0, "y_max": 300, "z_min": 0, "z_max": 20}
        printability._apply_placement_check(90, recs, bbox, printer_id="acme_mystery_one")
        assert any(UNCHECKED in r for r in recs)


