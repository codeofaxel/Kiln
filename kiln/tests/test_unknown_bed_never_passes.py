class TestASlicerPresetNamesItsPrinter:
    """On main "Prusa MK4S 0.4 nozzle" and "prusa_xl_5t" named no row, so the
    bed check passed a 300 mm part on an MK4S with nothing said."""

    @pytest.mark.parametrize(
        ("spelling", "row"),
        [
            ("Prusa MK4S 0.4 nozzle", "prusa_mk4"),
            ("Original Prusa MK4S HF0.4 nozzle", "prusa_mk4"),
            ("prusa_xl_5t", "prusa_xl"),
            ("Original Prusa XL 5T 0.4 nozzle", "prusa_xl"),
            ("prusa_xl_2_toolheads", "prusa_xl"),
            ("Creality K1C 0.4mm nozzle", "k1c"),
            ("Bambu Lab X1 Carbon 0.6 nozzle", "bambu_x1c"),
        ],
    )
    def test_the_preset_is_its_printers_row(self, spelling, row):
        from kiln.catalog_keys import resolve_printer_key

        keys = [k for k in bed_fit._load_printer_intelligence() if not k.startswith("_")]
        assert resolve_printer_key(spelling, keys) == row
        assert bed_fit.resolve_build_volume_printer_id(spelling) == row

    @pytest.mark.parametrize("spelling", ["bambu", "Bambu 0.4 nozzle", "prusa", "Creality"])
    def test_a_makers_name_alone_is_no_printer(self, spelling):
        """A guard, true on main too: taking a preset's suffix off must not
        leave a maker's name that then reads as one of its printers."""
        from kiln.catalog_keys import resolve_printer_key

        keys = [k for k in bed_fit._load_printer_intelligence() if not k.startswith("_")]
        assert resolve_printer_key(spelling, keys) is None
        assert bed_fit.get_build_volume(spelling) is None

    def test_a_trailing_number_without_nozzle_is_part_of_the_name(self):
        """A guard, true on main too: the Voron 2.4 is not a Voron 2 with a
        2.4 mm nozzle, and its 350 mm size keeps its own bed."""
        from kiln.catalog_keys import printer_key_candidates

        assert "voron_2" not in printer_key_candidates("voron_2_4_350")[:1]
        assert bed_fit.get_build_volume("voron_2_4_350") == (350.0, 350.0, 350.0)


