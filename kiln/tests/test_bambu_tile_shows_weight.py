class TestGramsFromSlicerComments:
    def test_prusaslicer_grams_are_taken_as_written(self):
        usage = bambu_3mf.filament_usage_from_gcode(_layers(2) + _PRUSA_FOOTER)
        assert usage.mm == pytest.approx((427.39,))
        assert usage.grams == pytest.approx((1.27,))
        assert usage.total_g == pytest.approx(1.27)
        assert usage.source == "slicer_grams"

    def test_orca_without_a_density_gets_grams_from_its_length(self):
        usage = bambu_3mf.filament_usage_from_gcode(_layers(4, tools=[0, 1, 0, 1]) + _ORCA_JAR_FOOTER)
        assert usage.mm == pytest.approx((11035.45, 584.76))
        assert usage.grams == pytest.approx((_grams(11035.45), _grams(584.76)), abs=0.005)
        assert usage.grams == pytest.approx((32.91, 1.74), abs=0.005)
        assert usage.total_g == pytest.approx(34.66, abs=0.005)
        assert usage.source == "slicer_length"

    def test_bambu_studio_header_totals_are_read(self):
        usage = bambu_3mf.filament_usage_from_gcode(_STUDIO_HEADER + _layers(2, tools=[0, 1]))
        assert usage.mm == pytest.approx((5127.93, 2704.70))
        assert usage.grams == pytest.approx((16.28, 8.13))
        assert usage.total_g == pytest.approx(24.41)

    def test_the_material_picks_the_density(self):
        body = _layers(2) + "; filament used [mm] = 1000\n; filament_density = 0\n; filament_type = PETG\n"
        usage = bambu_3mf.filament_usage_from_gcode(body)
        assert usage.grams == pytest.approx((_grams(1000, 1.27),), abs=0.005)

    def test_the_callers_material_outranks_the_profiles_default(self):
        body = _layers(2) + "; filament used [mm] = 1000\n; filament_type = PLA\n"
        usage = bambu_3mf.filament_usage_from_gcode(body, filament_types=["ABS"])
        assert usage.grams == pytest.approx((_grams(1000, 1.04),), abs=0.005)

    def test_the_slicers_own_density_outranks_the_table(self):
        body = _layers(2) + "; filament used [mm] = 1000\n; filament_density = 1.32\n; filament_type = PLA\n"
        usage = bambu_3mf.filament_usage_from_gcode(body)
        assert usage.grams == pytest.approx((_grams(1000, 1.32),), abs=0.005)

    def test_values_land_on_the_extruders_the_print_used(self):
        # Orca and Prusa list one value per USED extruder: a print on T0 and
        # T2 writes two numbers, and the second belongs to tray 3, not tray 2.
        body = _layers(4, tools=[0, 2, 0, 2]) + "; filament used [mm] = 100, 50\n"
        usage = bambu_3mf.filament_usage_from_gcode(body)
        assert usage.mm == pytest.approx((100.0, 0.0, 50.0))


class TestGramsFromEMoves:
    def test_relative_e_is_summed_when_no_comment_exists(self):
        body = "M83\nG1 X1 Y1 E400\nG1 E-0.8\nG1 E0.8\nG1 X2 Y2 E600 ; comment E999\n"
        usage = bambu_3mf.filament_usage_from_gcode(body)
        assert usage.mm == pytest.approx((1000.0,))
        assert usage.grams == pytest.approx((_grams(1000),), abs=0.005)
        assert usage.grams[0] == pytest.approx(2.98, abs=0.005)
        assert usage.source == "e_moves"

    def test_absolute_e_and_g92_resets_are_honoured(self):
        body = "M82\nG1 X1 E5\nG1 X2 E12\nG92 E0\nG1 X3 E3\n"
        usage = bambu_3mf.filament_usage_from_gcode(body)
        assert usage.mm == pytest.approx((15.0,))

    def test_multi_filament_split_follows_the_tool_changes(self):
        body = "M83\nT0\nG1 X1 E100\nT1\nG1 X2 E50\nT0\nG1 X3 E25\nT1000\nG1 E7\nT255\n"
        usage = bambu_3mf.filament_usage_from_gcode(body)
        # Bambu's T255 / T1000 are pseudo-tools of the start sequence, not trays.
        assert usage.mm == pytest.approx((125.0, 50.0))
        assert usage.grams == pytest.approx((_grams(125), _grams(50)), abs=0.005)

    def test_no_extrusion_is_zero_and_says_so(self):
        usage = bambu_3mf.filament_usage_from_gcode("G28\nG1 X10 Y10\nG1 Z5\n")
        assert usage.total_g == 0.0
        assert usage.total_mm == 0.0
        assert usage.source == "none"


