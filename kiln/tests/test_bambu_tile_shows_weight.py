class TestBuilderWritesTheWeight:
    def test_single_filament(self, tmp_path):
        out = str(tmp_path / "one.gcode.3mf")
        bambu_3mf.build_bambu_3mf(_layers(3) + _PRUSA_FOOTER, out)
        xml = _slice_info(out)
        assert _weight(xml) == "1.27"
        assert _filaments(xml) == [("0.43", "1.27")]

    def test_multi_filament_split(self, tmp_path):
        body = (
            _layers(4, tools=[0, 1, 2, 0])
            + "; filament_colour = #F2F2F2;#D32F2F;#1A1A1A\n"
            + "; filament_type = PLA;PETG;PLA\n"
            + "; filament used [mm] = 100.0, 50.0, 25.0\n"
        )
        out = str(tmp_path / "three.gcode.3mf")
        bambu_3mf.build_bambu_3mf(body, out)
        xml = _slice_info(out)
        expected = [_grams(100), _grams(50, 1.27), _grams(25)]
        assert _filaments(xml) == [
            ("0.10", f"{expected[0]:.2f}"),
            ("0.05", f"{expected[1]:.2f}"),
            ("0.03", f"{expected[2]:.2f}"),
        ]
        assert _weight(xml) == f"{sum(expected):.2f}"

    def test_the_declared_material_is_the_density_source(self, tmp_path):
        out = str(tmp_path / "petg.gcode.3mf")
        body = _layers(3) + "; filament used [mm] = 1000\n; filament_density = 0\n"
        bambu_3mf.build_bambu_3mf(body, out, settings=bambu_3mf.BambuPrintSettings(filament_type="PETG"))
        assert _weight(_slice_info(out)) == f"{_grams(1000, 1.27):.2f}"

    def test_no_extrusion_writes_zero_honestly(self, tmp_path):
        out = str(tmp_path / "empty.gcode.3mf")
        bambu_3mf.build_bambu_3mf(_layers(3, e=None), out)
        xml = _slice_info(out)
        assert _weight(xml) == "0.00"
        assert _filaments(xml) == [("0.00", "0.00")]


