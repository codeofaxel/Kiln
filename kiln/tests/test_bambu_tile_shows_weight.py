_FILAMENT = (
    '    <filament id="{id}" tray_info_idx="GFL99" type="PLA" color="{color}" used_m="{m}" used_g="{g}" '
    'used_for_object="true" used_for_support="false" group_id="0" nozzle_diameter="0.40" volume_type="Standard"/>\n'
)


def _slice_info_xml(weight: str, filaments: list[tuple[str, str, str]]) -> str:
    rows = "".join(_FILAMENT.format(id=i + 1, color=c, m=m, g=g) for i, (c, m, g) in enumerate(filaments))
    return (
        '<?xml version="1.0" encoding="UTF-8"?>\n<config>\n  <plate>\n'
        '    <metadata key="index" value="1"/>\n    <metadata key="prediction" value="6382"/>\n'
        f'    <metadata key="weight" value="{weight}"/>\n'
        '    <metadata key="filament_maps" value="0;1"/>\n'
        + rows
        + "  </plate>\n</config>\n"
    )


def _orca_jar_archive(tmp_path: Path, *, weight: str = "0.00", grams=("0.00", "0.00")) -> str:
    """The painted jar as Orca wrapped it: plate G-code with indented tool
    changes inside the AMS blocks, its own slice_info with 0.00 everywhere."""
    gcode = (
        "; generated by OrcaSlicer 2.3.2\nM83\nG28\nM620 S0A\n    T0\nM621 S0A\n"
        "G1 X10 Y10 Z0.2 E1\nM620 S1A\n    T1\nM621 S1A\nG1 X12 Y10 E1\n" + _ORCA_JAR_FOOTER
    )
    p = tmp_path / "jar.gcode.3mf"
    with zipfile.ZipFile(p, "w", zipfile.ZIP_DEFLATED) as zf:
        zf.writestr("3D/3dmodel.model", _MODEL)
        zf.writestr("Metadata/plate_1.gcode", gcode)
        zf.writestr(
            "Metadata/slice_info.config",
            _slice_info_xml(weight, [("#FFFFFF", "0.00", grams[0]), ("#F72323", "0.00", grams[1])]),
        )
        zf.writestr("Metadata/plate_1.json", json.dumps({"filament_colors": ["#FFFFFF", "#F72323"], "version": 2}))
    return str(p)


def _members(path: str) -> dict[str, bytes]:
    with zipfile.ZipFile(path) as zf:
        return {n: zf.read(n) for n in zf.namelist()}


class TestCompletionFillsTheWeight:
    def test_orcas_zero_becomes_the_jars_real_weight(self, tmp_path):
        path = _orca_jar_archive(tmp_path)
        before = _members(path)
        bambu_3mf.complete_bambu_archive(path)
        after = _members(path)
        assert after["Metadata/plate_1.gcode"] == before["Metadata/plate_1.gcode"]
        assert after["3D/3dmodel.model"] == before["3D/3dmodel.model"]
        xml = after["Metadata/slice_info.config"].decode("utf-8")
        assert _weight(xml) == "34.66"
        assert _filaments(xml) == [("11.04", "32.91"), ("0.58", "1.74")]
        # Everything else in the file is exactly what it was.
        assert 'key="prediction" value="6382"' in xml
        assert 'key="filament_maps" value="0;1"' in xml

    def test_a_weight_the_slicer_knew_is_left_alone(self, tmp_path):
        path = _orca_jar_archive(tmp_path, weight="24.41", grams=("16.28", "8.13"))
        bambu_3mf.complete_bambu_archive(path)
        xml = _members(path)["Metadata/slice_info.config"].decode("utf-8")
        assert _weight(xml) == "24.41"
        assert [g for _, g in _filaments(xml)] == ["16.28", "8.13"]

    def test_completion_is_idempotent_on_the_weight(self, tmp_path):
        path = _orca_jar_archive(tmp_path)
        bambu_3mf.complete_bambu_archive(path)
        first = _members(path)["Metadata/slice_info.config"]
        bambu_3mf.complete_bambu_archive(path)
        assert _members(path)["Metadata/slice_info.config"] == first


class TestRepackageDoorFillsTheWeight:
    """The third door: a plate object's gcode wrapped with the source
    archive's own slice_info, which used to carry the slicer's 0.00 verbatim."""

    def _repackage(self, tmp_path: Path) -> str:
        source = _orca_jar_archive(tmp_path)
        gcode = tmp_path / "object.gcode"
        gcode.write_text("M83\nG28\nG1 X10 Y10 Z0.2 E1\n" + _ORCA_JAR_FOOTER, encoding="utf-8")
        out = str(tmp_path / "object.gcode.3mf")
        bambu_3mf.repackage_gcode_as_bambu_3mf(str(gcode), out, source_3mf_path=source)
        return out

    def test_the_copied_zero_becomes_the_gcodes_weight(self, tmp_path):
        xml = _slice_info(self._repackage(tmp_path))
        assert _weight(xml) == "34.66"
        assert _filaments(xml) == [("11.04", "32.91"), ("0.58", "1.74")]

    def test_without_the_fill_the_zero_would_have_been_copied(self, tmp_path, monkeypatch):
        # The pin: with the fill switched off the door copies 0.00 through,
        # which is exactly what it did before.
        monkeypatch.setattr(bambu_3mf, "_slice_info_knows_its_weight", lambda _xml: True)
        assert _weight(_slice_info(self._repackage(tmp_path))) == "0.00"


class TestEMovesCountLikeTheSlicer:
    """The printer-screen fallback counts the way the slicer's own total is
    counted, so a file with no slicer totals weighs what it would have."""

    def test_a_bambu_studio_start_sequence_keeps_the_filament_through_t1000(self):
        # Bambu Studio's nozzle-load line runs under T1000; everything
        # printed after it used to be dropped as belonging to no tray.
        body = (
            "M83\nT0\nG1 X1 Y1 E100\n"
            "T1000\nG1 X18 Y1 Z0.8 F18000\nG0 E2 F300\nG0 X240 E15 F4800\n"
            "G1 X10 Y10 E200\nG1 X20 Y20 E300\n"
        )
        usage = bambu_3mf.filament_usage_from_gcode(body)
        assert usage.source == "e_moves"
        assert usage.mm == (pytest.approx(615.0),)

    def test_a_wipe_retract_and_its_prime_are_not_plastic(self):
        # OrcaSlicer retracts part-way while wiping (E-.32 on a travel),
        # finishes the retract, then primes E.8 before the next wall.
        # Signed sums netted +0.48 of that as filament.
        body = "M83\nG1 X10 Y10 E5\nG1 X11 Y10 E-.32\nG1 E-.48 F1800\nG1 E.8 F1800\nG1 X20 Y10 E5\n"
        usage = bambu_3mf.filament_usage_from_gcode(body)
        assert usage.mm == (pytest.approx(10.0),)

    def test_a_filament_change_unload_is_not_subtracted(self):
        body = "M83\nT0\nG1 X1 Y1 E100\nG1 E-15 F6000\nG1 E-55.3 F5400\nT1\nG1 E30\nG1 X2 Y2 E40\n"
        usage = bambu_3mf.filament_usage_from_gcode(body)
        assert usage.mm == (pytest.approx(100.0), pytest.approx(40.0))
