"""The A1's tile shows the print's filament weight, from every Kiln door.

The printer's screen reads ``Metadata/slice_info.config``: the plate's
``<metadata key="weight">`` (grams, two decimals) and each
``<filament ... used_m="…" used_g="…">`` (metres and grams, two decimals).
Reference: the Bambu Studio 02.05.00.66 plate on Adam's own A1 (the
chopstick holder) carries ``weight="24.41"`` with filaments
``used_m="5.13" used_g="16.28"`` and ``used_m="2.70" used_g="8.13"`` —
the weight is the sum of the per-filament grams, and ``used_m`` is the
G-code header's ``total filament length [mm] : 5127.93,2704.70`` in
metres.  Kiln wrote ``0.00`` in all three places, so every Kiln print
showed no weight.

What each slicer writes, measured 2026-09-18:

* PrusaSlicer 2.9.4 with a filament density: ``; filament used [mm] =
  427.39``, ``; filament used [cm3] = 1.03``, ``; filament used [g] =
  1.27``, ``; total filament used [g] = 1.27``.  Without one (Kiln's
  printer-only profiles) the ``[g]`` line is omitted and the total reads
  ``0.00``.
* OrcaSlicer 2.3.2 (the painted jar): ``; filament used [mm] = 11035.45,
  584.76``, ``; filament used [cm3] = 26.54, 1.41``, ``; total filament
  used [g] = 0.00``, ``; filament_density = 0`` — one value per USED
  extruder, comma separated.
* Bambu Studio: header lines only — ``; total filament length [mm] :
  5127.93,2704.70`` and ``; total filament weight [g] : 16.28,8.13``.

So grams come from the slicer when it knew them, else from its length
times the filament cross-section times the material's density, and when
no slicer comment exists at all from the E moves themselves.
"""

from __future__ import annotations

import json
import math
import re
import zipfile
from pathlib import Path

import pytest

from kiln.printers import bambu_3mf

_AREA_MM2 = math.pi * (1.75 / 2) ** 2  # 2.405 mm^2 of 1.75 mm filament
_PLA = 1.24


@pytest.fixture(autouse=True)
def _clear_singleton_cache():
    bambu_3mf._reset_cache()
    yield
    bambu_3mf._reset_cache()


def _grams(mm: float, density: float = _PLA) -> float:
    return mm * _AREA_MM2 * density / 1000.0


def _layers(n: int = 2, tools: list[int] | None = None, e: float | None = 0.5) -> str:
    """A PrusaSlicer-shaped body: relative E, one layer change per layer."""
    out = ["; generated by PrusaSlicer 2.9.4", "M83 ; use relative distances for extrusion", "G28", "M104 S200"]
    for i in range(n):
        out += [
            ";BEFORE_LAYER_CHANGE",
            f";Z:{0.2 * (i + 1):.1f}",
            ";LAYER_CHANGE",
            f"G1 Z{0.2 * (i + 1):.1f} F600",
        ]
        if tools:
            out.append(f"T{tools[i % len(tools)]}")
        move = f"G1 X{10 * (i + 1)} Y10"
        if e is not None:
            move += f" E{e}"
        out.append(move)
    return "\n".join(out) + "\n"


_PRUSA_FOOTER = (
    "; filament used [mm] = 427.39\n"
    "; filament used [cm3] = 1.03\n"
    "; filament used [g] = 1.27\n"
    "; total filament used [g] = 1.27\n"
    "; total filament cost = 0.00\n"
    "; filament_density = 1.24\n"
    "; filament_diameter = 1.75\n"
)

# The painted jar, as OrcaSlicer 2.3.2 wrote it through Kiln's density-less profile.
_ORCA_JAR_FOOTER = (
    "; filament used [mm] = 11035.45, 584.76\n"
    "; filament used [cm3] = 26.54, 1.41\n"
    "; total filament used [g] = 0.00\n"
    "; total filament cost = 0.00\n"
    "; total filament change = 8\n"
    "; filament_colour = #FFFFFF;#F72323\n"
    "; filament_density = 0\n"
    "; filament_diameter = 1.75,1.75\n"
    "; filament_type = PLA;PLA\n"
)

_STUDIO_HEADER = (
    "; HEADER_BLOCK_START\n"
    "; BambuStudio 02.05.00.66\n"
    "; total filament length [mm] : 5127.93,2704.70\n"
    "; total filament volume [cm^3] : 12334.13,6505.56\n"
    "; total filament weight [g] : 16.28,8.13\n"
    "; filament_density: 1.32,1.25,1.25,1.24,1.24\n"
    "; filament_diameter: 1.75,1.75,1.75,1.75,1.75\n"
    "; HEADER_BLOCK_END\n"
)


def _slice_info(path: str) -> str:
    with zipfile.ZipFile(path) as zf:
        return zf.read("Metadata/slice_info.config").decode("utf-8")


def _weight(xml: str) -> str:
    return re.search(r'<metadata key="weight" value="([^"]*)"', xml).group(1)


def _filaments(xml: str) -> list[tuple[str, str]]:
    return re.findall(r'<filament id="\d+"[^>]*used_m="([^"]*)" used_g="([^"]*)"', xml)


