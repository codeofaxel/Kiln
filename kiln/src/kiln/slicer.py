"""Slicer integration for Kiln — headless slicing via PrusaSlicer / OrcaSlicer CLI.

Wraps the command-line interface of PrusaSlicer and OrcaSlicer so that STL
(or 3MF/STEP) files can be sliced to G-code without opening the GUI.  The
slicer binary is auto-detected on PATH or can be specified explicitly.

Supported slicers:
    * PrusaSlicer (``prusa-slicer`` / ``PrusaSlicer``)
    * OrcaSlicer  (``orca-slicer`` / ``OrcaSlicer``)

Both expose the same ``--export-gcode`` flag for headless slicing.

Example::

    from kiln.slicer import slice_file, find_slicer

    slicer = find_slicer()                # auto-detect
    result = slice_file("model.stl")      # -> SliceResult
    print(result.output_path)             # <tempdir>/kiln_sliced/model.gcode
"""

from __future__ import annotations

import contextlib
import logging
import os
import re
import shutil
import subprocess
import sys
import tempfile
from dataclasses import dataclass
from pathlib import Path
from typing import Any

logger = logging.getLogger(__name__)

# ---------------------------------------------------------------------------
# Constants
# ---------------------------------------------------------------------------

# Kiln attribution header for generated gcode files.
_KILN_GCODE_HEADER = (
    "; Generated by Kiln — 3D printing infrastructure for AI agents\n"
    "; https://kiln3d.com\n"
    ";\n"
)

# Names to probe on PATH, in preference order.
_SLICER_NAMES: list[str] = [
    "prusa-slicer",
    "PrusaSlicer",
    "prusaslicer",
    "orca-slicer",
    "OrcaSlicer",
    "orcaslicer",
]

# Common install locations on macOS (app bundles).
# Only populated on macOS to avoid useless stat() calls on Linux/WSL.
_MACOS_PATHS: list[str] = (
    [
        "/Applications/PrusaSlicer.app/Contents/MacOS/PrusaSlicer",
        "/Applications/Original Prusa Drivers/PrusaSlicer.app/Contents/MacOS/PrusaSlicer",
        "/Applications/OrcaSlicer.app/Contents/MacOS/OrcaSlicer",
    ]
    if sys.platform == "darwin"
    else []
)

# One place to say how to get a slicer Kiln can actually drive, so the advice
# cannot drift from the capability again.  It said "PrusaSlicer or OrcaSlicer"
# while every command Kiln builds is PrusaSlicer-only — which sent the one
# group most likely to own OrcaSlicer, Bambu owners, straight into a wall.
_INSTALL_PRUSASLICER = (
    "Kiln slices with PrusaSlicer:\n"
    "  Linux/WSL: apt install prusa-slicer  (or download from prusaslicer.org)\n"
    "  macOS: brew install --cask prusaslicer\n"
    "Or set KILN_SLICER_PATH to a PrusaSlicer binary."
)

# CLI dialects.  OrcaSlicer and BambuStudio are forks of the same non-Slic3r
# command line: verified 2026-08-11 that OrcaSlicer 2.3.2 and BambuStudio
# 02.06.00.51 both reject --export-gcode / --output / --load and expose
# --slice / --outputdir / --load-settings instead.  They also load JSON
# presets rather than the PrusaSlicer .ini Kiln generates, so driving them is
# a new backend and not a flag rename.
_CLI_PRUSA = "prusa"
_CLI_BAMBU = "bambu"

# Extensions the slicer can accept as input.
_INPUT_EXTENSIONS = {".stl", ".3mf", ".step", ".stp", ".obj", ".amf"}

# Default output directory.
_DEFAULT_OUTPUT_DIR = os.path.join(tempfile.gettempdir(), "kiln_sliced")


# ---------------------------------------------------------------------------
# Exceptions
# ---------------------------------------------------------------------------


class SlicerError(Exception):
    """Raised when slicing fails."""


class SlicerNotFoundError(SlicerError):
    """Raised when no slicer binary is found on the system."""


# ---------------------------------------------------------------------------
# Dataclasses
# ---------------------------------------------------------------------------


@dataclass
class SlicerInfo:
    """Information about a discovered slicer binary."""

    path: str
    name: str
    version: str | None = None

    def to_dict(self) -> dict:
        return {
            "path": self.path,
            "name": self.name,
            "version": self.version,
        }


@dataclass
class SliceResult:
    """Outcome of a slicing operation."""

    success: bool
    output_path: str | None = None
    slicer: str | None = None
    message: str = ""
    stdout: str = ""
    stderr: str = ""

    def to_dict(self) -> dict:
        d = {
            "success": self.success,
            "output_path": self.output_path,
            "slicer": self.slicer,
            "message": self.message,
        }
        if self.stderr:
            d["stderr"] = self.stderr[:500]
        return d


