def slice_multicolor_copies(
    input_path: str,
    count: int,
    *,
    spacing_mm: float = 10.0,
    bed_width_mm: float = 256.0,
    bed_depth_mm: float = 256.0,
    printer_id: str | None = None,
    slicer_path: str | None = None,
    profile: str | None = None,
    extra_args: list[str] | None = None,
    output_dir: str | None = None,
    timeout: int = 300,
    material: str | None = None,
    loaded_material: str | None = None,
    loaded_determined_by: str = LOADED_OBSERVED,
    soft_nozzle_confirmed: bool = False,
) -> SliceResult:
    """Slice an STL into *count* copies, each assigned a different tool (T0, T1, ...).

    The approach: position each copy on a grid, slice each individually, then
    merge the gcode bodies with ``T`` commands between copies.  This avoids
    the need for a multi-extruder PrusaSlicer printer profile.

    The merged gcode will contain ``T0`` before copy 1's layers, ``T1`` before
    copy 2's layers, etc.  Downstream Bambu 3MF wrapping will convert these
    to M620/M621 AMS load sequences.

    :param input_path: Path to the source STL file.
    :param count: Number of copies (each gets a different tool).
    :param spacing_mm: Gap between copies in mm.
    :param bed_width_mm: Build plate width (X) in mm.
    :param bed_depth_mm: Build plate depth (Y) in mm.
    :param printer_id: Optional supported printer model id.  When provided,
        the bundled printer-intelligence build volume overrides the generic
        bed dimensions.
    :param slicer_path: Explicit slicer binary path.
    :param profile: Path to a slicer profile/config file.
    :param extra_args: Additional CLI arguments for the slicer.
    :param output_dir: Directory for output files.
    :param timeout: Slicing timeout per copy in seconds.
    :param material: The declared material, handed to every copy's slice
        (see :func:`slice_file`).
    :param loaded_material: The spool loaded on the printer, likewise.
    :param loaded_determined_by: Who decided it (``observed`` / ``user_reported``),
        likewise.
    :param soft_nozzle_confirmed: The owner's word to print anyway, handed
        to every copy's slice (see :func:`slice_file`).
    :returns: A :class:`SliceResult` with the merged gcode path.
    :raises SlicerError: If slicing any copy fails.
    :raises ValueError: If copies don't fit on the bed.
    """
    import math
    import tempfile as _tempfile

    from kiln.auto_orient import _parse_mesh, _translate_to_bed, _write_binary_stl

    if count < 2:
        raise ValueError(f"count must be >= 2, got {count}")
    if printer_id:
        from kiln.printers.bed_fit import printer_bed_volume

        build_volume = printer_bed_volume(printer_id)
        if build_volume is None:
            from kiln.printers.bed_fit import no_bed_reason

            raise ValueError(
                no_bed_reason(printer_id, instead="omit printer_id and pass bed_width_mm/bed_depth_mm explicitly")
            )
        bed_width_mm, bed_depth_mm = build_volume[0], build_volume[1]

    # Parse mesh and compute bounding box
    triangles, _vertices = _parse_mesh(input_path)
    triangles = _translate_to_bed(triangles)

    all_verts = [v for tri in triangles for v in tri]
    xs = [v[0] for v in all_verts]
    ys = [v[1] for v in all_verts]
    x_min, x_max = min(xs), max(xs)
    y_min, y_max = min(ys), max(ys)
    model_width = x_max - x_min
    model_depth = y_max - y_min

    if model_width <= 0 or model_depth <= 0:
        raise ValueError("Model has zero width or depth.")

    # Center mesh at origin
    center_x = (x_min + x_max) / 2.0
    center_y = (y_min + y_max) / 2.0
    centered = []
    for tri in triangles:
        tv = tuple((v[0] - center_x, v[1] - center_y, v[2]) for v in tri)
        centered.append(tv)

    # Grid layout
    cell_w = model_width + spacing_mm
    cell_d = model_depth + spacing_mm
    # N copies take N widths and N - 1 gaps, so the gap after the last
    # column is not charged against the bed.  Charging it refused, for one,
    # two 120 mm parts with a 10 mm gap on a 256 mm bed, which take 250 mm.
    cols = int((bed_width_mm + spacing_mm) // cell_w)
    rows = int((bed_depth_mm + spacing_mm) // cell_d)

    if cols < 1 or rows < 1:
        raise ValueError(
            f"Model ({model_width:.1f} x {model_depth:.1f} mm) is too large "
            f"for the build plate ({bed_width_mm} x {bed_depth_mm} mm)."
        )
    if count > cols * rows:
        raise ValueError(
            f"Cannot fit {count} copies on {bed_width_mm}x{bed_depth_mm} mm bed."
        )

    actual_cols = min(count, cols)
    actual_rows = math.ceil(count / actual_cols)
    grid_width = actual_cols * cell_w - spacing_mm
    grid_depth = actual_rows * cell_d - spacing_mm
    start_x = (bed_width_mm - grid_width) / 2.0 + model_width / 2.0
    start_y = (bed_depth_mm - grid_depth) / 2.0 + model_depth / 2.0

    # Supports are decided ONCE, on the part, and stated for every copy:
    # the copies are the same part moved, and each copy's slice would
    # otherwise read it again.
    profile, supports = ensure_profile_supports(
        profile, input_path, material=_supports_plastic(material, loaded_material), stated=True,
    )

    # Each copy is written where it stands, the copies are put on one plate
    # with a filament each, and the plate is sliced once.  The slicer then
    # writes one start, one end, every layer once and its own change of
    # filament between the copies.
    from kiln.multicolor_3mf import ColorPart, compose_multicolor_3mf

    work_dir = _tempfile.mkdtemp(prefix="kiln_multicolor_")
    stem = Path(input_path).stem
    try:
        copies: list[ColorPart] = []
        for placed in range(count):
            row, col = divmod(placed, actual_cols)
            offset_x = start_x + col * cell_w
            offset_y = start_y + row * cell_d
            positioned = [
                tuple((v[0] + offset_x, v[1] + offset_y, v[2]) for v in tri) for tri in centered
            ]
            copy_stl = os.path.join(work_dir, f"copy_{placed}.stl")
            _write_binary_stl(positioned, copy_stl)
            copies.append(ColorPart(copy_stl, extruder=placed + 1, name=f"copy {placed + 1}"))

        plate = os.path.join(work_dir, f"{stem}_copies.3mf")
        composed = compose_multicolor_3mf(copies, output_path=plate, printer_id=printer_id)
        if not composed.get("success"):
            raise SlicerError(
                f"Kiln couldn't put the {count} copies on one plate: "
                f"{composed.get('error') or 'the plate could not be written'}"
            )
        # The plate is scratch: the file handed over is the one recorded.
        quiet = _unrecorded.set(True)
        try:
            result = slice_file(
                plate,
                output_dir=os.path.join(work_dir, "sliced"),
                profile=profile,
                slicer_path=slicer_path,
                extra_args=list(extra_args) if extra_args else None,
                timeout=timeout,
                material=material,
                loaded_material=loaded_material,
                loaded_determined_by=loaded_determined_by,
                soft_nozzle_confirmed=soft_nozzle_confirmed,
            )
        finally:
            _unrecorded.reset(quiet)
        if not result.success or not result.output_path:
            raise SlicerError(f"Slicing the plate of {count} copies failed: {result.message}")

        # The file is read before it is handed over: a filament for every
        # copy, and one print from start to end.
        with open(result.output_path, errors="replace", encoding="utf-8") as fh:
            sliced = fh.read()
        wrong = _one_print_faults(sliced, tools=count)
        if wrong:
            raise SlicerError(
                f"Kiln sliced the {count} copies as one plate with {result.slicer or 'the slicer'}, but the file "
                f"{wrong[0]}, so it is not handed over. OrcaSlicer and Bambu Studio give each copy its own "
                "filament: slice with one of them (`--slicer`), or leave out `--ams-mapping` to print the "
                "copies in one colour."
            )

        out_dir = output_dir or kiln_output_dir(_DEFAULT_OUTPUT_NAME)
        os.makedirs(out_dir, mode=0o700, exist_ok=True)
        merged_path = os.path.join(out_dir, f"{stem}_multicolor.gcode")
        shutil.move(result.output_path, merged_path)
    finally:
        shutil.rmtree(work_dir, ignore_errors=True)

    merged_result = SliceResult(
        success=True,
        output_path=merged_path,
        slicer=result.slicer,
        message=f"Sliced {count} multi-color copies of {Path(input_path).name}",
        filament=result.filament,
        supports=supports,
    )
    # The file that prints gets its own record, and the owner's word to
    # print anyway is kept on it.
    from kiln.print_lineage import note_soft_nozzle

    _record_slice(profile, os.path.abspath(input_path), merged_path)
    if result.soft_nozzle:
        merged_result.soft_nozzle = result.soft_nozzle
        merged_result.message = f"{merged_result.message} {result.soft_nozzle.get('said') or ''}".strip()
        note_soft_nozzle(merged_path, result.soft_nozzle)
    return merged_result


_MOVES_ONLY = re.compile(r"^(?:G0*[0-3]\b|G1[01]\b|G92\b|\s*;|\s*$)")


def _without_its_ending(lines: list[str]) -> tuple[list[str], str]:
    """*lines* of one sliced file as ``(the lines up to its ending, its
    ending)``.  The ending starts at the first command after the last line
    the file lays that is not a move: the fan, the heaters, the motors, and
    the figures and settings a slicer writes after them."""
    last_laid = max(
        (i for i, line in enumerate(lines) if (m := _EXTRUDES.match(line)) and float(m.group(1)) > 0), default=None,
    )
    if last_laid is None:
        return lines, ""
    for i in range(last_laid + 1, len(lines)):
        if not _MOVES_ONLY.match(lines[i]):
            return lines[:i], "".join(lines[i:])
    return lines, ""


#: A command that ends a print or starts one: the nozzle or bed heater
#: switched off, the motors released, or the head sent home.
_ENDS_OR_STARTS = re.compile(r"^(?:M10[49]\s+S0\b|M1[49]0\s+S0\b|M84\b|M18\b|G28\b)")
_EXTRUDES = re.compile(r"^G[0-3]\s(?=[^;]*[XY]-?[\d.])[^;]*E(-?\d*\.?\d+)")
_TOOL_WORD = re.compile(r"^T(\d+)\s*(?:;.*)?$")


def _one_print_faults(gcode: str, *, tools: int = 0) -> list[str]:
    """What stops *gcode* being one print from start to end, each as the
    end of a sentence about the file; empty when nothing does.

    One print heats, homes, prints and stops, in that order and once: no
    heater is switched off, no motor released and no homing run between
    the first line it lays and the last.  With *tools*, every one of
    ``T0`` .. ``T<tools - 1>`` is called for.  And it holds layers.
    """
    lines = gcode.splitlines()
    laid = [i for i, line in enumerate(lines) if (m := _EXTRUDES.match(line)) and float(m.group(1)) > 0]
    faults: list[str] = []
    if not laid or not LAYER_CHANGE_LINE.search(gcode):
        return ["holds no layers Kiln can read"]
    for line in lines[laid[0]:laid[-1]]:
        if _ENDS_OR_STARTS.match(line):
            faults.append(
                "stops or starts over part-way through "
                f"(`{line.split(';')[0].strip()}` comes before the last of the printing)"
            )
            break
    if tools:
        called = {int(m.group(1)) for line in lines if (m := _TOOL_WORD.match(line))}
        missing = sum(1 for tool in range(tools) if tool not in called)
        if missing:
            faults.append(
                "prints every copy in one filament" if len(called) < 2
                else f"calls for {tools - missing} filaments where the {tools} copies need one each"
            )
    return faults


def merge_multipart_gcode(
    parts: list[dict[str, Any]],
    *,
    output_path: str | None = None,
) -> dict[str, Any]:
    """Merge separately-sliced gcode files into one multi-tool gcode.

    Uses a **batched** strategy that minimises tool changes: parts are
    grouped by Z-height overlap so the printer completes all layers of
    one tool in the overlap zone before switching, then continues with
    whichever tool has layers remaining.

    .. note::

        Parts **must be XY-disjoint** — their printed footprints must not
        overlap on the build plate.  The batched merge prints each tool's
        layers independently in the overlap zone; if parts share XY space,
        the later tool will collide with the earlier tool's deposited
        material.

    Each entry in *parts* must have:

    - ``gcode_path``: Path to the ``.gcode`` file.
    - ``tool_index``: Tool number (T0, T1, ...) for AMS mapping.
    - ``name``: Human-readable name (e.g. ``"body_grey"``).

    :param parts: List of part dicts.
    :param output_path: Output file path.  Defaults to a temp file.
    :returns: Dict with ``output_path``, ``total_layers``, ``phases``,
        and ``estimated_time_sec``.
    :raises ValueError: If parts list is empty or files not found.
    """
    if not parts:
        raise ValueError("No parts to merge.")

    # Parse each gcode into header + [(z, block), ...]
    parsed: list[tuple[str, list[tuple[float, str]], dict[str, Any]]] = []
    for p in parts:
        gcode_path = p["gcode_path"]
        if not os.path.isfile(gcode_path):
            raise ValueError(f"Gcode file not found: {gcode_path}")

        with open(gcode_path, encoding="utf-8", errors="replace") as f:
            lines = f.readlines()

        # Each slicer's own layer marks, read through the one pattern every
        # reader shares.  What follows a part's last printing is its ending
        # (heaters off, motors released) and is kept apart from its layers.
        lines, ending = _without_its_ending(lines)
        header_lines: list[str] = []
        layers: list[tuple[float, str]] = []
        current_block: list[str] = []
        current_z: float | None = None
        found_first = False

        for line in lines:
            at_a_layer = LAYER_CHANGE_LINE.match(line) is not None
            if at_a_layer and not found_first:
                found_first = True
            if not found_first:
                header_lines.append(line)
                continue
            if at_a_layer and current_block and current_z is not None:
                layers.append((current_z, "".join(current_block)))
                current_block = []
                current_z = None
            current_block.append(line)
            m = LAYER_Z_LINE.match(line)
            if m:
                current_z = float(m.group(1))

        if current_block and current_z is not None:
            layers.append((current_z, "".join(current_block)))

        if not layers:
            raise ValueError(
                f"Kiln couldn't find any layers in the G-code for {p['name']}, so the parts are not merged. "
                "It reads the layer marks PrusaSlicer, OrcaSlicer and Bambu Studio write; a file from another "
                "slicer, or one saved without its comments, can't be merged this way."
            )

        parsed.append(("".join(header_lines), layers, {**p, "_ending": ending}))

    # Find the Z overlap range — the max Z of the shortest part
    # layers is guaranteed non-empty per the zero-layer check above.
    z_maxes = [max(z for z, _ in layers) for _, layers, _ in parsed]
    overlap_ceiling = min(z_maxes)

    # Use the first part's header as the merged header
    merged_header = parsed[0][0]

    # Build tool names for the merge comment
    tool_names = ", ".join(
        f"T{p['tool_index']}={p['name']}" for p in parts
    )
    total_layers = max(len(layers) for _, layers, _ in parsed)

    # Build merged output using batched strategy:
    # Phase 1: For each part (in tool_index order), emit its overlap layers
    # Phase 2: For each part with layers above the overlap, emit those
    sorted_parts = sorted(enumerate(parsed), key=lambda x: x[1][2]["tool_index"])
    phases: list[dict[str, Any]] = []
    merged_blocks: list[str] = []
    last_printed: dict[str, Any] | None = None

    merged_blocks.append(merged_header)
    merged_blocks.append(
        f"; Kiln multi-color merge: {len(parts)} parts, "
        f"{total_layers} layers, tools: {tool_names}\n"
    )

    for _idx, (_header, layers, part_info) in sorted_parts:
        tool = part_info["tool_index"]
        name = part_info["name"]
        overlap = [(z, blk) for z, blk in layers if z <= overlap_ceiling]
        above = [(z, blk) for z, blk in layers if z > overlap_ceiling]

        if overlap:
            last_printed = part_info
            merged_blocks.append(f"; --- Tool change: T{tool} ({name}) ---\n")
            merged_blocks.append(f"T{tool}\n")
            merged_blocks.append("G92 E0\n")
            for _z, blk in overlap:
                merged_blocks.append(blk)
            phases.append({
                "tool": tool,
                "name": name,
                "zone": "overlap",
                "layers": len(overlap),
                "z_range": f"{overlap[0][0]}-{overlap[-1][0]}mm",
            })

    for _idx, (_header, layers, part_info) in sorted_parts:
        tool = part_info["tool_index"]
        name = part_info["name"]
        above = [(z, blk) for z, blk in layers if z > overlap_ceiling]

        if above:
            last_printed = part_info
            merged_blocks.append(f"; --- Tool change: T{tool} ({name}) ---\n")
            merged_blocks.append(f"T{tool}\n")
            merged_blocks.append("G92 E0\n")
            for _z, blk in above:
                merged_blocks.append(blk)
            phases.append({
                "tool": tool,
                "name": name,
                "zone": "upper",
                "layers": len(above),
                "z_range": f"{above[0][0]}-{above[-1][0]}mm",
            })

    # One ending, the last part's own, after every layer of every part.
    if last_printed is not None:
        merged_blocks.append(last_printed["_ending"])
    merged_body = "".join(merged_blocks)

    # Read before it is written: one print from start to end.
    wrong = _one_print_faults(merged_body)
    if wrong:
        raise ValueError(
            f"Kiln merged the parts, but the merged file {wrong[0]}, so it is not handed over. "
            "Slice the parts together as one multi-colour plate instead."
        )

    # Each part's own figures, read from the top and the end of its file,
    # where every slicer writes them: the merged print's time is their sum,
    # and each tool's filament, and the type it was sliced for, are its parts'.
    from kiln.gcode import (
        format_duration,
        slicer_filament_totals,
        slicer_filament_types,
        slicer_print_time,
    )
    from kiln.gcode_metadata import read_head_and_tail

    total_time = 0
    tool_mm: dict[int, float] = {}
    tool_g: dict[int, float] = {}
    tool_type: dict[int, str] = {}
    every_part_states_mm = every_part_states_g = True
    for _header, _layers, part_info in parsed:
        gcode_path = part_info.get("gcode_path", "")
        if not (gcode_path and os.path.isfile(gcode_path)):
            every_part_states_mm = every_part_states_g = False
            continue
        part_text = "\n".join(read_head_and_tail(gcode_path))
        printed = slicer_print_time(part_text)
        if printed is not None:
            total_time += printed.seconds
        totals = slicer_filament_totals(part_text)
        tool = int(part_info["tool_index"])
        part_types = slicer_filament_types(part_text)
        if part_types and part_types[0]:
            tool_type.setdefault(tool, part_types[0])
        if totals.mm:
            tool_mm[tool] = tool_mm.get(tool, 0.0) + totals.total_mm
        else:
            every_part_states_mm = False
        if totals.grams and sum(totals.grams) > 0:
            tool_g[tool] = tool_g.get(tool, 0.0) + sum(totals.grams)
        else:
            every_part_states_g = False

    # The merged file states its own totals at its very top, in the slicers'
    # own spellings.  Each part's footer still rides in the body behind its
    # last layer, so without these every reader took the first part's
    # figures for the whole print's.
    merged_totals = []
    if total_time > 0:
        merged_totals.append(f"; estimated printing time (normal mode) = {format_duration(total_time)}")
    merged_totals.append(f"; total layer number: {total_layers}")
    if every_part_states_mm and tool_mm:
        merged_totals.append("; filament used [mm] = " + ", ".join(f"{tool_mm[t]:.2f}" for t in sorted(tool_mm)))
        if every_part_states_g and tool_g:
            merged_totals.append("; filament used [g] = " + ", ".join(f"{tool_g[t]:.2f}" for t in sorted(tool_g)))
    if tool_type:
        # One entry per tool slot, a slot no part names left blank, so
        # entry i is T<i>'s.
        slots = range(max(tool_type) + 1)
        merged_totals.append("; filament_type = " + ";".join(tool_type.get(t, "") for t in slots))

    if not output_path:
        output_path = os.path.join(
            tempfile.mkdtemp(prefix="kiln_merge_"),
            "merged_multicolor.gcode",
        )

    with open(output_path, "w", encoding="utf-8") as f:
        f.write(_KILN_GCODE_HEADER + "".join(f"{line}\n" for line in merged_totals) + merged_body)

    return {
        "output_path": output_path,
        "total_layers": total_layers,
        "phases": phases,
        "estimated_time_sec": total_time,
        "parts_merged": len(parts),
    }
