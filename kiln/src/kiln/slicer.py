def _gcode_output_is_complete(out_file: str) -> bool:
    """Whether *out_file* looks like a finished slice, not a truncated one.

    Slicers write their summary footer (the ``filament used`` statistics
    block) only after the last toolpath is out, so a process killed
    mid-write never gets there.  Distinguishes "crashed AFTER finishing"
    from "crashed while writing" when the slicer dies on a signal:
    PrusaSlicer 2.9.4's CLI segfaults in its object-conflict bookkeeping
    (Print::export_gcode → ConflictResult assignment) on some multi-object
    files — stacked parts meeting at an exactly-coincident plane, the
    shape Kiln's banded multicolor compose produces — after exporting a
    complete, correct file.
    """
    try:
        with open(out_file, "rb") as fh:
            fh.seek(0, os.SEEK_END)
            size = fh.tell()
            fh.seek(max(0, size - 65536))
            tail = fh.read()
    except OSError:
        return False
    return b"filament used" in tail


def slice_file(
    input_path: str,
    *,
    output_dir: str | None = None,
    output_name: str | None = None,
    profile: str | None = None,
    slicer_path: str | None = None,
    extra_args: list[str] | None = None,
    timeout: int = 300,
) -> SliceResult:
    """Slice a 3D model file to G-code.

    Args:
        input_path: Path to the input file (STL, 3MF, STEP, OBJ, AMF).
        output_dir: Directory for the output G-code file.  Defaults to
            the system temp directory.
        output_name: Override the output file name.  Defaults to the
            input file's stem with ``.gcode`` extension.
        profile: Path to a slicer profile/config file (.ini or .json).
        slicer_path: Explicit slicer binary path.  Auto-detected if omitted.
        extra_args: Additional CLI arguments to pass to the slicer.
        timeout: Maximum slicing time in seconds (default 300).

    Returns:
        A :class:`SliceResult` with the path to the generated G-code.

    Raises:
        SlicerError: If slicing fails.
        SlicerNotFoundError: If no slicer binary is found.
        FileNotFoundError: If the input file does not exist.
    """
    # Validate input
    input_abs = os.path.abspath(input_path)
    if not os.path.isfile(input_abs):
        raise FileNotFoundError(f"Input file not found: {os.path.basename(input_abs)}")

    ext = Path(input_abs).suffix.lower()
    if ext not in _INPUT_EXTENSIONS:
        raise SlicerError(f"Unsupported input format '{ext}'. Supported: {', '.join(sorted(_INPUT_EXTENSIONS))}")

    # Find slicer
    slicer = find_slicer(slicer_path)

    # Say what is actually wrong.  Every command below is PrusaSlicer dialect,
    # so an Orca/BambuStudio binary used to reach the subprocess and come back
    # with "Invalid option --export-gcode" and exit 254 — a message about a
    # flag, for a user who chose a slicer.  Refusing here costs nothing that
    # worked a moment ago: those flags never ran on these binaries.
    if slicer_cli_family(slicer) == _CLI_BAMBU:
        raise SlicerError(
            f"{os.path.basename(slicer.path)} uses the BambuStudio/OrcaSlicer "
            f"command line, which has no --export-gcode, --output or --load "
            f"flag and loads presets as JSON rather than the PrusaSlicer .ini "
            f"Kiln generates. Kiln cannot drive it yet.\n"
            f"{_INSTALL_PRUSASLICER}\n"
            f"Your printer profile and settings are unaffected."
        )

    # Prepare output
    out_dir = output_dir or _DEFAULT_OUTPUT_DIR
    os.makedirs(out_dir, mode=0o700, exist_ok=True)

    if output_name:
        # Strict filename sanitisation: basename, null bytes, length, reserveds
        safe_name = output_name.replace("\x00", "")
        safe_name = os.path.basename(safe_name)
        if not safe_name or safe_name != output_name.replace("\x00", "") or safe_name in {".", ".."}:
            raise ValueError(
                f"output_name must be a plain filename without path separators "
                f"or traversal sequences, got: {output_name!r}"
            )
        if len(safe_name) > 255:
            raise ValueError(f"output_name too long ({len(safe_name)} chars, max 255)")
        out_file = os.path.join(out_dir, safe_name)
    else:
        stem = Path(input_abs).stem
        out_file = os.path.join(out_dir, f"{stem}.gcode")

    # Anything at out_file after the run must have been written BY the run.
    # The path is deterministic (input stem into a shared output dir), so a
    # previous slice of the same model leaves a complete-looking file here —
    # and without this unlink the crash-salvage check below would read that
    # STALE file and certify a slicer that died before writing anything as a
    # fresh success: the previous model's toolpath, headed for start_print.
    with contextlib.suppress(OSError):
        os.unlink(out_file)

    # Build command
    cmd: list[str] = [
        slicer.path,
        "--export-gcode",
        input_abs,
        "--output",
        out_file,
    ]

    if profile:
        if not os.path.isfile(profile):
            raise SlicerError(f"Profile file not found: {os.path.basename(profile)}")
        cmd.extend(["--load", profile])

    if extra_args:
        cmd.extend(extra_args)

    logger.info("Slicing: %s", " ".join(cmd))

    # Run
    try:
        result = subprocess.run(
            cmd,
            capture_output=True,
            text=True,
            timeout=timeout,
        )
    except subprocess.TimeoutExpired:
        # Clean up partial output on timeout
        with contextlib.suppress(OSError):
            os.unlink(out_file)
        raise SlicerError(
            f"Slicing timed out after {timeout}s. The model may be too complex or the slicer is hanging."
        ) from None
    except OSError as exc:
        raise SlicerError(f"Failed to run slicer: {exc}") from exc

    crashed_after_finishing = (
        result.returncode != 0
        and result.returncode < 0  # killed by a signal, not a reported error
        and _gcode_output_is_complete(out_file)
    )
    if result.returncode != 0 and not crashed_after_finishing:
        stderr_snippet = (result.stderr or "").strip()[:500]
        raise SlicerError(f"Slicer exited with code {result.returncode}. stderr: {stderr_snippet}")

    # Verify output exists
    if not os.path.isfile(out_file):
        raise SlicerError(
            f"Slicer completed but output file was not created. "
            f"stdout: {(result.stdout or '').strip()[:200]}"
        )

    # Telemetry: one successful slicer run = one slice.  Counted here —
    # the single function every slicing path funnels through (the
    # slice_model tool, slice_and_print, reslice_with_overrides,
    # pipelines, estimates, CLI, kiln-pro batch flows) — because the
    # count used to live in the slice_model tool body alone, and every
    # OTHER path reported zero.  Detail is the profile filename stem;
    # profiles are named for printers, never for users' models.
    try:
        from kiln.daily_stats import record_event

        record_event(
            "slices",
            detail=Path(profile).stem[:64] if profile else "unknown",
        )
    except Exception:  # noqa: BLE001 — stats must never fail a slice
        logger.debug("slice telemetry recording failed", exc_info=True)

    message = f"Sliced {Path(input_abs).name} -> {Path(out_file).name}"
    if crashed_after_finishing:
        message += (
            f" (the slicer crashed on exit AFTER writing complete G-code — "
            f"signal {-result.returncode}; the output was verified complete "
            f"and kept)"
        )
    return SliceResult(
        success=True,
        output_path=out_file,
        slicer=slicer.name,
        message=message,
        stdout=(result.stdout or "").strip(),
        stderr=(result.stderr or "").strip(),
    )


def estimate_print(
    file_path: str,
    *,
    profile: str | None = None,
    slicer_path: str | None = None,
) -> dict[str, Any]:
    """Estimate print time and filament usage by slicing to a temp file.

    Slices the model and parses the G-code comments for estimated
    print time, filament length, and filament weight.

    Args:
        file_path: Path to STL/3MF/OBJ file.
        profile: Optional slicer profile path.
        slicer_path: Optional explicit slicer binary path.

    Returns:
        Dict with ``estimated_time_seconds``, ``filament_length_mm``,
        ``filament_weight_g``, ``layer_count``, and ``gcode_path``.

    Raises:
        SlicerError: If slicing fails.
    """
    result = slice_file(file_path, profile=profile, slicer_path=slicer_path)
    if not result.success or not result.output_path:
        raise SlicerError("Slicing failed — cannot estimate print.")

    return _parse_gcode_estimates(result.output_path)


def _parse_gcode_estimates(gcode_path: str) -> dict[str, Any]:
    """Parse G-code file for slicer-generated estimates.

    Reads the first 200 and last 500 lines where PrusaSlicer/OrcaSlicer
    place their estimate comments.  PrusaSlicer puts estimates ~350 lines
    from EOF (after slicer config comments), so 200 was too small.
    """
    import re as _re

    estimates: dict[str, Any] = {"gcode_path": gcode_path}
    lines: list[str] = []

    try:
        with open(gcode_path, errors="replace") as fh:
            head = []
            for i, line in enumerate(fh):
                if i < 200:
                    head.append(line)
                lines.append(line)
            # Keep last 500 lines — PrusaSlicer puts estimates ~350 from EOF
            tail = lines[-500:] if len(lines) > 500 else []
            search_lines = head + tail
    except OSError:
        return estimates

    for line in search_lines:
        line = line.strip()

        # PrusaSlicer: ; estimated printing time (normal mode) = 1h 23m 45s
        time_match = _re.search(
            r"estimated printing time.*?=\s*(?:(\d+)d\s*)?(?:(\d+)h\s*)?(?:(\d+)m\s*)?(?:(\d+)s)?",
            line,
            _re.IGNORECASE,
        )
        if time_match:
            d = int(time_match.group(1) or 0)
            h = int(time_match.group(2) or 0)
            m = int(time_match.group(3) or 0)
            s = int(time_match.group(4) or 0)
            estimates["estimated_time_seconds"] = d * 86400 + h * 3600 + m * 60 + s
            estimates["estimated_time_human"] = line.split("=", 1)[-1].strip()

        # ; filament used [mm] = 1234.56
        fil_mm = _re.search(r"filament used \[mm\]\s*=\s*([\d.]+)", line, _re.IGNORECASE)
        if fil_mm:
            estimates["filament_length_mm"] = float(fil_mm.group(1))

        # ; filament used [g] = 12.34 or total filament used [g] = 12.34
        fil_g = _re.search(r"filament used \[g\]\s*=\s*([\d.]+)", line, _re.IGNORECASE)
        if fil_g:
            estimates["filament_weight_g"] = float(fil_g.group(1))

        # ; filament used [cm3] = 12.34
        fil_cm3 = _re.search(r"filament used \[cm3\]\s*=\s*([\d.]+)", line, _re.IGNORECASE)
        if fil_cm3:
            estimates["filament_volume_cm3"] = float(fil_cm3.group(1))

        # ; total layers count = 123
        layers = _re.search(r"total layers count\s*=\s*(\d+)", line, _re.IGNORECASE)
        if layers:
            estimates["layer_count"] = int(layers.group(1))

        # ; filament cost = 1.23
        cost = _re.search(r"filament cost\s*=\s*([\d.]+)", line, _re.IGNORECASE)
        if cost:
            estimates["filament_cost"] = float(cost.group(1))

    return estimates


