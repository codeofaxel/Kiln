class SlicerError(Exception):
    """Raised when slicing fails."""


class SlicerNotFoundError(SlicerError):
    """Raised when no slicer binary is found on the system."""


class MaterialNotPrintableError(SlicerError):
    """The target printer cannot melt the material the slice was declared for.

    The print gate's own verdict, raised before the slicer runs: a file
    sliced for a temperature the hotend never reaches is a file that cannot
    print.  ``code`` is the gate's (``MATERIAL_EXCEEDS_HOTEND``), so a door
    refuses in the words and with the code a print would.
    """

    def __init__(self, message: str, *, code: str, verdict: dict[str, Any] | None = None) -> None:
        super().__init__(message)
        self.code = code
        self.verdict = verdict or {}


class ProjectPlateError(SlicerError):
    """A project of several plates was handed over with no plate named, or
    the plate named cannot be had (:mod:`kiln.project_plates`).

    ``code`` is the door's error code (``PLATE_NOT_CHOSEN``,
    ``NO_SUCH_PLATE``, ``PLATE_NOT_READ``); ``plates`` lists what the
    project holds, each ``{"plate_number", "objects"}``.
    """

    def __init__(self, message: str, *, code: str, plates: list[dict[str, Any]]) -> None:
        super().__init__(message)
        self.code = code
        self.plates = plates


#: Part of the print lands off the printable area of the bed.
REFUSED_OFF_THE_BED = "off_the_bed"
#: The print paths of two objects on the plate collide.
REFUSED_PATHS_COLLIDE = "paths_collide"
#: A filament was put on a nozzle that cannot reach a part it prints.
REFUSED_NOZZLE_REACH = "nozzle_cannot_reach"
#: The layer asked for is as tall as the line the nozzle lays, or taller.
REFUSED_LAYER_TOO_TALL = "layer_too_tall"


#: How long, in seconds, a slicer may run before it is stopped, unless a
#: caller asks for less.
SLICE_TIME_LIMIT_S = 300


class SliceTimeLimitError(SlicerError):
    """The slicer ran past the time limit and was stopped; nothing was
    sliced.  ``code`` is the door's error code."""

    code = "SLICE_TOOK_TOO_LONG"


class NozzleMapError(SlicerError):
    """A slice for more than one nozzle that cannot be run as asked: the
    filament-to-nozzle map does not fit the print or the printer, the
    nozzles it would use are fitted at different sizes, an abrasive
    filament would print through a nozzle that is not wear-resistant, or
    the slicer in hand cannot slice for more than one nozzle.  Raised before
    any slicer is launched; ``code`` is the door's error code, and
    ``parts`` the refusal laid out (:class:`kiln.slicer_profiles.RefusalParts`)
    when one answer from the person lets it through."""

    def __init__(self, message: str, *, code: str, parts: Any = None) -> None:
        super().__init__(message)
        self.code = code
        self.parts = parts


class OneNozzleInstead(NozzleMapError):
    """A slice for more than one nozzle that the printer's maker's slicer
    would make, when that slicer is missing or older than Kiln needs on this
    computer (:func:`kiln.maker_slicer._miss`).  :func:`slice_file` slices
    it for one nozzle instead; anywhere else it is the refusal its message
    says.  ``miss`` is the :class:`kiln.maker_slicer.Miss` that names the
    slicer and whether it is to be installed or updated."""

    def __init__(self, message: str, *, code: str, miss: Any) -> None:
        super().__init__(message, code=code)
        self.miss = miss


class SlicerRefusal(SlicerError):
    """The slicer finished the slice and refused the result.

    A verdict about the print as placed, never a crash: no G-code it wrote
    is kept, and the message says what was refused and the fix.  ``kind`` is
    what it refused (:data:`REFUSED_OFF_THE_BED`, :data:`REFUSED_PATHS_COLLIDE`),
    so a door that can fix the cause (dropping a skirt) answers the refusal
    itself rather than its words; ``code`` is the door's error code;
    ``objects`` the names the slicer gave the objects, when it gave any;
    ``slicer`` the binary that refused.
    """

    def __init__(
        self, message: str, *, kind: str, code: str, slicer: str, objects: tuple[str, ...] = (),
    ) -> None:
        super().__init__(message)
        self.kind = kind
        self.code = code
        self.slicer = slicer
        self.objects = objects


