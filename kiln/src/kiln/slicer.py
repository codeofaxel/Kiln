def _gcode_output_is_complete(out_file: str) -> bool:
    """Whether *out_file* looks like a finished slice, not a truncated one.

    Slicers write their summary footer (the ``filament used`` statistics
    block) only after the last toolpath is out, so a process killed
    mid-write never gets there.  Distinguishes "crashed AFTER finishing"
    from "crashed while writing" when the slicer dies on a signal:
    PrusaSlicer 2.9.4's CLI segfaults in its object-conflict bookkeeping
    (Print::export_gcode → ConflictResult assignment) on some multi-object
    files — stacked parts meeting at an exactly-coincident plane, the
    shape Kiln's banded multicolor compose produces — after exporting a
    complete, correct file.
    """
    try:
        with open(out_file, "rb") as fh:
            fh.seek(0, os.SEEK_END)
            size = fh.tell()
            fh.seek(max(0, size - 65536))
            tail = fh.read()
    except OSError:
        return False
    return b"filament used" in tail


def _drawn_mesh_for(input_abs: str) -> str:
    """The mesh a slice of *input_abs* is drawn as: the file itself, or for a
    STEP file, Kiln's mesh of it.

    The slicer reads STEP itself, so slicing one never made a mesh, and
    everything that shows a slice draws triangles: the 3D stage, the print
    gate's look at the file before it prints, the Monitor's retained copy.
    Each was handed the STEP and could draw nothing, so the panel after a
    STEP slice opened empty.  The mesh comes from the one conversion every
    mesh tool shares, so it is the mesh an import of the same file shows,
    and a repeat is a cache hit.  It is made before the slice, so the
    ledger's freshness check reads the G-code as the newer file.

    The slicer is still handed the STEP: this changes what is drawn, never
    what prints.  A STEP this machine cannot convert is sliced as it always
    was and drawn as it always was -- not at all.
    """
    try:
        from kiln.step_import import ensure_mesh_path, is_step_file

        if not is_step_file(input_abs):
            return input_abs
        mesh, _note = ensure_mesh_path(input_abs)
        return os.path.abspath(mesh)
    except Exception:  # noqa: BLE001 — a picture must never cost a slice
        logger.debug("no mesh to draw this STEP slice as", exc_info=True)
        return input_abs


#: Set while a slice is made only to be read and thrown away: it is not
#: counted and leaves no record.
_unrecorded: contextvars.ContextVar[bool] = contextvars.ContextVar("kiln_slice_unrecorded", default=False)


def _record_slice(
    profile: str | None,
    input_abs: str | None = None,
    out_file: str | None = None,
    *,
    drawn_as: str | None = None,
) -> None:
    """Count one successful slice, and note the pair for the monitor twin.

    Recorded at the two runners rather than in a tool body: a count kept in
    the ``slice_model`` tool alone leaves every other path — the pipelines,
    estimates, CLI, kiln-pro batch flows — reporting zero.  Detail is
    the profile filename stem; profiles are named for printers, never for
    users' models.

    The twin note rides the same chokepoint for the same reason: the web
    Monitor's layer viewer needs the sliced toolpath of whatever ends up
    printing, and only the slice runner reliably knows the (mesh, gcode)
    pair — a per-tool note would cover one door and miss the pipelines.
    The mesh noted is the one the slice is drawn as (*drawn_as*, see
    :func:`_drawn_mesh_for`), with the file the slicer read beside it when
    the two differ.
    """
    if _unrecorded.get():
        return
    try:
        from kiln.daily_stats import record_event

        record_event("slices", detail=Path(profile).stem[:64] if profile else "unknown")
    except Exception:  # noqa: BLE001 — stats must never fail a slice
        logger.debug("slice telemetry recording failed", exc_info=True)
    if input_abs and out_file:
        try:
            from kiln.monitor_twin import note_sliced

            drawn = drawn_as or input_abs
            note_sliced(drawn, out_file, source=input_abs if drawn != input_abs else None)
        except Exception:  # noqa: BLE001 — the twin ledger must never fail a slice
            logger.debug("monitor-twin slice note failed", exc_info=True)
        # The sliced file remembers the part it is a print of, from here:
        # the one tail both runners share (kiln.print_lineage).
        try:
            from kiln.print_lineage import record_slice

            drawn = drawn_as or input_abs
            record_slice(drawn, out_file, profile=profile, source_path=input_abs if drawn != input_abs else None)
        except Exception:  # noqa: BLE001 — a record must never fail a slice
            logger.debug("slice lineage note failed", exc_info=True)


# Return codes the Orca dialect's crash salvage reads as a death by signal.
_ORCA_SIGSEGV_RETURNCODES = frozenset({-11, 139})

# The other way the Orca dialect exits non-zero: it finishes the slice,
# finds the result unprintable and exits with a status of its own.  Complete
# G-code may already be on disk, and it is a refusal, not a crash to look
# past.  The slicer's own words are read first, then the statuses.
_ORCA_REFUSAL_WORDS = (
    (REFUSED_OFF_THE_BED, re.compile(r"found gcode (?:in )?unprintable|g-code outside of the printable area", re.IGNORECASE)),
    (REFUSED_PATHS_COLLIDE, re.compile(r"path conflicts? found", re.IGNORECASE)),
    (REFUSED_NOZZLE_REACH, re.compile(r"cannot be mapped to correct extruders", re.IGNORECASE)),
    (REFUSED_LAYER_TOO_TALL, re.compile(
        r"layer height (?:cannot exceed|can't be greater than) nozzle diameter|too small line width", re.IGNORECASE,
    )),
)
#: Return codes read as a refusal, by kind.
_ORCA_REFUSAL_STATUSES = {
    152: REFUSED_OFF_THE_BED, 154: REFUSED_OFF_THE_BED, 155: REFUSED_PATHS_COLLIDE, 190: REFUSED_NOZZLE_REACH,
}
#: The two objects the slicer names in a path conflict.
_PATH_CONFLICT_OBJECTS = re.compile(r"path conflicts? found between (.+?) and (.+?)\s*$", re.IGNORECASE | re.MULTILINE)


def _orca_said(result: subprocess.CompletedProcess, work_dir: str) -> str:
    """Everything an Orca-dialect run said about why it stopped: the reason in
    its ``result.json`` (BambuStudio writes its refusal there and only a log
    line on stdout), then stdout, then stderr."""
    reason = ""
    try:
        status = json.loads((Path(work_dir) / "result.json").read_text(encoding="utf-8", errors="replace"))
        reason = str(status.get("error_string") or "").strip()
    except (OSError, ValueError, AttributeError):
        pass
    parts = (reason, (result.stdout or "").strip(), (result.stderr or "").strip())
    return "\n".join(part for part in parts if part)


def _orca_refusal(slicer_name: str, returncode: int, said: str) -> SlicerRefusal | None:
    """The refusal an Orca-dialect exit is, in the person's terms, or ``None``.

    Only an exit the slicer chose (a positive status) can be one: a death by
    signal is a crash, whatever was logged before it.
    """
    if returncode <= 0:
        return None
    kind = next((k for k, words in _ORCA_REFUSAL_WORDS if words.search(said)), None)
    kind = kind or _ORCA_REFUSAL_STATUSES.get(returncode)
    if kind == REFUSED_OFF_THE_BED:
        return SlicerRefusal(
            f"{slicer_name} refused to slice: as placed, part of the print would land off the "
            f"printable area of the bed (the skirt or brim around a part at the bed edge, or the "
            f"prime tower). Move the part in from the bed edge, or re-place it, and slice again.",
            kind=kind, code="PRINTS_PAST_BED", slicer=slicer_name,
        )
    if kind == REFUSED_PATHS_COLLIDE:
        named = _PATH_CONFLICT_OBJECTS.search(said)
        objects = tuple(n.strip() for n in named.groups()) if named else ()
        which = f', "{objects[0]}" and "{objects[1]}",' if objects else ""
        return SlicerRefusal(
            f"{slicer_name} refused to slice: as placed, the print paths of two objects on the "
            f"plate{which} would collide. Move them apart, or join them into one object, and "
            f"slice again.",
            kind=kind, code="OBJECTS_COLLIDE", slicer=slicer_name, objects=objects,
        )
    if kind == REFUSED_NOZZLE_REACH:
        return SlicerRefusal(
            f"{slicer_name} refused to slice: that nozzle cannot reach this part; move it toward "
            f"the middle or use the other nozzle.",
            kind=kind, code="NOZZLE_CANNOT_REACH", slicer=slicer_name,
        )
    if kind == REFUSED_LAYER_TOO_TALL:
        return _layer_too_tall(slicer_name)
    return None


def _layer_too_tall(slicer_name: str) -> SlicerRefusal:
    """The refusal of a layer as tall as the line the nozzle lays, in the
    person's terms, whichever slicer gave it."""
    return SlicerRefusal(
        f"{slicer_name} refused to slice: the layer height asked for is too tall for the nozzle. A layer "
        "has to be thinner than the line the nozzle lays. Choose a lower layer height and slice again.",
        kind=REFUSED_LAYER_TOO_TALL, code="LAYER_TOO_TALL", slicer=slicer_name,
    )


