def find_slicer(slicer_path: str | None = None) -> SlicerInfo:
    """Locate a slicer binary on the system.

    Args:
        slicer_path: Explicit path to a slicer binary.  If provided,
            this is used directly (validated for existence).  If ``None``,
            auto-detection is performed.

    Returns:
        A :class:`SlicerInfo` with the resolved path and name.

    Raises:
        SlicerNotFoundError: If no slicer binary can be found.
    """
    if slicer_path:
        if os.path.isfile(slicer_path) and os.access(slicer_path, os.X_OK):
            name = Path(slicer_path).stem.lower()
            version = _get_version(slicer_path)
            return SlicerInfo(path=slicer_path, name=name, version=version)
        raise SlicerNotFoundError(f"Slicer binary not found or not executable: {slicer_path}")

    # Check PATH
    for name in _SLICER_NAMES:
        found = shutil.which(name)
        if found:
            version = _get_version(found)
            return SlicerInfo(path=found, name=name.lower(), version=version)

    # Check macOS app bundles
    for path in _MACOS_PATHS:
        if os.path.isfile(path) and os.access(path, os.X_OK):
            name = Path(path).stem.lower()
            version = _get_version(path)
            return SlicerInfo(path=path, name=name, version=version)

    # Check env var
    env_path = os.environ.get("KILN_SLICER_PATH")
    if env_path and os.path.isfile(env_path) and os.access(env_path, os.X_OK):
        name = Path(env_path).stem.lower()
        version = _get_version(env_path)
        return SlicerInfo(path=env_path, name=name, version=version)

    raise SlicerNotFoundError(f"No slicer found. {_INSTALL_SLICER}")


def slicer_cli_family(info: SlicerInfo) -> str:
    """Which command-line dialect *info* speaks.

    ``find_slicer`` has always known which binary it resolved and then thrown
    that away: :func:`slice_file` built one Slic3r-dialect argv for everything.
    An OrcaSlicer-only user therefore got ``Invalid option --export-gcode``
    and exit 254 from a tool that had just reported finding their slicer.

    The ``--version`` banner is preferred over the file name, because a binary
    called ``orca-slicer`` that reports ``PrusaSlicer-2.9.4`` is a PrusaSlicer.
    Measured on this machine: PrusaSlicer answers
    ``"PrusaSlicer-2.9.4 based on Slic3r (with GUI support)"`` and OrcaSlicer
    answers ``"OrcaSlicer-2.3.2:"``, but BambuStudio's ``--version`` is itself
    an invalid option and its banner is a log line, so BambuStudio is
    recognised by file name alone.  Orca and Bambu are checked before Prusa
    because Orca is a Slic3r derivative and a build whose banner mentions
    Slic3r must not read as PrusaSlicer.

    Anything unrecognised is treated as PrusaSlicer — the behaviour before
    this function existed, so a binary Kiln cannot place keeps its old path
    instead of gaining a new refusal.
    """
    banner = (info.version or "").lower()
    if "orca" in banner or "bambu" in banner:
        return _CLI_BAMBU
    if "prusaslicer" in banner or "slic3r" in banner:
        return _CLI_PRUSA
    haystack = f"{info.name or ''} {os.path.basename(info.path or '')}".lower()
    if "orca" in haystack or "bambu" in haystack:
        return _CLI_BAMBU
    return _CLI_PRUSA


def supports_duplicate_flag(info: SlicerInfo) -> bool:
    """Whether *info*'s binary can lay out copies itself, via ``--duplicate``.

    The real question a multi-copy caller has, asked once.  Both callers used
    to ask it as ``"prusa" in slicer.name``, which is the FILE NAME: a
    PrusaSlicer installed under any other name fell back to duplicating the
    mesh, and a binary merely named like one would have been handed a flag the
    other command line does not have.  :func:`slicer_cli_family` reads the
    binary's own ``--version`` banner first and the name only as a fallback,
    so it answers what the program IS rather than what it is called.

    Named for the capability rather than the vendor because that is what the
    callers branch on — and because the answer stops being "is it PrusaSlicer"
    the moment a third dialect appears.
    """
    return slicer_cli_family(info) == _CLI_PRUSA


def _get_version(slicer_path: str) -> str | None:
    """Try to get the slicer version string."""
    try:
        result = subprocess.run(
            [slicer_path, "--version"],
            capture_output=True,
            text=True,
            timeout=10,
        )
        output = (result.stdout or result.stderr or "").strip()
        # PrusaSlicer outputs "PrusaSlicer-2.7.1+linux-..."
        # OrcaSlicer outputs "OrcaSlicer 2.0.0"
        if output:
            return output.split("\n")[0].rstrip("\r")[:100]
    except Exception as exc:
        logger.debug("Failed to get slicer version from %s: %s", slicer_path, exc)
    return None


