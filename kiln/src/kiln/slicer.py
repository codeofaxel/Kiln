def nozzle_bed_for_slice(
    input_path: str, profile: str | None, filament_map: Any = None, *, slots: int | None = None,
    maker_ready: bool | None = None,
) -> tuple[float, float, float, float] | None:
    """The bed a slice of the 3MF at *input_path* with *profile* is laid out
    and checked on when it is for more than one nozzle: the bed the
    profile's nozzle record states, for a plate of two or more filaments
    (*slots*, else read from the file) or one given a filament-to-nozzle
    map.  ``None`` for anything else, and while the slicer the record names
    is missing or too old here (:func:`kiln.maker_slicer.ready_for`), since
    the plate is then sliced for one nozzle; *maker_ready* answers that for
    a caller that already knows.  Never raises."""
    from kiln.slicer_profiles import nozzle_bed, nozzles_of

    record = nozzles_of(profile)
    bed = nozzle_bed(record)
    if bed is None or not str(input_path).lower().endswith(".3mf"):
        return None
    if filament_map in (None, "", []):
        if slots is None:
            try:
                from kiln.multicolor_3mf import detect_3mf_multicolor

                slots = int((detect_3mf_multicolor(input_path) or {}).get("filament_slots_needed", 0))
            except Exception:  # noqa: BLE001 -- an unreadable plate reads as one filament
                slots = 0
        if slots < 2:
            return None
    if maker_ready is None:
        from kiln.maker_slicer import is_ready

        maker_ready = is_ready(record)
    return bed if maker_ready else None


def checked_filament_map(filament_map: Any, *, filaments: int, positions: int) -> list[int] | None:
    """*filament_map* as a list of nozzle numbers, one per filament, or
    ``None`` when none was given.

    Entry ``i`` is the nozzle (1 for the first) that prints filament
    ``i + 1``.  Accepts a list of whole numbers or the same as
    comma-separated text.

    Raises:
        NozzleMapError: The printer is sliced for one nozzle
            (``NOZZLE_MAP_NOT_USED``), an entry is not a whole number or
            names a nozzle the printer does not have (``NO_SUCH_NOZZLE``),
            or the map does not have one entry per filament
            (``NOZZLE_MAP_WRONG_LENGTH``).
    """
    if filament_map is None or filament_map == "" or filament_map == []:
        return None
    if positions < 2:
        raise NozzleMapError(
            "A filament-to-nozzle map was given, and this printer is sliced with one nozzle, so "
            "there is nothing to map. Leave the map out and slice again.",
            code="NOZZLE_MAP_NOT_USED",
        )
    entries = filament_map.split(",") if isinstance(filament_map, str) else list(filament_map)
    asked: list[int] = []
    for entry in entries:
        text = str(entry).strip()
        if isinstance(entry, bool) or not text.isdigit() or not 1 <= int(text) <= positions:
            raise NozzleMapError(
                f"The filament-to-nozzle map names nozzle {text or entry!r}, and this printer has "
                f"nozzles 1 to {positions}. Give one of those numbers for each filament and slice again.",
                code="NO_SUCH_NOZZLE",
            )
        asked.append(int(text))
    if len(asked) != filaments:
        raise NozzleMapError(
            f"The filament-to-nozzle map has {len(asked)} "
            f"{'entry' if len(asked) == 1 else 'entries'}, and this print uses {filaments} "
            f"{'filament' if filaments == 1 else 'filaments'}. Give one nozzle number for each "
            f"filament, in filament order, and slice again.",
            code="NOZZLE_MAP_WRONG_LENGTH",
        )
    return asked


def _nozzle_said(nozzle: dict[str, Any]) -> str:
    """``nozzle 2 (brass)`` / ``nozzle 2 (material not on record)``."""
    material = str(nozzle.get("material") or "").strip().lower()
    if not material or material == "unknown":
        return f"nozzle {nozzle['id']} (material not on record)"
    return f"nozzle {nozzle['id']} ({material.replace('_', ' ')})"


def _abrasive_slots(slot_materials: Sequence[Sequence[str]]) -> list[tuple[int, str]]:
    """``(slot, word)`` for each filament slot a word names abrasive."""
    from kiln.material_safety import is_abrasive_filament

    found: list[tuple[int, str]] = []
    for slot, words in enumerate(slot_materials, start=1):
        word = next((w for w in words if w and is_abrasive_filament(w)), None)
        if word is not None:
            found.append((slot, word.strip()))
    return found


#: The code of a slice refused for an abrasive filament through a nozzle
#: that is not wear-resistant, until the owner says to print it anyway.
SOFT_NOZZLE_CODE = "ABRASIVE_ON_SOFT_NOZZLE"
#: The confirmation a refused abrasive slice can be sliced with, as its
#: refusal says it: one clause, the same at every door.
SOFT_NOZZLE_CONFIRM = "if the owner says to print it anyway, call again with soft_nozzle_confirmed=true"
#: The start of the refusal's advice to choose each filament's nozzle; the
#: filament and the nozzle follow.
MAP_ADVICE = "give a filament-to-nozzle map with "


def owner_asks(
    soft_nozzle_confirmed: Any = False, filament_map: Any = None, mixed_nozzle_experiment: Any = False,
    *, speed_by_height: Any = None,
) -> dict[str, Any]:
    """The slice keywords a door hands on for the owner's word to print
    anyway (``soft_nozzle_confirmed``), the filament-to-nozzle map
    (``filament_map``), the person's yes to nozzles of different sizes
    for this print (``mixed_nozzle_experiment``) and their own speeds for
    height ranges (``speed_by_height``): only what was given, so a door
    passes all of them the same way (:func:`slice_file`)."""
    out: dict[str, Any] = {}
    if speed_by_height:
        out["speed_by_height"] = speed_by_height
    if soft_nozzle_confirmed is True:
        out["soft_nozzle_confirmed"] = True
    if filament_map:
        out["filament_map"] = filament_map
    if mixed_nozzle_experiment is True:
        out["mixed_nozzle_experiment"] = True
    return out


def said_for(text: str, *, confirm: str, map_with: str, experiment: str) -> str:
    """*text*, a slicing refusal or one of its parts, with its three asks
    spelled for a door that takes them another way: *confirm* replaces "call
    again with soft_nozzle_confirmed=true" after "if the owner says to print
    it anyway, ", *map_with* replaces "give a filament-to-nozzle map with"
    (or its capitalised form) before the filament and the nozzle, and
    *experiment* replaces "call
    again with mixed_nozzle_experiment=true" after "if they say yes to
    trying it for this print, "."""
    from kiln.slicer_profiles import MIXED_SIZES_CONFIRM

    yes = MIXED_SIZES_CONFIRM.split(", call again")[0]
    return (
        text.replace(SOFT_NOZZLE_CONFIRM, f"if the owner says to print it anyway, {confirm}")
        .replace(MAP_ADVICE, f"{map_with} ")
        .replace(MAP_ADVICE[0].upper() + MAP_ADVICE[1:], f"{map_with[:1].upper()}{map_with[1:]} ")
        .replace(MIXED_SIZES_CONFIRM, f"{yes}, {experiment}")
    )


@dataclass(frozen=True)
class SoftNozzleRun:
    """An abrasive filament a slice would print through a nozzle that is
    not wear-resistant (:func:`soft_nozzle_run`)."""

    #: ``(slot, word)`` for each abrasive filament, 1 for the first slot.
    filaments: tuple[tuple[int, str], ...]
    #: The nozzles that are not wear-resistant, each ``{"id", "material"}``;
    #: ``id`` is ``None`` for the one nozzle on record.
    nozzles: tuple[dict[str, Any], ...]
    #: The refusal, laid out (:class:`kiln.slicer_profiles.RefusalParts`).
    parts: Any

    @property
    def refusal(self) -> str:
        """The refusal as one text, its answer named."""
        return self.parts.message()

    def confirmed(self, stated_map: Sequence[int] | None = None) -> dict[str, Any] | None:
        """The block a slice the owner said to print anyway carries, or
        ``None`` when the sliced file puts no abrasive filament on a nozzle
        that is not wear-resistant.

        *stated_map* is the filament-to-nozzle map the sliced file states:
        given, the nozzles are narrowed to the ones it puts an abrasive
        filament on.  ``{"confirmed_by": "owner", "filaments": [{"filament",
        "material"}], "nozzles": [{"position", "material"}], "said": str}``.
        """
        nozzles = list(self.nozzles)
        if stated_map and all(isinstance(n.get("id"), int) for n in nozzles):
            printed_on = {stated_map[slot - 1] for slot, _word in self.filaments if slot - 1 < len(stated_map)}
            nozzles = [n for n in nozzles if n["id"] in printed_on]
        if not nozzles:
            return None
        named = sorted({word for _slot, word in self.filaments})
        what = (
            f"{named[0]}, an abrasive filament," if len(named) == 1
            else f"{', '.join(named[:-1])} and {named[-1]}, abrasive filaments,"
        )
        if nozzles[0].get("id") is None:
            material = str(nozzles[0].get("material") or "").replace("_", " ")
            where = f"the nozzle on record ({material}), which is not wear-resistant and wears"
        else:
            verb = "is" if len(nozzles) == 1 else "are"
            where = f"{' and '.join(_nozzle_said(n) for n in nozzles)}, which {verb} not wear-resistant and wear"
            where += "s" if len(nozzles) == 1 else ""
        return {
            "confirmed_by": "owner",
            "filaments": [{"filament": slot, "material": word} for slot, word in self.filaments],
            "nozzles": [{"position": n.get("id"), "material": n.get("material")} for n in nozzles],
            "said": f"On the owner's say-so, {what} prints through {where} quickly on it.",
        }


def soft_nozzle_run(
    slot_materials: Sequence[Sequence[str]],
    filament_map: Sequence[int] | None = None,
    *,
    nozzles: Any = None,
    fitted: Sequence[dict[str, Any]] | None = None,
    on_record: str | None = None,
    mappable: bool = False,
) -> SoftNozzleRun | None:
    """The abrasive filaments a slice would print through a nozzle that is
    not wear-resistant, and the sentence refusing it; ``None`` when there
    are none.

    *slot_materials* lists, per filament slot in order, every word naming
    that filament's material; a slot is abrasive when any word is
    (:func:`kiln.material_safety.is_abrasive_filament`), and a nozzle is
    judged by :func:`kiln.material_safety.is_wear_resistant_nozzle`.  The
    nozzles judged, the first that applies:

    * *nozzles*, the record a slice for more than one nozzle carries with
      its owner's statement (:func:`kiln.slicer_profiles.used_nozzles`):
      with *filament_map*, an abrasive filament mapped to a nozzle that is
      not wear-resistant is refused; with none, the slicer's own choice is
      refused while any nozzle the slice uses is not wear-resistant;
    * *fitted*, the nozzles the owner stated fitted, for a slice for one
      nozzle: refused unless every one is wear-resistant;
    * *on_record*, the material of the one nozzle on record.

    *mappable* is whether a filament-to-nozzle map can choose the nozzle on
    this printer.  The sentence names the filament and the nozzle that can
    take it.
    """
    from kiln.material_safety import is_wear_resistant_nozzle
    from kiln.slicer_profiles import used_nozzles

    abrasive = _abrasive_slots(slot_materials)
    used = used_nozzles(nozzles) if nozzles is not None else []
    if used:
        candidates, known = used, True
    elif fitted:
        candidates, known = [dict(n) for n in fitted], False
    elif on_record:
        candidates, known = [{"id": None, "material": on_record}], False
    else:
        return None
    soft = [n for n in candidates if not is_wear_resistant_nozzle(n.get("material"))]
    if used and filament_map:
        mapped = {slot: filament_map[slot - 1] for slot, _word in abrasive if slot - 1 < len(filament_map)}
        on_soft = {
            slot for slot, nozzle in mapped.items()
            if 1 <= nozzle <= len(used) and not is_wear_resistant_nozzle(used[nozzle - 1].get("material"))
        }
        abrasive = [(slot, word) for slot, word in abrasive if slot in on_soft]
        soft = [used[k - 1] for k in sorted({mapped[slot] for slot in on_soft})]
    if not abrasive or not soft:
        return None
    from kiln.slicer_profiles import RefusalParts

    named = sorted({word for _slot, word in abrasive})
    one = len(abrasive) == 1
    it, they = ("it", "it wears") if one else ("them", "they wear")
    joined = " and ".join(named) if len(named) <= 2 else f"{', '.join(named[:-1])} and {named[-1]}"
    if len(slot_materials) > 1:
        slots = " and ".join(str(slot) for slot, _word in abrasive)
        what = f"{joined} (filament{'' if one else 's'} {slots}) {'is an abrasive filament' if one else 'are abrasive'}"
    else:
        what = f"{joined} {'is an abrasive filament' if len(named) == 1 else 'are abrasive filaments'}"
    hard = [str(n["id"]) for n in candidates if is_wear_resistant_nozzle(n.get("material"))]
    on = f"nozzle {' or '.join(hard)}"
    hardened = f"Fit a hardened nozzle for {it}."
    said = " and ".join(_nozzle_said(n) for n in soft)
    if not known and candidates[0]["id"] is None:
        material = str(on_record).replace("_", " ")
        reason = f"{what}, and this printer's nozzle is recorded as {material}, which {they} out quickly."
        fix = "Fit a hardened nozzle, or tell Kiln which nozzle is fitted."
    else:
        if known and filament_map:
            where = f"the filament-to-nozzle map puts {it} on {said}"
            fix = f"Put {it} on {on} in the map." if hard else hardened
        elif known:
            where = f"the slicer may print {it} through {said}"
            fix = f"{MAP_ADVICE[0].upper()}{MAP_ADVICE[1:]}{it} on {on}." if hard else hardened
        elif len(candidates) == 1:
            where = f"the only nozzle fitted is {said}"
            fix = hardened
        else:
            where = f"a slice for one nozzle can print through any nozzle fitted, including {said}"
            if hard and mappable:
                fix = f"{MAP_ADVICE[0].upper()}{MAP_ADVICE[1:]}{it} on {on}."
            elif hard:
                fix = f"Only {on} can take {it}: fit wear-resistant nozzles in place of the others."
            else:
                fix = hardened
        if not hard:
            fix = f"No nozzle {'this print uses' if known else 'fitted'} is wear-resistant: {hardened[0].lower()}{hardened[1:]}"
        reason = f"{what}, and {where}, which {they} out quickly."
    worn = "the nozzle" if len(soft) == 1 else "these nozzles"
    parts = RefusalParts(
        headline=f"{joined} would wear out {worn}",
        reason=reason[0].upper() + reason[1:],
        fix=fix,
        ask=SOFT_NOZZLE_CONFIRM,
    )
    return SoftNozzleRun(tuple(abrasive), tuple(soft), parts)


def filament_map_of(gcode_path: str | None) -> dict[str, Any] | None:
    """The filament-to-nozzle map the sliced file at *gcode_path* states,
    or ``None`` when it states none or cannot be read.  Never raises.

    ``filament_to_nozzle`` lists, per filament in order, the nozzle (1 for
    the first) that printed it; ``nozzle_filaments`` is the same read the
    other way, nozzle number to the filaments (1 for the first) on it;
    ``mode`` is who chose the map, in the slicer's own word, when the file
    says.
    """
    if not gcode_path:
        return None
    from kiln.gcode import stated_filament_map

    try:
        with open(gcode_path, errors="replace", encoding="utf-8") as fh:
            stated, mode = stated_filament_map(fh)
    except OSError:
        return None
    if stated is None:
        return None
    by_nozzle: dict[str, list[int]] = {}
    for filament, nozzle in enumerate(stated, start=1):
        by_nozzle.setdefault(str(nozzle), []).append(filament)
    read: dict[str, Any] = {"filament_to_nozzle": stated, "nozzle_filaments": by_nozzle}
    if mode:
        read["mode"] = mode
    return read


def _slot_materials(input_path: str, materials: Sequence[str | None], slots: int) -> list[list[str]]:
    """Per filament slot, every word naming its material: each of
    *materials* (the words the slice names every slot by) and, for a 3MF
    that states one per slot, the file's own.  Never raises."""
    named = [str(word).strip() for word in materials if word and str(word).strip()]
    words = [list(named) for _ in range(slots)]
    for slot, word in enumerate(_file_slot_types(input_path, slots)):
        if word:
            words[slot].append(word)
    return words


def _file_slot_types(input_path: str, slots: int) -> list[str]:
    """The filament type a 3MF states for each of its first *slots* slots,
    ``""`` for a slot it states none for; every slot ``""`` for any other
    file or one that cannot be read.  Never raises."""
    types = [""] * slots
    if not str(input_path).lower().endswith(".3mf"):
        return types
    try:
        from kiln.file_metadata import slicer_settings

        stated = re.split(r"[;,]", str(slicer_settings(input_path).get("filament_type") or ""))
    except Exception:  # noqa: BLE001 -- a file that cannot be read states no type
        logger.debug("filament types of %s not read", input_path, exc_info=True)
        return types
    for slot, word in enumerate(stated[:slots]):
        types[slot] = word.strip()
    return types


def _printer_id_of(profile: str | None) -> str | None:
    """The id of the printer whose bundled profile Kiln built *profile*
    from, or ``None`` for a profile that is the caller's own."""
    from kiln.slicer_profiles import profile_origin

    origin = profile_origin(profile)
    return origin.printer_id or origin.standing_in_for


def _printer_name_of(profile: str | None) -> str | None:
    """The name of the printer whose bundled profile Kiln built *profile*
    from, or ``None`` for a profile that is the caller's own."""
    from kiln.slicer_profiles import profile_origin, raw_profile

    origin = profile_origin(profile)
    printer_id = origin.printer_id or origin.standing_in_for
    name = (raw_profile(printer_id) or {}).get("display_name") if printer_id else None
    return str(name) if name else None


def _signal_of(returncode: int) -> int:
    """The signal a crash status names: ``-11`` from Python, ``139`` (128 + 11)
    as a shell reports the same death."""
    return -returncode if returncode < 0 else returncode - 128


# Startup crashes, slicer spelling.  As kiln.openscad_runner does for
# OpenSCAD, a crash inside the startup window is retried, and one that lands
# outside it is a real answer about real geometry and is not retried.
_SLIC3R_STARTUP_CRASH_RETURNCODES = frozenset(
    -sig for sig in present_signals("SIGTRAP", "SIGSEGV", "SIGBUS")
)

# The Orca dialect leaves SIGSEGV out of its retry set: -11 on that path is
# reported to the person as a crash inside the slicer program and is not
# retried (the openscad_runner rule about not retrying real answers).  The locale race has not been captured on
# an Orca binary; TRAP/BUS are covered so that if it ever is, the user
# gets the re-draw instead of the failure.
_ORCA_STARTUP_CRASH_RETURNCODES = frozenset(
    -sig for sig in present_signals("SIGTRAP", "SIGBUS")
)

#: A crash later than this is blamed on the model, not on startup.  The
#: observed crashes die in the first ~0.1s; ten seconds is far past any
#: plausible startup and far short of real slicing work on a big model.
_STARTUP_CRASH_WINDOW_S = 10.0

#: Total launches, so two re-draws after a first startup crash.
_SLICE_ATTEMPTS = 3


def _parse_bed_shape(shape: str) -> tuple[float, float, float, float] | None:
    """``"0x0,256x0,256x256,0x256"`` → ``(x_min, y_min, x_max, y_max)``.

    Corner-origin beds give ``(0, 0, w, d)``; center-origin (delta) beds
    keep their negative corners, so every fit check works for both.
    """
    xs: list[float] = []
    ys: list[float] = []
    for corner in shape.split(","):
        x, sep, y = corner.strip().partition("x")
        if not sep:
            continue
        try:
            xs.append(float(x))
            ys.append(float(y))
        except ValueError:
            continue
    if len(xs) < 3:
        return None
    return (min(xs), min(ys), max(xs), max(ys))


def profile_filament_slots(profile: str | None) -> int:
    """How many filament slots a PrusaSlicer profile ini can express.

    PrusaSlicer INI convention: per-extruder keys carry one
    comma-separated value per extruder, so ``nozzle_diameter = 0.4,0.4``
    is a two-extruder config.  No profile means the slicer's built-in
    single-extruder defaults — as is every bundled Kiln profile today.
    An unreadable profile reads as 1: if it were truly missing, the
    slice itself would fail on it moments later with the real error.

    Lives here, with the engine that acts on the answer, and is what the
    tool layer's flatten advisory calls too — a copy in each is how a
    backend gains a capability the advisory still reports it lacking.
    """
    if not profile or not os.path.isfile(profile):
        return 1
    try:
        value = ini_to_settings(profile).get("nozzle_diameter", "")
    except OSError:
        return 1
    return max(1, len([v for v in str(value).split(",") if v.strip()]))


def colours_expressed(profile: str | None, counted: tuple[int, int] | None) -> int:
    """How many filaments a slice with *profile* can print: the profile's
    own slots (:func:`profile_filament_slots`) or the tools the sliced file
    selects (*counted*, :func:`kiln.gcode.tool_changes`), whichever is more.
    A plate asking for more filaments than this prints them folded
    together, in one colour when this is 1."""
    return max(profile_filament_slots(profile), counted[1] if counted is not None else 0)


#: The bed PrusaSlicer, OrcaSlicer and Bambu Studio slice on when the profile
#: states none: 200 mm square, its corner at the origin.  Each arranges a
#: loose mesh on its centre.
_UNSTATED_BED: tuple[float, float, float, float] = (0.0, 0.0, 200.0, 200.0)


def _bed_xy_bounds_from_profile(
    profile: str | None,
) -> tuple[float, float, float, float] | None:
    """The bed's XY rectangle from a profile ini, or None."""
    if not profile or not os.path.isfile(profile):
        return None
    try:
        shape = ini_to_settings(profile).get("bed_shape", "")
    except OSError:
        return None
    return _parse_bed_shape(shape)


# Clearance kept between the prime tower and both the bed edge and the
# model's footprint (its brim included).  Covers the tower's own brim (3 mm)
# with room to spare, without eating plate space a small bed does not have.
_PRIME_TOWER_MARGIN_MM = 5.0


def _wipe_tower_position(
    settings: dict[str, str],
    input_abs: str,
    tower_width_mm: float,
) -> tuple[float, float] | None:
    """A prime-tower corner position on the bed, clear of the model.

    Orca's default placement can land off the plate, failing the whole
    slice with "found gcode in unprintable area" — so a multicolor slice
    states one whenever it can.  Candidates are tried on each side of the
    model's placed bbox (right, left, back, front), first one that fits
    the bed wins; when no side has room, or the bbox cannot be read, the
    tower goes to the back-right corner of the bed.

    Returns ``None`` when no honest position exists — an unknown bed
    shape, or a bed too small to hold the tower at all.  The caller then
    omits the tower rather than placing it off the plate, which keeps
    every color (measured: a multicolor file slices fine with no tower,
    purging into the object) instead of failing the whole slice.  An
    invented coordinate is the one outcome worse than no tower.
    """
    bed = _parse_bed_shape(str(settings.get("bed_shape", "")))
    if bed is None:
        return None
    bed_x_min, bed_y_min, bed_x_max, bed_y_max = bed
    m = _PRIME_TOWER_MARGIN_MM
    w = tower_width_mm

    # A bed that cannot hold the tower plus its margins has no position
    # to offer — the corner formula would return one OFF the plate.
    if (
        bed_x_max - bed_x_min < w + 2 * m
        or bed_y_max - bed_y_min < w + 2 * m
    ):
        logger.info(
            "Bed %gx%gmm is too small for a %gmm prime tower; slicing "
            "multicolor without one.",
            bed_x_max - bed_x_min, bed_y_max - bed_y_min, w,
        )
        return None

    def _clamp(v: float, lo: float, hi: float) -> float:
        return max(lo, min(v, hi))

    corner = (bed_x_max - m - w, bed_y_max - m - w)

    bbox = None
    try:
        from kiln.printers.bed_fit import compute_3mf_geometry_bbox

        bbox = compute_3mf_geometry_bbox(input_abs)
    except Exception:  # noqa: BLE001 — placement is best-effort, never fatal
        logger.debug("wipe tower bbox read failed for %s", input_abs, exc_info=True)
    if not bbox:
        return corner

    # The model's brim is part of what its first layer prints, so the tower
    # keeps its margin from the brim's outside edge.
    gap = m + outside_brim_mm(settings)
    cx = (bbox["x_min"] + bbox["x_max"]) / 2.0 - w / 2.0
    cy = (bbox["y_min"] + bbox["y_max"]) / 2.0 - w / 2.0
    candidates = [
        (bbox["x_max"] + gap, _clamp(cy, bed_y_min + m, bed_y_max - m - w)),
        (bbox["x_min"] - gap - w, _clamp(cy, bed_y_min + m, bed_y_max - m - w)),
        (_clamp(cx, bed_x_min + m, bed_x_max - m - w), bbox["y_max"] + gap),
        (_clamp(cx, bed_x_min + m, bed_x_max - m - w), bbox["y_min"] - gap - w),
    ]
    for x, y in candidates:
        if (
            x >= bed_x_min + m
            and y >= bed_y_min + m
            and x + w <= bed_x_max - m
            and y + w <= bed_y_max - m
        ):
            return (x, y)
    logger.info(
        "No side of the model has %gmm of clear bed for the prime tower; "
        "falling back to the back-right corner.", w,
    )
    return corner


#: What the tower takes beyond the purge volume spread one layer thick, as a
#: fractional margin.
_TOWER_ALLOWANCE = 1.25
#: Room kept at the bed's edge, past the tower's margin, for the skirt the
#: slicer draws around the tower.
_TOWER_SKIRT_MM = 3.0


def _layer_mm(settings: dict[str, str]) -> float | None:
    """The thinnest layer *settings* print, mm: the tower is deepest there."""
    heights = []
    for key in ("layer_height", "first_layer_height"):
        try:
            heights.append(float(str(settings.get(key, "")).strip()))
        except ValueError:
            continue
    heights = [h for h in heights if 0.0 < h < 5.0]
    return min(heights) if heights else None


def _wipe_tower_placement(
    settings: dict[str, str],
    input_abs: str,
    slots: int,
) -> tuple[float, float, float] | None:
    """Where the prime tower goes and how wide it is: ``(x, y, width)``.

    The Orca dialect purges each change of filament into the tower, so the
    tower's footprint is the purge volume spread one layer thick, and its
    shape follows the stated width rather than a square.

    So a file that states its purge volumes
    (:func:`kiln.project_plates.saved_purge_mm3`) gets a tower shaped for
    them: as wide as the free bed beside the model needs for the depth to
    fit, on the first side with room (right, left, back, front).  The area
    allows for one change for each filament after the first, in every
    layer, at the largest volume and the thinnest layer, and a quarter over
    (:data:`_TOWER_ALLOWANCE`).  A file that
    states none, or whose tower fits the square, is placed as it always was
    (:func:`_wipe_tower_position`).  ``None`` when no side has room: the
    slice goes without a tower rather than with one off the plate.
    """
    from kiln.project_plates import saved_purge_mm3

    width = PRIME_TOWER_WIDTH_MM
    purge, layer = saved_purge_mm3(input_abs), _layer_mm(settings)
    area = (
        None if purge is None or layer is None
        else _TOWER_ALLOWANCE * max(1, slots - 1) * (purge + PRIME_VOLUME_MM3) / layer
    )
    if area is None or area <= width * width:
        xy = _wipe_tower_position(settings, input_abs, width)
        return None if xy is None else (xy[0], xy[1], width)

    bed = _parse_bed_shape(str(settings.get("bed_shape", "")))
    if bed is None:
        return None
    m = _PRIME_TOWER_MARGIN_MM
    edge = m + _TOWER_SKIRT_MM
    x0, y0, x1, y1 = bed[0] + edge, bed[1] + edge, bed[2] - edge, bed[3] - edge
    bbox = None
    try:
        from kiln.printers.bed_fit import compute_3mf_geometry_bbox

        bbox = compute_3mf_geometry_bbox(input_abs)
    except Exception:  # noqa: BLE001 -- placement is best-effort, never fatal
        logger.debug("wipe tower bbox read failed for %s", input_abs, exc_info=True)
    if not bbox:
        return None
    gap = m + outside_brim_mm(settings)
    cx, cy = (bbox["x_min"] + bbox["x_max"]) / 2.0, (bbox["y_min"] + bbox["y_max"]) / 2.0

    def clamp(v: float, lo: float, hi: float) -> float:
        return max(lo, min(v, hi))

    def beside(free_width: float, at_x: Callable[[float], float]) -> tuple[float, float, float] | None:
        # A strip left or right of the model: as narrow as the bed's depth allows.
        wide = max(width, area / (y1 - y0))
        if wide > free_width:
            return None
        deep = area / wide
        return at_x(wide), clamp(cy - deep / 2.0, y0, y1 - deep), wide

    def across(free_depth: float, at_y: Callable[[float], float]) -> tuple[float, float, float] | None:
        # A strip behind or in front of the model: as wide as its depth needs.
        if free_depth <= 0:
            return None
        wide = max(width, area / free_depth)
        if wide > x1 - x0:
            return None
        return clamp(cx - wide / 2.0, x0, x1 - wide), at_y(area / wide), wide

    for placed in (
        beside(x1 - (bbox["x_max"] + gap), lambda _wide: bbox["x_max"] + gap),
        beside((bbox["x_min"] - gap) - x0, lambda wide: bbox["x_min"] - gap - wide),
        across(y1 - (bbox["y_max"] + gap), lambda _deep: bbox["y_max"] + gap),
        across((bbox["y_min"] - gap) - y0, lambda deep: bbox["y_min"] - gap - deep),
    ):
        if placed is not None:
            return placed
    logger.info(
        "No side of the model has room for a prime tower of %.0f mm^2; slicing multicolor without one.", area,
    )
    return None


# Matches kiln.printers.bed_fit._FIT_EPSILON_MM — floating-point noise on
# the bed edge must not reject a model that fits.
_BED_FIT_EPSILON_MM = 0.5


#: The PrusaSlicer command line's own copy layout: ``--duplicate N`` lays out
#: N copies of the model, ``--duplicate-distance D`` with D mm between them.
_DUPLICATE_FLAG = "--duplicate"
_DUPLICATE_DISTANCE_FLAG = "--duplicate-distance"


def _copies_requested(extra_args: list[str] | None) -> tuple[int, str | None, list[str]] | None:
    """``(copies, gap, the other arguments)`` when *extra_args* ask the
    slicer to lay out copies, else ``None``."""
    if not extra_args or _DUPLICATE_FLAG not in extra_args:
        return None
    copies: int | None = None
    gap: str | None = None
    rest: list[str] = []
    i = 0
    while i < len(extra_args):
        arg = extra_args[i]
        if arg in (_DUPLICATE_FLAG, _DUPLICATE_DISTANCE_FLAG) and i + 1 < len(extra_args):
            if arg == _DUPLICATE_FLAG:
                try:
                    copies = int(extra_args[i + 1])
                except ValueError:
                    return None
            else:
                gap = extra_args[i + 1]
            i += 2
            continue
        rest.append(arg)
        i += 1
    if copies is None or copies < 2:
        return None
    return copies, gap, rest


def _laid_out_copies(
    slicer: SlicerInfo,
    input_abs: str,
    profile: str | None,
    extra_args: list[str] | None,
    *,
    timeout: int,
) -> tuple[str, list[str]] | None:
    """The copies a slice asks the slicer for, laid out first as a plate Kiln
    can judge: ``(the plate, the other arguments)``, or ``None`` when the
    slice asks for no copies.

    The layout is exported first as a 3MF and judged by
    :func:`kiln.printers.bed_fit.plate_fit`, the judgment every door that
    lays out a plate makes.  Copies that do not fit are refused, in words;
    copies that do are sliced from that exported plate, so the printer gets
    exactly the plate that was judged.
    """
    request = _copies_requested(extra_args)
    if request is None:
        return None
    copies, gap, rest = request
    name = os.path.basename(input_abs)
    arranged = os.path.join(tempfile.mkdtemp(prefix="kiln_copies_"), f"{Path(input_abs).stem}_x{copies}.3mf")
    cmd = [slicer.path, "--export-3mf", _DUPLICATE_FLAG, str(copies)]
    if gap is not None:
        cmd += [_DUPLICATE_DISTANCE_FLAG, gap]
    if profile:
        cmd += ["--load", profile]
    cmd += ["--output", arranged, input_abs]

    def _drop_partial() -> None:
        with contextlib.suppress(OSError):
            os.unlink(arranged)

    result = _run_slicer_with_startup_retry(
        cmd,
        timeout=timeout,
        retryable_returncodes=_SLIC3R_STARTUP_CRASH_RETURNCODES,
        remove_partial_output=_drop_partial,
        output_is_complete=lambda: os.path.isfile(arranged),
    )
    if result.returncode != 0 or not os.path.isfile(arranged):
        detail = ((result.stderr or "").strip() or (result.stdout or "").strip())[:300]
        raise SlicerError(
            f"The slicer could not lay out {copies} copies of {name}: {detail or 'it wrote no plate'}."
        )
    from kiln.printers.bed_fit import PLATE_TOO_BIG_REMEDY, compute_3mf_geometry_bbox, plate_fit

    bed = _bed_xy_bounds_from_profile(profile)
    volume = (bed[2] - bed[0], bed[3] - bed[1], None) if bed is not None else None
    if plate_fit(compute_3mf_geometry_bbox(arranged), volume)["fits"] is False:
        raise SlicerError(
            f"{copies} copies of {name} do not fit on this {volume[0]:g} × {volume[1]:g} mm bed: "
            "laid out with their gap, some of them land off it. Kiln did not slice it, rather "
            f"than print fewer copies than were asked for. {PLATE_TOO_BIG_REMEDY}"
        )
    return arranged, rest


def _check_3mf_on_bed(input_abs: str, profile: str | None) -> None:
    """Refuse to slice a 3MF whose placed geometry misses the profile's bed.

    3MF only: a 3MF carries explicit build transforms that slicers honour
    literally, while loose STL geometry is auto-centred by PrusaSlicer.
    Without this gate the failure is invisible — PrusaSlicer prints "All
    objects are outside of the print volume." and exits 0 with no output
    file, which would otherwise surface as a generic "output file was not
    created".  Skips silently when the bed shape or the geometry cannot
    be determined: this is a diagnosis gate, not a new way to fail good
    files.
    """
    bed = _bed_xy_bounds_from_profile(profile)
    if bed is None:
        return
    from kiln.printers.bed_fit import compute_3mf_geometry_bbox

    bbox = compute_3mf_geometry_bbox(input_abs)
    if bbox is None:
        return
    bed_x_min, bed_y_min, bed_x_max, bed_y_max = bed
    eps = _BED_FIT_EPSILON_MM
    if (
        bbox["x_min"] >= bed_x_min - eps
        and bbox["x_max"] <= bed_x_max + eps
        and bbox["y_min"] >= bed_y_min - eps
        and bbox["y_max"] <= bed_y_max + eps
    ):
        return
    span_x = bbox["x_max"] - bbox["x_min"]
    span_y = bbox["y_max"] - bbox["y_min"]
    too_big = (
        span_x > (bed_x_max - bed_x_min) + eps
        or span_y > (bed_y_max - bed_y_min) + eps
    )
    fix = (
        # No translation can fit an oversize footprint — say so instead of
        # sending the user in circles re-centring it.
        "The footprint is larger than the bed: rescale the model or "
        "split it into parts that fit."
        if too_big
        else "Re-export the 3MF centred on the bed, or translate the "
        "model so its footprint fits."
    )
    raise SlicerError(
        f"Model geometry (with its 3MF build transform applied) spans "
        f"X[{bbox['x_min']:.1f}..{bbox['x_max']:.1f}] "
        f"Y[{bbox['y_min']:.1f}..{bbox['y_max']:.1f}] mm, outside the "
        f"profile's bed X[{bed_x_min:g}..{bed_x_max:g}] "
        f"Y[{bed_y_min:g}..{bed_y_max:g}] mm. Slicers honour a 3MF's "
        f"placement literally (no auto-centre), so this would slice to "
        f"nothing. {fix}"
    )


def _run_slicer_with_startup_retry(
    cmd: list[str],
    *,
    timeout: int,
    retryable_returncodes: frozenset[int],
    remove_partial_output,
    output_is_complete,
    cwd: str | None = None,
) -> subprocess.CompletedProcess:
    """Launch a slicer, re-drawing the startup-crash lottery when it hits.

    One loop for both CLI dialects so the retry rule cannot drift between
    them.  A retry fires only when ALL of these hold: the death was one of
    *retryable_returncodes*, it happened inside the startup window, the
    output is NOT already complete (a signal death after a complete write
    is the salvage case, owned by the caller), and an attempt remains.
    *remove_partial_output* runs between attempts so a half-written file
    from a crashed run can never pose as the next run's result.
    *cwd* is the slicer's working directory: the Orca path starts the
    slicer inside its own scratch directory, so anything it writes beside
    itself lands there and never in whatever directory the server happens
    to be running from.
    """
    result: subprocess.CompletedProcess | None = None
    for attempt in range(1, _SLICE_ATTEMPTS + 1):
        started = time.monotonic()
        try:
            # No input: a slicer that stops to ask something reads end of
            # file and goes on, rather than waiting on the server's own stdin.
            result = run_program.run(
                cmd, capture_output=True, text=True, timeout=timeout, cwd=cwd,
                stdin=subprocess.DEVNULL,
            )
        except subprocess.TimeoutExpired:
            remove_partial_output()
            raise SliceTimeLimitError(
                f"The slicer took too long: it was stopped after {timeout} seconds and nothing was "
                f"sliced. Slice again with a longer time limit, or a simpler plate."
            ) from None
        except OSError as exc:
            raise SlicerError(f"Kiln couldn't run the slicer: {_plain_words.said(exc)}.") from exc
        elapsed = time.monotonic() - started
        if (
            attempt < _SLICE_ATTEMPTS
            and result.returncode in retryable_returncodes
            and elapsed < _STARTUP_CRASH_WINDOW_S
            and not output_is_complete()
        ):
            logger.warning(
                "Slicer died of signal %d %.2fs after launch (the startup "
                "crash lottery) -- relaunching, attempt %d of %d",
                -result.returncode, elapsed, attempt + 1, _SLICE_ATTEMPTS,
            )
            remove_partial_output()
            continue
        break
    assert result is not None
    return result


def _slice_with_orca(
    slicer: SlicerInfo,
    input_abs: str,
    out_file: str,
    *,
    profile: str | None,
    extra_args: list[str] | None,
    timeout: int,
    multicolor: dict[str, Any] | None = None,
    drawn_as: str | None = None,
    nozzles: dict[str, Any] | None = None,
    filament_map: list[int] | None = None,
    routines: Mapping[str, str] | None = None,
    part_path: str | None = None,
) -> SliceResult:
    """Slice through the BambuStudio/OrcaSlicer command line.

    *part_path* is the part the slice is of when *input_abs* is a copy of
    it made for the slicer: the slice's record and message name the part.

    A different argv and a different preset format from
    :func:`slice_file`'s Slic3r path: ``--slice 0 --outputdir DIR
    [--arrange 0 --orient 0] --load-settings "machine.json;process.json"
    --load-filaments "f1.json[;f2.json…]"``, one filament preset per slot,
    where the presets are the JSON that :mod:`kiln.slicer_orca` writes out of
    the same bundled settings the ``.ini`` is built from.

    Orca names its own output (``plate_1.gcode``) inside ``--outputdir``
    rather than taking an output path, so it writes to a private directory
    and the result is moved to where the caller asked for it.

    *nozzles* is the printer's nozzle record when the slice is for more
    than one nozzle (:func:`kiln.slicer_orca.settings_to_orca_presets`).
    *filament_map* is the caller's filament-to-nozzle map, already checked
    (:func:`checked_filament_map`): the slicer is told to use it, and a
    file that states any other map is not kept.  With none, the slicer
    maps the filaments itself.  The result's ``filament_map`` is what the
    file states.  *routines* are the printer's own routines its maker's
    slicer holds (:func:`kiln.maker_slicer.slicer_for_several_nozzles`,
    :func:`kiln.maker_slicer.slicer_for_layer_routines`), written into the
    machine preset (:func:`kiln.slicer_orca.settings_to_orca_presets`).
    """
    with tempfile.TemporaryDirectory(prefix="kiln_orca_") as work_dir:
        cmd: list[str] = [slicer.path, "--slice", "0", "--outputdir", work_dir]
        if input_abs.lower().endswith(".3mf"):
            # A 3MF carries a placement, and it is the one the person
            # approved on the stage: ``--arrange 0 --orient 0`` prints the
            # plate where and how it was handed over.  Orca's CLI defaults
            # both to "auto", which is free to re-pack and turn parts, which
            # would undo the placement just approved.  Kiln's own gates
            # decide a 3MF's pose before the slicer runs
            # (:func:`_check_3mf_on_bed` refuses one that misses the bed),
            # so a plate that does not fit fails the slice honestly instead
            # of being quietly rearranged.  A loose STL carries no placement
            # and keeps Orca's auto.  *extra_args* follow, so a caller can
            # still ask Orca to arrange.
            cmd += ["--arrange", "0", "--orient", "0"]

        if profile and not os.path.isfile(profile):
            raise SlicerError(f"Profile file not found: {os.path.basename(profile)}")

        if not profile:
            # "No profile" cannot mean "no preset" here the way it does for
            # PrusaSlicer, which slices happily on its own defaults.  Orca's
            # defaults use relative extrusion with no per-layer reset, so a
            # bare slice_file("model.stl") — the documented form — fails
            # validation before it starts.  Kiln's own generic profile is a
            # real answer to "you didn't say", and it keeps the bare call
            # working on both backends.  slice_file resolves it before the
            # filament identity is written, so this branch serves only a
            # direct caller of this runner.
            #
            # Resolved through the ordinary door rather than read straight
            # off the profile, so it passes the same invariants every other
            # profile does — the per-layer E reset among them.
            from kiln.slicer_profiles import resolve_slicer_profile

            profile = resolve_slicer_profile("default")

        settings = ini_to_settings(profile)
        preset_name = Path(profile).stem[:48] or "kiln"
        slots = int((multicolor or {}).get("filament_slots_needed", 0))
        if slots >= 2 and any(stated := _file_slot_types(input_abs, slots)):
            # Each filament is loaded as the type the file states for it, in
            # the short form a printer reads.
            from kiln.slicer_filament import slicer_type_name

            own = str(settings.get("filament_type") or "").split(";")[0].split(",")[0].strip()
            settings["filament_type"] = ";".join(
                (slicer_type_name(word) if word else "") or own or "PLA" for word in stated
            )

        # A multicolor 3MF needs one filament preset PER SLOT, or Orca
        # slices every color with T0 — the exact flatten the advisory
        # layer warns about.  *multicolor* is the
        # evidence slice_file already gathered (one archive scan per
        # slice, wherever the input entered); detecting here again would
        # re-read the whole model XML.  Absent or below two slots, the
        # slice proceeds single-filament, exactly as before.
        filament_colors: list[str] | None = None
        wipe_xy: tuple[float, float] | None = None
        tower: tuple[float, float, float] | None = None
        if slots >= 2:
            from kiln.multicolor_3mf import multicolor_filament_colors

            filament_colors = multicolor_filament_colors(multicolor, slots)
            from kiln.slicer_profiles import rect_polygon, shared_reach

            # Every nozzle prints the tower, so it stands where all reach.
            shared = shared_reach(nozzles) if nozzles else None
            tower_settings = settings if shared is None else {**settings, "bed_shape": rect_polygon(shared)}
            tower = _wipe_tower_placement(tower_settings, input_abs, slots)
            wipe_xy = None if tower is None else tower[:2]
            logger.info(
                "Multicolor 3MF: emitting %d filament presets "
                "(prime tower at %s)", slots, tower,
            )

        presets = write_orca_presets(
            settings,
            work_dir,
            name=preset_name,
            filament_colors=filament_colors,
            wipe_tower_xy=wipe_xy,
            wipe_tower_width_mm=None if tower is None else tower[2],
            nozzles=nozzles,
            routines=routines,
        )
        cmd += ["--load-settings", f"{presets.machine_path};{presets.process_path}"]
        cmd += ["--load-filaments", ";".join(presets.filament_paths)]
        if filament_map:
            cmd += ["--filament-map-mode", "Manual", "--filament-map", ",".join(str(n) for n in filament_map)]
        from kiln.maker_slicer import is_slicer

        if nozzles and is_slicer("bambu_studio", slicer):
            # The slicer writes the print package for this slice beside it.
            cmd += ["--export-3mf", _SLICER_PACKAGE_NAME]

        if extra_args:
            cmd.extend(extra_args)
        cmd.append(input_abs)

        logger.info("Slicing (Orca dialect): %s", " ".join(cmd))

        def _latest_gcode_complete() -> bool:
            done = sorted(Path(work_dir).glob("*.gcode"), key=lambda p: p.stat().st_mtime)
            return bool(done) and _gcode_output_is_complete(str(done[-1]))

        def _drop_partial_gcode() -> None:
            for stale in Path(work_dir).glob("*.gcode"):
                with contextlib.suppress(OSError):
                    stale.unlink()

        result = _run_slicer_with_startup_retry(
            cmd,
            timeout=timeout,
            retryable_returncodes=_ORCA_STARTUP_CRASH_RETURNCODES,
            remove_partial_output=_drop_partial_gcode,
            output_is_complete=_latest_gcode_complete,
            cwd=work_dir,
        )

        produced = sorted(Path(work_dir).glob("*.gcode"), key=lambda p: p.stat().st_mtime)

        # A death by signal AFTER a complete write is salvageable, exactly as
        # it is on the Slic3r path — see _gcode_output_is_complete, which
        # exists because PrusaSlicer does this on some multi-object files.
        # Orca is a Slic3r derivative, so it inherits the possibility; without
        # this the two paths would disagree about the same event, and a good
        # slice would be thrown away with a message about a Bambu crash.
        # A crash only: this CLI also exits non-zero AFTER writing complete
        # G-code when it REFUSES the result (_orca_refusal), and that is a
        # verdict about the print, not a crash to look past.
        crashed_after_finishing = bool(
            (result.returncode < 0 or result.returncode in _ORCA_SIGSEGV_RETURNCODES)
            and produced
            and _gcode_output_is_complete(str(produced[-1]))
        )

        if result.returncode in _ORCA_SIGSEGV_RETURNCODES and not crashed_after_finishing:
            slicer_name = os.path.basename(slicer.path)
            printer_name = _printer_name_of(profile)
            if nozzles:
                raise SlicerError(
                    f"{slicer_name} crashed while slicing this print for more than one nozzle "
                    f"(it was stopped by signal {_signal_of(result.returncode)}): the slicer "
                    f"failed, not the print. Slice again; if it crashes the same way, check that "
                    f"{slicer_name} is up to date."
                )
            if printer_name and printer_name.startswith("Bambu Lab"):
                raise SlicerError(
                    f"{slicer_name} crashed while slicing. The crash is inside "
                    f"{slicer_name} itself, not in your model or your settings. Slice "
                    f"again, and if it crashes the same way, slice this printer with "
                    f"PrusaSlicer instead; Kiln wraps the result as a Bambu 3MF itself, "
                    f"so nothing about the print is lost. Please report it with "
                    f"`report_issue` so it can be looked into.\n"
                    f"{_INSTALL_SLICER}"
                )
            for_printer = f" for the {printer_name}" if printer_name else ""
            raise SlicerError(
                f"{slicer_name} crashed while slicing{for_printer} (it was stopped by "
                f"signal {_signal_of(result.returncode)}): the slicer failed, not the "
                f"print. Slice again; if it crashes the same way, slice this printer "
                f"with PrusaSlicer instead.\n{_INSTALL_SLICER}"
            )

        if result.returncode != 0 and not crashed_after_finishing:
            # This CLI reports the reason on stdout and in the result.json
            # Bambu Studio writes into --outputdir; stderr carries only what macOS adds
            # (a saved-window notice), so it is read last, never instead.
            stderr_snippet = _orca_said(result, work_dir)
            if "fully inside the print volume" in stderr_snippet and input_abs.lower().endswith(".3mf"):
                # The one refusal the arrange-off rule above can newly
                # produce: a plate whose placement grazes or leaves the
                # volume, which auto-arrange would move silently.  Said
                # in the person's terms, with the fix, instead of a CLI log
                # line.
                raise SlicerError(
                    f"{os.path.basename(slicer.path)} refused to slice: as placed, "
                    f"the plate is not fully inside the printer's build volume. Kiln "
                    f"slices a 3MF exactly where it was placed (the placement is the "
                    f"one that was approved, so the slicer is not allowed to "
                    f"rearrange it) — move the part in from the bed edge, or "
                    f"re-place it, and slice again."
                )
            refusal = _orca_refusal(os.path.basename(slicer.path), result.returncode, stderr_snippet)
            if refusal is not None:
                raise refusal
            logger.warning("slicer exited %s: %s", result.returncode, stderr_snippet[:500])
            said = f" It said: {stderr_snippet[:500]}" if stderr_snippet else ""
            what = "crashed" if result.returncode < 0 else "stopped with an error"
            raise SlicerError(f"The slicer {what} and made no file.{said}")

        if not produced:
            # This CLI reports on stdout, but surface both streams — the
            # Slic3r-family lesson: the reason for a silent exit-0 no-write
            # lives on whichever stream the message omitted.
            reason = (result.stdout or "").strip() or (result.stderr or "").strip()
            raise SlicerError(
                f"Slicer completed but wrote no G-code. "
                f"Slicer said: {reason[:500] if reason else '(no output)'}"
            )

        # One plate, because slice_file promises exactly one file.  The model
        # did not fit on a single plate, and quietly handing back the first
        # one is how a user prints half a job and finds out at the printer.
        if len(produced) > 1:
            raise SlicerError(
                f"This model needed {len(produced)} build plates, and a slice "
                f"returns a single G-code file. Split it into separate models, "
                f"or scale it down so it fits one plate."
            )

        used_map = filament_map_of(str(produced[0])) if nozzles else None
        if filament_map and (used_map or {}).get("filament_to_nozzle") != filament_map:
            raise SlicerError(
                f"{os.path.basename(slicer.path)} did not slice with the filament-to-nozzle map "
                f"that was asked for, so the file was not kept. Slice again without a map to let "
                f"the slicer choose, or check that this slicer is up to date."
            )

        if str(settings.get("machine_limits_usage", "")).strip() != "emit_to_gcode":
            _drop_unasked_machine_limits(str(produced[0]))
        shutil.move(str(produced[0]), out_file)
        made_package: str | None = None
        written = Path(work_dir, _SLICER_PACKAGE_NAME)
        if nozzles and written.is_file():
            made_package = out_file + ".made.3mf"
            shutil.move(str(written), made_package)

    _record_slice(profile, part_path or input_abs, out_file, drawn_as=drawn_as)
    if made_package is not None:
        _keep_print_package(made_package, out_file)
    message = f"Sliced {Path(part_path or input_abs).name} -> {Path(out_file).name}"
    if crashed_after_finishing:
        message += (
            f" (the slicer crashed on exit AFTER writing complete G-code — "
            f"signal {_signal_of(result.returncode)}; the output was verified complete "
            f"and kept)"
        )
    # The colour the part was asked to be shown -- and printed -- in follows
    # the file it was sliced into, so the print door that reads the G-code
    # still knows it (kiln.declared_color).
    try:
        from kiln.declared_color import carry as _carry_colour

        _carry_colour(part_path or input_abs, out_file)
    except Exception:  # noqa: BLE001 -- a note never costs a slice
        logger.debug("colour note not carried to %s", out_file, exc_info=True)
    return SliceResult(
        success=True,
        output_path=out_file,
        slicer=slicer.name,
        message=message,
        stdout=(result.stdout or "").strip(),
        stderr=(result.stderr or "").strip(),
        filament_map=used_map,
    )


#: A machine-limit line a slicer opens a file with: the axis limits, and the
#: acceleration limits in their ``P``/``R``/``T`` form (a print's own
#: acceleration is ``M204 S`` and is never one of these).
_MACHINE_LIMIT_LINE = re.compile(r"^(?:M201|M203|M205|M204(?=[^;\n]*\b[PRT]))\b")
_MACHINE_LIMIT_PROGRESS = re.compile(r"^M73\b")
_EXECUTABLE_BLOCK_START = "; EXECUTABLE_BLOCK_START"


def _drop_unasked_machine_limits(gcode_path: str) -> int:
    """Take the run of machine-limit lines that opens the executable block
    out of *gcode_path*.

    For settings that did not ask for limits in the G-code, so the printer
    keeps its own.  A limit anywhere else (a start sequence's, a person's
    custom G-code) stays.  Returns the number of lines taken.
    """
    taken = 0
    tmp_path = f"{gcode_path}.limits"
    with open(gcode_path, encoding="utf-8", errors="surrogateescape", newline="") as src, open(
        tmp_path, "w", encoding="utf-8", errors="surrogateescape", newline=""
    ) as dst:
        in_opening = False
        for line in src:
            if in_opening:
                if _MACHINE_LIMIT_LINE.match(line):
                    taken += 1
                    continue
                if line.strip() and not _MACHINE_LIMIT_PROGRESS.match(line):
                    in_opening = False
                    dst.write(line)
                    dst.writelines(src)
                    break
            elif line.strip() == _EXECUTABLE_BLOCK_START:
                in_opening = True
            dst.write(line)
    if taken:
        os.replace(tmp_path, gcode_path)
    else:
        os.unlink(tmp_path)
    return taken


def slice_file(input_path: str, **kwargs: Any) -> SliceResult:
    """Slice a 3D model file to G-code (arguments: :func:`_slice_file`).

    The one place every slicing door passes through, so a slice that fails
    on a part smaller than anything a printer makes says why first: the
    slicer's own "No layers were detected" names no unit, and the file is
    most often a model exported in meters.  That sentence of the slicer's
    goes on to advise repairing the model, which is wrong for a file whose
    only fault is its unit, so it is said as what it means at that size;
    any other failure keeps the slicer's words.
    """
    from kiln.speed_by_height import SpeedByHeightError

    try:
        return _slice_file(input_path, **kwargs)
    except SpeedByHeightError:
        raise
    except (
        SlicerNotFoundError, MaterialNotPrintableError, SlicerRefusal, ProjectPlateError, NozzleMapError,
        SliceTimeLimitError,
    ):
        # A refusal is about where the print lands, never its unit, and a
        # door answers it by its kind: rewrapped, it would lose both.
        raise
    except SlicerError as exc:
        question = _units_question_for(input_path)
        if not question:
            raise
        if _NO_LAYERS.search(str(exc)):
            raise SlicerError(f"{question}  At that size the slicer found no layer to print.") from exc
        raise SlicerError(f"{question}  The slicer said: {_plain_words.said(exc)}") from exc


def take_project_plate(input_path: str, plate_number: int | None, profile: str | None) -> Any | None:
    """Plate *plate_number* of a several-plate project as a file of its own
    (:func:`kiln.project_plates.one_plate`), placed for *profile*'s bed;
    ``None`` for a file that is sliced as it is.

    The one way a slicing door meets a project's plates, so the door's own
    checks and this module's judge the same file.

    :raises ProjectPlateError: no plate named for a project that holds
        several, or the one named cannot be had.
    """
    from kiln.project_plates import PlateChoiceError, one_plate

    def bed() -> tuple[float, float, float, float] | None:
        # Read only when a plate is taken, and a profile Kiln cannot read
        # says nothing about the bed: the project's own is used.
        try:
            return _bed_xy_bounds_from_profile(profile)
        except (ValueError, KeyError):
            return None

    try:
        return one_plate(input_path, plate_number, bed=bed)
    except PlateChoiceError as exc:
        raise ProjectPlateError(_plain_words.sentence(exc), code=exc.code, plates=exc.plates) from exc


def say_project_plate(result: SliceResult, taken: Any | None) -> SliceResult:
    """*result* saying which plate of the project it is a slice of: on the
    result, and on its message, which every door shows."""
    if taken is not None and result.project_plate is None:
        result.project_plate = taken.to_dict()
        result.message = f"{result.message.rstrip('.')}. {taken.note}" if result.message else taken.note
    return result


#: What a project calls the volumes that never print, in plain words.
_NEVER_PRINTS = {
    "support_enforcer": "support enforcer",
    "support_blocker": "support blocker",
    "modifier_part": "modifier",
}
#: The one that changes the part's shape: left out, the print is another part.
_CUTS_A_SHAPE = "negative_part"


def _printed_parts_for_prusa(input_abs: str) -> tuple[str, dict[str, int]] | None:
    """*input_abs* as PrusaSlicer can read it: the parts that print and no
    others (:func:`kiln.project_plates.printed_parts_only`); ``None`` for a
    file with nothing to leave out.

    :raises SlicerError: the project cuts a shape out of a part.  Left out,
        the cut would not be made and the print would be a different part.
    """
    from kiln.project_plates import printed_parts_only

    only = printed_parts_only(input_abs)
    if only is not None and _CUTS_A_SHAPE in only[1]:
        raise SlicerError(
            f"{os.path.basename(input_abs)} cuts a shape out of a part with a negative part, which PrusaSlicer "
            "cannot read from a project. Slice it with Bambu Studio or OrcaSlicer, or make the cut in the "
            "project's own slicer and save the part again."
        )
    return only


def _say_left_out(result: SliceResult, left_out: dict[str, int]) -> SliceResult:
    """*result* saying which volumes of the project PrusaSlicer was not handed."""
    if left_out:
        # Named from Kiln's own words only: a kind is text from the file.
        listed = ", ".join(
            f"{int(count)} {_NEVER_PRINTS.get(kind, 'other volume')}{'s' if count != 1 else ''}"
            for kind, count in sorted(left_out.items())
        )
        note = f"Left out, because PrusaSlicer reads only the parts of a project that print: {listed}."
        result.message = f"{result.message.rstrip('.')}. {note}" if result.message else note
    return result


#: The slicer's words for a model too thin to cut into a single layer.
_NO_LAYERS = re.compile(r"no layers were detected", re.IGNORECASE)


def _several_nozzle_ini(
    profile: str | None, nozzles: dict[str, Any], several: Any, *, slots: int, asked_map: list[int] | None,
) -> str | None:
    """The settings file for a slice for more than one nozzle by a slicer
    of PrusaSlicer's kind (:func:`kiln.maker_slicer.several_nozzle_profile`).

    Such a slicer prints each filament from the nozzle of the same number,
    so a print with more filaments than nozzles used
    (``MORE_FILAMENTS_THAN_NOZZLES``) and a map that says otherwise
    (``NOZZLE_MAP_FIXED``) are refused before slicing.
    """
    from kiln.maker_slicer import several_nozzle_profile
    from kiln.slicer_profiles import nozzle_positions

    used = nozzle_positions(nozzles)
    if slots > used:
        raise NozzleMapError(
            f"This print uses {slots} filaments, and this printer prints each filament from a nozzle of its "
            f"own with {used} fitted, so nothing was sliced. Use {used} filaments or fewer, or record the "
            "other nozzles as fitted, and slice again.",
            code="MORE_FILAMENTS_THAN_NOZZLES",
        )
    if asked_map and asked_map != list(range(1, len(asked_map) + 1)):
        raise NozzleMapError(
            "On this printer filament 1 prints from nozzle 1, filament 2 from nozzle 2 and so on, and a "
            "different map cannot be sliced, so nothing was sliced. Load each filament on the nozzle of "
            "its number, or leave the map out, and slice again.",
            code="NOZZLE_MAP_FIXED",
        )
    return several_nozzle_profile(profile, nozzles, used, several.routines)


def _stand_the_tower(
    slic3r_input: str, slicer_profile: str | None, input_abs: str, scratch: str,
) -> tuple[str, str | None]:
    """*slic3r_input* and *slicer_profile* with the purge tower stood clear
    of the parts, for a slice whose settings ask for one: a copy of the 3MF
    naming the place (:func:`kiln.maker_slicer.with_tower_position`).  With
    no clear place on the bed, or a file that cannot carry one, the slice is
    made without a tower.  Anything else is returned as it was."""
    if not slicer_profile or not slic3r_input.lower().endswith(".3mf"):
        return slic3r_input, slicer_profile
    settings = ini_to_settings(slicer_profile)
    if str(settings.get("wipe_tower", "0")).strip() != "1":
        return slic3r_input, slicer_profile
    from kiln.maker_slicer import TOWER_SQUARE_MM, with_tower_position
    from kiln.slicer_profiles import profile_with_overrides

    try:
        width = float(settings.get("wipe_tower_width") or TOWER_SQUARE_MM)
    except ValueError:
        width = TOWER_SQUARE_MM
    xy = _wipe_tower_position(settings, input_abs, width)
    placed = os.path.join(scratch, f"tower_{Path(slic3r_input).name}")
    if xy is not None and with_tower_position(slic3r_input, placed, xy):
        return placed, slicer_profile
    logger.info("No clear place for a purge tower; slicing for more than one nozzle without one.")
    return slic3r_input, profile_with_overrides(
        slicer_profile, {"wipe_tower": "0"}, prefix=f"{Path(slicer_profile).stem}_", stated=False,
    )


def _units_question_for(path: str) -> str:
    """The units question *path*'s size raises (``kiln.printability``), or
    ``""`` when it raises none or cannot be measured."""
    try:
        from kiln.printability import units_question
        from kiln.printers.bed_fit import compute_mesh_bbox

        bbox = compute_mesh_bbox(path)
        return units_question(bbox) if bbox else ""
    except Exception:  # noqa: BLE001 - a size nobody can read asks nothing
        logger.debug("units question unavailable for %s", path, exc_info=True)
        return ""


def _supports_plastic(
    material: str | None, loaded_material: str | None, filament: SliceFilament | None = None,
) -> str | None:
    """The plastic a slice's support decision reads: the one named for the
    slice, else the spool the printer reports loaded, else one the profile
    itself states; ``None`` when nothing names one, so the decision reads
    the plastic a check assumes (:func:`kiln.material_limits.assuming`).

    The word as given, never the material table's row for it: the support
    decision reads it through the same design limits every other check
    reads, so a name they cannot place is said to be one here too, and two
    spellings of one plastic are one plastic."""
    for word in (material, loaded_material):
        if isinstance(word, str) and word.strip():
            return word
    if filament is not None and filament.source == SOURCE_PROFILE:
        return filament.filament_type or filament.material
    return None


#: The code of a slice refused because the settings for nozzles of
#: different sizes could not be had.
MIXED_SIZES_UNAVAILABLE = "MULTI_NOZZLE_MIXED_SIZES_UNAVAILABLE"


def mixed_size_nozzles(
    profile: str | None, nozzles: dict[str, Any], filament_map: list[int] | None,
) -> dict[str, Any]:
    """*nozzles* for one slice with its nozzles at different sizes: the same
    record with the preset extras Kiln's servers give for those sizes (and
    for *filament_map*, when the person chose one).

    Raises :class:`NozzleMapError` (:data:`MIXED_SIZES_UNAVAILABLE`) when
    they cannot be had -- this computer is offline, Kiln is signed out, the
    servers did not answer, or they said no -- and its ``why`` names which.
    Nothing is sliced on a guess.
    """
    from kiln import _pro_catalogue_bridge, served_answer
    from kiln.slicer_profiles import _sizes_said, mixed_sizes, profile_origin

    used = mixed_sizes(nozzles)
    printer_id = profile_origin(profile).printer_id if profile else None
    served, miss = _pro_catalogue_bridge.nozzles_for_sizes(
        printer_id, [n["diameter_mm"] for n in used], filament_map,
    )
    if served is None:
        miss = miss or served_answer.Miss("unanswered")
        error = NozzleMapError(
            served_answer.sentence(
                miss,
                feature="servers",
                on_the_line=f"This print would use nozzles of different sizes at once ({_sizes_said(used)})",
                cannot="get the slicer settings for those sizes",
                wont="sliced nothing",
                safe_remedy="Slice it with one filament for one nozzle, or fit nozzles of one size",
            ),
            code=MIXED_SIZES_UNAVAILABLE,
        )
        error.why = miss.cause  # type: ignore[attr-defined]
        raise error
    return {**nozzles, "preset_extras": served["preset_extras"]}


def _slice_file(
    input_path: str,
    *,
    output_dir: str | None = None,
    output_name: str | None = None,
    profile: str | None = None,
    slicer_path: str | None = None,
    extra_args: list[str] | None = None,
    timeout: int = SLICE_TIME_LIMIT_S,
    material: str | None = None,
    loaded_material: str | None = None,
    loaded_determined_by: str = LOADED_OBSERVED,
    plate_number: int | None = None,
    filament_map: Sequence[int] | str | None = None,
    soft_nozzle_confirmed: bool = False,
    mixed_nozzle_experiment: bool = False,
    speed_by_height: Any = None,
) -> SliceResult:
    """Slice a 3D model file to G-code.

    Args:
        speed_by_height: The person's own speeds for height ranges of the
            part (:func:`kiln.speed_by_height.checked` reads and refuses
            them).  The slicer applies them, the sliced file is read back,
            and the result's ``speed_by_height`` says what each range
            commands; a range the slicer did not apply refuses the slice
            (:class:`kiln.speed_by_height.SpeedByHeightError`).
        soft_nozzle_confirmed: The owner has said to print anyway a slice
            refused because an abrasive filament would print through a
            nozzle on record that is not wear-resistant
            (``ABRASIVE_ON_SOFT_NOZZLE``).  Only on their word.  The slice
            then runs, and the result's ``soft_nozzle`` and message say
            which filament goes through which nozzle on their say-so; the
            slice's record on this computer keeps it.
        mixed_nozzle_experiment: The person agreed, for this print, to try
            printing with nozzles of different sizes at once.  Without it a
            slice that would use nozzles of different sizes is refused.
            With it the slice is made only when the settings for those
            sizes can be had (:func:`mixed_size_nozzles`), and the result's
            ``experimental`` says so.  It changes nothing for any other
            slice.
        filament_map: For a printer sliced with more than one nozzle, the
            nozzle (1 for the first) each filament prints from, one entry
            per filament in filament order.  Left out, the slicer maps the
            filaments itself.  A map that does not fit the print or the
            printer, or one given for a printer sliced with one nozzle, is
            refused before slicing (:class:`NozzleMapError`).  The result's
            ``filament_map`` says which nozzle printed each filament.
        plate_number: Which plate to slice of a project that holds several
            (1 for the first).  Such a project is never sliced on a guess:
            with none named the slice is refused and the refusal lists the
            plates.  Leave unset for any other file.
        input_path: Path to the input file (STL, 3MF, STEP, OBJ, AMF).
        output_dir: Directory for the output G-code file.  Defaults to
            the system temp directory.
        output_name: Override the output file name.  Defaults to the
            input file's stem with ``.gcode`` extension.
        profile: Path to a slicer profile/config file (.ini or .json).
        slicer_path: Explicit slicer binary path.  Auto-detected if omitted.
        extra_args: Additional CLI arguments to pass to the slicer.
        timeout: Maximum slicing time in seconds (default 300).
        material: The filament material the caller declared for this slice
            (``"PETG"``, in any spelling).  Its density is what the slicer
            weighs the print with.
        loaded_material: The spool loaded on the target printer, when the
            door knows it (:func:`kiln.slicer_filament.loaded_filament_type`).
            Answers when nothing was declared.
        loaded_determined_by: Who decided *loaded_material* -- ``observed``
            when the door read the machine's own unit (the default),
            ``user_reported`` when it read Kiln's record of what a person
            loaded.  Chooses the words the result's note uses, never the
            density.

    Every slice leaves with a filament density: the profile is given one
    before either slicer runs (declared > loaded > the profile's own >
    PLA), and the result's ``filament`` says which.  See
    :mod:`kiln.slicer_filament`.

    Returns:
        A :class:`SliceResult` with the path to the generated G-code.

    Raises:
        SlicerError: If slicing fails.
        SlicerNotFoundError: If no slicer binary is found.
        FileNotFoundError: If the input file does not exist.
    """
    # Validate input
    input_abs = os.path.abspath(input_path)
    if not os.path.isfile(input_abs):
        raise FileNotFoundError(f"Input file not found: {os.path.basename(input_abs)}")

    ext = Path(input_abs).suffix.lower()
    if ext not in _INPUT_EXTENSIONS:
        raise SlicerError(f"Unsupported input format '{ext}'. Supported: {', '.join(sorted(_INPUT_EXTENSIONS))}")

    from kiln import _pro_speed_plan_bridge as _speed_plan
    from kiln import speed_by_height as _speed_by_height

    # ``"kiln"`` asks Kiln to choose the ranges; anything else is the
    # person's own.
    kiln_ask = _speed_plan.read_ask(speed_by_height)
    speed_ranges = [] if kiln_ask is not None else _speed_by_height.checked(speed_by_height)

    # A project of several plates is sliced one plate at a time: the plate
    # named is taken out as a file of its own, and that file is what every
    # check below and the slicer are handed.
    taken = take_project_plate(input_abs, plate_number, profile)
    if taken is not None:
        input_abs = taken.path

    from kiln.slicer_profiles import (
        MIXED_SIZES_CODE,
        mixed_size_experiment,
        mixed_size_parts,
        nozzle_bed,
        nozzle_positions,
        nozzle_record_of,
        nozzles_of,
        profile_with_overrides,
        rect_polygon,
        unused_fitted_note,
    )

    # A printer with a bed of its own for more than one nozzle has its 3MF
    # judged once the slice is known to be for one nozzle or more.
    if ext == ".3mf" and nozzle_bed(nozzles_of(profile)) is None:
        _check_3mf_on_bed(input_abs, profile)

    # Find slicer
    slicer = find_slicer(slicer_path)

    # Copies the slicer is asked to lay out itself are laid out FIRST, as a
    # plate Kiln can judge, and that plate is what is sliced: the duplicate
    # flag alone leaves out, silently, the copies that do not fit.
    # PrusaSlicer reads a project's geometry and not what each part of it
    # is, so it is handed the parts that print and no others.
    printed_only = _printed_parts_for_prusa(input_abs) if slicer_cli_family(slicer) == _CLI_PRUSA else None
    if slicer_cli_family(slicer) == _CLI_PRUSA:
        laid_out = _laid_out_copies(
            slicer, printed_only[0] if printed_only else input_abs, profile, extra_args, timeout=timeout,
        )
        if laid_out is not None:
            from kiln.slicer_layer import carry as _carry_layer

            _carry_layer(input_abs, laid_out[0])
            input_abs, extra_args = laid_out
            ext = ".3mf"
            _check_3mf_on_bed(input_abs, profile)

    # Does this input ask for more than one filament?  Asked ONCE here,
    # at the chokepoint every slicing door funnels through, and carried
    # to whichever backend runs — the answer costs an archive scan, and
    # both the backend choice below and the Orca preset expansion need
    # it.  Never raises: no evidence reads as single-filament.
    multicolor: dict[str, Any] | None = None
    if ext == ".3mf":
        from kiln.multicolor_3mf import detect_3mf_multicolor

        multicolor = detect_3mf_multicolor(input_abs)
    slots_needed = int((multicolor or {}).get("filament_slots_needed", 0))

    # A multicolor 3MF through the Slic3r dialect flattens to one filament:
    # Kiln's profiles are single-slot, and the PrusaSlicer command line has
    # no per-slot preset expansion the way the Orca dialect now does.  When
    # the slicer was AUTO-detected, prefer an installed Orca/BambuStudio for
    # this input — the user asked for their colors, not for a binary.  An
    # explicit slicer_path is an explicit choice and is honoured as given.
    # A slice for more than one nozzle: a printer whose record is sliced
    # that way, and a plate of two or more filaments or a map the caller
    # gave.  It is made by the slicer the record names.  With that slicer
    # missing or too old here, the plate is sliced for one nozzle, exactly as
    # a printer sliced with one nozzle is, and the result says so; a map
    # cannot be kept on one nozzle, so with a map it is refused.  One
    # filament with no map slices for one nozzle, as it does without the
    # record.
    nozzles = nozzles_of(profile)
    asked_map = checked_filament_map(
        filament_map, filaments=max(slots_needed, 1), positions=nozzle_positions(nozzles),
    )
    several_filaments = bool(asked_map) or slots_needed >= 2
    several = None
    instead: OneNozzleInstead | None = None
    would_use = 1
    printer = _printer_id_of(profile) if nozzles is not None and several_filaments else None
    if nozzles is not None and several_filaments:
        from kiln.maker_slicer import slicer_for_several_nozzles

        try:
            several = slicer_for_several_nozzles(nozzles, slicer, chosen=slicer_path is not None, profile=profile)
        except OneNozzleInstead as miss:
            if asked_map:
                raise NozzleMapError(
                    f"{_plain_words.said(miss)} A filament-to-nozzle map needs it too: leave the map out and Kiln slices this "
                    "print for one nozzle, with filament swaps.",
                    code=miss.code,
                ) from miss
            instead = miss
            would_use = nozzle_positions(nozzles)
    experimental: dict[str, Any] | None = None
    if several is not None and (mixed := mixed_size_parts(nozzles)):
        if mixed_nozzle_experiment is not True:
            raise NozzleMapError(mixed.message(), code=MIXED_SIZES_CODE, parts=mixed)
        experimental = mixed_size_experiment(nozzles)
        nozzles = mixed_size_nozzles(profile, nozzles, asked_map)
    if ext == ".3mf" and nozzle_bed(nozzles) is not None:
        wider = nozzle_bed_for_slice(input_abs, profile, asked_map, slots=slots_needed, maker_ready=instead is None)
        if wider is not None:
            # Checked and sliced on the bed the nozzles print on.
            profile = profile_with_overrides(
                profile, {"bed_shape": rect_polygon(wider)}, prefix=f"{Path(profile).stem}_", stated=False,
            )
        _check_3mf_on_bed(input_abs, profile)
    mappable = nozzles is not None and instead is None
    if nozzles is not None and (not several_filaments or instead is not None):
        nozzles = None
    # The owner fitted more nozzles than this slice uses: said once, with
    # the slice, when it prints more than one filament.
    unused_note = unused_fitted_note(nozzle_record_of(profile)) if several_filaments and instead is None else ""
    multicolor_switched = False
    if several is not None:
        if several.info.path != slicer.path:
            slicer = several.info
            multicolor_switched = slots_needed >= 2
        if slicer_cli_family(slicer) == _CLI_PRUSA:
            profile = _several_nozzle_ini(profile, nozzles, several, slots=slots_needed, asked_map=asked_map)
            if printed_only is None:
                printed_only = _printed_parts_for_prusa(input_abs)
    if (
        slicer_path is None
        and slots_needed >= 2
        and slicer_cli_family(slicer) == _CLI_PRUSA
        and profile_filament_slots(profile) < slots_needed
    ):
        alt = _find_bambu_dialect_slicer()
        if alt is not None:
            logger.info(
                "Multicolor 3MF needs %d filaments; switching from %s "
                "to %s to keep the colors.",
                slots_needed, slicer.path, alt.path,
            )
            slicer = alt
            multicolor_switched = True

    # A slice for one nozzle carries the printer's own routines the record
    # names for it when the slicer making it is the printer's maker's; made
    # by any other slicer it carries none, and the reply says what adds them.
    maker = None
    without_routines = None
    routines_printer = None
    if several is None and instead is None:
        from kiln.maker_slicer import Miss, slicer_for_layer_routines

        found = slicer_for_layer_routines(nozzle_record_of(profile), slicer, profile=profile)
        if isinstance(found, Miss):
            without_routines, routines_printer = found, _printer_id_of(profile)
        elif found is not None and slicer_cli_family(found.info) == _CLI_BAMBU:
            maker = found

    left_out: dict[str, int] = {}
    if printed_only is not None and slicer_cli_family(slicer) == _CLI_PRUSA:
        left_out = printed_only[1]
        if input_abs != printed_only[0] and Path(input_abs).name == Path(printed_only[0]).name:
            from kiln.slicer_layer import carry as _carry_layer

            _carry_layer(input_abs, printed_only[0])
            input_abs = printed_only[0]

    # "No profile" cannot mean "no preset" on the Orca dialect the way it
    # does for PrusaSlicer (see _slice_with_orca); Kiln's own generic
    # profile is the answer, resolved here so the identity below is written
    # onto it rather than onto nothing.  An overrides-only Kiln file is the
    # same case with a few keys on top: Orca given only those has no bed
    # and refuses ("no object is fully inside the print volume").
    if slicer_cli_family(slicer) == _CLI_BAMBU:
        profile = _whole_profile_for_orca(profile)

    # The filament identity, applied HERE -- the one place every slicing
    # door funnels through -- so a slice cannot leave without a density
    # whatever door it entered by.  The derived file keeps the printer
    # profile's name, so telemetry still counts the slice against the
    # printer and Orca's presets are still named for it.
    try:
        slicer_profile, filament = ensure_profile_filament(
            profile,
            material=material,
            loaded_type=loaded_material,
            loaded_determined_by=loaded_determined_by,
        )
    except MaterialRefused as exc:
        raise MaterialNotPrintableError(_plain_words.sentence(exc), code=exc.code, verdict=exc.verdict) from exc
    # Supports, decided at the same place for the same reason: a part the
    # printability engine says needs them was sliced without them by every
    # tool door, and the estimate was of that file.  A caller's statement
    # (a stated support_material, or their own profile) is read and kept.
    # A project keeps the supports its person saved in it.
    from kiln.project_plates import saved_supports

    saved = saved_supports(input_abs)
    slicer_profile, supports = ensure_profile_supports(
        slicer_profile, input_abs, material=_supports_plastic(material, loaded_material, filament),
        **({"project": saved} if saved else {}),
    )
    # Which nozzle the profile was written for, read from the profile itself
    # so every door's reply says it whichever door resolved the profile.
    from kiln.slicer_profiles import nozzle_fit_of

    nozzle = nozzle_fit_of(slicer_profile)
    # Every slice for a printer whose nozzle record states a material: an
    # abrasive filament on a nozzle that is not wear-resistant is refused.
    # The owner may say to print it anyway; the slice then carries it.
    soft_run = soft_nozzle_run(
        _slot_materials(input_abs, [material, filament.filament_type, filament.material], max(slots_needed, 1)),
        asked_map,
        nozzles=nozzles,
        fitted=[p for p in (nozzle or {}).get("positions") or () if p.get("fitted") is True],
        on_record=(nozzle or {}).get("nozzle_material"),
        mappable=mappable,
    )
    if soft_run is not None and soft_nozzle_confirmed is not True:
        raise NozzleMapError(soft_run.parts.message(), code=SOFT_NOZZLE_CODE, parts=soft_run.parts)
    # The layer height the part was designed in, decided here for the same
    # reason: a relief made in whole 0.2 mm layers printed at the profile's
    # 0.3 by every door and lost its levels.  A stated layer height is the
    # caller's and is kept; the reply says what the part gets either way.
    slicer_profile, layer = ensure_profile_layer(
        slicer_profile, input_abs, nozzle_mm=(nozzle or {}).get("diameter_mm"),
    )

    # Prepare output
    out_dir = output_dir or kiln_output_dir(_DEFAULT_OUTPUT_NAME)
    os.makedirs(out_dir, mode=0o700, exist_ok=True)

    if output_name:
        # Strict filename sanitisation: basename, null bytes, length, reserveds
        safe_name = output_name.replace("\x00", "")
        safe_name = os.path.basename(safe_name)
        if not safe_name or safe_name != output_name.replace("\x00", "") or safe_name in {".", ".."}:
            raise ValueError(
                f"output_name must be a plain filename without path separators "
                f"or traversal sequences, got: {output_name!r}"
            )
        if len(safe_name) > 255:
            raise ValueError(f"output_name too long ({len(safe_name)} chars, max 255)")
        out_file = os.path.join(out_dir, safe_name)
    else:
        stem = Path(input_abs).stem
        out_file = os.path.join(out_dir, f"{stem}.gcode")

    # Anything at out_file after the run must have been written BY the run.
    # The path is deterministic (input stem into a shared output dir), so a
    # previous slice of the same model leaves a complete-looking file here —
    # and without this unlink the crash-salvage check below would read that
    # STALE file and certify a slicer that died before writing anything as a
    # fresh success: the previous model's toolpath, headed for start_print.
    with contextlib.suppress(OSError):
        os.unlink(out_file)

    drawn = _drawn_mesh_for(input_abs)
    # A 3MF that carries its designed layer as the object's own setting is
    # handed over without it when this slice decided another layer: the
    # object's setting would win over the profile the reply names.
    sliced_input, layer_scratch = for_the_slicer(input_abs, layer)
    # OrcaSlicer and Bambu Studio do not read a STEP file from the command
    # line: they are handed Kiln's mesh of it, the one the slice is drawn as.
    if slicer_cli_family(slicer) == _CLI_BAMBU and ext in (".step", ".stp"):
        if drawn == input_abs:
            from kiln.maker_slicer import said_name as _said_name

            raise SlicerError(
                f"{_said_name(slicer)} can't open a STEP file by itself, and Kiln couldn't turn this one "
                "into a mesh on this computer, so it wasn't sliced. Export the part as STL or 3MF and slice "
                "that, or slice with PrusaSlicer, which reads STEP."
            )
        sliced_input = drawn
    # A slice that carries supports keeps them off the faces the verdict
    # said print on their own: the mesh goes over as a 3MF with those faces
    # painted as blockers, or a thread beside the shelf that needs supports
    # comes back with its grooves packed.
    # The 3MF stands where the slicer would have arranged the mesh, the
    # bed's centre: the profile's bed, or the bed the slicer uses when the
    # profile states none (:data:`_UNSTATED_BED`).
    # A part whose one reason for supports is a piece that starts on nothing
    # is asked for them under that piece alone: its faces painted to be
    # supported, and the slicer told to support only what is painted.  Only
    # when every one of them was painted; otherwise the slice keeps supports
    # on for the whole part, with the faces above kept clear.
    # A blocker stops a support starting on a face, not one that starts under
    # an overhang above it and fills what it passes on its way to the plate.
    # So a slice Kiln decided, with faces painted clear, asks for supports
    # that stand off the model, unless the caller stated the style.  The
    # painted faces go with the decision, placed as the slicer has them, so
    # the sliced file is read for support under them.  Parts that print in
    # place apart have the faces in the joints between them painted with
    # the rest and read the same way; joints that could not be painted are
    # said to be unread.
    from kiln.slicer_profiles import profile_origin, profile_with_overrides

    kept_off_scratch: str | None = None
    is_3mf = sliced_input.lower().endswith(".3mf")
    if (supports.kept_off or supports.under or supports.in_joints) and (is_3mf or sliced_input == input_abs):
        # A 3MF stands where it stands: its own copy, with the paint added.
        keep_xy = is_3mf or "--dont-arrange" in (extra_args or [])
        bed = None if keep_xy else (_bed_xy_bounds_from_profile(slicer_profile) or _UNSTATED_BED)
        kept_off_scratch = tempfile.mkdtemp(prefix="kiln_kept_off_")
        centre = None if bed is None else ((bed[0] + bed[2]) / 2.0, (bed[1] + bed[3]) / 2.0)
        unpainted = sliced_input
        under = None
        if supports.under and PAINTED_ONLY_KEY not in profile_origin(slicer_profile).stated:
            under = asked_under_input(sliced_input, supports, kept_off_scratch, bed_centre=centre)
        if under is not None:
            sliced_input, faces = under
            only_painted = {PAINTED_ONLY_KEY: "0"}
            slicer_profile = profile_with_overrides(
                slicer_profile, only_painted,
                prefix=f"{Path(slicer_profile).stem}_" if slicer_profile else None, stated=False,
            )
            supports = replace(supports, under_painted=faces, settings={**supports.settings, **only_painted})
        else:
            painted = kept_off_input(sliced_input, supports, kept_off_scratch, bed_centre=centre)
            if painted is not None:
                sliced_input, faces = painted
                supports = replace(supports, kept_off_painted=faces)
                own_style = STYLE_KEY in profile_origin(slicer_profile).stated
                if supports.decided_by == DECIDED_ANALYSIS and not own_style:
                    stand_off = {STYLE_KEY: STAND_OFF_STYLE}
                    slicer_profile = profile_with_overrides(
                        slicer_profile, stand_off,
                        prefix=f"{Path(slicer_profile).stem}_" if slicer_profile else None, stated=False,
                    )
                    supports = replace(supports, settings={**supports.settings, **stand_off})
        supports = placed_for_reading(unpainted, supports, bed_centre=centre)
    # OrcaSlicer and Bambu Studio leave a brim out where their normal supports
    # stand, Bambu Studio all of it.  A slice that asks for a brim round the
    # part and whose supports Kiln decided asks those slicers for supports
    # that stand off the model, which keep the brim; a style the caller
    # stated is theirs.  The sliced file is read for the brim either way.
    asked_brim = _asked_brim_mm(slicer_profile)
    if (asked_brim and supports.enabled and supports.decided_by == DECIDED_ANALYSIS
            and slicer_cli_family(slicer) == _CLI_BAMBU and STYLE_KEY not in supports.settings
            and STYLE_KEY not in profile_origin(slicer_profile).stated):
        stand_off = {STYLE_KEY: STAND_OFF_STYLE}
        slicer_profile = profile_with_overrides(
            slicer_profile, stand_off,
            prefix=f"{Path(slicer_profile).stem}_" if slicer_profile else None, stated=False,
        )
        supports = replace(supports, settings={**supports.settings, **stand_off})

    def _decided(out_path: str, *, with_profile: str | None, prepare: Any = None) -> SliceResult:
        return _slice_decided(
            slicer, input_abs, sliced_input, out_path, ext=ext, input_path=input_path,
            profile=profile, slicer_profile=with_profile, extra_args=extra_args, timeout=timeout,
            multicolor=multicolor, multicolor_switched=multicolor_switched, drawn=drawn,
            filament=filament, nozzle=nozzle, supports=supports, layer=layer,
            nozzles=nozzles, filament_map=asked_map, several=several, maker=maker, prepare=prepare,
        )

    def _with_ranges() -> SliceResult:
        # A mesh is placed where the slicer would have arranged it, the
        # bed's centre; one the caller placed stays where it is.
        placed = "--dont-arrange" in (extra_args or [])
        bambu = slicer_cli_family(slicer) == _CLI_BAMBU
        bed = None if placed else _bed_xy_bounds_from_profile(slicer_profile)
        if bed is None and not placed and not sliced_input.lower().endswith(".3mf"):
            raise _speed_by_height.SpeedByHeightError(
                "Speed ranges need the printer's bed to place the part on, and this slice has no profile that "
                "states one. Name the printer, or slice without `speed_by_height`."
            )
        centre = None if bed is None else ((bed[0] + bed[2]) / 2.0, (bed[1] + bed[3]) / 2.0)

        def _run(out_path: str, *, prepare: Any, first_layer_speed: float | None = None, record: bool) -> SliceResult:
            with_profile = slicer_profile
            if first_layer_speed is not None:
                slower = f"{round(first_layer_speed, 2):g}"
                with_profile = profile_with_overrides(
                    slicer_profile,
                    {"first_layer_speed": slower},
                    prefix=f"{Path(slicer_profile).stem}_" if slicer_profile else None, stated=False,
                )
            quiet = _unrecorded.set(not record)
            try:
                return _decided(
                    out_path, with_profile=with_profile,
                    prepare=lambda path, out_dir: prepare(path, out_dir, centre),
                )
            finally:
                _unrecorded.reset(quiet)

        from kiln.maker_slicer import is_slicer

        slicer_id = next(
            (name for name in ("bambu_studio", "orcaslicer", "prusaslicer") if is_slicer(name, slicer)),
            "orcaslicer" if bambu else "prusaslicer",
        )
        return _speed_by_height.sliced(
            speed_ranges,
            family=_speed_by_height.BAMBU if bambu else _speed_by_height.PRUSA,
            out_file=out_file, run=_run,
            planner=None if kiln_ask is None else _speed_plan.planner(
                sliced_input, slicer_id=slicer_id, ask={"material": material, **kiln_ask},
            ),
            eases_acceleration=slicer_id == "bambu_studio",
        )

    def _sliced() -> SliceResult:
        if speed_ranges or kiln_ask is not None:
            return _with_ranges()
        return _decided(out_file, with_profile=slicer_profile)

    try:
        made = _sliced()
        # Supports asked for under one piece, and the slicer laid none: the
        # piece starts too low for a support with a gap over it.  The slice
        # is made once more with the gap closed, unless the caller stated
        # the gap; the first run is the one counted.
        if (supports.under_painted and made.supports is not None and made.supports.placed_none
                and CONTACT_KEY not in profile_origin(slicer_profile).stated):
            closed = {CONTACT_KEY: "0"}
            slicer_profile = profile_with_overrides(
                slicer_profile, closed,
                prefix=f"{Path(slicer_profile).stem}_" if slicer_profile else None, stated=False,
            )
            supports = replace(supports, settings={**supports.settings, **closed}, joined=True)
            quiet = _unrecorded.set(True)
            try:
                made = _sliced()
            finally:
                _unrecorded.reset(quiet)
        # A brim that reaches from one piece of a part printed in place to
        # another joins them at the bed.  The first layer is read for it: a
        # profile Kiln wrote is given the widest brim that keeps out of the
        # gap between them, or none where none fits, and the slice is made
        # once more and read again; a person's own profile is left as it is.
        # The answer says which, either way.
        brim_join: BrimJoin | None = None
        brim_kept: float | None = None
        brim_again: BrimJoin | None = None
        if asked_brim and made.success and made.output_path:
            brim_join = brim_joins_pieces(
                made.output_path, drawn, asked_brim, apart=True if supports.parts_apart else None,
            )
            if brim_join is not None and brim_join.joined and profile_origin(slicer_profile).kiln:
                brim_kept = brim_join.keep_mm
                slicer_profile = profile_with_overrides(
                    slicer_profile, {"brim_width": f"{brim_kept:g}"},
                    prefix=f"{Path(slicer_profile).stem}_" if slicer_profile else None, stated=False,
                )
                quiet = _unrecorded.set(True)
                try:
                    made = _sliced()
                finally:
                    _unrecorded.reset(quiet)
                if brim_kept and made.success and made.output_path:
                    brim_again = brim_joins_pieces(made.output_path, drawn, brim_kept, apart=True)
        result = _say_left_out(say_project_plate(made, taken), left_out)
        _say_brim_joined(result, asked_brim, brim_join, brim_kept, brim_again)
        if brim_kept != 0.0:
            _say_brim_left_out(result, brim_kept or asked_brim, slicer, slicer_profile)
        if unused_note:
            result.message = f"{result.message} {unused_note}".strip()
        if soft_run is not None:
            _say_soft_nozzle(result, soft_run)
        if experimental:
            result.experimental = experimental
            result.message = f"{result.message} {experimental['note']}".strip()
        from kiln import maker_slicer_notes

        if without_routines is not None:
            maker_slicer_notes.after_layer_routines(
                result, printer=routines_printer, miss=without_routines, made_with=slicer,
            )
        return maker_slicer_notes.after_slice(
            result, printer=printer, miss=instead.miss if instead else None, nozzles=would_use,
            colours=slots_needed, profile=profile,
        )
    finally:
        for scratch in (layer_scratch, kept_off_scratch):
            if scratch is not None:
                shutil.rmtree(scratch, ignore_errors=True)


def _asked_brim_mm(profile: str | None) -> float:
    """How wide a brim round the part *profile* asks for; 0 for none or for
    a profile that cannot be read."""
    if not profile:
        return 0.0
    try:
        return outside_brim_mm(ini_to_settings(profile))
    except (OSError, UnicodeDecodeError, ValueError):
        return 0.0


#: Brim samples are read this far apart along each brim line, in mm.
_BRIM_SAMPLE_MM = 0.25
#: A brim narrowed to stay out of the gap between two pieces is rounded down
#: to this step, in mm.
_BRIM_STEP_MM = 0.1
#: The most (brim sample, outline segment) pairs measured at once, and laid
#: out in all; a part that needs more is not read for its brim.
_BRIM_PAIRS_PER_PASS = 400_000
_BRIM_CELL_PAIRS_MAX = 4_000_000


@dataclass(frozen=True)
class BrimJoin:
    """What the first layer of a sliced file shows of its brim between two
    pieces of a part printed in place apart."""

    #: Whether the brim reaches from one piece to another.
    joined: bool
    #: How far apart, at the bed, the narrowest two pieces it joins stand,
    #: in mm; ``None`` when it joins none.
    gap_mm: float | None = None
    #: The widest brim that keeps out of that gap, in mm: 0 when no brim
    #: fits there without joining the two.
    keep_mm: float = 0.0


def brim_joins_pieces(
    gcode_path: str, input_path: str, reach_mm: float, *, apart: bool | None = None,
) -> BrimJoin | None:
    """Whether the brim in *gcode_path*'s first layer joins two pieces of the
    part in *input_path* that print in place apart.

    The pieces are the part's separate solids, read at the height of the
    first layer and placed where the file's own footprint of the part puts
    them; the brim is the file's own brim lines (:mod:`kiln.slicer_geometry`
    tells a brim from a skirt).  A brim line that lies between two pieces,
    with one on each side of it and each within *reach_mm* (the brim's
    width), is in the brims of both at once: the slicer fills a brim with
    lines laid side by side, so there the brim runs from one piece to the
    other.  A brim round the outside that only meets two pieces at their
    outer edges, and one that never reaches a piece standing in another's
    hole, join nothing.  *apart* is the caller's reading of whether the
    pieces print in place apart (``None`` reads it here).

    ``BrimJoin(joined=False)`` when the brim joins no two pieces, the part
    is one piece, or its pieces do not print in place apart; ``None`` when
    the file or the part cannot be read for it.
    """
    import numpy as np

    from kiln.slicer_geometry import DEFAULT_LINE_WIDTH_MM, parse_slicer_features
    from kiln.slicer_supports import shift_to_footprint

    try:
        parsed = parse_slicer_features(gcode_path)
    except (OSError, ValueError):
        return None
    brim = parsed.buckets.get("brim")
    if brim is None or not brim.segments:
        return BrimJoin(joined=False)
    segs = np.asarray(brim.segments, dtype=np.float64).reshape(-1, 6)
    first = segs[:, 2] <= segs[:, 2].min() + 0.01
    segs = segs[first]
    pieces = _first_layer_pieces(input_path, float(segs[:, 2].min()) / 2.0, apart=apart)
    if pieces is None:
        return None
    outline, solid, box = pieces
    if outline is None:
        return BrimJoin(joined=False)
    shift = shift_to_footprint(parsed, box)
    if shift is None:
        return None
    outline = outline + np.asarray(shift, dtype=np.float64)
    width = max(brim.widths, key=brim.widths.get) if brim.widths else DEFAULT_LINE_WIDTH_MM
    points = _along(segs, _BRIM_SAMPLE_MM)
    between = _between_two_pieces(points, outline, solid, reach_mm)
    if between is None:
        return None
    if not between.size:
        return BrimJoin(joined=False)
    # The gap where the brim lies between them, read across it.
    gap = float(between.min())
    # Two brims a line apart do not touch: each reaches half of what is left.
    steps = int(max(0.0, (gap - width) / 2.0) / _BRIM_STEP_MM + 1e-9)
    keep = round(steps * _BRIM_STEP_MM, 1)
    return BrimJoin(joined=True, gap_mm=gap, keep_mm=keep if keep >= width else 0.0)


def _along(segs: Any, step: float) -> Any:
    """Points every *step* mm along each segment of *segs* (rows of x0, y0,
    z0, x1, y1, z1), both ends included: rows of x, y."""
    import numpy as np

    a, b = segs[:, 0:2], segs[:, 3:5]
    n = np.maximum(1, np.ceil(np.linalg.norm(b - a, axis=1) / step).astype(np.int64))
    which = np.repeat(np.arange(len(segs)), n + 1)
    t = (np.arange(which.size) - np.repeat(np.cumsum(n + 1) - (n + 1), n + 1)) / n[which]
    return a[which] + (b - a)[which] * t[:, None]


def _first_layer_pieces(input_path: str, height: float, *, apart: bool | None) -> tuple[Any, Any, Any] | None:
    """The outline of each separate solid of *input_path* at *height* mm over
    the plate, as segments ``(S, 2, 2)`` in the part's own XY, the solid each
    belongs to, and the part's XY box: what the brim is read against.  The
    outline is ``None`` when the part is one solid or its solids do not
    print in place apart; ``None`` in all when the part cannot be read."""
    import numpy as np

    from kiln.mesh_bodies import read_triangles
    from kiln.printability import _parse_mesh, _parts_stand_apart, _prepare_parsed

    try:
        facets, vertices = _parse_mesh(input_path)
        triangles = _prepare_parsed(list(facets), vertices)[0]
        tris = np.asarray(triangles, dtype=np.float64).reshape(-1, 3, 3)
        reading = read_triangles(tris)
    except (OSError, ValueError, MemoryError):
        logger.debug("pieces not read for the brim", exc_info=True)
        return None
    if len(tris) == 0 or not np.isfinite(tris).all():
        return None
    lo, hi = tris[:, :, :2].reshape(-1, 2).min(axis=0), tris[:, :, :2].reshape(-1, 2).max(axis=0)
    box = (float(lo[0]), float(lo[1]), float(hi[0]), float(hi[1]))
    piece = np.asarray(reading.face_piece, dtype=np.int64)
    solid_of = np.asarray(reading.solid_of or range(reading.piece_count), dtype=np.int64)
    if piece.shape[0] != len(tris) or solid_of.size == 0:
        return None
    solid = np.where(piece >= 0, solid_of[np.clip(piece, 0, None)], -1)
    if np.unique(solid[solid >= 0]).size < 2:
        return None, None, box
    if apart is None:
        apart = _parts_stand_apart(list(triangles), reading)
    if not apart:
        return None, None, box
    level = float(tris[:, :, 2].min()) + height + 1e-6
    d = tris[:, :, 2] - level
    crossing = (d.min(axis=1) < 0.0) & (d.max(axis=1) > 0.0) & (solid >= 0)
    t, dd = tris[crossing], d[crossing]
    ends = []
    for i, j in ((0, 1), (1, 2), (2, 0)):
        cut = (dd[:, i] < 0.0) != (dd[:, j] < 0.0)
        f = np.where(cut, dd[:, i] / np.where(cut, dd[:, i] - dd[:, j], 1.0), 0.0)
        ends.append((t[:, i, :2] + (t[:, j, :2] - t[:, i, :2]) * f[:, None], cut))
    points = np.stack([p for p, _cut in ends], axis=1)
    cuts = np.stack([c for _p, c in ends], axis=1)
    two = cuts.sum(axis=1) == 2
    order = np.argsort(~cuts[two], axis=1, kind="stable")[:, :2]
    outline = np.take_along_axis(points[two], order[:, :, None], axis=1)
    return outline, solid[crossing][two], box


def _between_two_pieces(points: Any, outline: Any, solid: Any, reach: float) -> Any | None:
    """The distance across, from one piece to the other, at each of
    *points* that lies between two pieces: its two nearest pieces' outlines
    are each within *reach* of it, on opposite sides of it.  ``None`` when
    that is more than this reads.  The outline's segments are laid out by
    the cells their reach covers, so each point is measured against the few
    that can reach it."""
    import numpy as np

    if len(points) == 0 or len(outline) == 0:
        return np.zeros(0)
    cell = max(reach, 0.5)
    lo = np.floor((outline.min(axis=1) - reach) / cell).astype(np.int64)
    span = np.floor((outline.max(axis=1) + reach) / cell).astype(np.int64) - lo + 1
    count = span.prod(axis=1)
    total = int(count.sum())
    if total > _BRIM_CELL_PAIRS_MAX:
        return None
    which = np.repeat(np.arange(len(outline)), count)
    step = np.arange(total) - np.repeat(np.cumsum(count) - count, count)
    cells = lo[which] + np.stack([step // span[which, 1], step % span[which, 1]], axis=1)
    p_cell = np.floor(points / cell).astype(np.int64)
    origin = np.minimum(cells.min(axis=0), p_cell.min(axis=0))
    width = int(max(cells[:, 1].max(), p_cell[:, 1].max()) - origin[1] + 1)
    keys = (cells[:, 0] - origin[0]) * width + (cells[:, 1] - origin[1])
    p_keys = (p_cell[:, 0] - origin[0]) * width + (p_cell[:, 1] - origin[1])
    order = np.argsort(keys, kind="stable")
    keys, by_key = keys[order], which[order]
    start = np.searchsorted(keys, p_keys, side="left")
    many = np.searchsorted(keys, p_keys, side="right") - start
    todo = np.flatnonzero(many > 0)
    across: list[Any] = []
    at = 0
    while at < todo.size:
        stop = at + 1
        budget = int(many[todo[at]])
        while stop < todo.size and budget + int(many[todo[stop]]) <= _BRIM_PAIRS_PER_PASS:
            budget += int(many[todo[stop]])
            stop += 1
        chunk = todo[at:stop]
        at = stop
        point_of = np.repeat(chunk, many[chunk])
        offset = np.arange(point_of.size) - np.repeat(np.cumsum(many[chunk]) - many[chunk], many[chunk])
        seg = by_key[start[point_of] + offset]
        a, b = outline[seg, 0], outline[seg, 1]
        ab = b - a
        t = np.clip(((points[point_of] - a) * ab).sum(axis=1) / np.maximum((ab * ab).sum(axis=1), 1e-12), 0.0, 1.0)
        toward = a + ab * t[:, None] - points[point_of]
        dist = np.linalg.norm(toward, axis=1)
        near = dist <= reach
        point_of, owner, dist, toward = point_of[near], solid[seg[near]], dist[near], toward[near]
        if point_of.size == 0:
            continue
        # Each point's nearest stretch of each piece, then its two nearest pieces.
        by = np.lexsort((dist, owner, point_of))
        point_of, owner, dist, toward = point_of[by], owner[by], dist[by], toward[by]
        head = np.r_[True, (np.diff(point_of) != 0) | (np.diff(owner) != 0)]
        point_of, dist, toward = point_of[head], dist[head], toward[head]
        by = np.lexsort((dist, point_of))
        point_of, dist, toward = point_of[by], dist[by], toward[by]
        lead = np.r_[True, np.diff(point_of) != 0]
        runner = np.r_[False, (np.diff(point_of) == 0) & lead[:-1]]
        second = np.flatnonzero(runner)
        first = second - 1
        opposite = (toward[first] * toward[second]).sum(axis=1) < 0.0
        across.append(dist[first][opposite] + dist[second][opposite])
    return np.concatenate(across) if across else np.zeros(0)


def _say_brim_joined(
    result: SliceResult, asked_mm: float, join: BrimJoin | None, kept_mm: float | None, again: BrimJoin | None,
) -> None:
    """Say on *result* what the first layer showed of a brim *asked_mm* wide
    between two pieces of a part printed in place apart (*join*), and what
    the slice did about it: drew it *kept_mm* wide, read once more as
    *again*, or left it off at 0; ``None`` for a person's own profile, left
    as it is.  Nothing is said when the brim joins no two pieces."""
    if not asked_mm or not result.success:
        return
    if join is None:
        said = ("Whether the brim runs into the gap between two pieces of the part could not be read from the "
                "sliced file, so look at the first layer in the slicer before printing.")
        result.brim = {"asked_mm": asked_mm, "joins_pieces": None, "said": said}
        result.message = f"{result.message} {said}".strip()
        return
    if not join.joined:
        return
    gap = "" if join.gap_mm is None else f", which stand {join.gap_mm:.1f} mm apart at the bed,"
    into = f"into the gap between two of the part's pieces{gap} and can stick them together there"
    if kept_mm is None:
        fix = (f"Set `brim_width` to {join.keep_mm:g} mm or less before printing." if join.keep_mm
               else "Set `brim_width` to 0 before printing: no brim fits in that gap.")
        said = f"The {asked_mm:g} mm brim in your profile runs {into}. {fix}"
        drawn, joins = asked_mm, True
    elif not kept_mm:
        said = (f"The {asked_mm:g} mm brim asked for would run {into}. No brim fits in that gap, so this slice "
                "has none: the part is held by its own footprint alone.")
        drawn, joins = 0.0, False
    elif again is not None and not again.joined:
        said = (f"The {asked_mm:g} mm brim asked for would run {into}, so it is drawn {kept_mm:g} mm wide, which "
                "keeps it out of that gap.")
        drawn, joins = kept_mm, False
    elif again is not None:
        said = (f"The {asked_mm:g} mm brim asked for would run {into}. It is drawn {kept_mm:g} mm wide, and the "
                "sliced file still shows brim in that gap, so look at the first layer in the slicer before printing.")
        drawn, joins = kept_mm, True
    else:
        said = (f"The {asked_mm:g} mm brim asked for would run {into}, so it is drawn {kept_mm:g} mm wide. "
                "Whether that keeps it out of the gap could not be read from the sliced file, so look at the "
                "first layer in the slicer before printing.")
        drawn, joins = kept_mm, None
    result.brim = {"asked_mm": asked_mm, "drawn_mm": drawn, "joins_pieces": joins, "said": said}
    result.message = f"{result.message} {said}".strip()


def _say_brim_left_out(result: SliceResult, asked_mm: float, slicer: SlicerInfo, profile: str | None) -> None:
    """Say on *result* that the sliced file draws no brim, when the slice
    asked for one *asked_mm* wide round the part.

    The file is read by its own feature labels.  A file with a brim, or one
    whose labels cannot be read, is left as it is: nothing is claimed either
    way.  Never raises.
    """
    if not asked_mm or not result.success or not result.output_path:
        return
    try:
        from kiln.maker_slicer import said_name
        from kiln.slicer_geometry import parse_slicer_features

        parsed = parse_slicer_features(result.output_path)
        if not parsed.labelled or "brim" in parsed.buckets:
            return
        name = said_name(slicer)
        supports = result.supports
        beside_supports = (
            slicer_cli_family(slicer) == _CLI_BAMBU and supports is not None and supports.enabled
            and ini_to_settings(profile).get(STYLE_KEY, "").strip().lower() != STAND_OFF_STYLE
        )
        if beside_supports:
            fix = (
                f"{name} leaves the brim out beside the supports it builds this way. Tree supports keep it "
                "(`support_material_style=organic`, through reslice_with_overrides), and so does slicing "
                "without supports."
            )
        else:
            fix = "Look at the first layer in the slicer before printing: the part is held by its own footprint alone."
        said = f"The sliced file has no brim, though a {asked_mm:g} mm brim was asked for. {fix}"
    except Exception:  # noqa: BLE001 -- a file that cannot be read claims nothing
        logger.debug("the sliced file's brim could not be read", exc_info=True)
        return
    result.brim = {"asked_mm": asked_mm, "drawn": False, "said": said}
    result.message = f"{result.message} {said}".strip()


def _say_sliced_with(result: SliceResult, several: Any) -> SliceResult:
    """*result* naming the maker's slicer a slice was made with (*several*),
    and the sliced file's record keeping it
    (:func:`kiln.print_lineage.note_sliced_with`).  With none, *result* is
    returned as it was."""
    if several is None:
        return result
    result.sliced_with = dict(several.sliced_with)
    try:
        from kiln.print_lineage import note_sliced_with

        note_sliced_with(result.output_path, result.sliced_with)
    except Exception:  # noqa: BLE001 -- a record never costs a slice
        logger.debug("slicer not noted for %s", result.output_path, exc_info=True)
    return result


def _say_soft_nozzle(result: SliceResult, run: SoftNozzleRun) -> None:
    """*result*, sliced on the owner's say-so though *run* refused it: its
    ``soft_nozzle`` block and message say so, and the slice's record keeps
    it (:func:`kiln.print_lineage.note_soft_nozzle`)."""
    stated = (result.filament_map or {}).get("filament_to_nozzle")
    block = run.confirmed(stated if isinstance(stated, list) else None)
    if block is None:
        return
    result.soft_nozzle = block
    result.message = f"{result.message} {block['said']}".strip()
    try:
        from kiln.print_lineage import note_soft_nozzle

        note_soft_nozzle(result.output_path, block)
    except Exception:  # noqa: BLE001 -- a record never costs a slice
        logger.debug("soft-nozzle confirmation not kept with the slice", exc_info=True)


def _slice_decided(
    slicer: SlicerInfo,
    input_abs: str,
    sliced_input: str,
    out_file: str,
    *,
    ext: str,
    input_path: str,
    profile: str | None,
    slicer_profile: str | None,
    extra_args: list[str] | None,
    timeout: int,
    multicolor: dict[str, Any] | None,
    multicolor_switched: bool,
    drawn: str | None,
    filament: Any,
    nozzle: dict[str, Any] | None,
    supports: Any,
    layer: SliceLayer | None,
    nozzles: dict[str, Any] | None = None,
    filament_map: list[int] | None = None,
    several: Any = None,
    maker: Any = None,
    prepare: Any = None,
) -> SliceResult:
    """Run the slicer on *sliced_input* with everything :func:`_slice_file`
    decided; *input_abs* is the part as the caller named it.  *prepare*,
    when given, is called with the file about to be handed to the slicer
    and a scratch folder, and returns the file to hand over in its place
    (:func:`kiln.speed_by_height.sliced`).  *several* is
    the slicer chosen for a slice for more than one nozzle, and *maker* the
    printer's maker's slicer making a slice for one nozzle with the
    printer's own routines (:class:`kiln.maker_slicer.SeveralNozzleSlicer`
    either way): its routines go into the machine preset, and the result
    and the sliced file's record say which slicer it was."""
    chosen = several if several is not None else maker
    # Two command lines, one function.  Everything below this point is the
    # Slic3r dialect; an Orca/BambuStudio binary needs a different argv AND a
    # different preset format, so it gets its own runner rather than a flag
    # swap.  The branch is here — at the one place all twelve slicing doors
    # funnel through — so none of them has to know which slicer is installed.
    if slicer_cli_family(slicer) == _CLI_BAMBU:
        prepared_dir = tempfile.mkdtemp(prefix="kiln_prepared_") if prepare is not None else None
        try:
            result = _slice_with_orca(
                slicer,
                sliced_input if prepare is None else prepare(sliced_input, prepared_dir),
                out_file,
                profile=slicer_profile,
                extra_args=extra_args,
                timeout=timeout,
                multicolor=multicolor,
                drawn_as=drawn,
                # Named only for a slice for more than one nozzle, and for one
                # carrying the printer's own routines read from its maker's slicer.
                **({"nozzles": nozzles, "filament_map": filament_map} if nozzles else {}),
                **({"routines": chosen.routines} if chosen is not None else {}),
                **({"part_path": sliced_input} if prepare is not None else {}),
            )
        finally:
            if prepared_dir is not None:
                shutil.rmtree(prepared_dir, ignore_errors=True)
        result.filament = filament
        result.nozzle = nozzle
        result.supports = witnessed(supports, result.output_path)
        result.layer = layer_witnessed(layer, result.output_path)
        result.stage_mesh_path = drawn
        if multicolor_switched:
            result.message += (
                f" (multicolor 3MF: auto-selected "
                f"{os.path.basename(slicer.path)} to keep the colors)"
            )
        return _say_sliced_with(result, chosen)

    # PrusaSlicer reads each component of a joined object as an object of
    # its own, so a 3MF whose objects hold several parts is handed over in
    # PrusaSlicer's own multi-part form (one object, one volume per part).
    slic3r_input = sliced_input
    parts_dir: str | None = None
    if ext == ".3mf":
        from kiln.multicolor_3mf import prusa_multipart_copy

        parts_dir = tempfile.mkdtemp(prefix="kiln_prusa_parts_")
        joined_copy = os.path.join(parts_dir, Path(input_abs).name)
        if prusa_multipart_copy(sliced_input, joined_copy):
            slic3r_input = joined_copy
        if several is not None:
            slic3r_input, slicer_profile = _stand_the_tower(slic3r_input, slicer_profile, input_abs, parts_dir)
    if prepare is not None and parts_dir is None:
        parts_dir = tempfile.mkdtemp(prefix="kiln_prusa_parts_")
    try:
        if prepare is not None:
            prepared_dir = os.path.join(parts_dir, "prepared")
            os.makedirs(prepared_dir, exist_ok=True)
            slic3r_input = prepare(slic3r_input, prepared_dir)
        result = _slice_with_slic3r(
            slicer,
            input_abs,
            slic3r_input,
            out_file,
            profile=profile,
            slicer_profile=slicer_profile,
            extra_args=extra_args,
            timeout=timeout,
            filament=filament,
            nozzle=nozzle,
            supports=supports,
            drawn=drawn,
            input_path=input_path,
        )
        result.layer = layer_witnessed(layer, result.output_path)
        if several is not None:
            # Each filament printed from the nozzle of its own number.
            slots = max(int((multicolor or {}).get("filament_slots_needed", 0)), 1)
            several = replace(
                several, sliced_with={**several.sliced_with, "filament_to_nozzle": list(range(1, slots + 1))},
            )
        return _say_sliced_with(result, several)
    finally:
        if parts_dir is not None:
            shutil.rmtree(parts_dir, ignore_errors=True)


def _slice_with_slic3r(
    slicer: SlicerInfo,
    input_abs: str,
    slic3r_input: str,
    out_file: str,
    *,
    profile: str | None,
    slicer_profile: str | None,
    extra_args: list[str] | None,
    timeout: int,
    filament: SliceFilament,
    nozzle: dict[str, Any] | None,
    supports: SliceSupports,
    drawn: str | None,
    input_path: str,
) -> SliceResult:
    """The PrusaSlicer-dialect run of :func:`slice_file`.

    *slic3r_input* is the file handed to the slicer (*input_abs*, or its
    multi-part copy); everything recorded and reported names *input_abs*.
    """
    # Build command
    cmd: list[str] = [
        slicer.path,
        "--export-gcode",
        slic3r_input,
        "--output",
        out_file,
    ]

    if slicer_profile:
        if not os.path.isfile(slicer_profile):
            raise SlicerError(f"Profile file not found: {os.path.basename(slicer_profile)}")
        cmd.extend(["--load", slicer_profile])

    if extra_args:
        cmd.extend(extra_args)

    logger.info("Slicing: %s", " ".join(cmd))

    def _drop_partial_out_file() -> None:
        with contextlib.suppress(OSError):
            os.unlink(out_file)

    result = _run_slicer_with_startup_retry(
        cmd,
        timeout=timeout,
        retryable_returncodes=_SLIC3R_STARTUP_CRASH_RETURNCODES,
        remove_partial_output=_drop_partial_out_file,
        output_is_complete=lambda: _gcode_output_is_complete(out_file),
    )

    crashed_after_finishing = (
        result.returncode != 0
        and result.returncode < 0  # killed by a signal, not a reported error
        and _gcode_output_is_complete(out_file)
    )
    if result.returncode != 0 and not crashed_after_finishing:
        stderr_snippet = (result.stderr or "").strip()[:500]
        logger.warning("slicer exited %s: %s", result.returncode, stderr_snippet)
        said = f" It said: {stderr_snippet}" if stderr_snippet else ""
        what = "crashed" if result.returncode < 0 else "stopped with an error"
        raise SlicerError(f"The slicer {what} and made no file.{said}")

    # Verify output exists.  PrusaSlicer can exit 0 without writing — e.g.
    # "All objects are outside of the print volume." — and it says why on
    # STDERR; a message that omitted stderr turned that specific reason
    # into a generic mystery.
    if not os.path.isfile(out_file):
        reason = (result.stderr or "").strip() or (result.stdout or "").strip()
        if dict(_ORCA_REFUSAL_WORDS)[REFUSED_LAYER_TOO_TALL].search(reason):
            raise _layer_too_tall(os.path.basename(slicer.path))
        raise SlicerError(
            f"Slicer completed but output file was not created. "
            f"Slicer said: {reason[:500] if reason else '(no output)'}"
        )

    _record_slice(profile, input_abs, out_file, drawn_as=drawn)

    message = f"Sliced {Path(input_abs).name} -> {Path(out_file).name}"
    if crashed_after_finishing:
        message += (
            f" (the slicer crashed on exit AFTER writing complete G-code — "
            f"signal {-result.returncode}; the output was verified complete "
            f"and kept)"
        )
    # The colour the part was asked to be shown -- and printed -- in follows
    # the file it was sliced into, so the print door that reads the G-code
    # still knows it (kiln.declared_color).
    try:
        from kiln.declared_color import carry as _carry_colour

        _carry_colour(input_path, out_file)
    except Exception:  # noqa: BLE001 -- a note never costs a slice
        logger.debug("colour note not carried to %s", out_file, exc_info=True)
    return SliceResult(
        success=True,
        output_path=out_file,
        slicer=slicer.name,
        message=message,
        stdout=(result.stdout or "").strip(),
        stderr=(result.stderr or "").strip(),
        filament=filament,
        nozzle=nozzle,
        supports=witnessed(supports, out_file),
        stage_mesh_path=drawn,
    )


def _whole_profile_for_orca(profile: str | None) -> str | None:
    """The profile the Orca dialect is handed: never nothing, never a few keys.

    No profile is Kiln's generic one.  A Kiln-written overrides-only file
    (no printer behind it: the CLI's stated support mode with no printer,
    ``reslice_with_overrides`` with none) is laid over the generic profile,
    its stated keys still stated, so Orca gets a bed and the caller keeps
    every key they chose.  A profile with a printer behind it, or the
    caller's own, is returned as given.
    """
    from kiln.slicer_profiles import profile_origin, profile_with_overrides, resolve_slicer_profile

    if not profile:
        return resolve_slicer_profile("default")
    origin = profile_origin(profile)
    if not origin.kiln or origin.printer_id or not os.path.isfile(profile):
        return profile
    layered = ini_to_settings(profile)
    stated = {key: value for key, value in layered.items() if key in origin.stated}
    own = {key: value for key, value in layered.items() if key not in origin.stated}
    whole = resolve_slicer_profile("default")
    if own:
        whole = profile_with_overrides(whole, own, prefix="default_", stated=False)
    if stated:
        whole = profile_with_overrides(whole, stated, prefix="default_", stated=True)
    return whole


def derive_filament_weight(estimates: dict[str, Any], material: str | None) -> None:
    """Fill in a filament weight the slicer could not work out, in place.

    A slicer gets weight by multiplying extruded volume by the filament's
    density, and density lives on a FILAMENT profile.  Kiln's bundled profiles
    describe a printer — bed, speeds, temperatures — and name no filament, so
    a slicer left with no density reports ``0``.  Every slice Kiln runs
    carries one (:mod:`kiln.slicer_filament`), so on a Kiln-sliced
    file the weight is already there and this returns at once; it remains
    for G-code sliced elsewhere.  The volume is right there in the same
    G-code, so the missing half is only the material.

    Weight is physics and is computed here when the caller names a material,
    or, when the caller names none, when the file itself says what it was
    sliced for (``filament_types``) and every filament is the same material.
    Cost is not: the table's price is a generic figure, not what anyone paid,
    and a made-up price is the kind of confident wrong number this is meant to
    stop.  ``estimate_material_cost`` takes a real ``cost_per_kg`` for that.

    Recorded as *generic*, because a table density is the family's nominal
    value and not a measurement of the spool on the shelf.
    """
    if estimates.get("filament_weight_g"):
        return
    volume_cm3 = estimates.get("filament_volume_cm3")
    if not volume_cm3:
        return
    try:
        from kiln.cost_estimator import resolve_material
    except ImportError:  # pragma: no cover — cost table always ships
        return

    if material:
        profile = resolve_material(material)
        whose = "generic"
    else:
        # The file's own types: one material for the whole plate, or no
        # single density can weigh it.
        rows = [resolve_material(t) for t in estimates.get("filament_types") or () if t]
        names = {row.name if row is not None else None for row in rows}
        profile = rows[0] if rows and len(names) == 1 and None not in names else None
        whose = "the file's own filament type, generic"
    if profile is None:
        return
    estimates["filament_weight_g"] = round(volume_cm3 * profile.density_g_per_cm3, 2)
    estimates["filament_weight_basis"] = (
        f"computed from extruded volume x {whose} {profile.name} density "
        f"({profile.density_g_per_cm3} g/cm3)"
    )


def estimate_print(
    file_path: str,
    *,
    profile: str | None = None,
    slicer_path: str | None = None,
    material: str | None = None,
) -> dict[str, Any]:
    """Estimate print time and filament usage by slicing to a temp file.

    Slices the model and parses the G-code comments for estimated
    print time, filament length, and filament weight.

    Args:
        file_path: Path to STL/3MF/OBJ file.
        profile: Optional slicer profile path.
        slicer_path: Optional explicit slicer binary path.
        material: Optional filament family (``"PLA"``, ``"PETG"``, …).  Only
            a density source: the slice is run with it, so the slicer weighs
            the print itself; without it the slice weighs as PLA and says so.

    Returns:
        Dict with ``estimated_time_seconds``, ``filament_length_mm``,
        ``filament_weight_g``, ``layer_count``, and ``gcode_path``.  Keys the
        slicer could not answer are ABSENT, never zero.

    Raises:
        SlicerError: If slicing fails.
    """
    result = slice_file(
        file_path, profile=profile, slicer_path=slicer_path, material=material,
    )
    return estimates_for_result(result, material)


def estimates_for_result(result: SliceResult, material: str | None = None) -> dict[str, Any]:
    """The time / filament / layer estimates of a :class:`SliceResult`.

    What :func:`estimate_print` reads off the file it sliced, split out so a
    door that slices through its own gate (the plate gate every slice door
    shares) can estimate the same way without slicing twice.

    Raises:
        SlicerError: If the slice did not produce a file.
    """
    if not result.success or not result.output_path:
        raise SlicerError("Slicing failed — cannot estimate print.")

    estimates = _parse_gcode_estimates(result.output_path)
    derive_filament_weight(estimates, material)
    if result.filament is not None:
        estimates["filament"] = result.filament.to_dict()
    return estimates


def _parse_gcode_estimates(gcode_path: str) -> dict[str, Any]:
    """Parse G-code file for slicer-generated estimates.

    Every estimate a slicer writes is a COMMENT, so the whole file is read
    and only comment lines are matched.  Toolpath lines are the overwhelming
    majority and are rejected on their first character, which is what makes
    reading all of them cheap.

    Every line is read, so an estimate is found wherever in the file the
    slicer wrote it.
    """
    import re as _re

    from kiln.gcode import (
        slicer_filament_totals,
        slicer_filament_types,
        slicer_layer_count,
        slicer_print_time,
    )

    estimates: dict[str, Any] = {"gcode_path": gcode_path}

    try:
        with open(gcode_path, errors="replace", encoding="utf-8") as fh:
            search_lines = [line for line in fh if line.startswith(";")]
    except OSError:
        return estimates

    # The filament totals, read once by the one reader for what a slicer
    # says (kiln.gcode.slicer_filament_totals): one value per extruder on a
    # multi-filament plate, and the plate uses the sum.
    #
    # A zero weight is the slicer saying it could not work it out — it
    # needs a filament density, which a Kiln slice now always carries
    # (kiln.slicer_filament) and G-code sliced elsewhere may not.  Nothing
    # that gets extruded weighs nothing, so the key is left ABSENT rather
    # than recorded as 0: "I don't know" is a true statement about every
    # print, "0 g" is a false one.  See derive_filament_weight, which fills
    # it in when a material is named.
    comments = "".join(search_lines)
    totals = slicer_filament_totals(comments)
    if totals.mm:
        estimates["filament_length_mm"] = totals.total_mm
    if totals.weight_g:
        estimates["filament_weight_g"] = totals.weight_g
    if totals.cm3:
        estimates["filament_volume_cm3"] = float(sum(totals.cm3))

    # The print time and layer total, read by the one reader of each.  The
    # normal-mode time wins over a slower silent-mode line written after it.
    printed = slicer_print_time(comments)
    if printed is not None:
        estimates["estimated_time_seconds"] = printed.seconds
        if not printed.as_written.replace(".", "", 1).isdigit():
            # Cura writes bare seconds; words only where the slicer wrote them.
            estimates["estimated_time_human"] = printed.as_written
    layers = slicer_layer_count(comments)
    if layers is not None:
        estimates["layer_count"] = layers
    types = slicer_filament_types(comments)
    if any(types):
        estimates["filament_types"] = list(types)

    for line in search_lines:
        line = line.strip()

        # ; filament cost = 1.23
        #
        # Zero for the same reason, and left absent for the same reason: a
        # price comes off a filament profile Kiln's printer profiles do not
        # carry.  Unlike weight this one is NOT derived downstream — the
        # material table's price is a generic figure rather than what anyone
        # paid, and estimate_material_cost takes a real cost_per_kg.
        cost = _re.search(r"filament cost\s*=\s*([\d.]+)", line, _re.IGNORECASE)
        if cost and float(cost.group(1)) > 0:
            estimates["filament_cost"] = float(cost.group(1))

    return estimates


