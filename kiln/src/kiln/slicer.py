def _gcode_output_is_complete(out_file: str) -> bool:
    """Whether *out_file* looks like a finished slice, not a truncated one.

    Slicers write their summary footer (the ``filament used`` statistics
    block) only after the last toolpath is out, so a process killed
    mid-write never gets there.  Distinguishes "crashed AFTER finishing"
    from "crashed while writing" when the slicer dies on a signal:
    PrusaSlicer 2.9.4's CLI segfaults in its object-conflict bookkeeping
    (Print::export_gcode → ConflictResult assignment) on some multi-object
    files — stacked parts meeting at an exactly-coincident plane, the
    shape Kiln's banded multicolor compose produces — after exporting a
    complete, correct file.
    """
    try:
        with open(out_file, "rb") as fh:
            fh.seek(0, os.SEEK_END)
            size = fh.tell()
            fh.seek(max(0, size - 65536))
            tail = fh.read()
    except OSError:
        return False
    return b"filament used" in tail


def _record_slice(
    profile: str | None,
    input_abs: str | None = None,
    out_file: str | None = None,
) -> None:
    """Count one successful slice, and note the pair for the monitor twin.

    Recorded at the two runners rather than in a tool body, because the count
    used to live in the ``slice_model`` tool alone and every other path — the
    pipelines, estimates, CLI, kiln-pro batch flows — reported zero.  Detail is
    the profile filename stem; profiles are named for printers, never for
    users' models.

    The twin note rides the same chokepoint for the same reason: the web
    Monitor's layer viewer needs the sliced toolpath of whatever ends up
    printing, and only the slice runner reliably knows the (mesh, gcode)
    pair — a per-tool note would cover one door and miss the pipelines.
    """
    try:
        from kiln.daily_stats import record_event

        record_event("slices", detail=Path(profile).stem[:64] if profile else "unknown")
    except Exception:  # noqa: BLE001 — stats must never fail a slice
        logger.debug("slice telemetry recording failed", exc_info=True)
    if input_abs and out_file:
        try:
            from kiln.monitor_twin import note_sliced

            note_sliced(input_abs, out_file)
        except Exception:  # noqa: BLE001 — the twin ledger must never fail a slice
            logger.debug("monitor-twin slice note failed", exc_info=True)


# The crash any Bambu Lab machine preset provokes in both forks, and the one
# thing Kiln cannot serialize its way around.  Measured 2026-08-11 against
# OrcaSlicer 2.3.2 and BambuStudio 02.06.00.51: both die in
# Slic3r::DynamicPrintConfig::update_values_to_printer_extruders_for_multiple_filaments
# (null deref, EXC_BAD_ACCESS) on their OWN bundled Bambu presets as readily as
# on Kiln's, while a Creality preset through the identical code path slices
# fine.  So it is upstream and profile-specific, not a Kiln argv or preset bug.
_ORCA_SIGSEGV_RETURNCODES = frozenset({-11, 139})

# The macOS locale-race startup crash, slicer spelling.  The same libc race
# kiln.openscad_runner retries for OpenSCAD kills PrusaSlicer too: seven
# crash reports on one machine 2026-08-11..2026-08-17, every one SIGTRAP
# with libc's "loc->decimal_point is NULL" guard, every one 0.06-0.13s
# after launch -- dead before the model mattered.  Same shape, same
# remedy, same honesty about the bounds: the crash is upstream
# (macOS 26.5 libc + a multithreaded process touching the locale during
# startup), a retry is a lottery re-draw, and a crash that lands OUTSIDE
# the startup window is a real answer about real geometry and is not
# retried.  SIGSEGV/SIGBUS ride along because the OpenSCAD twin showed
# one underlying race spelling itself as either a libc guard trap or a
# wild read, depending on where the torn pointer lands.
_SLIC3R_STARTUP_CRASH_RETURNCODES = frozenset({
    -int(signal.SIGTRAP), -int(signal.SIGSEGV), -int(signal.SIGBUS),
})

# The Orca dialect keeps SIGSEGV out of its retry set on purpose: -11 on
# that path is the deterministic Bambu-preset crash above, a real verdict
# with a real message, and retrying it would crash the same way twice
# more just to say the same thing later (the openscad_runner rule about
# not retrying real answers).  The locale race has not been captured on
# an Orca binary; TRAP/BUS are covered so that if it ever is, the user
# gets the re-draw instead of the failure.
_ORCA_STARTUP_CRASH_RETURNCODES = frozenset({
    -int(signal.SIGTRAP), -int(signal.SIGBUS),
})

#: A crash later than this is blamed on the model, not on startup.  The
#: observed crashes die in the first ~0.1s; ten seconds is far past any
#: plausible startup and far short of real slicing work on a big model.
_STARTUP_CRASH_WINDOW_S = 10.0

#: Total launches, so two re-draws after a first startup crash.
_SLICE_ATTEMPTS = 3


def _bed_xy_bounds_from_profile(
    profile: str | None,
) -> tuple[float, float, float, float] | None:
    """The bed's XY rectangle from a profile ini, or None.

    Parses ``bed_shape = 0x0,256x0,256x256,0x256`` into
    ``(x_min, y_min, x_max, y_max)``.  Corner-origin beds give
    ``(0, 0, w, d)``; center-origin (delta) beds keep their negative
    corners, so the fit check below works for both.
    """
    if not profile or not os.path.isfile(profile):
        return None
    try:
        shape = ini_to_settings(profile).get("bed_shape", "")
    except OSError:
        return None
    xs: list[float] = []
    ys: list[float] = []
    for corner in shape.split(","):
        x, sep, y = corner.strip().partition("x")
        if not sep:
            continue
        try:
            xs.append(float(x))
            ys.append(float(y))
        except ValueError:
            continue
    if len(xs) < 3:
        return None
    return (min(xs), min(ys), max(xs), max(ys))


# Matches kiln.printers.bed_fit._FIT_EPSILON_MM — floating-point noise on
# the bed edge must not reject a model that fits.
_BED_FIT_EPSILON_MM = 0.5


def _check_3mf_on_bed(input_abs: str, profile: str | None) -> None:
    """Refuse to slice a 3MF whose placed geometry misses the profile's bed.

    3MF only: a 3MF carries explicit build transforms that slicers honour
    literally, while loose STL geometry is auto-centred by PrusaSlicer.
    Without this gate the failure is invisible — PrusaSlicer prints "All
    objects are outside of the print volume." and exits 0 with no output
    file, which used to surface as a generic "output file was not
    created".  Skips silently when the bed shape or the geometry cannot
    be determined: this is a diagnosis gate, not a new way to fail good
    files.
    """
    bed = _bed_xy_bounds_from_profile(profile)
    if bed is None:
        return
    from kiln.printers.bed_fit import compute_3mf_geometry_bbox

    bbox = compute_3mf_geometry_bbox(input_abs)
    if bbox is None:
        return
    bed_x_min, bed_y_min, bed_x_max, bed_y_max = bed
    eps = _BED_FIT_EPSILON_MM
    if (
        bbox["x_min"] >= bed_x_min - eps
        and bbox["x_max"] <= bed_x_max + eps
        and bbox["y_min"] >= bed_y_min - eps
        and bbox["y_max"] <= bed_y_max + eps
    ):
        return
    raise SlicerError(
        f"Model geometry (with its 3MF build transform applied) spans "
        f"X[{bbox['x_min']:.1f}..{bbox['x_max']:.1f}] "
        f"Y[{bbox['y_min']:.1f}..{bbox['y_max']:.1f}] mm, outside the "
        f"profile's bed X[{bed_x_min:g}..{bed_x_max:g}] "
        f"Y[{bed_y_min:g}..{bed_y_max:g}] mm. Slicers honour a 3MF's "
        f"placement literally (no auto-centre), so this would slice to "
        f"nothing. Re-export the 3MF centred on the bed, or translate "
        f"the model so its footprint fits."
    )


def _run_slicer_with_startup_retry(
    cmd: list[str],
    *,
    timeout: int,
    retryable_returncodes: frozenset[int],
    remove_partial_output,
    output_is_complete,
) -> subprocess.CompletedProcess:
    """Launch a slicer, re-drawing the startup-crash lottery when it hits.

    One loop for both CLI dialects so the retry rule cannot drift between
    them.  A retry fires only when ALL of these hold: the death was one of
    *retryable_returncodes*, it happened inside the startup window, the
    output is NOT already complete (a signal death after a complete write
    is the salvage case, owned by the caller), and an attempt remains.
    *remove_partial_output* runs between attempts so a half-written file
    from a crashed run can never pose as the next run's result.
    """
    result: subprocess.CompletedProcess | None = None
    for attempt in range(1, _SLICE_ATTEMPTS + 1):
        started = time.monotonic()
        try:
            result = subprocess.run(cmd, capture_output=True, text=True, timeout=timeout)
        except subprocess.TimeoutExpired:
            remove_partial_output()
            raise SlicerError(
                f"Slicing timed out after {timeout}s. The model may be too complex "
                f"or the slicer is hanging."
            ) from None
        except OSError as exc:
            raise SlicerError(f"Failed to run slicer: {exc}") from exc
        elapsed = time.monotonic() - started
        if (
            attempt < _SLICE_ATTEMPTS
            and result.returncode in retryable_returncodes
            and elapsed < _STARTUP_CRASH_WINDOW_S
            and not output_is_complete()
        ):
            logger.warning(
                "Slicer died of signal %d %.2fs after launch (the startup "
                "crash lottery) -- relaunching, attempt %d of %d",
                -result.returncode, elapsed, attempt + 1, _SLICE_ATTEMPTS,
            )
            remove_partial_output()
            continue
        break
    assert result is not None
    return result


def _slice_with_orca(
    slicer: SlicerInfo,
    input_abs: str,
    out_file: str,
    *,
    profile: str | None,
    extra_args: list[str] | None,
    timeout: int,
) -> SliceResult:
    """Slice through the BambuStudio/OrcaSlicer command line.

    A different argv and a different preset format from
    :func:`slice_file`'s Slic3r path: ``--slice 0 --outputdir DIR
    --load-settings "machine.json;process.json" --load-filaments "f.json"``,
    where the presets are the JSON that :mod:`kiln.slicer_orca` writes out of
    the same bundled settings the ``.ini`` is built from.

    Orca names its own output (``plate_1.gcode``) inside ``--outputdir``
    rather than taking an output path, so it writes to a private directory
    and the result is moved to where the caller asked for it.
    """
    with tempfile.TemporaryDirectory(prefix="kiln_orca_") as work_dir:
        cmd: list[str] = [slicer.path, "--slice", "0", "--outputdir", work_dir]

        if profile and not os.path.isfile(profile):
            raise SlicerError(f"Profile file not found: {os.path.basename(profile)}")

        if not profile:
            # "No profile" cannot mean "no preset" here the way it does for
            # PrusaSlicer, which slices happily on its own defaults.  Orca's
            # defaults use relative extrusion with no per-layer reset, so a
            # bare slice_file("model.stl") — the documented form — fails
            # validation before it starts.  Kiln's own generic profile is a
            # real answer to "you didn't say", and it keeps the bare call
            # working on both backends.
            #
            # Resolved through the ordinary door rather than read straight
            # off the profile, so it passes the same invariants every other
            # profile does — the per-layer E reset among them.
            from kiln.slicer_profiles import resolve_slicer_profile

            profile = resolve_slicer_profile("default")

        settings = ini_to_settings(profile)
        preset_name = Path(profile).stem[:48] or "kiln"

        presets = write_orca_presets(settings, work_dir, name=preset_name)
        cmd += ["--load-settings", f"{presets.machine_path};{presets.process_path}"]
        cmd += ["--load-filaments", str(presets.filament_path)]

        if extra_args:
            cmd.extend(extra_args)
        cmd.append(input_abs)

        logger.info("Slicing (Orca dialect): %s", " ".join(cmd))

        def _latest_gcode_complete() -> bool:
            done = sorted(Path(work_dir).glob("*.gcode"), key=lambda p: p.stat().st_mtime)
            return bool(done) and _gcode_output_is_complete(str(done[-1]))

        def _drop_partial_gcode() -> None:
            for stale in Path(work_dir).glob("*.gcode"):
                with contextlib.suppress(OSError):
                    stale.unlink()

        result = _run_slicer_with_startup_retry(
            cmd,
            timeout=timeout,
            retryable_returncodes=_ORCA_STARTUP_CRASH_RETURNCODES,
            remove_partial_output=_drop_partial_gcode,
            output_is_complete=_latest_gcode_complete,
        )

        produced = sorted(Path(work_dir).glob("*.gcode"), key=lambda p: p.stat().st_mtime)

        # A death by signal AFTER a complete write is salvageable, exactly as
        # it is on the Slic3r path — see _gcode_output_is_complete, which
        # exists because PrusaSlicer does this on some multi-object files.
        # Orca is a Slic3r derivative, so it inherits the possibility; without
        # this the two paths would disagree about the same event, and a good
        # slice would be thrown away with a message about a Bambu crash.
        crashed_after_finishing = bool(
            result.returncode != 0
            and produced
            and _gcode_output_is_complete(str(produced[-1]))
        )

        if result.returncode in _ORCA_SIGSEGV_RETURNCODES and not crashed_after_finishing:
            raise SlicerError(
                f"{os.path.basename(slicer.path)} crashed while slicing. This is a "
                f"known crash in BambuStudio and OrcaSlicer themselves, on Bambu Lab "
                f"printer profiles specifically — their own bundled Bambu presets "
                f"crash the same way, and the same Kiln code slices other printers "
                f"fine. Slice this printer with PrusaSlicer instead; Kiln wraps the "
                f"result as a Bambu 3MF itself, so nothing about the print is lost.\n"
                f"{_INSTALL_SLICER}"
            )

        if result.returncode != 0 and not crashed_after_finishing:
            # This CLI reports the reason on stdout and leaves stderr empty.
            stderr_snippet = (result.stderr or "").strip() or (result.stdout or "").strip()
            raise SlicerError(f"Slicer exited with code {result.returncode}. stderr: {stderr_snippet[:500]}")

        if not produced:
            # This CLI reports on stdout, but surface both streams — the
            # Slic3r-family lesson: the reason for a silent exit-0 no-write
            # lives on whichever stream the message omitted.
            reason = (result.stdout or "").strip() or (result.stderr or "").strip()
            raise SlicerError(
                f"Slicer completed but wrote no G-code. "
                f"Slicer said: {reason[:500] if reason else '(no output)'}"
            )

        # One plate, because slice_file promises exactly one file.  The model
        # did not fit on a single plate, and quietly handing back the first
        # one is how a user prints half a job and finds out at the printer.
        if len(produced) > 1:
            raise SlicerError(
                f"This model needed {len(produced)} build plates, and a slice "
                f"returns a single G-code file. Split it into separate models, "
                f"or scale it down so it fits one plate."
            )

        shutil.move(str(produced[0]), out_file)

    _record_slice(profile, input_abs, out_file)
    message = f"Sliced {Path(input_abs).name} -> {Path(out_file).name}"
    if crashed_after_finishing:
        message += (
            f" (the slicer crashed on exit AFTER writing complete G-code — "
            f"signal {-result.returncode}; the output was verified complete "
            f"and kept)"
        )
    return SliceResult(
        success=True,
        output_path=out_file,
        slicer=slicer.name,
        message=message,
        stdout=(result.stdout or "").strip(),
        stderr=(result.stderr or "").strip(),
    )


def slice_file(
    input_path: str,
    *,
    output_dir: str | None = None,
    output_name: str | None = None,
    profile: str | None = None,
    slicer_path: str | None = None,
    extra_args: list[str] | None = None,
    timeout: int = 300,
) -> SliceResult:
    """Slice a 3D model file to G-code.

    Args:
        input_path: Path to the input file (STL, 3MF, STEP, OBJ, AMF).
        output_dir: Directory for the output G-code file.  Defaults to
            the system temp directory.
        output_name: Override the output file name.  Defaults to the
            input file's stem with ``.gcode`` extension.
        profile: Path to a slicer profile/config file (.ini or .json).
        slicer_path: Explicit slicer binary path.  Auto-detected if omitted.
        extra_args: Additional CLI arguments to pass to the slicer.
        timeout: Maximum slicing time in seconds (default 300).

    Returns:
        A :class:`SliceResult` with the path to the generated G-code.

    Raises:
        SlicerError: If slicing fails.
        SlicerNotFoundError: If no slicer binary is found.
        FileNotFoundError: If the input file does not exist.
    """
    # Validate input
    input_abs = os.path.abspath(input_path)
    if not os.path.isfile(input_abs):
        raise FileNotFoundError(f"Input file not found: {os.path.basename(input_abs)}")

    ext = Path(input_abs).suffix.lower()
    if ext not in _INPUT_EXTENSIONS:
        raise SlicerError(f"Unsupported input format '{ext}'. Supported: {', '.join(sorted(_INPUT_EXTENSIONS))}")

    if ext == ".3mf":
        _check_3mf_on_bed(input_abs, profile)

    # Find slicer
    slicer = find_slicer(slicer_path)

    # Prepare output
    out_dir = output_dir or _DEFAULT_OUTPUT_DIR
    os.makedirs(out_dir, mode=0o700, exist_ok=True)

    if output_name:
        # Strict filename sanitisation: basename, null bytes, length, reserveds
        safe_name = output_name.replace("\x00", "")
        safe_name = os.path.basename(safe_name)
        if not safe_name or safe_name != output_name.replace("\x00", "") or safe_name in {".", ".."}:
            raise ValueError(
                f"output_name must be a plain filename without path separators "
                f"or traversal sequences, got: {output_name!r}"
            )
        if len(safe_name) > 255:
            raise ValueError(f"output_name too long ({len(safe_name)} chars, max 255)")
        out_file = os.path.join(out_dir, safe_name)
    else:
        stem = Path(input_abs).stem
        out_file = os.path.join(out_dir, f"{stem}.gcode")

    # Anything at out_file after the run must have been written BY the run.
    # The path is deterministic (input stem into a shared output dir), so a
    # previous slice of the same model leaves a complete-looking file here —
    # and without this unlink the crash-salvage check below would read that
    # STALE file and certify a slicer that died before writing anything as a
    # fresh success: the previous model's toolpath, headed for start_print.
    with contextlib.suppress(OSError):
        os.unlink(out_file)

    # Two command lines, one function.  Everything below this point is the
    # Slic3r dialect; an Orca/BambuStudio binary needs a different argv AND a
    # different preset format, so it gets its own runner rather than a flag
    # swap.  The branch is here — at the one place all twelve slicing doors
    # funnel through — so none of them has to know which slicer is installed.
    if slicer_cli_family(slicer) == _CLI_BAMBU:
        return _slice_with_orca(
            slicer,
            input_abs,
            out_file,
            profile=profile,
            extra_args=extra_args,
            timeout=timeout,
        )

    # Build command
    cmd: list[str] = [
        slicer.path,
        "--export-gcode",
        input_abs,
        "--output",
        out_file,
    ]

    if profile:
        if not os.path.isfile(profile):
            raise SlicerError(f"Profile file not found: {os.path.basename(profile)}")
        cmd.extend(["--load", profile])

    if extra_args:
        cmd.extend(extra_args)

    logger.info("Slicing: %s", " ".join(cmd))

    def _drop_partial_out_file() -> None:
        with contextlib.suppress(OSError):
            os.unlink(out_file)

    result = _run_slicer_with_startup_retry(
        cmd,
        timeout=timeout,
        retryable_returncodes=_SLIC3R_STARTUP_CRASH_RETURNCODES,
        remove_partial_output=_drop_partial_out_file,
        output_is_complete=lambda: _gcode_output_is_complete(out_file),
    )

    crashed_after_finishing = (
        result.returncode != 0
        and result.returncode < 0  # killed by a signal, not a reported error
        and _gcode_output_is_complete(out_file)
    )
    if result.returncode != 0 and not crashed_after_finishing:
        stderr_snippet = (result.stderr or "").strip()[:500]
        raise SlicerError(f"Slicer exited with code {result.returncode}. stderr: {stderr_snippet}")

    # Verify output exists.  PrusaSlicer can exit 0 without writing — e.g.
    # "All objects are outside of the print volume." — and it says why on
    # STDERR; a message that omitted stderr turned that specific reason
    # into a generic mystery.
    if not os.path.isfile(out_file):
        reason = (result.stderr or "").strip() or (result.stdout or "").strip()
        raise SlicerError(
            f"Slicer completed but output file was not created. "
            f"Slicer said: {reason[:500] if reason else '(no output)'}"
        )

    _record_slice(profile, input_abs, out_file)

    message = f"Sliced {Path(input_abs).name} -> {Path(out_file).name}"
    if crashed_after_finishing:
        message += (
            f" (the slicer crashed on exit AFTER writing complete G-code — "
            f"signal {-result.returncode}; the output was verified complete "
            f"and kept)"
        )
    return SliceResult(
        success=True,
        output_path=out_file,
        slicer=slicer.name,
        message=message,
        stdout=(result.stdout or "").strip(),
        stderr=(result.stderr or "").strip(),
    )


def derive_filament_weight(estimates: dict[str, Any], material: str | None) -> None:
    """Fill in a filament weight the slicer could not work out, in place.

    A slicer gets weight by multiplying extruded volume by the filament's
    density, and density lives on a FILAMENT profile.  Kiln's bundled profiles
    describe a printer — bed, speeds, temperatures — and name no filament, so
    the slicer has no density and reports ``0``.  The volume is right there in
    the same G-code, so the missing half is only the material.

    Weight is physics and is computed here when the caller names a material.
    Cost is not: the table's price is a generic figure, not what anyone paid,
    and a made-up price is the kind of confident wrong number this is meant to
    stop.  ``estimate_material_cost`` takes a real ``cost_per_kg`` for that.

    Recorded as *generic*, because a table density is the family's nominal
    value and not a measurement of the spool on the shelf.
    """
    if not material or estimates.get("filament_weight_g"):
        return
    volume_cm3 = estimates.get("filament_volume_cm3")
    if not volume_cm3:
        return
    try:
        from kiln.cost_estimator import BUILTIN_MATERIALS
    except ImportError:  # pragma: no cover — cost table always ships
        return

    profile = BUILTIN_MATERIALS.get(str(material).strip().upper())
    if profile is None:
        return
    estimates["filament_weight_g"] = round(volume_cm3 * profile.density_g_per_cm3, 2)
    estimates["filament_weight_basis"] = (
        f"computed from extruded volume x generic {profile.name} density "
        f"({profile.density_g_per_cm3} g/cm3)"
    )


def estimate_print(
    file_path: str,
    *,
    profile: str | None = None,
    slicer_path: str | None = None,
    material: str | None = None,
) -> dict[str, Any]:
    """Estimate print time and filament usage by slicing to a temp file.

    Slices the model and parses the G-code comments for estimated
    print time, filament length, and filament weight.

    Args:
        file_path: Path to STL/3MF/OBJ file.
        profile: Optional slicer profile path.
        slicer_path: Optional explicit slicer binary path.
        material: Optional filament family (``"PLA"``, ``"PETG"``, …).  Only
            a density source: without it a weight the slicer could not work
            out is reported as absent rather than guessed.

    Returns:
        Dict with ``estimated_time_seconds``, ``filament_length_mm``,
        ``filament_weight_g``, ``layer_count``, and ``gcode_path``.  Keys the
        slicer could not answer are ABSENT, never zero.

    Raises:
        SlicerError: If slicing fails.
    """
    result = slice_file(file_path, profile=profile, slicer_path=slicer_path)
    if not result.success or not result.output_path:
        raise SlicerError("Slicing failed — cannot estimate print.")

    estimates = _parse_gcode_estimates(result.output_path)
    derive_filament_weight(estimates, material)
    return estimates


def _parse_gcode_estimates(gcode_path: str) -> dict[str, Any]:
    """Parse G-code file for slicer-generated estimates.

    Every estimate a slicer writes is a COMMENT, so the whole file is read
    and only comment lines are matched.  Toolpath lines are the overwhelming
    majority and are rejected on their first character, which is what makes
    reading all of them cheap.

    This used to search a window — the first 200 lines and the last 500 —
    and the window kept being the bug.  It was widened once already when
    PrusaSlicer's estimates turned out to sit ~350 lines from EOF, behind its
    trailing config block.  OrcaSlicer's block is longer still: measured at
    584-589 lines from EOF, just outside the 500, so every estimate came back
    empty for an Orca slice while the values sat in the file.  A window tuned
    to today's slicers is a bug waiting for the next one to add a setting.
    """
    import re as _re

    estimates: dict[str, Any] = {"gcode_path": gcode_path}

    try:
        with open(gcode_path, errors="replace") as fh:
            search_lines = [line for line in fh if line.startswith(";")]
    except OSError:
        return estimates

    for line in search_lines:
        line = line.strip()

        # PrusaSlicer: ; estimated printing time (normal mode) = 1h 23m 45s
        time_match = _re.search(
            r"estimated printing time.*?=\s*(?:(\d+)d\s*)?(?:(\d+)h\s*)?(?:(\d+)m\s*)?(?:(\d+)s)?",
            line,
            _re.IGNORECASE,
        )
        if time_match:
            d = int(time_match.group(1) or 0)
            h = int(time_match.group(2) or 0)
            m = int(time_match.group(3) or 0)
            s = int(time_match.group(4) or 0)
            estimates["estimated_time_seconds"] = d * 86400 + h * 3600 + m * 60 + s
            estimates["estimated_time_human"] = line.split("=", 1)[-1].strip()

        # ; filament used [mm] = 1234.56
        fil_mm = _re.search(r"filament used \[mm\]\s*=\s*([\d.]+)", line, _re.IGNORECASE)
        if fil_mm:
            estimates["filament_length_mm"] = float(fil_mm.group(1))

        # ; filament used [g] = 12.34 or total filament used [g] = 12.34
        #
        # A zero here is the slicer saying it could not work the weight out —
        # it needs a filament density, and Kiln's profiles describe a printer,
        # not a filament.  Nothing that gets extruded weighs nothing, so the
        # key is left ABSENT rather than recorded as 0: "I don't know" is a
        # true statement about every print, "0 g" is a false one.  See
        # derive_filament_weight, which fills it in when a material is named.
        fil_g = _re.search(r"filament used \[g\]\s*=\s*([\d.]+)", line, _re.IGNORECASE)
        if fil_g and float(fil_g.group(1)) > 0:
            estimates["filament_weight_g"] = float(fil_g.group(1))

        # ; filament used [cm3] = 12.34
        fil_cm3 = _re.search(r"filament used \[cm3\]\s*=\s*([\d.]+)", line, _re.IGNORECASE)
        if fil_cm3:
            estimates["filament_volume_cm3"] = float(fil_cm3.group(1))

        # ; total layers count = 123
        layers = _re.search(r"total layers count\s*=\s*(\d+)", line, _re.IGNORECASE)
        if layers:
            estimates["layer_count"] = int(layers.group(1))

        # ; filament cost = 1.23
        #
        # Zero for the same reason, and left absent for the same reason: a
        # price comes off a filament profile Kiln's printer profiles do not
        # carry.  Unlike weight this one is NOT derived downstream — the
        # material table's price is a generic figure rather than what anyone
        # paid, and estimate_material_cost takes a real cost_per_kg.
        cost = _re.search(r"filament cost\s*=\s*([\d.]+)", line, _re.IGNORECASE)
        if cost and float(cost.group(1)) > 0:
            estimates["filament_cost"] = float(cost.group(1))

    return estimates


