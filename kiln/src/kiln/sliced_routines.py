def _shares() -> bool:
    """Whether this install shares what it learns: telemetry on AND community
    sharing on, the same two switches as :func:`kiln.bench.sharing`."""
    try:
        from kiln.community_sync import community_sharing_enabled
        from kiln.heartbeat import _telemetry_enabled

        return bool(_telemetry_enabled()) and bool(community_sharing_enabled())
    except Exception:  # noqa: BLE001
        return False


def said_yes() -> bool:
    """Whether the person said yes to sharing their printer's routines; no
    answer is no."""
    try:
        from kiln.sharing_consent import routines_answer

        return routines_answer() is True
    except Exception:  # noqa: BLE001 -- unsure is no
        return False


def sending() -> bool:
    """Whether anything may leave for the shared table: the person said yes
    (:func:`said_yes`) and this install shares (:func:`_shares`)."""
    return said_yes() and _shares()


def kept_printer_name() -> str | None:
    """The name of the printer whose routines a print file last left on this
    computer (the catalogue's name for it, else the slicer's), or ``None``."""
    try:
        folder = _store_dir()
        stores = [_load(p.stem) for p in folder.glob("*.json")] if folder.is_dir() else []
    except OSError:
        return None
    stores = [s for s in stores if isinstance(s.get("routines"), dict) and s.get("model")]
    if not stores:
        return None
    latest = max(stores, key=lambda s: str(s.get("read_at") or ""))
    try:
        from kiln.printers.bed_fit import get_printer_display_name

        listed = get_printer_display_name(str(latest["model"]))
    except Exception:  # noqa: BLE001 -- the slicer's own name still names it
        listed = None
    return str(listed or latest.get("printer_model") or latest["model"]).strip()[:80] or None


#: The fields of a payload Kiln makes itself (a hash, its own random ids),
#: judged by their form; every other field is judged by the outbound guard.
_KILN_MADE = {
    "p_sha256": re.compile(r"[0-9a-f]{64}"),
    "p_unit": re.compile(r"[0-9a-f]{16,64}"),
    "p_installation_id": re.compile(r"[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}"),
}


def _guarded(payload: dict[str, Any], version_keys: frozenset[str] = frozenset()) -> bool:
    """Whether *payload* may leave as it is: every value read off the file
    passes the outbound guard unchanged, and every value Kiln made has its
    own form (or is empty)."""
    from kiln import outbound_guard

    read = {k: v for k, v in payload.items() if k not in _KILN_MADE and v is not None}
    if outbound_guard.scrub(read, version_keys=version_keys) != read:
        return False
    return all(payload.get(k) is None or (isinstance(payload[k], str) and form.fullmatch(payload[k]))
               for k, form in _KILN_MADE.items())


def _payload(data: dict[str, Any], block: str, routine: dict[str, Any], installation_id: str | None) -> dict[str, Any]:
    from kiln import outbound_guard

    version = outbound_guard.version_text(data.get("version") or "")
    return {
        "p_printer_id": data["model"],
        "p_block": block,
        "p_sha256": routine["sha256"],
        "p_text": routine["text"],
        "p_slicer": data["slicer"],
        "p_slicer_version": version,
        "p_unit": data.get("unit"),
        "p_installation_id": installation_id,
    }


def _signed_in() -> bool:
    """Whether this computer holds a Kiln sign-in it can send with."""
    try:
        from kiln.auth_session import resolve_api_bearer

        return bool(resolve_api_bearer().token)
    except Exception:  # noqa: BLE001 -- unsure is signed out
        return False


def _push_signed_in(data: dict[str, Any], pending: list[tuple[str, dict[str, Any]]]) -> bool:
    """One printer's pending routines to Kiln's API as the signed-in person,
    with no install id; whether Kiln took them."""
    from kiln import outbound_guard
    from kiln.history_courier import _request

    body = {
        "format": "printer_routines/1", "model": data["model"], "slicer": data["slicer"],
        "version": outbound_guard.version_text(data.get("version") or ""), "unit": data.get("unit"),
        "routines": [{"block": block, "text": r["text"], "sha256": r["sha256"]} for block, r in pending],
    }
    read = {k: v for k, v in body.items() if k != "unit" and v is not None}
    if outbound_guard.scrub(read, version_keys=outbound_guard.VERSION_FIELDS["kiln/sliced_routines.py"]) != read:
        return False
    if body["unit"] is not None and not _KILN_MADE["p_unit"].fullmatch(str(body["unit"])):
        return False
    answer = _request("printer_routines", "POST", PUSH_PATH, body, timeout=_TIMEOUT_S)
    return bool(isinstance(answer, dict) and answer.get("success") and "kept" in answer)


def send_pending(supabase_url: str, anon_key: str) -> int:
    """Send every shareable routine on this computer that has not landed;
    how many landed.  Signed in, each printer's routines go to Kiln's API
    as the person (:data:`PUSH_PATH`), with no install id; signed out, each
    goes through the database door with this install's id.  Only while
    :func:`sending`; never raises."""
    if not sending():
        return 0
    import urllib.request

    from kiln import outbound_guard

    signed_in = _signed_in()
    installation_id: str | None = None
    if not signed_in:
        try:
            from kiln.installation import get_installation_id

            installation_id = get_installation_id()
        except Exception:  # noqa: BLE001
            installation_id = None
    version_keys = outbound_guard.VERSION_FIELDS.get("kiln/sliced_routines.py", frozenset())
    landed = 0
    try:
        folder = _store_dir()
        paths = sorted(folder.glob("*.json")) if folder.is_dir() else []
    except OSError:
        return 0
    for path in paths:
        key = path.stem
        with _lock:
            data = _load(key)
        routines = data.get("routines") if isinstance(data.get("routines"), dict) else {}
        sent = dict(data.get("sent") or {})
        pending: list[tuple[str, dict[str, Any]]] = []
        for block, routine in sorted(routines.items()):
            if block not in BLOCKS or not isinstance(routine, dict) or not routine.get("share"):
                continue
            mark = f"{block}|{routine.get('sha256')}|{data.get('slicer')}|{data.get('version')}"
            if mark in sent:
                continue
            if not _guarded(_payload(data, block, routine, None), version_keys):
                continue
            pending.append((block, routine))
        took: list[str] = []
        if pending and signed_in:
            try:
                if _push_signed_in(data, pending):
                    took = [block for block, _r in pending]
            except Exception as exc:  # noqa: BLE001 -- non-fatal, like the heartbeat
                _logger.debug("sliced routines: not sent (non-fatal): %s", exc)
        elif pending:
            for block, routine in pending:
                try:
                    req = urllib.request.Request(
                        f"{supabase_url.rstrip('/')}/rest/v1/rpc/{RPC}",
                        data=json.dumps(_payload(data, block, routine, installation_id)).encode("utf-8"),
                        headers={"Content-Type": "application/json", "apikey": anon_key,
                                 "Authorization": f"Bearer {anon_key}"},
                        method="POST",
                    )
                    with urllib.request.urlopen(req, timeout=_TIMEOUT_S) as resp:
                        if resp.status < 300:
                            took.append(block)
                except Exception as exc:  # noqa: BLE001 -- non-fatal, like the heartbeat
                    _logger.debug("sliced routines: not sent (non-fatal): %s", exc)
        if took:
            now = datetime.now(timezone.utc).isoformat(timespec="seconds")
            for block in took:
                routine = routines[block]
                sent[f"{block}|{routine.get('sha256')}|{data.get('slicer')}|{data.get('version')}"] = now
            landed += len(took)
            with _lock, contextlib.suppress(OSError):
                fresh = _load(key)
                fresh["sent"] = {**dict(fresh.get("sent") or {}), **sent}
                _save(key, fresh)
    return landed


def routines_for_request(adapter: Any) -> dict[str, Any] | None:
    """What a print-beside request for *adapter* carries: this printer's
    routines, with no hash, id or version, so its own verdict can use them
    at once.  ``None`` until the person said yes (:func:`said_yes`: nothing
    leaves this computer without it), when nothing is kept, or when no
    routine passes the outbound guard."""
    try:
        if not said_yes():
            return None
        declared = _declared_model(adapter)
        if not declared:
            return None
        key, _unit = _key_of(adapter, declared)
        with _lock:
            data = _load(key)
        if data.get("model") != declared or not isinstance(data.get("routines"), dict):
            return None
        routines = [
            {"block": block, "text": r["text"], "sha256": r["sha256"]}
            for block, r in sorted(data["routines"].items())
            if block in BLOCKS and isinstance(r, dict) and isinstance(r.get("text"), str)
        ]
        routines = [r for r in routines if _guarded({"text": r["text"]})]
        if not routines:
            return None
        return {"format": "printer_routines/1", "model": declared, "slicer": data.get("slicer"),
                "routines": routines}
    except Exception:  # noqa: BLE001
        _logger.debug("sliced routines: nothing for the request", exc_info=True)
        return None
