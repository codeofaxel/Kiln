"""A printer's own routines, read from a print file a slicer made for it.

A file sliced in Bambu Studio, OrcaSlicer or PrusaSlicer carries the printer
settings it was sliced with, and among them that printer's own routines: how
it starts and ends a print, pauses, changes filament, changes layer and takes
a timelapse picture.  This module reads those routines, and nothing else
from the file, when a print starts on a printer of the model the file was
made for (:func:`note_print_started`, called once from
:meth:`kiln.printers.base.PrinterAdapter.start_print`), and keeps them on
this computer, per printer.

What leaves, and when:

* only after the person has said yes to sharing them, once, themselves
  (:func:`kiln.sharing_consent.routines_answer`, asked once by
  :mod:`kiln.sharing_nudge`; no answer is no), and only while this install
  shares at all (telemetry and community sharing both on);
* signed in, each printer's routines to Kiln's API as the person
  (:data:`PUSH_PATH`); signed out, each routine through one database door
  (:data:`RPC`) with this install's random id.  Either way: the routine's
  text, its SHA-256, its one word (:data:`BLOCKS`), the printer model, the
  slicer's name and version, and the one-way hash of the printer's serial
  (:func:`kiln.bench.unit_of`);
* and the same routines, with no hash, id or version, ride the person's own
  print-beside requests (:func:`routines_for_request`).

What never leaves: the toolpath, the part, the file's name, the print and
filament settings, preset names, and every other custom G-code field.  A
routine the outbound guard would change (an address, a folder path, a key,
an email address) is not sent at all, and a routine the file itself lists as
changed from the slicer's preset is never sent to the database door: it only
rides the person's own requests.

Kiln's own slices are never read (:func:`kiln.print_lineage.read_stamps`, a
package Kiln wrapped carries no printer settings), nor is a file whose model
is not the printer's.  Nothing here raises into a print or slows one: the
read runs on a daemon thread after the print has started.
"""

from __future__ import annotations

import contextlib
import hashlib
import json
import logging
import re
import struct
import threading
import zlib
from datetime import datetime, timezone
from pathlib import Path
from typing import Any

_logger = logging.getLogger(__name__)


#: The database door a signed-out install's routines go through.
RPC = "record_printer_sliced_routine"
#: Kiln's API route a signed-in computer's routines go through.
PUSH_PATH = "/api/printer-routines"

#: The one word each routine is kept and sent under.
BLOCKS = (
    "start", "end", "pause", "filament_change", "color_change",
    "layer_change", "before_layer_change", "timelapse",
)

#: The routine fields each slicer writes into its printer settings, by the
#: name it writes them under.  Every other field is never read.
ROUTINE_FIELDS: dict[str, dict[str, str]] = {
    "bambu_studio": {
        "machine_start_gcode": "start",
        "machine_end_gcode": "end",
        "machine_pause_gcode": "pause",
        "change_filament_gcode": "filament_change",
        "layer_change_gcode": "layer_change",
        "before_layer_change_gcode": "before_layer_change",
        "time_lapse_gcode": "timelapse",
    },
    "prusa_slicer": {
        "start_gcode": "start",
        "end_gcode": "end",
        "pause_print_gcode": "pause",
        "toolchange_gcode": "filament_change",
        "color_change_gcode": "color_change",
        "layer_gcode": "layer_change",
        "before_layer_gcode": "before_layer_change",
    },
}
ROUTINE_FIELDS["orca_slicer"] = ROUTINE_FIELDS["bambu_studio"]

#: The longest routine kept, in characters.
MAX_ROUTINE_CHARS = 64 * 1024
#: How much of a plain G-code file is read for its settings, at each end.
_HEAD_BYTES = 2 * 1024 * 1024
_TAIL_BYTES = 1024 * 1024
#: The largest settings member read out of a sliced package.
_MAX_SETTINGS_BYTES = 4 * 1024 * 1024
_TIMEOUT_S = 5

_PRINT_FILE_SUFFIXES = (".gcode", ".gco", ".g", ".bgcode", ".3mf")
_VERSION = re.compile(r"\d{1,6}(?:\.\d{1,6}){1,4}")
_GENERATED_BY = re.compile(r"^;\s*(?:generated by\s+)?(BambuStudio|OrcaSlicer|PrusaSlicer)[ -]v?(\S+)", re.IGNORECASE)
_SLICER_WORDS = {"bambustudio": "bambu_studio", "orcaslicer": "orca_slicer", "prusaslicer": "prusa_slicer"}

_lock = threading.Lock()

__all__ = [
    "BLOCKS", "MAX_ROUTINE_CHARS", "PUSH_PATH", "ROUTINE_FIELDS", "RPC", "kept_printer_name", "said_yes",
    "note_print_started", "read_routines", "routines_for_request", "send_pending", "sending",
]


# ---------------------------------------------------------------------------
# Reading a print file
# ---------------------------------------------------------------------------


def _slicer_of_header(line: str) -> tuple[str, str] | None:
    match = _GENERATED_BY.match(line.strip())
    if not match:
        return None
    version = _VERSION.match(match.group(2))
    return _SLICER_WORDS[match.group(1).lower()], (version.group(0) if version else "")


def _unescape(value: str) -> str:
    """A G-code comment's setting value as the slicer held it."""
    out: list[str] = []
    i = 0
    while i < len(value):
        ch = value[i]
        if ch == "\\" and i + 1 < len(value):
            nxt = value[i + 1]
            out.append({"n": "\n", "r": "\r", "t": "\t", "\\": "\\"}.get(nxt, "\\" + nxt))
            i += 2
            continue
        out.append(ch)
        i += 1
    return "".join(out)


def _settings_from_lines(lines: list[str]) -> dict[str, str]:
    """``; key = value`` settings between a slicer's config markers."""
    settings: dict[str, str] = {}
    inside = False
    for raw in lines:
        line = raw.rstrip("\r\n")
        mark = line.strip().lower()
        if mark in ("; config_block_start", "; prusaslicer_config = begin"):
            inside = True
            continue
        if mark in ("; config_block_end", "; prusaslicer_config = end"):
            inside = False
            continue
        if not inside or not line.startswith(";"):
            continue
        key, sep, value = line[1:].strip().partition(" = ")
        if sep:
            settings[key.strip()] = value
    return settings


def _read_plain(path: Path) -> tuple[str, str, dict[str, Any]] | None:
    size = path.stat().st_size
    with path.open("rb") as fh:
        head = fh.read(_HEAD_BYTES)
        tail = b""
        if size > _HEAD_BYTES:
            fh.seek(max(_HEAD_BYTES, size - _TAIL_BYTES))
            tail = fh.read(_TAIL_BYTES)
    head_lines = head.decode("utf-8", errors="replace").splitlines()
    slicer = next((s for s in (_slicer_of_header(line) for line in head_lines[:8]) if s), None)
    if slicer is None:
        return None
    lines = head_lines + tail.decode("utf-8", errors="replace").splitlines()
    settings: dict[str, Any] = {k: _unescape(v) for k, v in _settings_from_lines(lines).items()}
    return slicer[0], slicer[1], settings


def _read_package(path: Path) -> tuple[str, str, dict[str, Any]] | None:
    from kiln.untrusted_zip import UntrustedZipFile

    with UntrustedZipFile(str(path)) as zf:
        names = set(zf.namelist())
        if "Metadata/project_settings.config" not in names:
            return None
        info = zf.getinfo("Metadata/project_settings.config")
        if info.file_size > _MAX_SETTINGS_BYTES:
            return None
        # Read through a capped stream, whatever the member says its size is.
        with zf.open(info) as fh:
            raw = fh.read(_MAX_SETTINGS_BYTES + 1)
        if len(raw) > _MAX_SETTINGS_BYTES:
            return None
        settings = json.loads(raw.decode("utf-8", errors="replace"))
        if not isinstance(settings, dict) or not settings:
            return None
        plate = next((n for n in sorted(names) if re.fullmatch(r"Metadata/plate_\d+\.gcode", n)), None)
        if plate is None:
            return None
        with zf.open(plate) as fh:
            first = fh.read(512).decode("utf-8", errors="replace").splitlines()
    slicer = next((s for s in (_slicer_of_header(line) for line in first[:4]) if s), None)
    if slicer is None:
        return None
    return slicer[0], slicer[1], settings


#: A binary G-code file's block types and compression kinds that are read.
_BG_SLICER_META, _BG_FILE_META, _BG_GCODE = 2, 0, 1
_BG_PLAIN, _BG_DEFLATE = 0, 1


def _read_binary(path: Path) -> tuple[str, str, dict[str, Any]] | None:
    """A PrusaSlicer binary G-code file's settings block, read up to the
    first block of G-code and no further."""
    with path.open("rb") as fh:
        data = fh.read(_MAX_SETTINGS_BYTES + 64 * 1024)
    if data[:4] != b"GCDE" or len(data) < 10:
        return None
    checksum = struct.unpack("<H", data[8:10])[0]
    pos = 10
    producer = ""
    settings: dict[str, Any] = {}
    # Every block's text, inflated, adds up to at most the cap: a small
    # crafted file must not inflate into gigabytes.
    budget = _MAX_SETTINGS_BYTES
    while pos + 8 <= len(data):
        kind, compression, size = struct.unpack("<HHI", data[pos:pos + 8])
        pos += 8
        stored = size
        if compression:
            stored = struct.unpack("<I", data[pos:pos + 4])[0]
            pos += 4
        pos += 6 if kind == 5 else 2
        body = data[pos:pos + stored]
        pos += stored + (4 if checksum else 0)
        if kind == _BG_GCODE:
            break
        if kind not in (_BG_SLICER_META, _BG_FILE_META) or compression not in (_BG_PLAIN, _BG_DEFLATE):
            continue
        if compression == _BG_DEFLATE:
            inflater = zlib.decompressobj()
            raw = inflater.decompress(body, budget + 1)
            if inflater.unconsumed_tail or len(raw) > budget:
                return None
        else:
            raw = body
        if len(raw) > budget:
            return None
        budget -= len(raw)
        text = raw.decode("utf-8", errors="replace")
        for line in text.splitlines():
            key, sep, value = line.partition("=")
            if not sep:
                continue
            if kind == _BG_FILE_META and key.strip().lower() == "producer":
                producer = value.strip()
            elif kind == _BG_SLICER_META:
                settings[key.strip()] = _unescape(value.strip())
    slicer = _slicer_of_header("; " + producer) if producer else None
    if slicer is None or not settings:
        return None
    return slicer[0], slicer[1], settings


def _changed_fields(settings: dict[str, Any]) -> set[str]:
    """The fields the file says differ from the slicer's own presets."""
    raw = settings.get("different_settings_to_system")
    parts = raw if isinstance(raw, list) else [raw]
    out: set[str] = set()
    for part in parts:
        out.update(s.strip() for s in str(part or "").split(";") if s.strip())
    return out


def _model_slug(text: str | None) -> str:
    return re.sub(r"[^a-z0-9]+", "_", str(text or "").lower()).strip("_")[:80]


def _model_id(text: str | None) -> str | None:
    """The catalogue's id for a model name, else the name as a slug."""
    if not text:
        return None
    try:
        from kiln.printers.bed_fit import catalogue_printer_id

        listed = catalogue_printer_id(str(text))
    except Exception:  # noqa: BLE001 -- an unreadable catalogue still compares names
        listed = None
    return listed or (_model_slug(text) or None)


def read_routines(path: str | Path) -> dict[str, Any] | None:
    """The printer routines a sliced print file carries, or ``None``.

    ``{"model", "printer_model", "slicer", "version",
    "routines": {block: {"text", "sha256", "share"}}}`` -- *share* is false
    for a routine the file lists as changed from the slicer's own preset.
    ``None`` for a file no listed slicer made, a file Kiln sliced, or one
    with no routine in it.  Never raises.
    """
    try:
        p = Path(path)
        if not p.is_file() or not p.name.lower().endswith(_PRINT_FILE_SUFFIXES):
            return None
        from kiln.print_lineage import read_stamps

        if read_stamps(str(p)):
            return None
        lower = p.name.lower()
        if lower.endswith(".3mf"):
            read = _read_package(p)
        elif lower.endswith(".bgcode"):
            read = _read_binary(p)
        else:
            read = _read_plain(p)
        if read is None:
            return None
        slicer, version, settings = read
        if slicer == "prusa_slicer" and not str(settings.get("printer_settings_id") or "").strip():
            # A slice with no named printer preset is a command-line run, not a
            # person's slicer.
            return None
        printer_model = str(settings.get("printer_model") or "").strip()
        model = _model_id(printer_model)
        if not model:
            return None
        changed = _changed_fields(settings)
        routines: dict[str, dict[str, Any]] = {}
        for field, block in ROUTINE_FIELDS[slicer].items():
            value = settings.get(field)
            if isinstance(value, list):
                value = value[0] if len(value) == 1 and isinstance(value[0], str) else None
            if not isinstance(value, str):
                continue
            text = value.replace("\r\n", "\n")
            if not text.strip() or len(text) > MAX_ROUTINE_CHARS or "\x00" in text:
                continue
            routines[block] = {
                "text": text,
                "sha256": hashlib.sha256(text.encode("utf-8")).hexdigest(),
                "share": field not in changed,
            }
        if not routines:
            return None
        return {
            "model": model, "printer_model": printer_model[:80], "slicer": slicer, "version": version,
            "routines": routines,
        }
    except Exception:  # noqa: BLE001 -- a file Kiln cannot read carries nothing
        _logger.debug("sliced routines: file not read", exc_info=True)
        return None


# ---------------------------------------------------------------------------
# Keeping, per printer
# ---------------------------------------------------------------------------


def _store_dir() -> Path:
    from kiln.startup_failure import kiln_home

    return kiln_home() / "sliced_routines"


def _hosted() -> bool:
    try:
        from kiln.runtime_env import is_hosted_multitenant

        return bool(is_hosted_multitenant())
    except Exception:  # noqa: BLE001 -- an unknown posture keeps nothing
        return True


def _key_of(adapter: Any, model: str) -> tuple[str, str | None]:
    try:
        from kiln.bench import unit_of

        unit = unit_of(adapter)
    except Exception:  # noqa: BLE001
        unit = None
    return (unit or "model-" + _model_slug(model)), unit


def _load(key: str) -> dict[str, Any]:
    try:
        data = json.loads((_store_dir() / f"{key}.json").read_text(encoding="utf-8"))
        return data if isinstance(data, dict) else {}
    except (OSError, ValueError):
        return {}


def _save(key: str, data: dict[str, Any]) -> None:
    folder = _store_dir()
    folder.mkdir(parents=True, exist_ok=True)
    tmp = folder / f".{key}.json.tmp"
    tmp.write_text(json.dumps(data, sort_keys=True), encoding="utf-8")
    tmp.replace(folder / f"{key}.json")


def _declared_model(adapter: Any) -> str | None:
    try:
        from kiln.plate_state import declared_model_of

        return _model_id(declared_model_of(adapter))
    except Exception:  # noqa: BLE001
        return None


def keep(adapter: Any, read: dict[str, Any]) -> bool:
    """Keep *read* as *adapter*'s routines when the file was made for this
    printer's model.  The latest file read replaces the routines before it;
    what was sent is kept.  Never raises."""
    try:
        if _hosted() or not read:
            return False
        declared = _declared_model(adapter)
        if not declared or declared != read.get("model"):
            return False
        key, unit = _key_of(adapter, declared)
        with _lock:
            data = _load(key)
            data.update({
                "unit": unit, "model": read["model"], "printer_model": read.get("printer_model"),
                "slicer": read["slicer"], "version": read.get("version") or "",
                "routines": read["routines"], "read_at": datetime.now(timezone.utc).isoformat(timespec="seconds"),
            })
            data.setdefault("sent", {})
            _save(key, data)
        return True
    except Exception:  # noqa: BLE001
        _logger.debug("sliced routines: not kept", exc_info=True)
        return False


def _note(adapter: Any, paths: list[str]) -> None:
    for path in paths:
        read = read_routines(path)
        if read is None:
            continue
        if keep(adapter, read) and sending():
            from kiln.heartbeat import _SUPABASE_ANON_KEY, _SUPABASE_URL

            send_pending(_SUPABASE_URL, _SUPABASE_ANON_KEY)
        return


def note_print_started(adapter: Any, file_name: str | None, kwargs: dict[str, Any] | None = None) -> None:
    """A print just started on *adapter*: read the routines of the file it
    printed from this computer's copy, off the print's path.  Never raises."""
    try:
        if _hosted() or not file_name:
            return
        from kiln.print_lineage import local_copies

        paths = local_copies(file_name, kwargs or {})
        if not paths:
            return
        threading.Thread(target=_note, args=(adapter, paths), name="kiln-sliced-routines", daemon=True).start()
    except Exception:  # noqa: BLE001 -- a routine read never affects a print
        _logger.debug("sliced routines: start note failed", exc_info=True)


